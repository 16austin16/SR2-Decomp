/// `cdq; idiv dword ptr [p]` on EDX:EAX (a zero or overflowing divisor faults, as in the original).
/// Returns (quotient, remainder).
unsafe fn idiv_mem(eax: u32, p: usize) -> (u32, u32) {
    let q: u32;
    let rem: u32;
    unsafe {
        std::arch::asm!(
            "cdq",
            "idiv dword ptr [{p}]",
            p = in(reg) p,
            inout("eax") eax => q,
            out("edx") rem,
            options(nostack),
        );
    }
    (q, rem)
}

