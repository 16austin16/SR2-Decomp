//! The per-frame vehicle update chain (doc 16, "vehicles_pre_update / vehicles_update porting
//! map"), called from sim_frame :4 and :5:
//! - `vehicles_pre_update` (0xAE3A80): the nav / obstacle refreshes, then `vehicle_pre_update`
//!   for every full vehicle, then the deferred object packets.
//! - `vehicles_update` (0xAE3C60): `vehicle_update` for the full vehicles, `vehicle_update_light`
//!   for the light list, the light-vehicle cull, then the collision-pair reactions.
//! - `vehicle_pre_update` (0xAB2AA0): the per-vehicle pre-physics step (speed clamp, fall
//!   slow-motion, seats, driver, transform history, the "stopped" check).
//!
//! Both list functions copy the two full-vehicle lists (and `vehicles_update` later the light
//! list) into an unchecked 32-entry stack array; a 33rd entry overwrites the return address. The
//! ports count first, and when a list would not fit they hand over, with the stack exactly as the
//! original has it at that point, to a relocated copy of the original body, so the overrun
//! happens exactly as in the game.

use std::sync::atomic::{AtomicU32, AtomicUsize, Ordering};

use core::arch::x86::*;

use crate::portlib::*;
use crate::{detour, log};

const MP_ACTIVE: usize = 0x0252_8B48; // u8
const MP_CLIENT: usize = 0x0252_8B49; // u8
const GAME_NOW: usize = 0x00E8_43AC; // ms
const FRAME_DT: usize = 0x00E8_437C; // f32
const SLOW_MOTION: usize = 0x00E8_ECAC; // f32 divisor read by physics_frame_time

const FULL_LIST_A: usize = 0x022A_84E0;
const FULL_LIST_B: usize = 0x022A_84D4;
const LIGHT_LIST: usize = 0x022A_84DC;
const LINK: usize = 0x84DC;

/// Room in the originals' stack arrays: [esp+0xC .. esp+0x8C) in vehicles_pre_update and
/// [esp+0x14 .. esp+0x94) in vehicles_update. Entry 32 is the return address.
const CAP: usize = 32;

static PRE_CALLS: AtomicU32 = AtomicU32::new(0);
static UPD_CALLS: AtomicU32 = AtomicU32::new(0);
static VPU_CALLS: AtomicU32 = AtomicU32::new(0);
static VPU_CLAMPS: AtomicU32 = AtomicU32::new(0);
static VPU_SLOWMO: AtomicU32 = AtomicU32::new(0);
static OVERFLOWS: AtomicU32 = AtomicU32::new(0);
static NULL_PHYS: AtomicU32 = AtomicU32::new(0);
static PRE_ON: AtomicU32 = AtomicU32::new(0);
static UPD_ON: AtomicU32 = AtomicU32::new(0);
static VPU_ON: AtomicU32 = AtomicU32::new(0);

/// Resume points in the relocated originals (0 = not available).
static PRE_RESUME: AtomicUsize = AtomicUsize::new(0); // copy + 0x28 (0xAE3AA8)
static UPD_COPY: AtomicUsize = AtomicUsize::new(0); // copy + 0
static UPD_RESUME: AtomicUsize = AtomicUsize::new(0); // copy + 0x8D (0xAE3CED)

fn note_overflow(what: &str, n: usize) {
    let k = OVERFLOWS.fetch_add(1, Ordering::Relaxed) + 1;
    if k <= 10 {
        log(&format!(
            "port_vehicles: {what}: {n} entries for a {CAP}-entry stack array; running the original (it overruns its frame)"
        ));
    }
}

// --- Small call helpers -------------------------------------------------------------------------

/// Call `f` with EAX = `eax` (no stack arguments); the ST0 result rounded to f32.
unsafe fn st0_eax(f: usize, eax: u32) -> f32 {
    let mut out = 0f32;
    unsafe {
        std::arch::asm!(
            "push edi",
            "call {f}",
            "pop edi",
            "fstp dword ptr [edi]",
            f = in(reg) f,
            inout("eax") eax => _,
            in("edi") &mut out as *mut f32,
            clobber_abi("C"),
        );
    }
    out
}

/// Call `f` with one cdecl argument; the ST0 result rounded to f32.
unsafe fn st0_arg(f: usize, a: u32) -> f32 {
    let mut out = 0f32;
    unsafe {
        std::arch::asm!(
            "push edi",
            "push {a}",
            "call {f}",
            "add esp, 4",
            "pop edi",
            "fstp dword ptr [edi]",
            f = in(reg) f,
            a = in(reg) a,
            in("edi") &mut out as *mut f32,
            clobber_abi("C"),
        );
    }
    out
}

/// The game's float-to-int (0xDA0140) on the f32 at `p`, loaded onto ST0 as the original does.
unsafe fn game_ftol(p: usize) -> u32 {
    let r: u32;
    unsafe {
        std::arch::asm!(
            "fld dword ptr [{p}]",
            "call {f}",
            p = in(reg) p,
            f = in(reg) 0x00DA_0140usize,
            out("eax") r,
            clobber_abi("C"),
        );
    }
    r
}

#[repr(C, align(16))]
struct Vec4([f32; 4]);

// --- List copies ----------------------------------------------------------------------------------

/// Copy a circular list into `out` from `n` on, the original's loop: store, step, stop at the head
/// or 0. Only called once the list is known to fit.
unsafe fn copy_list(head: usize, out: &mut [u32; CAP], n: &mut usize) {
    unsafe {
        let h = rd(head);
        let mut e = h;
        while e != 0 {
            out[*n] = e;
            *n += 1;
            e = rd(e as usize + LINK);
            if e == h {
                break;
            }
        }
    }
}

/// The same walk, counting only.
unsafe fn count_list(head: usize) -> usize {
    let mut n = 0;
    unsafe {
        let h = rd(head);
        let mut e = h;
        while e != 0 {
            n += 1;
            if n > 4096 {
                break; // the original would be far past its frame already
            }
            e = rd(e as usize + LINK);
            if e == h {
                break;
            }
        }
    }
    n
}

// --- vehicles_pre_update (0xAE3A80) -------------------------------------------------------------

const VEHICLES_PRE_UPDATE: usize = 0x00AE_3A80;

/// Returns 0 when done, or the address to continue at (into the relocated original) on overflow.
extern "C" fn vehicles_pre_update() -> usize {
    PRE_CALLS.fetch_add(1, Ordering::Relaxed);
    unsafe {
        // humans_nav_node_refresh_all, vehicle_obstacles_rebuild, vehicle_recent_list_prune
        calls(&[0x00B2_6340, 0x00B2_E1E0, 0x00B2_F370]);
        wb(0x0252_A10C, 0);
        // player_vehicle_tracking_update, vehicle_deferred_calls_flush
        calls(&[0x009E_32D0, 0x004C_2D30]);
        let total = count_list(FULL_LIST_A) + count_list(FULL_LIST_B);
        if total > CAP {
            note_overflow("vehicles_pre_update", total);
            return pre_overflow_stub as extern "C" fn() as usize;
        }
        let mut list = [0u32; CAP];
        let mut n = 0;
        copy_list(FULL_LIST_A, &mut list, &mut n);
        copy_list(FULL_LIST_B, &mut list, &mut n);
        let dt = call_f32(0x006F_F860); // physics_frame_time, fstp dword
        for &v in &list[..n] {
            call_regs(VEHICLE_PRE_UPDATE, v, 0, 0, 0, 0, &[v, dt.to_bits()]);
        }
        call(0x0073_7C10); // the original's tail jmp: object_deferred_packets_flush
    }
    0
}

/// The original's frame at 0xAE3AA8 (after the six calls), then on into the relocated copy.
#[unsafe(naked)]
extern "C" fn pre_overflow_stub() {
    std::arch::naked_asm!("sub esp, 0x84", "push esi", "push edi", "jmp dword ptr [{r}]", r = sym PRE_RESUME)
}

/// Keeps ECX / EDX; a non-zero result is jumped to with the entry stack.
#[unsafe(naked)]
extern "C" fn vehicles_pre_update_thunk() {
    std::arch::naked_asm!(
        "push ecx",
        "push edx",
        "call {f}",
        "pop edx",
        "pop ecx",
        "test eax, eax",
        "jnz 2f",
        "ret",
        "2:",
        "jmp eax",
        f = sym vehicles_pre_update,
    )
}

// --- vehicles_update (0xAE3C60) -----------------------------------------------------------------

const VEHICLES_UPDATE: usize = 0x00AE_3C60;

extern "C" fn vehicles_update() -> usize {
    UPD_CALLS.fetch_add(1, Ordering::Relaxed);
    unsafe {
        let total = count_list(FULL_LIST_A) + count_list(FULL_LIST_B);
        if total > CAP {
            note_overflow("vehicles_update (full lists)", total);
            return UPD_COPY.load(Ordering::Relaxed);
        }
        let mut list = [0u32; CAP];
        let mut n = 0;
        copy_list(FULL_LIST_A, &mut list, &mut n);
        copy_list(FULL_LIST_B, &mut list, &mut n);
        for &v in &list[..n] {
            let carrier = rd(v as usize + 0x9050);
            if carrier != 0 && rd(carrier as usize + 0x1C) != 0 {
                continue;
            }
            if rb(v as usize + 0x80) & 0xB != 0 {
                continue;
            }
            call_regs(0x00AB_3550, v, carrier, 0, 0, 0, &[v]); // vehicle_update
        }

        // The light list goes through the same array.
        let lights = count_list(LIGHT_LIST);
        if lights > CAP {
            note_overflow("vehicles_update (light list)", lights);
            return upd_overflow_stub as extern "C" fn() as usize;
        }
        let mut n = 0;
        copy_list(LIGHT_LIST, &mut list, &mut n);
        for &v in &list[..n] {
            if v != 0 && rb(v as usize + 0x80) & 0xB == 0 {
                call_regs(0x00AB_4460, v, 0, 0, 0, 0, &[]); // vehicle_update_light, EAX = vehicle
            }
        }

        // Count the light vehicles without +0x8F50 bit 0x40 (next = link != head ? link : 0).
        let head = rd(LIGHT_LIST);
        let mut counted = 0i32;
        let mut e = head;
        while e != 0 {
            let l = rd(e as usize + LINK);
            if rb(e as usize + 0x8F50) & 0x40 == 0 {
                counted += 1;
            }
            e = if l != head { l } else { 0 };
        }
        if counted > 4 {
            call(0x00AE_1CF0); // vehicles_cull_light
        }

        let mut pairs = 0u32;
        let mut count = 0u32;
        let pp = &mut pairs as *mut u32;
        let cp = &mut count as *mut u32;
        // vehicle_collision_pairs_collect(&array, &count), EAX = &count, ECX = &array
        call_regs(0x00AC_2080, cp as u32, pp as u32, 0, 0, 0, &[pp as u32, cp as u32]);
        let (mut p, k) = (std::ptr::read_volatile(pp), std::ptr::read_volatile(cp));
        for _ in 0..k {
            call_regs(0x00AE_3B30, 0, 0, 0, 0, 0, &[p]); // vehicle_collision_pair_react
            p = p.wrapping_add(12);
        }
    }
    0
}

