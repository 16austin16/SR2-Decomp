//! Ten of the most-used mission script bindings in Rust (docs/analysis/09_script.md, "Ten top
//! bindings at instruction level"): trigger_enable, thread_new, thread_kill, on_trigger, on_death,
//! sizeof_table, coop_is_active, group_show, character_is_dead and door_lock.
//!
//! Argument reading follows the originals exactly: `n` is the argument count clamped to the most
//! a binding reads, argument k is read at `k - 1 - n` through the game's lua_tostring /
//! luaA_index, so a missing argument is the stale slot at `L->top`, not nil (door_lock with one
//! argument, on_trigger with one, any binding with none). The truth test treats a missing slot,
//! nil and `false` as false, everything else (including the number 0) as true.
//!
//! Quirks kept: trigger_enable treats an explicit nil as "enable"; character_is_dead reports a
//! missing character as dead, and a living one as dead while 0xEAAF44 >= 0; thread_new runs the
//! child to its first yield inside the call; sizeof_table always counts argument 1; the
//! on_death / character_is_dead "is human" flag lives in the L argument slot in the originals, so
//! its initial value is L's low byte here too.

use std::sync::atomic::{AtomicU32, Ordering};

use crate::gfx_cmd::call_regs;
use crate::{detour, log};

const LUAA_INDEX: usize = 0x00CD_BE80;
const LUA_TOSTRING: usize = 0x00CD_CA80;
const LUA_TONUMBER: usize = 0x00CD_C250;
const TRIGGER_FIND_BY_NAME: usize = 0x00A6_C870; // EAX = name
const TRIGGER_SET_ENABLED: usize = 0x00A6_D0C0; // ECX = trigger, cdecl (u8)
const TRIGGER_ACTIVATE: usize = 0x00A6_BCE0; // ESI = trigger
const TRIGGER_DEACTIVATE: usize = 0x00A6_BD60; // EAX = trigger
const SCRIPT_SET_CALLBACK: usize = 0x00A5_30F0; // ECX = block, EAX = &zero, (name)
const SCRIPT_FIND_OBJECT_BY_NAME: usize = 0x00A5_2BB0; // ECX = name, EAX = &is_human byte
const HUMAN_SCRIPT_CALLBACK_SET: usize = 0x00A5_3060; // ECX = human + 0x1234, EAX = &zero, (name)
const SCRIPT_OBJECT_FIND: usize = 0x00A6_18A0; // EAX = name
const OBJECT_SCRIPT_CALLBACK_SET: usize = 0x00A5_3470; // ECX = object + 0xBC, EAX = &zero, (name)
const HUMAN_IS_DEAD: usize = 0x0098_5630; // cdecl (human) -> al
const SCRIPT_FOLLOWER_INDEX: usize = 0x00A2_75F0; // EAX = name
const SCRIPT_FOLLOWER_GET: usize = 0x00A2_7660; // cdecl (index)
const SCRIPT_THREAD_FIND: usize = 0x00CD_FEB0; // cdecl (id)
const SCRIPT_THREAD_CREATE: usize = 0x00CE_01E0; // EAX = slot, cdecl (name, 0, 0, 0)
const SCRIPT_THREAD_RESUME: usize = 0x00CE_0570; // EDI = &entry, cdecl (0)
const LUA_XMOVE: usize = 0x00CD_BE40; // EDI = from, EDX = to, cdecl (n)
const LUA_TABLE_COUNT: usize = 0x0077_62E0; // EAX = index, cdecl (L)
const COOP_SESSION_ACTIVE: usize = 0x007F_7AD0;
const GROUP_FIND_BY_NAME: usize = 0x00A5_7730; // EAX = name
const GROUP_SET_HIDDEN: usize = 0x00A5_8070; // EDI = group, cdecl (u8)
const SCRIPT_DOOR_FIND_BY_NAME: usize = 0x00A5_B6E0; // EAX = name
const DOOR_SET_LOCKED: usize = 0x0091_B690; // ECX = door, cdecl (u8)
const GAME_TIME: usize = 0x00E8_43AC;
const NO_THREAD: usize = 0x00E5_BFA8; // f64 65535.0

unsafe fn rd(p: usize) -> u32 {
    unsafe { *(p as *const u32) }
}

unsafe fn wd(p: usize, v: u32) {
    unsafe { *(p as *mut u32) = v }
}

unsafe fn top(l: u32) -> u32 {
    unsafe { rd(l as usize + 8) }
}

unsafe fn nargs(l: u32) -> i32 {
    unsafe { (top(l).wrapping_sub(rd(l as usize + 0xC)) as i32) >> 4 }
}

unsafe fn tostring(l: u32, i: i32) -> u32 {
    unsafe { call_regs(LUA_TOSTRING, i as u32, l, 0, 0, 0, &[]) }
}

unsafe fn index(l: u32, i: i32) -> u32 {
    unsafe { call_regs(LUAA_INDEX, i as u32, l, 0, 0, 0, &[]) }
}

unsafe fn int_arg(l: u32, i: i32) -> u32 {
    let mut out = 0f64;
    unsafe {
        std::arch::asm!(
            "call {f}",
            "fstp qword ptr [edi]",
            f = in(reg) LUA_TONUMBER,
            in("eax") i,
            in("ecx") l,
            in("edi") &mut out as *mut f64,
            clobber_abi("C"),
        );
    }
    if out.abs() < 9.2e18 { out as i64 as u32 } else { 0 }
}

/// The truth test of a slot pointer: missing, nil or false -> false.
unsafe fn truth(p: u32) -> bool {
    unsafe {
        if p == 0 {
            return false;
        }
        match rd(p as usize) {
            0 => false,
            1 => rd(p as usize + 8) != 0,
            _ => true,
        }
    }
}

unsafe fn push(l: u32, tt: u32, v: impl FnOnce(usize)) {
    unsafe {
        let t = top(l) as usize;
        wd(t, tt);
        v(t + 8);
        wd(l as usize + 8, t as u32 + 16);
    }
}

unsafe fn push_bool(l: u32, b: bool) {
    unsafe { push(l, 1, |p| wd(p, b as u32)) };
}

unsafe fn push_number(l: u32, x: f64) {
    unsafe { push(l, 3, |p| *(p as *mut f64) = x) };
}

/// Stamp a trigger's +0x11C with the game time (wrapping at 1.8e9 ms).
unsafe fn stamp(t: u32) {
    unsafe {
        let mut v = rd(GAME_TIME) as i32;
        wd(t as usize + 0x11C, v as u32);
        if v > 0x6B49_D200 {
            v = v.wrapping_add(0x94B6_2E00u32 as i32);
            wd(t as usize + 0x11C, v as u32);
        }
    }
}

/// `trigger_enable(name, [enable = true])`; an explicit nil also enables.
extern "C" fn trigger_enable(l: u32) -> i32 {
    CALLS[0].fetch_add(1, Ordering::Relaxed);
    unsafe {
        let n = nargs(l).min(2);
        let name = tostring(l, -n);
        let m = n - 1;
        let enable = if m <= 0 {
            true
        } else {
            let p = index(l, -m);
            if p != 0 && rd(p as usize) == 0 { true } else { truth(index(l, -m)) }
        };
        let t = call_regs(TRIGGER_FIND_BY_NAME, name, 0, 0, 0, 0, &[]);
        if t == 0 {
            return 0;
        }
        call_regs(TRIGGER_SET_ENABLED, 0, t, 0, 0, 0, &[enable as u32]);
        if enable {
            call_regs(TRIGGER_ACTIVATE, 0, 0, 0, t, 0, &[]);
            stamp(t);
        } else {
            call_regs(TRIGGER_DEACTIVATE, t, 0, 0, 0, 0, &[]);
        }
    }
    0
}

/// `thread_new(function name, args...)` -> thread id, or 65535 on failure. The child runs to its
/// first yield before this returns.
extern "C" fn thread_new(l: u32) -> i32 {
    CALLS[1].fetch_add(1, Ordering::Relaxed);
    unsafe {
        let n = nargs(l);
        let name = tostring(l, -n.min(20));
        let slot = rd(0x0252_6360);
        let st = if slot == 0 || slot > 16 { 0 } else { rd(0x0252_6364 + slot as usize * 4) };
        // A bad slot reads [0 + 8] and crashes, as the original does.
        let rec = call_regs(SCRIPT_THREAD_CREATE, rd(st as usize + 8), 0, 0, 0, 0, &[name, 0, 0, 0]);
        let mut id = None;
        if rec != 0 {
            wd(rec as usize + 0x14, rd(st as usize + 0x14));
            let k = n - 1;
            call_regs(LUA_XMOVE, 0, 0, rd(rec as usize + 4), 0, l, &[k as u32]);
            wd(rec as usize + 0x1C, k as u32);
            let mut entry = rec;
            call_regs(SCRIPT_THREAD_RESUME, 0, 0, 0, 0, &mut entry as *mut u32 as u32, &[0]);
            if entry != 0 {
                id = Some(*(entry as *const u16) as f64);
            }
        }
        push_number(l, id.unwrap_or(*(NO_THREAD as *const f64)));
    }
    1
}

/// `thread_kill(id)`: flags the thread for removal on the scheduler's next pass.
extern "C" fn thread_kill(l: u32) -> i32 {
    CALLS[2].fetch_add(1, Ordering::Relaxed);
    unsafe {
        let n = nargs(l).min(1);
        let id = int_arg(l, -n);
        let r = call_regs(SCRIPT_THREAD_FIND, 0, 0, 0, 0, 0, &[id]);
        if r != 0 {
            *((r + 0x18) as *mut u16) |= 4;
        }
    }
    0
}

/// `on_trigger(callback, trigger name)`: sets the callback only if the trigger has none
/// (+0x13C == 0); stamps the time when a callback is set.
extern "C" fn on_trigger(l: u32) -> i32 {
    CALLS[3].fetch_add(1, Ordering::Relaxed);
    unsafe {
        let n = nargs(l).min(2);
        let cb = tostring(l, -n);
        let name = tostring(l, 1 - n);
        let t = call_regs(TRIGGER_FIND_BY_NAME, name, 0, 0, 0, 0, &[]);
        if t == 0 {
            return 0;
        }
        if rd(t as usize + 0x13C) == 0 {
            let mut zero = 0u32;
            call_regs(SCRIPT_SET_CALLBACK, &mut zero as *mut u32 as u32, t + 0x150, 0, 0, 0, &[cb]);
        }
        if rd(t as usize + 0x150) != u32::MAX {
            stamp(t);
        }
    }
    0
}

/// `on_death(callback, object name)`: on a human's callback block (+0x1234) or an object's
/// script info (+0xBC).
extern "C" fn on_death(l: u32) -> i32 {
    CALLS[4].fetch_add(1, Ordering::Relaxed);
    unsafe {
        let n = nargs(l).min(2);
        let cb = tostring(l, -n);
        let name = tostring(l, 1 - n);
        let mut is_human = l;
        let obj = call_regs(SCRIPT_FIND_OBJECT_BY_NAME, &mut is_human as *mut u32 as u32, name, 0, 0, 0, &[]);
        let mut zero = 0u32;
        let pz = &mut zero as *mut u32 as u32;
        if is_human as u8 != 0 {
            if obj != 0 {
                call_regs(HUMAN_SCRIPT_CALLBACK_SET, pz, obj + 0x1234, 0, 0, 0, &[cb]);
            }
        } else {
            let o = call_regs(SCRIPT_OBJECT_FIND, name, 0, 0, 0, 0, &[]);
            if o != 0 {
                call_regs(OBJECT_SCRIPT_CALLBACK_SET, pz, o + 0xBC, 0, 0, 0, &[cb]);
            }
        }
    }
    0
}

/// `sizeof_table(table)` -> the count of argument 1, or -1 with no argument.
extern "C" fn sizeof_table(l: u32) -> i32 {
    CALLS[5].fetch_add(1, Ordering::Relaxed);
    unsafe {
        let count = if nargs(l) >= 1 { call_regs(LUA_TABLE_COUNT, 1, 0, 0, 0, 0, &[l]) as i32 } else { -1 };
        push_number(l, count as f64);
    }
    1
}

/// `coop_is_active()` -> boolean.
extern "C" fn coop_is_active(l: u32) -> i32 {
    CALLS[6].fetch_add(1, Ordering::Relaxed);
    unsafe {
        let a = call_regs(COOP_SESSION_ACTIVE, 0, 0, 0, 0, 0, &[]) as u8 != 0;
        push_bool(l, a);
    }
    1
}

/// `group_show(group name)`.
extern "C" fn group_show(l: u32) -> i32 {
    CALLS[7].fetch_add(1, Ordering::Relaxed);
    unsafe {
        let n = nargs(l).min(1);
        let name = tostring(l, -n);
        let g = call_regs(GROUP_FIND_BY_NAME, name, 0, 0, 0, 0, &[]);
        if g != 0 {
            call_regs(GROUP_SET_HIDDEN, 0, 0, 0, 0, g, &[0]);
        }
    }
    0
}

/// `character_is_dead(name)` -> boolean; a missing character counts as dead.
extern "C" fn character_is_dead(l: u32) -> i32 {
    CALLS[8].fetch_add(1, Ordering::Relaxed);
    unsafe {
        let n = nargs(l).min(1);
        let name = tostring(l, -n);
        let mut is_human = l;
        let obj = call_regs(SCRIPT_FIND_OBJECT_BY_NAME, &mut is_human as *mut u32 as u32, name, 0, 0, 0, &[]);
        let dead = |h: u32| call_regs(HUMAN_IS_DEAD, 0, 0, 0, 0, 0, &[h]) as u8 != 0;
        let r = if is_human as u8 != 0 {
            obj == 0 || dead(obj) || rd(0x00EA_AF44) as i32 >= 0
        } else if name == 0 {
            true
        } else {
            let i = call_regs(SCRIPT_FOLLOWER_INDEX, name, 0, 0, 0, 0, &[]) as i32;
            let h = if i > 0 {
                call_regs(SCRIPT_FOLLOWER_GET, 0, 0, 0, 0, 0, &[i as u32])
            } else {
                let o = call_regs(SCRIPT_OBJECT_FIND, name, 0, 0, 0, 0, &[]);
                if o == 0 { 0 } else { call_regs(rd(rd(o as usize) as usize + 0x34) as usize, 0, o, 0, 0, 0, &[]) }
            };
            h == 0 || dead(h)
        };
        push_bool(l, r);
    }
    1
}

/// `door_lock(door name, [locked])`: with one argument "locked" is the stale top slot.
extern "C" fn door_lock(l: u32) -> i32 {
    CALLS[9].fetch_add(1, Ordering::Relaxed);
    unsafe {
        let n = nargs(l).min(2);
        let name = tostring(l, -n);
        let i = 1 - n;
        let p = if i > 0 {
            let a = rd(l as usize + 0xC) + (i as u32 - 1) * 16;
            if a < top(l) { a } else { 0 }
        } else {
            index(l, i)
        };
        let locked = truth(p);
        let door = call_regs(SCRIPT_DOOR_FIND_BY_NAME, name, 0, 0, locked as u32, 0, &[]);
        if door != 0 {
            call_regs(DOOR_SET_LOCKED, 0, door, 0, 0, 0, &[locked as u32]);
        }
    }
    0
}

const FLOORF: usize = 0x0042_7600; // cdecl f32 -> ST0
const LUA_PUSHSTRING: usize = 0x00CD_CAF0; // ESI = L, cdecl (str)
const SCRIPT_VEHICLE_FIND: usize = 0x00A7_0030; // EAX = name
const RAND_TABLE: usize = 0x00EC_3AC0; // 2048 pre-made values
const RAND_CURSOR: usize = 0x00EC_3ABC;

unsafe fn number_arg(l: u32, i: i32) -> f64 {
    let mut out = 0f64;
    unsafe {
        std::arch::asm!(
            "call {f}",
            "fstp qword ptr [edi]",
            f = in(reg) LUA_TONUMBER,
            in("eax") i,
            in("ecx") l,
            in("edi") &mut out as *mut f64,
            clobber_abi("C"),
        );
    }
    out
}

/// `floor(x)`: x goes through f32 first, then floorf and a truncating int conversion
/// (0x80000000 out of range).
extern "C" fn lua_floor(l: u32) -> i32 {
    CALLS[10].fetch_add(1, Ordering::Relaxed);
    unsafe {
        let n = nargs(l).min(1);
        let x = number_arg(l, -n) as f32;
        let mut fl = 0f64;
        std::arch::asm!(
            "push edi",
            "push {v}",
            "call {f}",
            "add esp, 4",
            "pop edi",
            "fstp qword ptr [edi]",
            v = in(reg) x.to_bits(),
            f = in(reg) FLOORF,
            in("edi") &mut fl as *mut f64,
            clobber_abi("C"),
        );
        let i = if fl >= -2147483648.0 && fl < 2147483648.0 { fl as i32 } else { i32::MIN };
        push_number(l, i as f64);
    }
    1
}

/// `rand_int(lo, hi)`: the next value of the game's pre-made table (cursor wraps at 2048), lo +
/// value mod (hi - lo + 1) with an unsigned divide.
extern "C" fn rand_int(l: u32) -> i32 {
    CALLS[11].fetch_add(1, Ordering::Relaxed);
    unsafe {
        let n = nargs(l).min(2);
        let mut lo = int_arg(l, -n) as i32;
        let mut hi = int_arg(l, 1 - n) as i32;
        if lo > hi {
            std::mem::swap(&mut lo, &mut hi);
        }
        let c = rd(RAND_CURSOR);
        let r = rd(RAND_TABLE + c as usize * 4);
        wd(RAND_CURSOR, c + 1);
        if c + 1 >= 0x800 {
            wd(RAND_CURSOR, 0);
        }
        let range = (hi as u32).wrapping_sub(lo as u32).wrapping_add(1);
        let v = (r % range).wrapping_add(lo as u32) as i32;
        push_number(l, v as f64);
    }
    1
}

/// `get_platform()` -> "PC".
extern "C" fn get_platform(l: u32) -> i32 {
    CALLS[12].fetch_add(1, Ordering::Relaxed);
    unsafe { call_regs(LUA_PUSHSTRING, 0, 0, 0, l, 0, &[0x00E2_4AA8]) };
    1
}

/// `group_is_loaded(name)` -> boolean (+0x18 bit 2; a missing group is not loaded).
extern "C" fn group_is_loaded(l: u32) -> i32 {
    CALLS[13].fetch_add(1, Ordering::Relaxed);
    unsafe {
        let n = nargs(l).min(1);
        let g = call_regs(GROUP_FIND_BY_NAME, tostring(l, -n), 0, 0, 0, 0, &[]);
        push_bool(l, g != 0 && (*((g + 0x18) as *const u8) >> 1) & 1 != 0);
    }
    1
}

/// `vehicle_is_destroyed(name)` -> boolean; a missing vehicle counts as destroyed.
extern "C" fn vehicle_is_destroyed(l: u32) -> i32 {
    CALLS[14].fetch_add(1, Ordering::Relaxed);
    unsafe {
        let n = nargs(l).min(1);
        let v = call_regs(SCRIPT_VEHICLE_FIND, tostring(l, -n), 0, 0, 0, 0, &[]);
        let h = if v != 0 { call_regs(rd(rd(v as usize) as usize + 0x34) as usize, 0, v, 0, 0, 0, &[]) } else { 0 };
        push_bool(l, h == 0 || *((h + 0x8F50) as *const u8) & 1 != 0);
    }
    1
}

const VEHICLE_SCRIPT_CALLBACK_SET: usize = 0x00A5_31E0; // ECX = vehicle + 0x7C, EAX = &type, (name)

/// on_vehicle_destroyed / on_vehicle_enter (callback, name): a human gets the callback on +0x1234
/// with `human_type`, else a vehicle on +0x7C with `vehicle_type`.
unsafe fn vehicle_callback(l: u32, human_type: u32, vehicle_type: u32) {
    unsafe {
        let n = nargs(l).min(2);
        let cb = tostring(l, -n);
        let name = tostring(l, 1 - n);
        let h = call_regs(SCRIPT_FIND_OBJECT_BY_NAME, 0, name, 0, 0, 0, &[]);
        if h != 0 {
            let mut t = human_type;
            call_regs(HUMAN_SCRIPT_CALLBACK_SET, &mut t as *mut u32 as u32, h + 0x1234, 0, 0, 0, &[cb]);
            return;
        }
        let v = call_regs(SCRIPT_VEHICLE_FIND, name, 0, 0, 0, 0, &[]);
        if v != 0 {
            let mut t = vehicle_type;
            call_regs(VEHICLE_SCRIPT_CALLBACK_SET, &mut t as *mut u32 as u32, v + 0x7C, 0, 0, 0, &[cb]);
        }
    }
}

extern "C" fn on_vehicle_destroyed(l: u32) -> i32 {
    CALLS[15].fetch_add(1, Ordering::Relaxed);
    unsafe { vehicle_callback(l, 0xF, 0) };
    0
}

extern "C" fn on_vehicle_enter(l: u32) -> i32 {
    CALLS[16].fetch_add(1, Ordering::Relaxed);
    unsafe { vehicle_callback(l, 0x13, 6) };
    0
}

