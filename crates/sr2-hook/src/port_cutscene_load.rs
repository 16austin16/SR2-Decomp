//! Port module: `cutscene_player_create` (0x6BDC80) and `cutscene_parse_characters` (0x6D16C0),
//! hand-ported from the disassembly (the machine-lifted versions in port_tables.rs are not
//! installed: with them cutscenes played with no characters).
//!
//! Check type at run time: per-branch counters only (the callees allocate and have side effects,
//! so no shadow). Offline: native differential tests against the original bytes (see
//! `port_cutscene2::dt`): every callee is a recording stub or a small native model; the original
//! and the Rust version run on the same random world and must make the same calls in the same
//! order with the same registers / stack arguments, write the same memory and preserve the same
//! registers.
//!
//!   RUSTFLAGS="-C target-feature=+crt-static -C link-arg=/DYNAMICBASE:NO -C link-arg=/BASE:0x10000000"
//!   cargo test --release -p sr2-hook --target i686-pc-windows-msvc port_cutscene_load -- --ignored --test-threads=1
//!
//! ## cutscene_player_create 0x6BDC80 (1084 bytes)
//! LTCG: ESI = the 0x43E8-byte player block (allocated by the caller from the pool), one stack
//! argument (a pointer to a pointer to the cutscene name), `ret 4`, returns ESI in EAX; EBX / EBP /
//! EDI / ESI preserved, ECX / EDX are scratch. It fills in the player's vectors (seven
//! `vector_constructor_iterator` calls 0x402450 (ptr, size, count, ctor), `ret 0x10`), the default
//! floats, and finally the flag byte +0xAFE from the cutscene name (`strncmp(name, 0xE0C4C0, 3)`
//! == 0 -> 0; `stricmp(name, 0xE0C4C4)` == 0 -> 1; last char '1' -> 1; `strncmp(name, 0xE0C4D0,
//! 3)` != 0 -> 1; else `!isdigit(last char)`).
//!
//! ## cutscene_parse_characters 0x6D16C0 (2070 bytes)
//! LTCG: EAX = the xml root node, one cdecl stack argument = the player (0x2527D10 object). Returns
//! nothing (EAX scratch); EBX / EBP / ESI / EDI preserved. Reads `Characters` / `Character` and
//! fills the player's character array {ptr +0x100, cap +0x104, count +0x108} of 0x7C-byte records
//! (name +0, position +4..0xC, scale +0x10, sub-arrays +0x40 (0x38-byte records, the shot
//! positions) and +0x70 (0x20-byte records)), by calling the sub-parsers 0x6D1190, 0x6D0C00,
//! 0x6D0FE0 and 0x6D1440.
//!
//! ### What the lifted version in port_tables.rs got wrong
//! Found by running the lifted `f34` in this module's differential harness: the lifted parser is
//! exact except for ONE call. The `sscanf`-style call 0xC97089 at 0x6D192A (`"x y z"` position
//! string of the `0xE0CC2C` attribute) takes FIVE cdecl arguments (string, format, &x, &y, &z); the
//! lifter passed only three. The callee then read its 4th / 5th argument from the words above
//! `call_regs`' arguments (the caller's saved EBP / EDI) and wrote the y / z floats through them,
//! so y and z never reached the record and the Rust frame / records were scribbled over. With the
//! two arguments added the lifted parser matches the original over 1000 cases. (The lifted 0x6D0FE0
//! call is given five stack words instead of one; that is harmless, the callee is cdecl and reads
//! one.) The lifted `cutscene_player_create` matches the original under the same harness, so the
//! character loss came from the parser.
//!
//! ### Deviations from the original
//! - The record fields the original never writes (it copies uninitialised stack bytes into the
//!   array records) are zero here.
//! - When a record array is full (count + 1 > capacity) the original writes before the array (heap
//!   corruption); here the writes go to a local scratch record. The capacity comes from counting
//!   the same nodes the loop visits, so this does not happen with a consistent tree.

