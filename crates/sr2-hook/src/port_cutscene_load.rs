    // ---- cutscene_parse_characters
    fn parse_callees() -> Vec<Callee> {
        let nat = |t: usize, nargs: usize, pop: usize, reads: u8| {
            let mut x = c(t, nargs, pop, reads, Ret::Any, Fx::None);
            x.native = addr(t).unwrap();
            x
        };
        let mut v = vec![
            c(STRICMP, 2, 0, 0, Ret::Mod(2), Fx::None),
            nat(0x6D_69D0, 1, 0, EAX | EDI),
            nat(0x6D_6A30, 1, 0, EAX),
            nat(0x6D_6AC0, 1, 0, EAX),
            nat(0x6D_0C00, 4, 0, 0),
            c(0xB7_4EF0, 1, 0, ECX | ESI, Ret::Any, Fx::WriteFloat),
            c(0xB7_4F60, 1, 0, ECX | ESI, Ret::Bool, Fx::WriteFloat),
            c(0xB7_47D0, 1, 0, ECX | ESI, Ret::Any, Fx::WriteUint),
            c(0xB7_4910, 1, 0, ECX | ESI, Ret::Any, Fx::WriteUint),
            c(0x6D_1190, 1, 0, EAX, Ret::Any, Fx::None),
            c(0x6D_0FE0, 1, 0, EAX, Ret::Any, Fx::None),
            c(0x6D_1440, 2, 0, EAX, Ret::Any, Fx::None),
        ];
        let mut x = c(0xB7_5050, 2, 0, ECX, Ret::Any, Fx::None);
        x.outs.push((Src::Arg(0), Out::Byte01));
        v.push(x);
        let mut x = c(0xC9_7089, 5, 0, 0, Ret::Any, Fx::None);
        for k in 2..5 {
            x.outs.push((Src::Arg(k), Out::Floats(1)));
        }
        v.push(x);
        // the allocator's vtable slot (a fake target, stored in the vtable)
        v.push(c(IMP, 2, 8, ECX, Ret::Ptr(0), Fx::None));
        v
    }
    const IMP: usize = 0xCB00_0100;

    /// A random xml-like tree: nodes of 0x10 bytes {name, next sibling, first child, value}.
    struct Tree {
        nodes: Vec<u32>,
        used: usize,
        strs: Vec<u32>,
    }
    impl Tree {
        unsafe fn build(&mut self, rng: &mut Rng, depth: u32) -> u32 {
            unsafe {
                let n = if depth <= 2 { 2 + rng.below(4) } else { rng.below(5) } as usize;
                let n = if depth > 6 { 0 } else { n };
                let mut first = 0u32;
                let mut prev = 0u32;
                for _ in 0..n {
                    if self.used >= self.nodes.len() {
                        break;
                    }
                    let node = self.nodes[self.used];
                    self.used += 1;
                    put(node, 0, rng.mix(&self.strs, 0));
                    put(node, 4, 0);
                    put(node, 0xC, if rng.one_in(5) { 0 } else { rng.pick(&self.strs) });
                    let ch = self.build(rng, depth + 1);
                    put(node, 8, ch);
                    if prev != 0 {
                        put(prev, 4, node);
                    } else {
                        first = node;
                    }
                    prev = node;
                }
                first
            }
        }
    }

    #[test]
    #[ignore = "needs the test exe linked at /BASE:0x10000000 (see the module comment)"]
    fn parse_matches_original() {
        let _g = lock();
        let extras = [(0x33D_6308usize, 16usize), (tn::R, tn::RLEN)];
        let mut h = Harness::new(CP_ADDR, &CP_BODY, &CP_CALLS_AT, &CP_DISPS, parse_callees(), &extras, parse_t as *const () as usize);
        h.orig = parse_adapter(h.orig);
        h.thunk = parse_adapter(h.thunk);
        let mut rng = Rng(0x5EED_CAFE_F00D_0001);
        let cases: u32 = std::env::var("CASES").ok().and_then(|v| v.parse().ok()).unwrap_or(3000);
        let mut bad = 0;
        for i in 0..cases {
            unsafe {
                h.mem.fill_random(&mut rng);
                let mut a = Arena::new();
                let vt = a.pool(1, 0x100)[0];
                let pl = a.pool(1, 0x200)[0];
                let strs = a.pool(48, 0x40);
                let bufs = a.pool(96, 0x80);
                let nodes = a.pool(400, 0x10);
                let root = a.pool(1, 0x10)[0];
                set_pools(vec![bufs.clone()]);
                for &s in &strs {
                    let n = match rng.below(4) {
                        0 => rng.below(4),
                        _ => rng.below(40),
                    };
                    let b: Vec<u8> = (0..n).map(|_| 0x41 + rng.below(40) as u8).collect();
                    putstr(s, &b);
                }
                put(vt, 0x1C, redirect(IMP) as u32);
                wd(0x277_1178, vt);
                wd(R, (R + 0x1000) as u32);
                wd(R + 4, (R + 0x100) as u32);
                wd(R + 8, 0);
                let kr1 = rng.u32() as u64;
                let kr2 = rng.u32() as u64;
                let kbits = rng.pick(&[0.25f64.to_bits(), 1.5f64.to_bits(), kr1 | kr2 << 32, 0x7FF8_0000_0000_0001, 0x3FF0_0000_0000_0000]);
                wd(0xE5_C2A8, kbits as u32);
                wd(0xE5_C2A8 + 4, (kbits >> 32) as u32);
                put(pl, 8, rng.pick(&[0, 1, 1, 2, 0xFFFF_FFFF]));
                put(pl, 0x160, rng.mix(&[0, 1, 100, 0x7FFF_FFFF], 0));
                put(pl, 0x15C, rng.u32());
                let mut tree = Tree { nodes, used: 0, strs: strs.clone() };
                // the root's children: make "Characters" likely deep enough
                let first = tree.build(&mut rng, 0);
                put(root, 8, first);
                let rootp = if rng.one_in(25) { 0 } else { root };
                if let Err(e) = h.check(0, [rootp, pl, 0], rng.u32() as u64) {
                    bad += 1;
                    if bad <= 5 {
                        eprintln!("case {i}: {e}");
                    }
                }
            }
        }
        eprintln!("{}", summary());
        assert_eq!(bad, 0, "{bad} of {cases} cases differ");
    }
