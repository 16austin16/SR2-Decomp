/// `set_ignore_ai_flag(name, [flag = true])`: bit 3 of byte +0x103; setting it also gets the
/// human out of a vehicle interaction or teleports it.
unsafe fn set_ignore_ai_flag_impl(l: u32) -> i32 {
    unsafe {
        let n = nargs(l).min(2);
        let name = tostring(l, -n);
        let flag = flag_at(l, n - 1, true);
        if name == 0 {
            return 0;
        }
        let h = match follower_or_object_human(name) {
            Some(h) => h,
            None => return 0,
        };
        if h == 0 {
            return 0;
        }
        let hp = h as usize;
        if ((rb(hp + 0x103) >> 3) & 1) == flag as u8 {
            return 0;
        }
        if flag {
            call_regs(0x0044_1D20, 0, 0, 0, 0, 0, &[h + 0xF8, 1]);
            if call_regs(0x009B_9350, 0, 0, 0, 0, 0, &[h]) as u8 != 0 {
                return 0;
            }
            if call_regs(HUMAN_IN_VEHICLE, 0, 0, 0, h, 0, &[]) as u8 != 0 {
                call_regs(0x0045_6070, 0, h, 0, 0, 0, &[]);
                return 0;
            }
            if rb(hp + 0x149) == 0 || rb(hp + 0x148) == 1 {
                return 0;
            }
            call_regs(0x0044_7CD0, 0, 0, 0, 0, 0, &[h, 0, 0]);
        } else {
            call_regs(0x0044_1D20, 0, 0, 0, 0, 0, &[h + 0xF8, 0]);
        }
    }
    0
}
