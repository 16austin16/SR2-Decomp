/// `set_max_hit_points(name, value, [full = false])`. A human keeps its hit point ratio (0 when
/// the old maximum was not positive) unless `full`; a vehicle gets the network properties; an
/// unspawned object gets +0x74.
unsafe fn set_max_hit_points_impl(l: u32) -> i32 {
    unsafe {
        let n = nargs(l).min(3);
        let name = tostring(l, -n);
        let value = int_arg(l, 1 - n);
        let full = flag_at(l, n - 2, false);
        let h = human_chain(name, true, false);
        if h != 0 {
            let hp = h as usize;
            let max = rd(hp + 0x1120) as i32;
            let ratio: f64 = if max > 0 { rf(hp + 0x1124) as f64 / max as f64 } else { 0.0 };
            let mut v = value;
            call_regs(0x0096_9ED0, 0, h, 0, 0, 0, &[&mut v as *mut u32 as u32]);
            let mut f: f32 = if full {
                (rd(hp + 0x1120) as i32 as f64) as f32
            } else {
                ((ratio as f32 as f64) * (value as i32 as f64)) as f32
            };
            call_regs(0x0096_9C90, 0, h, 0, 0, 0, &[&mut f as *mut f32 as u32]);
            return 0;
        }
        let v = vehicle_find(name);
        if v != 0 {
            let veh = vcall(v, 13);
            if veh == 0 {
                return 0;
            }
            call_regs(0x00AB_B960, 0, veh, 0, 0, 0, &[value]);
            if full {
                let veh = vcall(v, 13);
                call_regs(0x00AB_B6B0, 0, veh, 0, 0, 0, &[value]);
            }
            return 0;
        }
        let o = object_find(name);
        if o != 0 {
            wd(o as usize + 0x74, value);
        }
    }
    0
}
counted!(set_max_hit_points, I_SET_MAX_HIT_POINTS, set_max_hit_points_impl);

