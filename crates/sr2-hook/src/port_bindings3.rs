/// The "human chain": by name, then a follower (always asked, any index), then a script object's
/// human (vtbl +0x34, optionally behind the +0x2C "has a human" test, optionally called twice
/// with a null check in between). 0 when nothing resolves.
unsafe fn human_chain(name: u32, test_2c: bool, twice: bool) -> u32 {
    unsafe {
        let h = find_human(name);
        if h != 0 {
            return h;
        }
        let h = follower_get(follower_index(name));
        if h != 0 {
            return h;
        }
        let o = object_find(name);
        if o == 0 {
            return 0;
        }
        if test_2c && vcall(o, 11) as u8 == 0 {
            return 0;
        }
        let h = vcall(o, 13);
        if twice {
            if h == 0 {
                return 0;
            }
            return vcall(o, 13);
        }
        h
    }
}

/// A human by follower index (when the name is a follower) or by script object, with no player
/// lookup and no +0x2C test: the chain of set_ignore_ai_flag / npc_combat_enable /
/// npc_weapon_spread. `None` when the object does not exist.
unsafe fn follower_or_object_human(name: u32) -> Option<u32> {
    unsafe {
        let idx = follower_index(name);
        if idx > 0 {
            return Some(follower_get(idx));
        }
        let o = object_find(name);
        if o == 0 { None } else { Some(vcall(o, 13)) }
    }
}

unsafe fn cb_set(f: usize, ecx: u32, ty: u32, name: u32) {
    let mut t = ty;
    unsafe { call_regs(f, &mut t as *mut u32 as u32, ecx, 0, 0, 0, &[name]) };
}

/// `script_lua_opt_int`: EDI = L, cdecl (&args left, &default 3).
unsafe fn opt_int(f: usize, l: u32, left: i32) -> u32 {
    let mut left = left;
    let mut def = 3u32;
    unsafe { call_regs(f, 0, 0, 0, 0, l, &[&mut left as *mut i32 as u32, &mut def as *mut u32 as u32]) }
}

/// The game's `_ftol2_sse` on a float (cvttsd2si: out of range gives 0x80000000).
unsafe fn ftol2_sse(x: f32) -> u32 {
    let r: u32;
    unsafe {
        std::arch::asm!(
            "fld dword ptr [{p}]",
            "call {f}",
            p = in(reg) &x as *const f32,
            f = in(reg) FTOL2_SSE,
            out("eax") r,
            clobber_abi("C"),
        );
    }
    r
}

/// The trigger's +0x11C = game time, minus 1.8e9 above 0x6B49D200.
unsafe fn stamp(t: u32) {
    unsafe {
        let mut v = rd(GAME_TIME) as i32;
        wd(t as usize + 0x11C, v as u32);
        if v > 0x6B49_D200 {
            v = v.wrapping_add(0x94B6_2E00u32 as i32);
            wd(t as usize + 0x11C, v as u32);
        }
    }
}

// --- Shadow harness ------------------------------------------------------------------------

/// The pushed slots as comparable words: type, then the payload (strings by content).
unsafe fn snapshot(l: u32, from: u32, to: u32) -> Vec<u32> {
    let mut v = Vec::new();
    unsafe {
        let mut p = from;
        while p < to {
            let tt = rd(p as usize);
            v.push(tt);
            match tt {
                0 => {}
                3 => {
                    v.push(rd(p as usize + 8));
                    v.push(rd(p as usize + 12));
                }
                4 => {
                    let idx = -(((to - p) / 16) as i32);
                    let s = tostring(l, idx);
                    if s != 0 {
                        let mut q = s as usize;
                        while rb(q) != 0 && q - (s as usize) < 0x10000 {
                            v.push(rb(q) as u32);
                            q += 1;
                        }
                    }
                    v.push(0xFFFF_FFFF);
                }
                _ => v.push(rd(p as usize + 8)),
            }
            p += 16;
        }
    }
    v
}

/// Run the Rust body, then (for the first 3000 calls) the relocated original on the same stack
/// position, compare the Lua stack effect and keep the original's. `restore` lists game dwords the
/// Rust body advances that must be put back before the original runs.
unsafe fn shadowed(i: usize, l: u32, rust: unsafe fn(u32) -> i32, restore: &[usize]) -> i32 {
    let n = CALLS[i].fetch_add(1, Ordering::Relaxed);
    let orig = ORIGINALS[i].load(Ordering::Relaxed);
    if orig == 0 || n >= SHADOW_CALLS {
        return unsafe { rust(l) };
    }
    unsafe {
        let t0 = top(l);
        let saved: Vec<u32> = restore.iter().map(|&a| rd(a)).collect();
        let r1 = rust(l);
        let t1 = top(l);
        let s1 = snapshot(l, t0, t1);
        wd(l as usize + 8, t0);
        for (k, &a) in restore.iter().enumerate() {
            wd(a, saved[k]);
        }
        let r2 = call_regs(orig, 0, 0, 0, 0, 0, &[l]) as i32;
        let t2 = top(l);
        let s2 = snapshot(l, t0, t2);
        if r1 != r2 || t1 != t2 || s1 != s2 {
            let m = MISMATCHES[i].fetch_add(1, Ordering::Relaxed) + 1;
            if m <= 10 {
                log(&format!(
                    "port_bindings3: {} mismatch (call {n}): original {r2} results {s2:?}, Rust {r1} results {s1:?}",
                    BINDINGS[i].name
                ));
            }
        }
        if n + 1 == SHADOW_CALLS {
            log(&format!(
                "port_bindings3: {}: {SHADOW_CALLS} calls shadowed, {} mismatched",
                BINDINGS[i].name,
                MISMATCHES[i].load(Ordering::Relaxed)
            ));
        }
        r2
    }
}

macro_rules! counted {
    ($name:ident, $idx:expr, $body:ident) => {
        extern "C" fn $name(l: u32) -> i32 {
            CALLS[$idx].fetch_add(1, Ordering::Relaxed);
            unsafe { $body(l) }
        }
    };
}

macro_rules! shadow_checked {
    ($name:ident, $idx:expr, $body:ident, $restore:expr) => {
        extern "C" fn $name(l: u32) -> i32 {
            unsafe { shadowed($idx, l, $body, $restore) }
        }
    };
}

