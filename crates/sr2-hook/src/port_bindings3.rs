const LOCALISATION_HOOKS: usize = 0x0252_A1E0;
const TEMP_POOL: usize = 0x0252_A250;
const VINT_VALUE_FROM_LUA: usize = 0x00B8_D200; // EAX = hint, cdecl (out, L, &args left, 1)
const VINT_VALUE_FROM_TABLE_ENTRY: usize = 0x00B9_1630; // EAX = hint, cdecl (out, L, n, &i)
const VINT_VALUE_ASSIGN: usize = 0x00B9_3620; // ESI = dst, EDI = src
