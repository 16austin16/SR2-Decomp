//! Script bindings ranked 41-80 (docs/analysis/43_bindings_41_80.md) in Rust: on_take_damage,
//! set_max_hit_points, set_ignore_ai_flag, effect_stop, get_max_hit_points, hud_timer_stop,
//! audio_get_audio_id, notoriety_set, mission_end_success, objective_text_clear,
//! vint_document_find, rand_float, inv_item_equip, mission_set_checkpoint, on_trigger_exit,
//! vehicle_chase, peg_unload, vehicle_speed_override, player_controls_enable / _disable,
//! vint_datagroup_add_subscription, set_unjackable_flag, vint_insert_values_in_string, door_open,
//! set_current_hit_points, on_dismiss, spawning_pedestrians, vehicle_suppress_npc_exit,
//! vint_dataitem_get, npc_combat_enable, peg_load, npc_weapon_spread, waypoint_remove /
//! waypoint_add, hud_timer_set, get_current_hit_points, vint_document_unload, on_vehicle_exit and
//! character_exists. (set_mission_author is a 3-byte `xor eax, eax; ret` and cannot be detoured.)
//!
//! Argument reading follows the originals exactly, as in lua_bindings.rs / port_bindings2.rs:
//! argument k is read at `k - 1 - n` (n clamped to the most a binding reads), so a missing
//! argument is the stale slot at `L->top`. Optional flags test the slot for nil first, then the
//! truth test (the number 0 is true). "Running count" bindings read front to back with an args
//! left counter. Flags passed to callees as a byte inside L's own argument slot keep L's upper
//! three bytes.
//!
//! Bindings that only read state and push (get_max_hit_points, get_current_hit_points,
//! audio_get_audio_id, vint_document_find, rand_float, character_exists, vint_dataitem_get,
//! vint_insert_values_in_string) are shadow-checked against a relocated copy of the original for
//! the first 3000 calls: the Lua stack effect (values pushed, result count) is compared and the
//! original's effect is kept. The others write game state and only count calls.
//!
//! Deliberate deviations (all on paths where the original crashes or reads garbage):
//! vint_insert_values_in_string keeps the table copy unclamped (t[0..tn-1]) but holds the values
//! in a heap array of max(32, tn) entries instead of overrunning the stack frame; a NULL source
//! for its byte-widening loop is treated as an empty string; a table count above 0x10000 is
//! clamped. vint_dataitem_get never walks more than 32 values. Everything else, including the
//! unchecked indexes of hud_timer_stop / objective_text_clear and the NULL names that crash
//! script_follower_index, is kept as is.

