/// `on_take_damage(callback, name)`: the first match wins: human (type 4), script object (6),
/// vehicle (2), mover (2).
unsafe fn on_take_damage_impl(l: u32) -> i32 {
    unsafe {
        let n = nargs(l).min(2);
        let cb = tostring(l, -n);
        let name = tostring(l, 1 - n);
        let h = find_human(name);
        if h != 0 {
            cb_set(HUMAN_CALLBACK_SET, h + 0x1234, 4, cb);
            return 0;
        }
        let o = object_find(name);
        if o != 0 {
            cb_set(OBJECT_CALLBACK_SET, o + 0xBC, 6, cb);
            return 0;
        }
        let v = vehicle_find(name);
        if v != 0 {
            cb_set(VEHICLE_CALLBACK_SET, v + 0x7C, 2, cb);
            return 0;
        }
        let m = door_find(name);
        if m != 0 {
            cb_set(MOVER_CALLBACK_SET, m + 0x64, 2, cb);
        }
    }
    0
}
counted!(on_take_damage, I_ON_TAKE_DAMAGE, on_take_damage_impl);

