/// `rng_float01(0xEC30F8)`: the shared generator (the same cursor as rand_int).
unsafe fn rng_float01() -> f32 {
    unsafe {
        let cur = rd(RNG_CURSOR);
        let r = rd(RNG_TABLE + cur as usize * 4);
        wd(RNG_CURSOR, cur.wrapping_add(1));
        if cur.wrapping_add(1) == 0x800 {
            wd(RNG_CURSOR, 0);
        }
        let mut x = r as i32 as f64;
        if (r as i32) < 0 {
            x += 4294967296.0;
        }
        (x * rf64(0x00E5_C030)) as f32
    }
}

/// `rand_float(a, b)` -> f32(min + r * (max - min)); swaps only when b < a (a NaN keeps the order).
unsafe fn rand_float_impl(l: u32) -> i32 {
    unsafe {
        let n = nargs(l).min(2);
        let a = number_arg(l, -n) as f32;
        let b = number_arg(l, 1 - n) as f32;
        let (min, max) = if b < a { (b, a) } else { (a, b) };
        let r = rng_float01();
        let d = max as f64 - min as f64;
        let res = (min as f64 + d * r as f64) as f32;
        push_number(l, res as f64);
    }
    1
}
