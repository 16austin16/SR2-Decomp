/// The temp allocator's `(size, align)` allocation, vtbl +0x1C.
unsafe fn pool_alloc(size: u32) -> u32 {
    unsafe {
        let pool = rd(TEMP_POOL);
        call_regs(vslot(pool, 7), 0, pool, 0, 0, 0, &[size, 0])
    }
}

unsafe fn pool_release(mark: u32) {
    unsafe {
        let pool = rd(TEMP_POOL);
        call_regs(vslot(pool, 13), 0, pool, 0, 0, 0, &[mark]);
    }
}

/// `vint_insert_values_in_string(format, [values table])` -> the expanded text. A localisation id
/// (number) with no text pushes nothing. The table is copied t[0..tn-1] with no 32 clamp.
unsafe fn vint_insert_values_in_string_impl(l: u32) -> i32 {
    unsafe {
        let mut n = nargs(l).min(2);
        let mut hint = [0u32; 4];
        let mut a = [0u32; 4];
        let pa = a.as_mut_ptr() as u32;
        let ph = hint.as_mut_ptr() as u32;
        call_regs(VINT_VALUE_FROM_LUA, ph, 0, 0, 0, 0, &[pa, l, &mut n as *mut i32 as u32, 1]);
        value_free(ph);

        let mut tn: i32 = if n > 0 { call_regs(LUA_TABLE_COUNT, n as u32, 0, 0, 0, 0, &[l]) as i32 } else { -1 };
        if tn > 0x10000 {
            tn = 0x10000;
        }
        let mut values: Vec<[u32; 4]> = vec![[0u32; 4]; (tn.max(32)) as usize];
        let mut i = 0u32;
        while (i as i32) < tn {
            let mut t = [0u32; 4];
            hint[0] = 0;
            let pt = t.as_mut_ptr() as u32;
            let src = call_regs(
                VINT_VALUE_FROM_TABLE_ENTRY,
                ph,
                0,
                0,
                0,
                0,
                &[pt, l, n as u32, &mut i as *mut u32 as u32],
            );
            let dst = values[i as usize].as_mut_ptr() as u32;
            call_regs(VINT_VALUE_ASSIGN, 0, 0, 0, dst, src, &[]);
            value_free(pt);
            value_free(ph);
            hint[0] = 0;
            i += 1;
        }

        let pool = rd(TEMP_POOL);
        let mark = call_regs(vslot(pool, 12), 0, pool, 0, 0, 0, &[]);
        let tag = a[0];
        let mut fmt = 0u32;
        if tag == 1 || tag == 2 {
            let hook = rd(LOCALISATION_HOOKS);
            if hook != 0 {
                let f = rd(hook as usize + 4);
                if f != 0 {
                    let handle = call_regs(VINT_VALUE_TO_HANDLE, 0, pa, 0, 0, 0, &[]);
                    fmt = call_regs(f as usize, 0, 0, 0, 0, 0, &[handle]);
                }
            }
            if fmt == 0 {
                pool_release(mark);
                for v in values.iter_mut().rev() {
                    value_free(v.as_mut_ptr() as u32);
                    v[0] = 0;
                }
                value_free(pa);
                return 0;
            }
        }
        let buf1 = pool_alloc(0x2000);
        let vp = values.as_mut_ptr() as u32;
        if fmt != 0 {
            call_regs(VINT_INSERT_EXPAND, 0, 0, 0, 0, 0, &[buf1, fmt, 0x1000, vp, tn as u32]);
        } else {
            let buf2 = pool_alloc(0x800);
            let src = if tag == 4 { a[1] } else { 0 };
            let wide;
            if call_regs(VINT_DECODE_WIDE, src, 0, buf2, 0, 0, &[0x400]) as u8 != 0 {
                wide = buf2;
            } else {
                let hook = rd(LOCALISATION_HOOKS);
                let lookup = |s: u32| -> u32 {
                    if hook == 0 {
                        return 0;
                    }
                    let f = rd(hook as usize);
                    if f == 0 { 0 } else { call_regs(f as usize, 0, 0, 0, 0, 0, &[s]) }
                };
                if lookup(src) != 0 {
                    wide = lookup(src);
                } else {
                    // Widen the bytes (at most 0x400 characters), terminated at the end.
                    for k in 0..0x400usize {
                        let c = if src == 0 { 0 } else { rb(src as usize + k) };
                        *((buf2 as usize + k * 2) as *mut u16) = c as u16;
                        if c == 0 {
                            break;
                        }
                    }
                    *((buf2 as usize + 0x7FE) as *mut u16) = 0;
                    wide = buf2;
                }
            }
            call_regs(VINT_INSERT_EXPAND, 0, 0, 0, 0, 0, &[buf1, wide, 0x1000, vp, tn as u32]);
        }
        let buf3 = pool_alloc(0x2000);
        call_regs(VINT_ENCODE_WIDE, buf3, buf1, 0, 0, 0, &[0x2000]);
        call_regs(LUA_PUSHSTRING, 0, 0, 0, l, 0, &[buf3]);
        pool_release(mark);
        for v in values.iter_mut().rev() {
            value_free(v.as_mut_ptr() as u32);
            v[0] = 0;
        }
        value_free(pa);
    }
    1
}
