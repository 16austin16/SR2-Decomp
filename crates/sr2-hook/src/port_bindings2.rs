//! Nine more mission script bindings in Rust (docs/analysis/09_script.md, "Bindings 21-40 at
//! instruction level"): vint_object_clone, mission_end_failure, vint_subscribe_to_input_event,
//! get_dist, notoriety_force_no_spawn, group_destroy, character_is_in_vehicle, effect_play and
//! teleport.
//!
//! Argument reading follows the originals exactly, as in lua_bindings.rs: argument k is read at
//! `k - 1 - n` (n clamped to the most a binding reads), so a missing argument is the stale slot at
//! `L->top`. Optional arguments test the slot for nil first (a nil means "absent"), and boolean
//! flags use the truth test (missing, nil or false -> false; the number 0 is true).
//!
//! Quirks kept: get_dist pushes FLT_MAX when either position fails, and takes its sqrt from the
//! game's 0x40EA20; character_is_in_vehicle pushes an extra `false` (2 results) when the vehicle
//! name does not resolve; vint_subscribe_to_input_event returns no result at all when it has no
//! document, event or function, or the event is unknown; handles are pushed unsigned.

use std::sync::atomic::{AtomicU32, Ordering};

use crate::log;
use crate::portlib::*;

const LUAA_INDEX: usize = 0x00CD_BE80; // EAX = index, ECX = L
const LUA_TOSTRING: usize = 0x00CD_CA80; // EAX = index, ECX = L
const LUA_TONUMBER: usize = 0x00CD_C250; // EAX = index, ECX = L -> ST0
const PRINTF: usize = 0x00C9_9400; // CRT printf
const SQRTF: usize = 0x0040_EA20; // cdecl (f32) -> ST0
const U32_BIAS: usize = 0x00E5_C0E0; // f64 2^32 (for unsigned pushes)
const FLT_MAX_F64: usize = 0x00E5_C308; // f64 3.4028234663852886e38
const MINUS_ONE_F64: usize = 0x00E5_C180; // f64 -1.0

const VINT_LUA_CURRENT_DOCUMENT: usize = 0x00B8_E020;
const VINT_DOCUMENT_OBJECT_FIND: usize = 0x00B9_7910; // ESI = document, EDX = handle
const VINT_HANDLES: usize = 0x022E_F2B8; // [handle & 0x3F], chain +0xC, handle +0x28
const VINT_CLONE_NOT_FOUND: u32 = 0x00E4_C9B0; // "vint_object_clone() - object handle %u not found.\n"
const VINT_INPUT_EVENT_INDEX: usize = 0x00B9_9F70; // EDI = event name -> index or -1
const STRING_CRC32_LOWER: usize = 0x00BD_C9B0; // ECX = string
const VINT_CALLBACK_FIND: usize = 0x00BA_0950; // EDX = hash -> callback (refcount +0x1C)
const VINT_CALLBACK_CREATE: usize = 0x00B8_DBB0; // EDX = function name
const VINT_CALLBACK_RELEASE: usize = 0x00BA_0850; // ECX = callback
const VINT_INPUT_SUBSCRIBE: usize = 0x00B9_9380; // ESI = document, cdecl (priority)
const VINT_SUBSCRIPTION_SET: usize = 0x00B9_9460; // ECX = subscription, EDX = event index
const VINT_INPUT_NO_CALLBACK: usize = 0x00B9_9530; // EAX = priority

const STRING_HASH_LOWER: usize = 0x00BD_CB30; // ECX = string, EAX = seed, stdcall (&out)
const STRING_HASH: usize = 0x00BD_CA30; // EAX = &out, EDX = seed, stdcall (string)
const LOCALIZED_STRING_FIND: usize = 0x0061_2460; // EAX = name, ESI = table
const LOCALIZED_TABLE: usize = 0x0252_9838;
const MISSION_FAILED_FALLBACK: u32 = 0x00E4_09D8;
const ACT_PACKET_SEND_MISSION_FAILED: usize = 0x006A_6B30; // cdecl (0, text, 0, v, v)
const MISSION_FAILED_ARG: usize = 0x033D_6308;
const CURRENT_MISSION: usize = 0x027B_3C60;

const SCRIPT_POSITION_FROM_NAME: usize = 0x00A2_77F0; // ECX = &pos, EAX = &orient, cdecl (name)
const ZERO_VECTOR: usize = 0x0252_A6D0;

const TEAM_FROM_NAME: usize = 0x0096_0DA0; // EDI = team name -> id
const TEAM_INFO_GET: usize = 0x0092_4940; // EAX = id - 1 (0..5) -> record or 0

const GROUP_FIND_BY_NAME: usize = 0x00A5_7730; // EAX = name
const HUMAN_GROUP_RELEASE: usize = 0x00A5_6F80; // EAX = human
const OBJECT_VISIBILITY_CACHED: usize = 0x0092_55C0; // ESI = object, stdcall (mode)
const HUMAN_APPLY_DAMAGE: usize = 0x0096_45A0; // ESI = amount, CL = flag, EDX = source, cdecl (human)
const VEHICLE_TAKE_DAMAGE: usize = 0x00AA_BCC0; // cdecl (vehicle, amount, flags, attacker)

const SCRIPT_FIND_OBJECT_BY_NAME: usize = 0x00A5_2BB0; // ECX = name, EAX = &is_human byte
const SCRIPT_OBJECT_TO_HUMAN: usize = 0x00A5_2C70; // ESI = name (not the object)
const SCRIPT_VEHICLE_FIND: usize = 0x00A7_0030; // EAX = name
const HUMAN_IN_VEHICLE: usize = 0x009B_8C50; // ESI = human, EDI = vehicle or 0 -> al

const LUA_OPT_INT_ARG: usize = 0x00A5_3EB0; // EDI = L, cdecl (&args left, &default)
const EFFECT_FIND_BY_NAME: usize = 0x0050_DB60; // ECX = name -> id or -1
const NAVPOINT_FIND: usize = 0x00A5_EB50; // EAX = &name hash
const EFFECT_PARAMS_INIT: usize = 0x0041_71C0; // ESI = id, ECX = &orient, EDX = &pos, stdcall (&params)
const EFFECT_START: usize = 0x0050_E330; // cdecl (&params)

const TELEPORT_FLAG: usize = 0x0068_3F40; // EAX = object, cdecl (4, 0) -> ax
const OBJECT_IS_PLAYER_HUMAN: usize = 0x0096_3540; // EAX = object -> al
const PLAYER_TELEPORT: usize = 0x009D_B480; // ECX = human, cdecl (&pos, &orient, 1, 1, flag, f)
const OBJECT_TELEPORT_PREPARE: usize = 0x0044_7CD0; // cdecl (object, 0, 0)
const OBJECT_TELEPORT: usize = 0x009A_0B00; // ECX = &orient, EDX = &pos, cdecl (obj, 0, 1, f != 0, 0)

unsafe fn top(l: u32) -> u32 {
    unsafe { rd(l as usize + 8) }
}

unsafe fn nargs(l: u32) -> i32 {
    unsafe { (top(l).wrapping_sub(rd(l as usize + 0xC)) as i32) >> 4 }
}

unsafe fn tostring(l: u32, i: i32) -> u32 {
    unsafe { call_regs(LUA_TOSTRING, i as u32, l, 0, 0, 0, &[]) }
}

/// The slot of index `i` as the bindings compute it inline: positive indexes are base-relative
/// (0 when at or past top), the others go through luaA_index.
unsafe fn slot(l: u32, i: i32) -> u32 {
    unsafe {
        if i > 0 {
            let a = rd(l as usize + 0xC).wrapping_add((i as u32 - 1) * 16);
            if a < top(l) { a } else { 0 }
        } else {
            call_regs(LUAA_INDEX, i as u32, l, 0, 0, 0, &[])
        }
    }
}

/// The "nil -> absent" test: the slot exists and holds nil.
unsafe fn is_nil(p: u32) -> bool {
    unsafe { p != 0 && rd(p as usize) == 0 }
}

unsafe fn number_arg(l: u32, i: i32) -> f64 {
    let mut out = 0f64;
    unsafe {
        std::arch::asm!(
            "call {f}",
            "fstp qword ptr [edi]",
            f = in(reg) LUA_TONUMBER,
            in("eax") i,
            in("ecx") l,
            in("edi") &mut out as *mut f64,
            clobber_abi("C"),
        );
    }
    out
}

/// `_ftol2(lua_tonumber(i))`: truncation, the low dword of the 64-bit result.
unsafe fn int_arg(l: u32, i: i32) -> u32 {
    let out = unsafe { number_arg(l, i) };
    if out.abs() < 9.2e18 { out as i64 as u32 } else { 0 }
}

/// The truth test of a slot pointer: missing, nil or false -> false.
unsafe fn truth(p: u32) -> bool {
    unsafe {
        if p == 0 {
            return false;
        }
        match rd(p as usize) {
            0 => false,
            1 => rd(p as usize + 8) != 0,
            _ => true,
        }
    }
}

/// An optional flag: nil -> false, else the truth test of the same slot fetched again.
unsafe fn opt_flag(l: u32, i: i32) -> bool {
    unsafe { if is_nil(slot(l, i)) { false } else { truth(slot(l, i)) } }
}

unsafe fn push(l: u32, tt: u32, v: impl FnOnce(usize)) {
    unsafe {
        let t = top(l) as usize;
        wd(t, tt);
        v(t + 8);
        wd(l as usize + 8, t as u32 + 16);
    }
}

unsafe fn push_bool(l: u32, b: bool) {
    unsafe { push(l, 1, |p| wd(p, b as u32)) };
}

unsafe fn push_number(l: u32, x: f64) {
    unsafe { push(l, 3, |p| *(p as *mut f64) = x) };
}

unsafe fn rf64(p: usize) -> f64 {
    unsafe { *(p as *const f64) }
}

/// `fild` of a dword plus 2^32 when negative, as the originals push handles.
unsafe fn push_unsigned(l: u32, v: u32) {
    unsafe {
        let mut x = v as i32 as f64;
        if (v as i32) < 0 {
            x += rf64(U32_BIAS);
        }
        push_number(l, x);
    }
}

/// `vint_object_clone(handle, [parent handle])` -> the clone's handle (unsigned), or 0.
extern "C" fn vint_object_clone(l: u32) -> i32 {
    CALLS[0].fetch_add(1, Ordering::Relaxed);
    unsafe {
        let n = nargs(l).min(2);
        let h = int_arg(l, -n);
        let m = n - 1;
        let parent = if m <= 0 || is_nil(slot(l, -m)) { 0 } else { int_arg(l, -m) };
        let doc = call_regs(VINT_LUA_CURRENT_DOCUMENT, 0, 0, 0, 0, 0, &[]);
        if doc == 0 {
            push_number(l, 0.0);
            return 1;
        }
        let mut obj = 0u32;
        if h != 0 {
            let head = rd(VINT_HANDLES + (h as usize & 0x3F) * 4);
            let mut o = head;
            while o != 0 {
                if rd(o as usize + 0x28) == h {
                    obj = o;
                    break;
                }
                o = rd(o as usize + 0xC);
                if o == head {
                    break;
                }
            }
        }
        if obj == 0 {
            call_regs(PRINTF, 0, 0, 0, 0, 0, &[VINT_CLONE_NOT_FOUND, h]);
            push_number(l, 0.0);
            return 1;
        }
        let mut p = call_regs(VINT_DOCUMENT_OBJECT_FIND, doc, 0, parent, doc, obj, &[]);
        if p == 0 {
            p = rd(obj as usize + 0x24);
        }
        let clone = call_regs(vslot(obj, 5), 0, obj, 0, 0, 0, &[1, p]);
        if clone == 0 {
            push_number(l, 0.0);
        } else {
            push_unsigned(l, rd(clone as usize + 0x28));
        }
    }
    1
}

/// `mission_end_failure(mission, reason)`: fails the current mission only if its name hash
/// matches.
extern "C" fn mission_end_failure(l: u32) -> i32 {
    CALLS[1].fetch_add(1, Ordering::Relaxed);
    unsafe {
        let n = nargs(l).min(2);
        let mission = tostring(l, -n);
        let reason = tostring(l, 1 - n);
        let mut hash = 0u32;
        call_regs(STRING_HASH_LOWER, 0, mission, 0, 0, 0, &[&mut hash as *mut u32 as u32]);
        let cur = rd(CURRENT_MISSION);
        if cur != 0 && rd(cur as usize) == hash {
            let mut text = call_regs(LOCALIZED_STRING_FIND, reason, 0, 0, rd(LOCALIZED_TABLE), 0, &[]);
            if text == 0 {
                text = MISSION_FAILED_FALLBACK;
            }
            let v = rd(MISSION_FAILED_ARG);
            call_regs(ACT_PACKET_SEND_MISSION_FAILED, text, 0, v, 0, 0, &[0, text, 0, v, v]);
        }
    }
    0
}

/// `vint_subscribe_to_input_event(handle, event, function, [priority])` -> subscription id
/// (unsigned) or 0; no result at all when it has nothing to subscribe.
extern "C" fn vint_subscribe_to_input_event(l: u32) -> i32 {
    CALLS[2].fetch_add(1, Ordering::Relaxed);
    unsafe {
        let mut r = nargs(l).min(4);
        // Argument 1 is read and thrown away.
        if r > 0 {
            if !is_nil(slot(l, -r)) {
                number_arg(l, -r);
            }
            r -= 1;
        }
        let string = |r: &mut i32| {
            if *r <= 0 {
                return 0;
            }
            let i = -*r;
            *r -= 1;
            if is_nil(slot(l, i)) { 0 } else { tostring(l, i) }
        };
        let event = string(&mut r);
        let func = string(&mut r);
        let prio = if r <= 0 || is_nil(slot(l, -r)) { 0 } else { int_arg(l, -r) };
        let doc = call_regs(VINT_LUA_CURRENT_DOCUMENT, 0, 0, 0, 0, 0, &[]);
        if doc == 0 || event == 0 || func == 0 {
            return 0;
        }
        let idx = call_regs(VINT_INPUT_EVENT_INDEX, doc, 0, 0, doc, event, &[]);
        if idx == u32::MAX {
            return 0;
        }
        let hash = call_regs(STRING_CRC32_LOWER, idx, func, 0, doc, event, &[]);
        let mut cb = call_regs(VINT_CALLBACK_FIND, hash, 0, hash, doc, event, &[]);
        if cb != 0 {
            wd(cb as usize + 0x1C, rd(cb as usize + 0x1C).wrapping_add(1));
        } else {
            cb = call_regs(VINT_CALLBACK_CREATE, 0, 0, func, doc, event, &[]);
        }
        if cb == 0 {
            if prio != 0 {
                call_regs(VINT_INPUT_NO_CALLBACK, prio, 0, 0, doc, 0, &[]);
            }
            push_number(l, 0.0);
            return 1;
        }
        let sub = call_regs(VINT_INPUT_SUBSCRIBE, 0, prio, 0, doc, cb, &[prio]);
        if sub == 0 {
            call_regs(VINT_CALLBACK_RELEASE, 0, cb, 0, doc, cb, &[]);
            push_number(l, 0.0);
            return 1;
        }
        call_regs(VINT_SUBSCRIPTION_SET, 0, sub, idx, sub, cb, &[]);
        call_regs(VINT_CALLBACK_RELEASE, 0, cb, 0, sub, cb, &[]);
        push_unsigned(l, rd(sub as usize + 0x20));
    }
    1
}

/// `0x40EA20(v)`: the game's f32 sqrt, read straight from ST0.
unsafe fn game_sqrt(v: f32) -> f64 {
    let mut out = 0f64;
    unsafe {
        std::arch::asm!(
            "push edi",
            "push {v}",
            "call {f}",
            "add esp, 4",
            "pop edi",
            "fstp qword ptr [edi]",
            v = in(reg) v.to_bits(),
            f = in(reg) SQRTF,
            in("edi") &mut out as *mut f64,
            clobber_abi("C"),
        );
    }
    out
}

/// `get_dist(a, b)` -> the distance between two named objects / navpoints, or FLT_MAX when
/// either does not resolve (the second is not looked up when the first fails).
extern "C" fn get_dist(l: u32) -> i32 {
    CALLS[3].fetch_add(1, Ordering::Relaxed);
    unsafe {
        let n = nargs(l).min(2);
        let a = tostring(l, -n);
        let b = tostring(l, 1 - n);
        let z = [rf(ZERO_VECTOR), rf(ZERO_VECTOR + 4), rf(ZERO_VECTOR + 8)];
        let mut p1 = z;
        let mut p2 = z;
        let mut scratch = [0u32; 9];
        let ps = scratch.as_mut_ptr() as u32;
        let ok = call_regs(SCRIPT_POSITION_FROM_NAME, ps, p1.as_mut_ptr() as u32, 0, 0, 0, &[a]) as u8 != 0
            && call_regs(SCRIPT_POSITION_FROM_NAME, ps, p2.as_mut_ptr() as u32, 0, 0, 0, &[b]) as u8 != 0;
        if !ok {
            push_number(l, rf64(FLT_MAX_F64));
            return 1;
        }
        // The original computes p2 - p1; each difference goes through an fstp dword.
        let dx = (p2[0] as f64 - p1[0] as f64) as f32 as f64;
        let dy = (p2[1] as f64 - p1[1] as f64) as f32 as f64;
        let dz = (p2[2] as f64 - p1[2] as f64) as f32 as f64;
        let s = ((dy * dy + dx * dx) + dz * dz) as f32;
        push_number(l, game_sqrt(s));
    }
    1
}

/// `notoriety_force_no_spawn(team, flag)`: teams 5 and 6 set fixed byte flags, teams 1-4 the
/// team record's +0x2B1.
extern "C" fn notoriety_force_no_spawn(l: u32) -> i32 {
    CALLS[4].fetch_add(1, Ordering::Relaxed);
    unsafe {
        let n = nargs(l).min(2);
        let team = tostring(l, -n);
        let flag = truth(slot(l, 1 - n)) as u8;
        let id = call_regs(TEAM_FROM_NAME, 0, 0, 0, 0, team, &[]);
        match id {
            5 => {
                for a in [0x00EB_5629, 0x00EB_58E1, 0x00EB_5B99, 0x00EB_6BF9, 0x00EB_6EB1, 0x00EB_6679, 0x00EB_6939] {
                    wb(a, flag);
                }
            }
            6 => {
                for a in [0x00EB_7169, 0x00EB_7421, 0x00EB_76D9, 0x00EB_7991] {
                    wb(a, flag);
                }
            }
            _ => {
                let k = id.wrapping_sub(1);
                if k <= 5 {
                    let t = call_regs(TEAM_INFO_GET, k, 0, 0, 0, 0, &[]);
                    if t != 0 {
                        wb(t as usize + 0x2B1, flag);
                    }
                }
            }
        }
    }
    0
}

/// `group_destroy(group)`: only for a created group (+0x18 bit 2, cleared here). Outside
/// missions, members on screen are killed (humans, vehicles) or removed (type 2), other types
/// stay; members off screen, or any member during a mission, are removed.
extern "C" fn group_destroy(l: u32) -> i32 {
    CALLS[5].fetch_add(1, Ordering::Relaxed);
    unsafe {
        let n = nargs(l).min(1);
        let name = tostring(l, -n);
        let g = call_regs(GROUP_FIND_BY_NAME, name, 0, 0, 0, 0, &[]);
        if g == 0 || rb(g as usize + 0x18) & 2 == 0 {
            return 0;
        }
        let first = rd(g as usize + 0x1C);
        wb(g as usize + 0x18, rb(g as usize + 0x18) & 0xFD);
        if first == 0 {
            return 0;
        }
        let mut m = first;
        loop {
            if call_regs(vslot(m, 11), 0, m, 0, 0, 0, &[]) as u8 != 0 {
                let obj = call_regs(vslot(m, 13), 0, m, 0, 0, 0, &[]);
                if rd(obj as usize + 0x4C) == 1 {
                    call_regs(HUMAN_GROUP_RELEASE, obj, 0, 0, obj, m, &[]);
                }
                let remove = || call_regs(vslot(m, 7), 0, m, 0, 0, 0, &[]);
                let visible = call_regs(OBJECT_VISIBILITY_CACHED, 0, 0, 0, obj, m, &[2]) as u8 != 0;
                if !visible || rd(CURRENT_MISSION) != 0 {
                    remove();
                } else {
                    match rd(obj as usize + 0x4C) {
                        1 => {
                            call_regs(vslot(m, 8), 0, m, 0, 0, 0, &[0]);
                            call_regs(HUMAN_APPLY_DAMAGE, 0, 1, 0, 1000, m, &[obj]);
                        }
                        2 => {
                            remove();
                        }
                        5 => {
                            call_regs(vslot(m, 8), 0, m, 0, 0, 0, &[0]);
                            call_regs(VEHICLE_TAKE_DAMAGE, 0, 0, 0, obj, m, &[obj, 1000, 1, 0]);
                        }
                        _ => {}
                    }
                }
            }
            m = rd(m as usize + 0x58);
            if m == rd(g as usize + 0x1C) || m == 0 {
                break;
            }
        }
    }
    0
}

/// `character_is_in_vehicle(name, [vehicle])` -> boolean; an unresolved vehicle name pushes an
/// extra `false` first (2 results).
extern "C" fn character_is_in_vehicle(l: u32) -> i32 {
    CALLS[6].fetch_add(1, Ordering::Relaxed);
    unsafe {
        let n = nargs(l).min(2);
        let name = tostring(l, -n);
        let m = n - 1;
        let vname = if m <= 0 || is_nil(slot(l, -m)) { 0 } else { tostring(l, -m) };
        let mut human = 0u32;
        if name != 0 {
            let mut is_human = 0u32;
            let obj = call_regs(SCRIPT_FIND_OBJECT_BY_NAME, &mut is_human as *mut u32 as u32, name, 0, name, 0, &[]);
            human = if is_human as u8 == 0 { call_regs(SCRIPT_OBJECT_TO_HUMAN, obj, 0, 0, name, 0, &[]) } else { obj };
        }
        let mut results = 1;
        let mut veh = 0u32;
        if vname != 0 {
            let v = call_regs(SCRIPT_VEHICLE_FIND, vname, 0, 0, human, 0, &[]);
            if v != 0 {
                veh = call_regs(vslot(v, 13), 0, v, 0, human, 0, &[]);
            } else {
                push_bool(l, false);
                results = 2;
            }
        }
        let r = human != 0 && call_regs(HUMAN_IN_VEHICLE, 0, 0, 0, human, veh, &[]) as u8 != 0;
        push_bool(l, r);
        results
    }
}

/// The effect parameter block 0x4171C0 fills (0x6C bytes on the original's stack; the loop
/// byte is at +0x34 and the trailing int at +0x58).
#[repr(C, align(8))]
struct EffectParams([u8; 0x70]);

/// `effect_play(effect, navpoint, [loop], [int = 3])` -> the effect instance (unsigned), or -1
/// when the effect or the navpoint is not found.
extern "C" fn effect_play(l: u32) -> i32 {
    CALLS[7].fetch_add(1, Ordering::Relaxed);
    unsafe {
        let n = nargs(l).min(4);
        let effect = tostring(l, -n);
        let nav = tostring(l, 1 - n);
        let mut left = n - 2;
        let looped = if left <= 0 {
            false
        } else {
            let i = -left;
            left -= 1;
            opt_flag(l, i)
        };
        let mut default = 3u32;
        let pl = &mut left as *mut i32 as u32;
        let extra = call_regs(LUA_OPT_INT_ARG, 0, 0, 0, 0, l, &[pl, &mut default as *mut u32 as u32]);
        let id = call_regs(EFFECT_FIND_BY_NAME, extra, effect, 0, 0, l, &[]);
        if id == u32::MAX {
            push_number(l, rf64(MINUS_ONE_F64));
            return 1;
        }
        let mut hash = 0u32;
        let ph = &mut hash as *mut u32 as u32;
        call_regs(STRING_HASH, ph, 0, 0, id, l, &[nav]);
        let np = call_regs(NAVPOINT_FIND, ph, 0, 0, id, l, &[]);
        if np == 0 {
            push_number(l, rf64(MINUS_ONE_F64));
            return 1;
        }
        let mut params = EffectParams([0; 0x70]);
        let pp = params.0.as_mut_ptr() as u32;
        call_regs(EFFECT_PARAMS_INIT, pp, np + 0x28, np + 0x1C, id, l, &[pp]);
        params.0[0x34] = looped as u8;
        *(params.0.as_mut_ptr().add(0x58) as *mut u32) = extra;
        let inst = call_regs(EFFECT_START, 0, extra, pp, id, l, &[pp]);
        push_unsigned(l, inst);
    }
    1
}

/// `teleport(who, navpoint, [flag])`: players go through player_teleport (which takes the
/// flag), everything else through object_teleport.
extern "C" fn teleport(l: u32) -> i32 {
    CALLS[8].fetch_add(1, Ordering::Relaxed);
    unsafe {
        let n = nargs(l).min(3);
        let who = tostring(l, -n);
        let nav = tostring(l, 1 - n);
        let m = n - 2;
        let flag = m > 0 && opt_flag(l, -m);
        let mut hash = 0u32;
        let ph = &mut hash as *mut u32 as u32;
        call_regs(STRING_HASH, ph, 0, 0, who, 0, &[nav]);
        let np = call_regs(NAVPOINT_FIND, ph, 0, 0, who, 0, &[]);
        if np == 0 || who == 0 {
            return 0;
        }
        let mut is_human = 0u32;
        let mut obj = call_regs(SCRIPT_FIND_OBJECT_BY_NAME, &mut is_human as *mut u32 as u32, who, 0, who, np, &[]);
        if is_human as u8 == 0 {
            obj = call_regs(SCRIPT_OBJECT_TO_HUMAN, obj, 0, 0, who, np, &[]);
        }
        if obj == 0 {
            return 0;
        }
        let f = call_regs(TELEPORT_FLAG, obj, 0, 0, obj, np, &[4, 0]) & 0xFFFF;
        let pos = np + 0x1C;
        let orient = np + 0x28;
        if call_regs(OBJECT_IS_PLAYER_HUMAN, obj, 0, 0, obj, np, &[]) as u8 != 0 {
            call_regs(PLAYER_TELEPORT, 0, obj, 0, obj, pos, &[pos, orient, 1, 1, flag as u32, f]);
        } else {
            call_regs(OBJECT_TELEPORT_PREPARE, 0, 0, 0, obj, np, &[obj, 0, 0]);
            call_regs(OBJECT_TELEPORT, 0, orient, pos, obj, np, &[obj, 0, 1, (f != 0) as u32, 0]);
        }
    }
    0
}

