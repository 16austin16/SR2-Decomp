//! Port module s6: small functions from the round-9 list (AI order handlers, vint helpers, packet
//! thunks, diversion helpers, ...). Every address is pinned to its whole original body by
//! `replace_pinned`; the judge (`sr2-judge`) accepts each one.
//!
//! Every thunk saves XMM0-7 and `pushad`s; the Rust body threads the original's register flow
//! through an `St` (callees are called by address with exactly the registers the original holds,
//! and the registers they leave behind flow on), then writes the final registers back into the
//! `pushad` block. `popad` restores them.

#![allow(unused_imports)]

use std::sync::atomic::{AtomicU32, Ordering};

use crate::portlib::*;
use crate::{detour, log};

const COUNT: usize = 72;
const CAP: u32 = 1 << 24;
static CNT: [AtomicU32; COUNT] = [const { AtomicU32::new(0) }; COUNT];

#[inline(always)]
fn count(i: usize) {
    let c = &CNT[i];
    if c.load(Ordering::Relaxed) < CAP {
        c.fetch_add(1, Ordering::Relaxed);
    }
}

/// The seven general registers as a straight-line asm function would hold them.
#[derive(Clone, Copy)]
struct St {
    eax: u32,
    ecx: u32,
    edx: u32,
    ebx: u32,
    esi: u32,
    edi: u32,
    ebp: u32,
}

impl St {
    #[inline(always)]
    fn of(r: &Pushad) -> St {
        St { eax: r.eax, ecx: r.ecx, edx: r.edx, ebx: r.ebx, esi: r.esi, edi: r.edi, ebp: r.ebp }
    }

    /// Write the registers back into the `pushad` block.
    #[inline(always)]
    fn out(&self, r: &mut Pushad) {
        r.eax = self.eax;
        r.ecx = self.ecx;
        r.edx = self.edx;
        r.ebx = self.ebx;
        r.esi = self.esi;
        r.edi = self.edi;
        r.ebp = self.ebp;
    }

    /// Call a game function by address with the current registers; returns its EAX.
    #[inline(always)]
    unsafe fn call(&mut self, f: usize, args: &[u32]) -> u32 {
        unsafe { call_regs_st(f, self, args) };
        self.eax
    }
}

#[inline(never)]
unsafe fn call_regs_st(f: usize, st: &mut St, args: &[u32]) {
    let mut a8 = [0u32; 16];
    a8[..args.len()].copy_from_slice(args);
    let block: [u32; 3] = [f as u32, a8.as_ptr() as u32, st as *mut St as u32];
    unsafe {
        std::arch::asm!(
            "push ebx", "push esi", "push edi", "push ebp",
            "push dword ptr [eax + 8]",
            "push dword ptr fs:[0x14]",
            "mov ebx, eax",
            "mov fs:[0x14], esp",
            "push dword ptr [ebx]",
            "mov esi, [ebx + 4]",
            "mov ecx, 16",
            "2:",
            "push dword ptr [esi + ecx*4 - 4]",
            "dec ecx",
            "jnz 2b",
            "mov ebx, [ebx + 8]",
            "mov eax, [ebx]", "mov ecx, [ebx + 4]", "mov edx, [ebx + 8]",
            "mov esi, [ebx + 16]", "mov edi, [ebx + 20]", "mov ebp, [ebx + 24]", "mov ebx, [ebx + 12]",
            "call dword ptr [esp + 64]",
            "push edi",
            "mov edi, fs:[0x14]",
            "mov edi, [edi + 4]",
            "mov [edi], eax", "mov [edi + 4], ecx", "mov [edi + 8], edx", "mov [edi + 12], ebx",
            "mov [edi + 16], esi", "mov [edi + 24], ebp",
            "pop dword ptr [edi + 20]",
            "mov esp, fs:[0x14]",
            "pop dword ptr fs:[0x14]",
            "add esp, 4",
            "pop ebp", "pop edi", "pop esi", "pop ebx",
            inout("eax") block.as_ptr() => _, lateout("ecx") _, lateout("edx") _,
            clobber_abi("C"),
        );
    }
}

/// The `pushad` block, lowest address first.
#[repr(C)]
#[derive(Clone, Copy)]
#[allow(dead_code)] // not every register is read
struct Pushad {
    edi: u32,
    esi: u32,
    ebp: u32,
    esp: u32,
    ebx: u32,
    edx: u32,
    ecx: u32,
    eax: u32,
}

/// `pushad`, XMM0-7 saved, `f(&mut block, &stack args)`, XMM0-7 restored, `popad`, `ret N`.
macro_rules! thunk {
    ($name:ident, $f:ident, $ret:literal) => {
        #[allow(dead_code)]
        #[unsafe(naked)]
        extern "C" fn $name() {
            std::arch::naked_asm!(
                "pushad",
                "sub esp, 128",
                "movups xmmword ptr [esp], xmm0",
                "movups xmmword ptr [esp + 16], xmm1",
                "movups xmmword ptr [esp + 32], xmm2",
                "movups xmmword ptr [esp + 48], xmm3",
                "movups xmmword ptr [esp + 64], xmm4",
                "movups xmmword ptr [esp + 80], xmm5",
                "movups xmmword ptr [esp + 96], xmm6",
                "movups xmmword ptr [esp + 112], xmm7",
                "lea eax, [esp + 128]",
                "lea ecx, [esp + 164]",
                "push ecx",
                "push eax",
                "call {f}",
                "add esp, 8",
                "movups xmm0, xmmword ptr [esp]",
                "movups xmm1, xmmword ptr [esp + 16]",
                "movups xmm2, xmmword ptr [esp + 32]",
                "movups xmm3, xmmword ptr [esp + 48]",
                "movups xmm4, xmmword ptr [esp + 64]",
                "movups xmm5, xmmword ptr [esp + 80]",
                "movups xmm6, xmmword ptr [esp + 96]",
                "movups xmm7, xmmword ptr [esp + 112]",
                "add esp, 128",
                "popad",
                $ret,
                f = sym $f,
            )
        }
    };
}

/// Define one port: `port!(index, handler, thunk, "ret N", |r, a| { body })`. `r` is the
/// `pushad` block (final registers go in it), `a` points at the first stack argument.
macro_rules! port {
    ($idx:expr, $e:ident, $t:ident, $ret:literal, |$r:ident, $a:ident| { $($body:tt)* }) => {
        #[allow(dead_code, unused_variables)]
        extern "C" fn $e($r: &mut Pushad, $a: *const u32) {
            count($idx);
            #[allow(unused_unsafe)]
            unsafe {
                $($body)*
            }
        }
        thunk!($t, $e, $ret);
    };
}

struct Port {
    name: &'static str,
    addr: usize,
    body: &'static [u8],
    thunk: extern "C" fn(),
}

/// The stack argument `i` of the caller.
#[inline(always)]
unsafe fn arg(a: *const u32, i: usize) -> u32 {
    unsafe { *a.add(i) }
}

/// A callee's view of the stack when the original had pushed `pre` (and not yet cleaned up),
/// saved registers `saved` (lowest address first), then its return address and the caller's own
/// stack arguments: 16 words.
#[inline(always)]
unsafe fn frame(a: *const u32, pre: &[u32], saved: &[u32]) -> [u32; 16] {
    unsafe {
        let mut f = [0u32; 16];
        let mut n = 0;
        for &w in pre.iter().chain(saved.iter()) {
            f[n] = w;
            n += 1;
        }
        f[n] = *a.sub(1);
        n += 1;
        let mut i = 0;
        while n < 16 {
            f[n] = *a.add(i);
            n += 1;
            i += 1;
        }
        f
    }
}

#[allow(dead_code)]
unsafe fn setarg(a: *const u32, i: usize, v: u32) {
    unsafe { *(a.add(i) as *mut u32) = v }
}

