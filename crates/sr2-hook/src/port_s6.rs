/// `fldz; fcomp dword [v]; fnstsw ax`: the status word with the stack empty again (TOP = 0).
fn status_zero_vs(v: u32) -> u32 {
    let f = f32::from_bits(v);
    let mut sw = if f.is_nan() {
        0x4500 | 1
    } else if 0.0f32 < f {
        0x0100
    } else if f == 0.0 {
        0x4000
    } else {
        0
    };
    if v & 0x7F80_0000 == 0 && v & 0x007F_FFFF != 0 {
        sw |= 2; // denormal operand
    }
    sw
}

