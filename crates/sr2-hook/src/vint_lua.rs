//! The four vint Lua bindings the HUD scripts call most, in Rust
//! (docs/analysis/09_script.md, "The 20 most-used Lua bindings"; 06_vint.md):
//!
//! | Binding | Address | Lua |
//! |---|---|---|
//! | `vint_set_property` | 0xB8FAC0 | (handle, property name, value…, [extra]) → nothing |
//! | `vint_object_find` | 0xB8F400 | (name, [parent handle], [document handle]) → handle, 0 if none |
//! | `vint_get_property` | 0xB8F570 | (handle, property name) → the value(s) |
//! | `vint_object_destroy` | 0xB8F310 | (handle, [delay]) → nothing; the delay is read and ignored |
//!
//! Together they are 64% of the binding call sites in the shipped scripts. Two leaves
//! they use are ported with them: `vint_lua_current_document` (0xB8E020) and
//! `vint_object_unlink_from_parent` (0xB97A20).
//!
//! The Lua API (`luaA_index`, `lua_tostring`, `lua_tonumber`) and the vint property
//! machinery (property descriptors, the typed value union, the setters) stay the
//! game's and are called with their LTCG register conventions.
//!
//! The argument reading follows the originals exactly, including the index arithmetic
//! for missing arguments: `n` = the argument count clamped to the most the binding
//! reads, then argument `k` is read at index `k - 1 - n`, so missing trailing ones
//! come out as nil.
//!
//! **Shadow check.** For the first `SHADOW_CALLS` calls of `vint_object_find` and
//! `vint_get_property` (they only read), a relocated copy of the original runs first;
//! its results are taken off the Lua stack, then the Rust one runs and the pushed
//! values are compared.

use std::sync::atomic::{AtomicU32, AtomicUsize, Ordering};

use crate::gfx_cmd::call_regs;
use crate::{detour, log};

// Lua 5.0 API (lua_State: +8 top, +0xC base; values are 16 bytes {tt, _, value}).
const LUAA_INDEX: usize = 0x00CD_BE80; // EAX = index, ECX = L -> TObject *
const LUA_TOSTRING: usize = 0x00CD_CA80; // EAX = index, ECX = L -> char *
const LUA_TONUMBER: usize = 0x00CD_C250; // EAX = index, ECX = L -> st0
const TT_NIL: u32 = 0;
const TT_NUMBER: u32 = 3;

// vint.
const HANDLE_BUCKETS: usize = 0x022E_F2B8; // 64 chains through +0xC, handle at +0x28
const DOCUMENTS: usize = 0x0319_F6B0; // 12 x 0x57C, handle at +0x4C
const DOC_SIZE: usize = 0x57C;
const DOC_COUNT: u32 = 12;
const CONTEXT_DEPTH: usize = 0x0252_6360; // Lua context stack: depth, then threads
const CONTEXT_THREADS: usize = 0x0252_6364;
const ELEMENT_TYPE: usize = 0x00EB_DF6C; // -> the element type id
const TWEEN_TYPE: usize = 0x00EB_E2F8; // -> the tween type id
const HASH: usize = 0x00BD_C9B0; // vint_hash_string: ECX = string (NULL -> 0)
const FIND_BY_HASH: usize = 0x00B9_7970; // EDX = hash, ESI = document
const FIND_CHILD_BY_HASH: usize = 0x00B9_8340; // ECX = parent, (hash), ret 4
const PROPERTY_FIND: usize = 0x00B9_78A0; // ESI = object, ECX = name -> descriptor
const PROPERTY_GET: usize = 0x00B9_7680; // ESI = object, EDI = &value, (hash), ret 4 -> al
const PROPERTY_SET: usize = 0x00B9_7810; // ESI = object, ECX = name, (&value, extra), ret 8
const VALUE_INIT: usize = 0x00B9_3A10; // EAX = &value, ECX = type
const VALUE_FREE: usize = 0x00B9_3790; // EAX = &value
const VALUE_ASSIGN: usize = 0x00B9_3620; // ESI = &dst, EDI = &src
const VALUE_FROM_LUA: usize = 0x00B8_D200; // EAX = &value, (&scratch, L, &n, 0) -> &value read
const VALUE_PUSH: usize = 0x00B8_D8F0; // EAX = L, EDX = &value -> results pushed
const VALUE_TO_HANDLE: usize = 0x0063_4BA0; // ECX = &value
const LUA_OPT_INT: usize = 0x0055_75E0; // EDI = &n, (L, 0, &default)
const STRICMP: usize = 0x00C9_9030;
const STR_START_VALUE: u32 = 0x00E4_CC50;
const STR_END_VALUE: u32 = 0x00E4_CC5C;
const STR_TARGET_PROPERTY: u32 = 0x00E4_CC68;
const VARIANT: u32 = 0xD; // property value type: a tween's start / end value
const STRING: u32 = 4;

// vint_object_base fields and vtable slots.
const OBJ_NEXT_IN_BUCKET: usize = 0x0C;
const OBJ_FIRST_CHILD: usize = 0x1C;
const OBJ_NEXT_SIBLING: usize = 0x20;
const OBJ_PARENT: usize = 0x24;
const OBJ_HANDLE: usize = 0x28;
const OBJ_DOCUMENT: usize = 0x30;
const DOC_ROOT: usize = 0x458;
const SLOT_DESTROY: usize = 2;
const SLOT_IS_TYPE: usize = 6;
const SLOT_GET_TYPE: usize = 7;
const SLOT_TWEEN_GET_TARGET_HANDLE: usize = 11;

const SHADOW_CALLS: u32 = 5000;

/// The vint value union {tag, data}: tag 0 = empty; colours use all three words.
#[repr(C, align(8))]
#[derive(Default)]
struct Value {
    tag: u32,
    data: [u32; 3],
}

unsafe fn rd(p: usize) -> u32 {
    unsafe { *(p as *const u32) }
}

unsafe fn wr(p: usize, v: u32) {
    unsafe { *(p as *mut u32) = v }
}

// --- Lua -------------------------------------------------------------------------------

unsafe fn top(l: u32) -> u32 {
    unsafe { rd(l as usize + 8) }
}

/// The argument count, clamped.
unsafe fn args(l: u32, most: i32) -> i32 {
    let n = unsafe { (top(l).wrapping_sub(rd(l as usize + 0xC)) as i32) >> 4 };
    n.min(most)
}

unsafe fn index(l: u32, i: i32) -> u32 {
    unsafe { call_regs(LUAA_INDEX, i as u32, l, 0, 0, 0, &[]) }
}

/// True if the argument at `i` exists and is nil.
unsafe fn is_nil(l: u32, i: i32) -> bool {
    let p = unsafe { index(l, i) };
    p != 0 && unsafe { rd(p as usize) } == TT_NIL
}

unsafe fn tostring(l: u32, i: i32) -> u32 {
    unsafe { call_regs(LUA_TOSTRING, i as u32, l, 0, 0, 0, &[]) }
}

unsafe fn tonumber(l: u32, i: i32) -> f64 {
    let mut out = 0f64;
    unsafe {
        std::arch::asm!(
            "call {f}",
            "fstp qword ptr [edi]",
            f = in(reg) LUA_TONUMBER,
            in("eax") i,
            in("ecx") l,
            in("edi") &mut out as *mut f64,
            clobber_abi("C"),
        );
    }
    out
}

/// `_ftol2` as the bindings use it: truncate to 64 bits and keep the low 32
/// (out of range gives 0x8000000000000000, so 0).
fn ftol(x: f64) -> u32 {
    if x.abs() < 9.2e18 { x as i64 as u32 } else { 0 }
}

unsafe fn int_arg(l: u32, i: i32) -> u32 {
    ftol(unsafe { tonumber(l, i) })
}

unsafe fn push_number(l: u32, x: f64) {
    unsafe {
        let t = top(l) as usize;
        wr(t, TT_NUMBER);
        *((t + 8) as *mut f64) = x;
        wr(l as usize + 8, t as u32 + 16);
    }
}

// --- vint ------------------------------------------------------------------------------

unsafe fn vslot(obj: u32, slot: usize) -> usize {
    unsafe { rd(rd(obj as usize) as usize + slot * 4) as usize }
}

/// The object with this handle, from the handle buckets (circular chains).
unsafe fn object(handle: u32) -> u32 {
    let head = unsafe { rd(HANDLE_BUCKETS + (handle as usize & 0x3F) * 4) };
    let mut o = head;
    while o != 0 {
        if unsafe { rd(o as usize + OBJ_HANDLE) } == handle {
            return o;
        }
        o = unsafe { rd(o as usize + OBJ_NEXT_IN_BUCKET) };
        if o == head {
            break;
        }
    }
    0
}

/// The document record for a document handle (index | generation << 16), or 0.
unsafe fn document(handle: u32) -> u32 {
    let i = handle & 0xFFFF;
    if i >= DOC_COUNT {
        return 0;
    }
    let d = DOCUMENTS + i as usize * DOC_SIZE;
    if unsafe { rd(d + 0x4C) } == handle { d as u32 } else { 0 }
}

/// `vint_lua_current_document` (0xB8E020): the document of the running Lua thread.
extern "C" fn current_document() -> u32 {
    unsafe {
        let depth = rd(CONTEXT_DEPTH);
        if depth == 0 || depth > 16 {
            return 0;
        }
        let thread = rd(CONTEXT_THREADS + depth as usize * 4);
        if thread == 0 {
            return 0;
        }
        let h = rd(thread as usize + 0x14);
        if h == 0 { 0 } else { document(h) }
    }
}

/// `vint_object_unlink_from_parent` (0xB97A20, ECX = object -> al): take the object
/// out of its parent's child list. False if the parent doesn't list it.
extern "C" fn unlink_from_parent(obj: u32) -> bool {
    unsafe {
        let o = obj as usize;
        let parent = rd(o + OBJ_PARENT) as usize;
        let detach = || {
            wr(o + OBJ_PARENT, 0);
            wr(o + OBJ_NEXT_SIBLING, 0);
        };
        if parent == 0 {
            wr(o + OBJ_NEXT_SIBLING, 0);
            return true;
        }
        let first = rd(parent + OBJ_FIRST_CHILD);
        if first == 0 {
            return false;
        }
        if first == obj {
            wr(parent + OBJ_FIRST_CHILD, rd(o + OBJ_NEXT_SIBLING));
            detach();
            return true;
        }
        let mut p = first as usize;
        loop {
            let next = rd(p + OBJ_NEXT_SIBLING);
            if next == obj {
                break;
            }
            if next == 0 {
                return false;
            }
            p = next as usize;
        }
        wr(p + OBJ_NEXT_SIBLING, rd(o + OBJ_NEXT_SIBLING));
        detach();
        true
    }
}

#[unsafe(naked)]
extern "C" fn unlink_thunk() {
    std::arch::naked_asm!(
        "push ecx",
        "push edx",
        "push ecx",
        "call {f}",
        "add esp, 4",
        "pop edx",
        "pop ecx",
        "ret",
        f = sym unlink_from_parent,
    )
}

unsafe fn hash(s: u32) -> u32 {
    unsafe { call_regs(HASH, 0, s, 0, 0, 0, &[]) }
}

unsafe fn value_free(v: &mut Value) {
    unsafe { call_regs(VALUE_FREE, v as *mut Value as u32, 0, 0, 0, 0, &[]) };
}

/// Property lookup by name hash into `v`; false if the object has no such property.
unsafe fn property_get(obj: u32, h: u32, v: &mut Value) -> bool {
    unsafe { call_regs(PROPERTY_GET, 0, 0, 0, obj, v as *mut Value as u32, &[h]) as u8 != 0 }
}

unsafe fn property_find(obj: u32, name: u32) -> u32 {
    unsafe { call_regs(PROPERTY_FIND, 0, name, 0, obj, 0, &[]) }
}

// --- The bindings ----------------------------------------------------------------------

static CALLS: [AtomicU32; 4] = [const { AtomicU32::new(0) }; 4];
static SHADOWED: [AtomicU32; 2] = [const { AtomicU32::new(0) }; 2];
static MISMATCHES: [AtomicU32; 2] = [const { AtomicU32::new(0) }; 2];
static ORIG_FIND: AtomicUsize = AtomicUsize::new(0);
static ORIG_GET: AtomicUsize = AtomicUsize::new(0);

/// `vint_object_destroy(handle, [delay])`.
extern "C" fn object_destroy(l: u32) -> i32 {
    CALLS[3].fetch_add(1, Ordering::Relaxed);
    unsafe {
        let n = args(l, 2);
        let handle = int_arg(l, -n);
        // The original converts a non-nil delay with lua_tonumber and drops it; the
        // conversion has no side effects, so it is skipped.
        if handle == 0 {
            return 0;
        }
        let obj = object(handle);
        if obj == 0 {
            return 0;
        }
        let doc = rd(obj as usize + OBJ_DOCUMENT);
        if doc == 0 {
            return 0;
        }
        let element = rd(rd(ELEMENT_TYPE) as usize);
        let is_element = call_regs(vslot(obj, SLOT_IS_TYPE), 0, obj, 0, 0, 0, &[element]) as u8 != 0;
        // An element of a document without a root is left linked.
        if !(is_element && rd(doc as usize + DOC_ROOT) == 0) && rd(obj as usize + OBJ_DOCUMENT) == doc {
            unlink_from_parent(obj);
        }
        call_regs(vslot(obj, SLOT_DESTROY), 0, obj, 0, 0, 0, &[]);
    }
    0
}

/// `vint_object_find(name, [parent handle], [document handle])` -> handle, or 0.
unsafe fn find(l: u32) -> u32 {
    unsafe {
        let mut n = args(l, 3);
        let name = tostring(l, -n);
        n -= 1;
        let mut parent = 0;
        if n > 0 {
            if !is_nil(l, -n) {
                parent = int_arg(l, -n);
            }
            n -= 1;
        }
        let doc = if n <= 0 || is_nil(l, -n) {
            current_document()
        } else {
            match int_arg(l, -n) {
                0 => current_document(),
                h => document(h),
            }
        };
        if doc == 0 {
            return 0;
        }
        let obj = if parent != 0 {
            let p = object(parent);
            if p == 0 {
                return 0;
            }
            call_regs(FIND_CHILD_BY_HASH, 0, p, 0, 0, 0, &[hash(name)])
        } else {
            if name == 0 {
                return 0;
            }
            call_regs(FIND_BY_HASH, 0, 0, hash(name), doc, 0, &[])
        };
        if obj == 0 { 0 } else { rd(obj as usize + OBJ_HANDLE) }
    }
}

extern "C" fn object_find(l: u32) -> i32 {
    CALLS[1].fetch_add(1, Ordering::Relaxed);
    shadowed(0, l, ORIG_FIND.load(Ordering::Relaxed), |l| unsafe {
        push_number(l, find(l) as f64);
        1
    })
}

/// `vint_get_property(handle, property name)` -> the value(s).
unsafe fn get(l: u32) -> i32 {
    unsafe {
        let n = args(l, 2);
        let handle = int_arg(l, -n);
        let name = tostring(l, 1 - n);
        if name == 0 || current_document() == 0 || handle == 0 {
            return 0;
        }
        let obj = object(handle);
        if obj == 0 {
            return 0;
        }
        let mut v = Value::default();
        if !property_get(obj, hash(name), &mut v) {
            value_free(&mut v);
            return 0;
        }
        let pushed = call_regs(VALUE_PUSH, l, 0, &mut v as *mut Value as u32, 0, 0, &[]) as i32;
        value_free(&mut v);
        pushed
    }
}

extern "C" fn get_property(l: u32) -> i32 {
    CALLS[2].fetch_add(1, Ordering::Relaxed);
    shadowed(1, l, ORIG_GET.load(Ordering::Relaxed), |l| unsafe { get(l) })
}

/// `vint_set_property(handle, property name, value…, [extra])`.
extern "C" fn set_property(l: u32) -> i32 {
    CALLS[0].fetch_add(1, Ordering::Relaxed);
    unsafe {
        let mut n = args(l, 6);
        let mut handle = 0;
        if n > 0 {
            let p = index(l, -n);
            if p != 0 && rd(p as usize) == TT_NUMBER {
                handle = int_arg(l, -n);
            }
        }
        n -= 1;
        let name = tostring(l, -n);
        // The values (and the optional trailing int) are what's left.
        let mut left = n - 1;
        if name == 0 || handle == 0 {
            return 0;
        }
        let obj = object(handle);
        if obj == 0 {
            return 0;
        }
        let prop = property_find(obj, name);
        if prop == 0 {
            return 0;
        }
        let mut ty = rd(prop as usize + 4);
        let mut a = Value::default();
        let mut b = Value::default();
        // A tween's start / end value takes the type of the property it animates.
        if ty == VARIANT
            && call_regs(vslot(obj, SLOT_GET_TYPE), 0, obj, 0, 0, 0, &[]) == rd(rd(TWEEN_TYPE) as usize)
            && (call_regs(STRICMP, 0, 0, 0, 0, 0, &[name, STR_START_VALUE]) == 0
                || call_regs(STRICMP, 0, 0, 0, 0, 0, &[name, STR_END_VALUE]) == 0)
        {
            let pb = &mut b as *mut Value as u32;
            call_regs(vslot(obj, SLOT_TWEEN_GET_TARGET_HANDLE), 0, obj, 0, 0, 0, &[pb, 0]);
            let th = call_regs(VALUE_TO_HANDLE, 0, pb, 0, 0, 0, &[]);
            let target = if th == 0 { 0 } else { object(th) };
            property_get(obj, hash(STR_TARGET_PROPERTY), &mut a);
            let target_property = if a.tag == STRING { a.data[0] } else { 0 };
            if target != 0 && target_property != 0 {
                let p = property_find(target, target_property);
                if p != 0 {
                    ty = rd(p as usize + 4);
                }
            }
            value_free(&mut a);
            a.tag = 0;
            value_free(&mut b);
        }
        a.tag = 0;
        let pa = &mut a as *mut Value as u32;
        let pb = &mut b as *mut Value as u32;
        if ty as i32 <= 0xB {
            call_regs(VALUE_INIT, pa, ty, 0, 0, 0, &[]);
        }
        let pleft = &mut left as *mut i32 as u32;
        let read = call_regs(VALUE_FROM_LUA, pa, 0, 0, 0, 0, &[pb, l, pleft, 0]);
        call_regs(VALUE_ASSIGN, 0, 0, 0, pa, read, &[]);
        value_free(&mut b);
        let mut default = 0u32;
        let extra = call_regs(LUA_OPT_INT, 0, 0, 0, 0, pleft, &[l, 0, &mut default as *mut u32 as u32]);
        call_regs(PROPERTY_SET, 0, name, 0, obj, 0, &[pa, extra]);
        value_free(&mut a);
    }
    0
}

/// Run the original copy first (for the first SHADOW_CALLS calls), take its results
/// off the stack, then run the Rust one and compare what each pushed.
fn shadowed(k: usize, l: u32, orig: usize, rust: impl Fn(u32) -> i32) -> i32 {
    if orig == 0 || SHADOWED[k].load(Ordering::Relaxed) >= SHADOW_CALLS {
        return rust(l);
    }
    SHADOWED[k].fetch_add(1, Ordering::Relaxed);
    unsafe {
        let t0 = top(l);
        let f: extern "C" fn(u32) -> i32 = std::mem::transmute(orig);
        let rn = f(l);
        let theirs: Vec<[u32; 4]> = (0..(top(l) - t0) / 16).map(|i| *((t0 + i * 16) as *const [u32; 4])).collect();
        wr(l as usize + 8, t0);
        let n = rust(l);
        let ours: Vec<[u32; 4]> = (0..(top(l) - t0) / 16).map(|i| *((t0 + i * 16) as *const [u32; 4])).collect();
        // Compare the type tag and the 8-byte value; +4 is padding.
        let key = |v: &Vec<[u32; 4]>| v.iter().map(|s| (s[0], s[2], s[3])).collect::<Vec<_>>();
        if n != rn || key(&ours) != key(&theirs) {
            let m = MISMATCHES[k].fetch_add(1, Ordering::Relaxed) + 1;
            if m <= 20 {
                let which = ["vint_object_find", "vint_get_property"][k];
                log(&format!("vint_lua: {which} mismatch: original {rn} {theirs:x?}, Rust {n} {ours:x?}"));
            }
        }
        n
    }
}

// --- Install -----------------------------------------------------------------------------

pub fn install() {
    let mut ok = 0;
    unsafe {
        for (name, addr, body, calls, slot) in [
            ("vint_object_find", 0x00B8_F400usize, &FIND_BODY[..], &FIND_CALLS[..], Some(&ORIG_FIND)),
            ("vint_get_property", 0x00B8_F570, &GET_BODY[..], &GET_CALLS[..], Some(&ORIG_GET)),
        ] {
            match detour::relocate(addr, body, calls) {
                Ok(copy) => {
                    if let Some(s) = slot {
                        s.store(copy, Ordering::Relaxed);
                    }
                }
                Err(e) => log(&format!("vint_lua: no shadow copy of {name}: {e:?}")),
            }
        }
        let ports: [(&str, usize, &[u8], usize); 6] = [
            ("vint_lua_current_document", 0x00B8_E020, &CURRENT_DOC_BODY, current_document as extern "C" fn() -> u32 as usize),
            ("vint_object_unlink_from_parent", 0x00B9_7A20, &UNLINK_BODY, unlink_thunk as extern "C" fn() as usize),
            ("vint_object_find", 0x00B8_F400, &FIND_BODY, object_find as extern "C" fn(u32) -> i32 as usize),
            ("vint_get_property", 0x00B8_F570, &GET_BODY, get_property as extern "C" fn(u32) -> i32 as usize),
            ("vint_set_property", 0x00B8_FAC0, &SET_BODY, set_property as extern "C" fn(u32) -> i32 as usize),
            ("vint_object_destroy", 0x00B8_F310, &DESTROY_BODY, object_destroy as extern "C" fn(u32) -> i32 as usize),
        ];
        for (name, addr, body, f) in ports {
            match detour::replace(addr, body, f) {
                Ok(()) => ok += 1,
                Err(e) => log(&format!("vint_lua: replacing {name} @ {addr:#x} failed: {e:?}")),
            }
        }
    }
    let _ = (&DESTROY_CALLS, &SET_CALLS, &CURRENT_DOC_CALLS, &UNLINK_CALLS);
    log(&format!("vint_lua: replaced {ok}/6 (the four HUD Lua bindings and two vint leaves)"));
}

pub fn summary() -> String {
    let c: Vec<u32> = CALLS.iter().map(|c| c.load(Ordering::Relaxed)).collect();
    format!(
        "vint_lua: set_property {}, object_find {} (shadowed {}, {} mismatched), get_property {} (shadowed {}, {} mismatched), object_destroy {}",
        c[0],
        c[1],
        SHADOWED[0].load(Ordering::Relaxed),
        MISMATCHES[0].load(Ordering::Relaxed),
        c[2],
        SHADOWED[1].load(Ordering::Relaxed),
        MISMATCHES[1].load(Ordering::Relaxed),
        c[3]
    )
}

