//! `player_controls_update` (0x4FE760) in Rust: builds the player control block
//! `0x2659908` from the active pad record once a frame (docs/analysis/14_input.md,
//! "Game actions and the player control block").
//!
//! - Buttons (87 records of 0x24 bytes in the pad record): down (value above the
//!   threshold), pressed-or-repeated and just-pressed, each only when not eaten; the
//!   two "available" masks reset to 0xFF; the frame time of each press. The analog
//!   triggers 0x23 / 0x24 get an adaptive threshold: down -> at least value - K, up ->
//!   at most value + K (K = 0xDD50E8, f64), so a half-held trigger can press again.
//! - Sticks (entries of 0x28 bytes): x / y with eaten -> 0 and inverted -> negated, a
//!   copy without the filter (+0x10), then the sign-flip filter: a value whose sign
//!   flipped since last frame (+8) reads 0 for a frame. Step values for sticks 0 and 1
//!   from the pad's auto-repeat pulses; the taken flags of entries 0, 1 and 5 cleared.
//!
//! The original's x87 code has one quirk, kept here: in entry 6's y filter, the
//! "previous was negative" branch tests entry 3's y (already filtered) instead of
//! entry 6's own y, which it never loads; the compiler reused a stack slot.
//!
//! **Shadow check.** For the first `SHADOW_FRAMES` calls the relocated original runs
//! first on the same state; the control block and trigger thresholds it leaves are compared
//! byte for byte with what the Rust version writes, and on a mismatch the original's
//! result is kept.

use std::sync::atomic::{AtomicU32, AtomicUsize, Ordering};

use crate::{detour, log};

const PLAYER_CONTROLS_UPDATE: usize = 0x004F_E760;
const PADS: usize = 0x0234_78B8; // 0x104C bytes per pad
const PAD_SIZE: usize = 0x104C;
const PAD_INDEX: usize = 0x00E9_8DB0; // -1 = pad 0
const BUTTONS: usize = 87;
const BUTTON_SIZE: usize = 0x24; // +0 value, +8 threshold, +0x1C pressed, +0x1D repeat, +0x20 eaten
const STICKS: usize = 0xC3C; // in the pad: 0x40 per stick, +0 x, +4 y, +0xC/D inverted, +0xE/F eaten
const STICK_SIZE: usize = 0x40;
const TRIGGER_K: usize = 0x00DD_50E8; // f64
const GAME_TIME: usize = 0x0252_A3C8;

const BLOCK: usize = 0x0265_9908;
const BLOCK_END: usize = 0x0265_9D58;
const ENTRY: usize = 0x28;
const DOWN: usize = 0x0265_9A48;
const REPEAT: usize = 0x0265_9A9F;
const AVAIL: usize = 0x0265_9AF6;
const PRESSED: usize = 0x0265_9B4D;
const AVAIL_PRESSED: usize = 0x0265_9BA4;
const PRESS_TIME: usize = 0x0265_9BFC;

const SHADOW_FRAMES: u32 = 20000;
/// Off until the narrowed shadow check has been tested in game.
const ENABLED: bool = true;

static ORIGINAL: AtomicUsize = AtomicUsize::new(0);
static CALLS: AtomicU32 = AtomicU32::new(0);
static SHADOWED: AtomicU32 = AtomicU32::new(0);
static MISMATCHES: AtomicU32 = AtomicU32::new(0);

unsafe fn f(p: usize) -> f32 {
    unsafe { *(p as *const f32) }
}

unsafe fn setf(p: usize, v: f32) {
    unsafe { *(p as *mut f32) = v }
}

unsafe fn b(p: usize) -> u8 {
    unsafe { *(p as *const u8) }
}

fn pad_base() -> usize {
    let i = unsafe { *(PAD_INDEX as *const i32) };
    PADS + if i == -1 { 0 } else { i as usize } * PAD_SIZE
}

/// Copy a pad stick into a block slot: eaten -> +0, inverted -> negated.
unsafe fn stick(slot: usize, s: usize) {
    unsafe {
        let (mut x, mut y) = (f(s), f(s + 4));
        if b(s + 0xE) != 0 {
            x = 0.0;
        } else if b(s + 0xC) != 0 {
            x = -x;
        }
        if b(s + 0xF) != 0 {
            y = 0.0;
        } else if b(s + 0xD) != 0 {
            y = -y;
        }
        setf(slot, x);
        setf(slot + 4, y);
    }
}

/// The sign-flip filter: zero `cur` if its sign is opposite to last frame's (+8).
unsafe fn flip(cur: usize) {
    unsafe {
        let (c, p) = (f(cur), f(cur + 8));
        if (p < 0.0 && c > 0.0) || (p > 0.0 && c < 0.0) {
            setf(cur, 0.0);
        }
    }
}

/// The auto-repeat step: -1 / +1 from the stick's pulses, else 0.
unsafe fn step(s: usize, minus: usize, plus: usize) -> u32 {
    unsafe {
        if b(s + minus) != 0 { u32::MAX } else { (b(s + plus) != 0) as u32 }
    }
}

extern "C" fn rust() {
    unsafe {
        let p = pad_base();
        let k = *(TRIGGER_K as *const f64);
        std::ptr::write_bytes(DOWN as *mut u8, 0, BUTTONS);
        for i in 0..BUTTONS {
            let e = p + i * BUTTON_SIZE;
            let eaten = b(e + 0x20);
            let down = f(e) > f(e + 8) && eaten == 0;
            *((DOWN + i) as *mut u8) = down as u8;
            if i == 0x23 || i == 0x24 {
                let a = (if eaten == 1 { 0.0 } else { f(e) }) as f64;
                let t = f(e + 8);
                let thr = if down {
                    let m = a - k;
                    if t as f64 > m { t } else { m as f32 }
                } else {
                    let m = a + k;
                    if (t as f64) < m { t } else { m as f32 }
                };
                setf(e + 8, thr);
            }
        }
        for i in 0..BUTTONS {
            let e = p + i * BUTTON_SIZE;
            *((REPEAT + i) as *mut u8) = (b(e + 0x20) == 0 && b(e + 0x1D) != 0) as u8;
        }
        std::ptr::write_bytes(AVAIL as *mut u8, 0xFF, BUTTONS);
        let now = *(GAME_TIME as *const u32);
        for i in 0..BUTTONS {
            let e = p + i * BUTTON_SIZE;
            let pressed = b(e + 0x20) == 0 && b(e + 0x1C) != 0;
            *((PRESSED + i) as *mut u8) = pressed as u8;
            if pressed {
                *((PRESS_TIME + i * 4) as *mut u32) = now;
            }
        }
        std::ptr::write_bytes(AVAIL_PRESSED as *mut u8, 0xFF, BUTTONS);

        // Last frame's values, for entries 0, 1, 5, 3 and 6 (not 4 or 7).
        for e in [0, 1, 5, 3, 6] {
            let a = BLOCK + e * ENTRY;
            setf(a + 8, f(a));
            setf(a + 0xC, f(a + 4));
        }
        let s = |n: usize| p + STICKS + n * STICK_SIZE;
        let slot = |e: usize, raw: bool| BLOCK + e * ENTRY + if raw { 0x10 } else { 0 };
        for (e, raw, n) in [
            (0, false, 0),
            (1, false, 1),
            (5, false, 5),
            (5, true, 5),
            (4, false, 4),
            (3, false, 3),
            (3, true, 3),
            (4, true, 4),
            (6, false, 6),
            (6, true, 6),
            (7, true, 7),
            (0, true, 0),
            (1, true, 1),
        ] {
            stick(slot(e, raw), s(n));
        }
        for e in [0, 1, 5, 4, 3] {
            flip(slot(e, false));
            flip(slot(e, false) + 4);
        }
        let e3y = f(slot(3, false) + 4);
        let e6 = slot(6, false);
        flip(e6);
        // The quirk: the "previous negative" branch checks entry 3's y.
        let (c6y, p6y) = (f(e6 + 4), f(e6 + 0xC));
        if (p6y < 0.0 && e3y > 0.0) || (p6y > 0.0 && c6y < 0.0) {
            setf(e6 + 4, 0.0);
        }
        flip(slot(7, false));
        flip(slot(7, false) + 4);

        let w = |a: usize, v: u32| *(a as *mut u32) = v;
        w(BLOCK + 0x18, step(s(0), 0x30, 0x3C));
        w(BLOCK + 0x1C, step(s(0), 0x18, 0x24));
        w(BLOCK + ENTRY + 0x18, step(s(1), 0x30, 0x3C));
        w(BLOCK + ENTRY + 0x1C, step(s(1), 0x18, 0x24));
        for e in [0, 1, 5] {
            std::ptr::write_bytes((BLOCK + e * ENTRY + 0x20) as *mut u8, 0, 6);
        }
    }
}

extern "C" fn hook() {
    let n = CALLS.fetch_add(1, Ordering::Relaxed);
    let orig = ORIGINAL.load(Ordering::Relaxed);
    if orig == 0 || n >= SHADOW_FRAMES {
        return rust();
    }
    SHADOWED.fetch_add(1, Ordering::Relaxed);
    unsafe {
        // Only the trigger thresholds of the pad record are written here; the rest of
        // it belongs to the input thread, so it is neither saved nor restored.
        let p = pad_base();
        let thr = [p + 0x23 * BUTTON_SIZE + 8, p + 0x24 * BUTTON_SIZE + 8];
        let save = || {
            let mut v = std::slice::from_raw_parts(BLOCK as *const u8, BLOCK_END - BLOCK).to_vec();
            for a in thr {
                v.extend_from_slice(&*(a as *const [u8; 4]));
            }
            v
        };
        let load = |v: &[u8]| {
            let n = BLOCK_END - BLOCK;
            std::ptr::copy_nonoverlapping(v.as_ptr(), BLOCK as *mut u8, n);
            for (k, a) in thr.iter().enumerate() {
                std::ptr::copy_nonoverlapping(v[n + k * 4..].as_ptr(), *a as *mut u8, 4);
            }
        };
        let before = save();
        let original: extern "C" fn() = std::mem::transmute(orig);
        original();
        let theirs = save();
        load(&before);
        rust();
        let ours = save();
        if theirs != ours {
            let m = MISMATCHES.fetch_add(1, Ordering::Relaxed) + 1;
            if m <= 20 {
                let len = BLOCK_END - BLOCK;
                let at = |i: usize| if i < len { BLOCK + i } else { thr[(i - len) / 4] + (i - len) % 4 };
                let diff: Vec<String> = (0..ours.len())
                    .filter(|&i| theirs[i] != ours[i])
                    .take(8)
                    .map(|i| format!("{:#x}: {:02x} vs {:02x}", at(i), theirs[i], ours[i]))
                    .collect();
                log(&format!("controls: player_controls_update mismatch (call {n}), original vs Rust: {diff:?}"));
            }
            load(&theirs);
        }
    }
}

pub fn install() {
    if !ENABLED {
        log("controls: player_controls_update port disabled");
        return;
    }
    unsafe {
        match detour::relocate(PLAYER_CONTROLS_UPDATE, &BODY, &BODY_CALLS) {
            Ok(copy) => ORIGINAL.store(copy, Ordering::Relaxed),
            Err(e) => log(&format!("controls: no shadow copy: {e:?}")),
        }
        match detour::replace(PLAYER_CONTROLS_UPDATE, &BODY, hook as extern "C" fn() as usize) {
            Ok(()) => log("controls: replaced player_controls_update @ 0x4fe760 with Rust (shadow-checked)"),
            Err(e) => log(&format!("controls: replacing player_controls_update failed: {e:?}")),
        }
    }
}

pub fn summary() -> String {
    format!(
        "controls: player_controls_update {} calls, {} shadowed, {} mismatched",
        CALLS.load(Ordering::Relaxed),
        SHADOWED.load(Ordering::Relaxed),
        MISMATCHES.load(Ordering::Relaxed)
    )
}

