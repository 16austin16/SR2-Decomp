/// `_ftol2`: truncate; out of range (and NaN) gives the integer indefinite, whose low dword is 0.
fn ftol_low(v: f32) -> u32 {
    let v = v as f64;
    if v.is_finite() && v.abs() < 9.223_372_036_854_775e18 { v as i64 as u32 } else { 0 }
}

/// A cached SetSamplerState for sampler 0, written straight into the ring (no bounds check).
unsafe fn sampler0(cache: usize, value: u32, state: u32) {
    unsafe {
        if rd(cache) != value {
            let w = rd(RING_WRITE) as usize;
            wd(cache, value);
            wd(w, 0x13);
            wd(w + 4, 0);
            wd(w + 8, state);
            wd(w + 12, value);
            wd(RING_WRITE, rd(RING_WRITE).wrapping_add(0x10));
        }
    }
}

