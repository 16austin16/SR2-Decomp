fn bump(c: C) {
    CNT[c as usize].fetch_add(1, Ordering::Relaxed);
}

// --- Helpers --------------------------------------------------------------------------------

const HANDLE_TABLE: usize = 0x0214_9C64;

unsafe fn rw(p: usize) -> u16 {
    *(p as *const u16)
}

/// The handle-table slot pointer for handle `h` (no validation).
unsafe fn slot(h: u32) -> usize {
    rd(HANDLE_TABLE + (((h & 0xFFF) << 4) as usize)) as usize
}

/// `fld dword` + `fstp dword`: an f32 round trip through the x87.
unsafe fn f32rt(p: usize) -> f32 {
    (rf(p) as f64) as f32
}


// --- zone_watchers_update (0xA93FF0) ----------------------------------------------------------

keep_ecx_edx!(zone_watchers_thunk, zone_watchers);

extern "C" fn zone_watchers() {
    unsafe {
        bump(C::ZwCalls);
        const G: usize = 0x0223_E95C; // list of watchers
        const MOVED: usize = 0x0223_E964; // list of members that left
        let mut edi = rd(G) as usize;
        if edi == 0 {
            return;
        }
        loop {
            let al = rb(edi + 0xC);
            let mut esi = rd(edi + 8) as usize;
            wb(edi + 0xD, al);
            wb(edi + 0xC, 1);
            if esi != 0 {
                while esi != 0 {
                    let eax = rd(esi);
                    wb(esi + 0x11, rb(esi + 0x10));
                    let ebp = if eax != rd(edi + 8) { eax as usize } else { 0 };
                    let r = call_regs(0x00A9_3BC0, 0, 0, 0, esi as u32, 0, &[]) as u8;
                    if r != 0 {
                        bump(C::ZwMoved);
                        let mut single = false;
                        if rd(edi + 8) as usize == esi {
                            let n = rd(esi);
                            if n as usize == esi {
                                wd(esi, 0);
                                wd(esi + 4, 0);
                                wd(edi + 8, 0);
                                single = true;
                            } else {
                                wd(edi + 8, n);
                            }
                        }
                        if !single {
                            let p = rd(esi + 4) as usize;
                            if p != 0 {
                                wd(p, rd(esi));
                            }
                            let n = rd(esi) as usize;
                            if n != 0 {
                                wd(n + 4, rd(esi + 4));
                            }
                            wd(esi, 0);
                            wd(esi + 4, 0);
                        }
                        let h = rd(MOVED) as usize;
                        if h == 0 {
                            wd(esi, esi as u32);
                            wd(esi + 4, esi as u32);
                            wd(MOVED, esi as u32);
                        } else {
                            let t = rd(h + 4);
                            wd(esi + 4, t);
                            wd(esi, h as u32);
                            let t2 = rd(h + 4) as usize;
                            wd(t2, esi as u32);
                            wd(h + 4, esi as u32);
                        }
                    } else {
                        bump(C::ZwStay);
                        let r2 = call_regs(0x00A9_3D30, esi as u32, 0, 0, 0, 0, &[]) as u8;
                        wb(esi + 0x10, r2);
                        wb(edi + 0xC, rb(edi + 0xC) & r2);
                    }
                    esi = ebp;
                }
                // a940bb: compare the new flag with the old one
                let cur = rb(edi + 0xC);
                let prev = rb(edi + 0xD);
                if cur != 0 {
                    if prev == 0 {
                        let f = rd(edi + 0x10) as usize;
                        if f != 0 {
                            bump(C::ZwEnter);
                            call_regs(f, 0, 0, 0, 0, 0, &[edi as u32]);
                        }
                    }
                } else if prev != 0 {
                    let f = rd(edi + 0x14) as usize;
                    if f != 0 {
                        bump(C::ZwLeave);
                        call_regs(f, 0, 0, 0, 0, 0, &[edi as u32]);
                    }
                } else {
                    let mut m = rd(edi + 8) as usize;
                    if m != 0 {
                        loop {
                            if rb(m + 0x10) != 0 && rb(m + 0x11) == 0 {
                                let f = rd(edi + 0x18) as usize;
                                if f != 0 {
                                    bump(C::ZwMember);
                                    call_regs(f, 0, 0, 0, 0, 0, &[m as u32]);
                                }
                            }
                            m = rd(m) as usize;
                            if m == rd(edi + 8) as usize || m == 0 {
                                break;
                            }
                        }
                    }
                }
            }
            edi = rd(edi) as usize;
            if edi == rd(G) as usize || edi == 0 {
                break;
            }
        }
    }
}

// --- persona_events_update (0x6ADB10) ---------------------------------------------------------

keep_ecx_edx!(persona_thunk, persona_events);

extern "C" fn persona_events() {
    unsafe {
        bump(C::PeCalls);
        const HEAD: usize = 0x0145_0404; // pending timers
        const DONE: usize = 0x0145_0400; // fired timers
        const NOW: usize = 0x00E8_43AC;
        call(0x006A_C5A0);
        call(0x00A5_6710);
        if rb(0x0252_7CCE) != 0 {
            let al = call_regs(0x00A5_7160, 0, 0, 0, 0, 0, &[rd(0x0217_03D4)]) as u8;
            if al == 0 {
                wb(0x0252_7CCE, al);
            }
        }
        let mut now = rd(NOW) as i32;
        let mut esi = rd(HEAD) as usize;
        while esi != 0 {
            let head = rd(HEAD);
            let nx = rd(esi + 0x14);
            let edi = if nx != head { nx as usize } else { 0 };
            let t = rd(esi + 0x10) as i32;
            if t < 0 || !time_due(t, now) {
                esi = edi;
                continue;
            }
            bump(C::PeTimers);
            let cl = rb(esi + 0xE) as u32;
            let fl = f32rt(esi + 8);
            let w = rw(esi + 0xC) as u32;
            call_regs(0x006A_E180, rd(esi), cl, w, esi as u32, edi as u32, &[rd(esi + 4), fl.to_bits(), w, cl]);
            // unlink from the pending list ...
            let mut skip = false;
            if rd(HEAD) as usize == esi {
                let n = rd(esi + 0x14);
                if n as usize == esi {
                    wd(esi + 0x14, 0);
                    wd(esi + 0x18, 0);
                    wd(HEAD, 0);
                    skip = true;
                } else {
                    wd(HEAD, n);
                }
            }
            if !skip {
                let p = rd(esi + 0x18) as usize;
                if p != 0 {
                    wd(p + 0x14, rd(esi + 0x14));
                }
                let n = rd(esi + 0x14) as usize;
                if n != 0 {
                    wd(n + 0x18, rd(esi + 0x18));
                }
                wd(esi + 0x14, 0);
                wd(esi + 0x18, 0);
            }
            // ... and append to the fired list
            let h = rd(DONE) as usize;
            if h == 0 {
                wd(esi + 0x14, esi as u32);
                wd(esi + 0x18, esi as u32);
                wd(DONE, esi as u32);
            } else {
                let tail = rd(h + 0x18);
                wd(esi + 0x18, tail);
                wd(esi + 0x14, h as u32);
                let tail2 = rd(h + 0x18) as usize;
                wd(tail2 + 0x14, esi as u32);
                wd(h + 0x18, esi as u32);
            }
            now = rd(NOW) as i32;
            esi = edi;
        }

        // Deferred calls keyed by a 16-bit id through a hash table.
        let mut esi = rd(0x027D_8724) as usize;
        let mut ebx = rd(0x0212_E258) as usize;
        while esi != 0 {
            let eax = rd(esi + 0x10);
            let ebp = if eax != rd(0x027D_8724) { eax as usize } else { 0 };
            let ax = rw(esi);
            if ax != 0xFFFF {
                let edi = ax as u32;
                let mut e = edi << 15;
                e = !e;
                e = e.wrapping_add(edi);
                let mut c = e;
                c = ((c as i32) >> 10) as u32;
                c ^= e;
                c = c.wrapping_add(c.wrapping_mul(8)); // lea ecx,[ecx+ecx*8]
                let d = ((c as i32) >> 6) as u32;
                c ^= d;
                let mut e2 = c << 11;
                e2 = !e2;
                c = c.wrapping_add(e2);
                let mut e3 = ((c as i32) >> 16) as u32;
                e3 ^= c;
                let rem: i32;
                std::arch::asm!(
                    "cdq",
                    "idiv dword ptr [{d}]",
                    d = in(reg) ebx + 0x60,
                    inout("eax") e3 => _,
                    out("edx") rem,
                );
                let tbl = rd(ebx + 0x5C);
                let mut node = rd(tbl.wrapping_add((rem as u32).wrapping_mul(4)) as usize) as usize;
                let mut found = false;
                while node != 0 {
                    if edi == rd(node + 0xC) {
                        found = true;
                        break;
                    }
                    node = rd(node + 4) as usize;
                }
                if found {
                    let n = rd(node) as usize;
                    if n != 0 {
                        let handle = rd(n + 4);
                        if handle != 0 {
                            bump(C::PeLookups);
                            let s = slot(handle);
                            let obj = if s != 0 && rd(s + 0x44) == handle && rd(s + 0x4C) == 1 { s as u32 } else { 0 };
                            let w8 = rw(esi + 8) as u32;
                            bump(C::PeDeferred);
                            call_regs(
                                0x006A_F190,
                                obj,
                                rd(esi + 4),
                                w8,
                                esi as u32,
                                edi,
                                &[obj, rd(esi + 4), w8, rd(esi + 0xC)],
                            );
                            call_regs(0x006B_0000, 0, 0, 0, esi as u32, 0x027D_8718, &[]);
                            ebx = rd(0x0212_E258) as usize;
                        }
                    }
                }
            }
            esi = ebp;
        }
    }
}

// --- nav_detours_update (0xA0AFF0) ------------------------------------------------------------

keep_ecx_edx!(nav_detours_thunk, nav_detours);

extern "C" fn nav_detours() {
    unsafe {
        bump(C::NdCalls);
        const H: usize = 0x021F_2C08;
        let mut cnt: i32 = 0;
        let mut edi = rd(H) as usize;
        loop {
            if edi == 0 {
                return;
            }
            let c = rd(edi);
            let next = if c != rd(H) { c as usize } else { 0 };
            let prior = cnt;
            cnt += 1;
            if prior > 0x96 {
                // Rotate the circular list so that this record becomes the head.
                bump(C::NdRotate);
                let eax = rd(H) as usize;
                if eax == 0 {
                    wd(H, 0);
                    return;
                }
                if eax != edi {
                    let edx = rd(edi + 4) as usize;
                    let ecx = rd(eax + 4);
                    wd(edx, eax as u32);
                    let edx2 = rd(edi + 4);
                    wd(eax + 4, edx2);
                    wd(edi + 4, ecx);
                    wd(ecx as usize, edi as u32);
                    let ecx2 = rd(edi + 4) as usize;
                    wd(ecx2, eax as u32);
                    let edx3 = rd(eax + 4) as usize;
                    wd(edx3, edi as u32);
                    let edx4 = rd(edi + 4);
                    let ecx3 = rd(eax + 4);
                    wd(eax + 4, edx4);
                    wd(edi + 4, ecx3);
                }
                wd(H, edi as u32);
                return;
            }
            let ty = rd(edi + 0x10) as i32;
            let valid = match ty {
                0 => {
                    let h = rd(edi + 0xC);
                    h != 0 && {
                        let s = slot(h);
                        s != 0 && rd(s + 0x44) == h
                    }
                }
                1 => {
                    let h = rd(edi + 0xC);
                    h != 0 && rd(0x02AE_50E0 + (h & 0xFFFF) as usize * 0x134 + 8) == h
                }
                2 => {
                    let h = rd(edi + 0xC);
                    h != 0 && rd(0x0267_4DE0 + (h & 0x1FF) as usize * 0x208 + 0x10) == h
                }
                _ => false,
            };
            if !valid {
                bump(C::NdInvalid);
                call_regs(0x00A0_E0C0, 0, rd(edi + 8), 0, 0, 0, &[]);
                edi = next;
                continue;
            }
            let mut out: u32 = 0;
            let al = call_regs(0x00A0_9B10, edi as u32, 0, 0, 0, 0, &[&mut out as *mut u32 as u32]) as u8;
            if al != 0 {
                bump(C::NdActive);
                if rd(edi + 0x18) != 0 {
                    let r = call_regs(0x00A0_9FE0, 0, 0, 0, edi as u32, 0, &[out]) as u8;
                    if r != 0 {
                        call_regs(0x00A0_AED0, 0, 0, 0, 0, edi as u32, &[]);
                        call_regs(0x00A0_A760, 0, 0, 0, 0, 0, &[edi as u32, out]);
                    }
                } else {
                    call_regs(0x00A0_A760, 0, 0, 0, 0, 0, &[edi as u32, out]);
                }
            } else {
                bump(C::NdInactive);
                if rd(edi + 0x18) != 0 {
                    let h = rd(edi + 0xC);
                    let mut ok = false;
                    if h != 0 {
                        let s = slot(h);
                        ok = s != 0 && rd(s + 0x44) == h && rd(s + 0x4C) == 1;
                    }
                    if ok {
                        call_regs(0x00A0_E1D0, 0, rd(edi + 8), 0, 0, 0, &[]);
                    } else {
                        call_regs(0x00A0_AED0, 0, 0, 0, 0, edi as u32, &[]);
                    }
                }
            }
            edi = next;
        }
    }
}

// --- vehicle_attached_effects_update (0x4D1D50) -----------------------------------------------

keep_ecx_edx!(vae_thunk, vehicle_attached_effects);

extern "C" fn vehicle_attached_effects() {
    unsafe {
        bump(C::VaCalls);
        const HA: usize = 0x00F9_991C;
        const HB: usize = 0x00F9_9920;
        let mut ebx = rd(HA) as usize;
        while ebx != 0 {
            let nx = rd(ebx + 8);
            let ebp = if nx != rd(HA) { nx as usize } else { 0 };
            let h1 = rd(ebx);
            let mut copy_from = 0usize; // the human (ESI in the original)
            if h1 != 0 {
                let s = slot(h1);
                if s != 0 && rd(s + 0x44) == h1 && rd(s + 0x4C) == 5 && (rd(s + 0x8C28) as i32) > 0 {
                    let r = call_regs(0x00AA_B5E0, s as u32, 0, 0, 0, 0, &[]) as u8;
                    if r == 0 {
                        let r2 = call_regs(0x00AA_B6B0, 0, 0, 0, 0, s as u32, &[]) as u8;
                        if r2 == 0 {
                            copy_from = s;
                        }
                    }
                }
            }
            if copy_from != 0 {
                bump(C::VaCopy);
                let esi = copy_from;
                let mut buf = [0u32; 3];
                call_regs(0x004D_1A50, buf.as_mut_ptr() as u32, 0, 0, esi as u32, 0, &[]);
                let h2 = rd(ebx + 4);
                if h2 != 0 {
                    let q = slot(h2);
                    if q != 0 && rd(q + 0x44) == h2 && rd(q + 0x4C) == 6 {
                        let list = rd(q + 0xC4) as usize;
                        if list != 0 {
                            let mut e = list;
                            loop {
                                wd(e + 0x2C, buf[0]);
                                wd(e + 0x30, buf[1]);
                                wd(e + 0x34, buf[2]);
                                let nxt = rd(e) as usize;
                                copy_dwords(e + 0x38, esi + 0x20, 9);
                                e = nxt;
                                if e == rd(q + 0xC4) as usize || e == 0 {
                                    break;
                                }
                            }
                        }
                    }
                }
                ebx = ebp;
                continue;
            }
            let c = rd(ebx + 4);
            if c != 0 {
                let s = slot(c);
                let obj = if s != 0 && rd(s + 0x44) == c && rd(s + 0x4C) == 6 { s as u32 } else { 0 };
                call_regs(0x0050_AB60, 0, 0, 0, 0, obj, &[0, 0]);
            }
            // Move the node from list A to the tail of list B.
            bump(C::VaMoved);
            let mut single = false;
            if rd(HA) as usize == ebx {
                let n = rd(ebx + 8);
                if n as usize == ebx {
                    wd(HA, 0);
                    single = true;
                } else {
                    wd(HA, n);
                }
            }
            if !single {
                let p = rd(ebx + 0xC) as usize;
                if p != 0 {
                    wd(p + 8, rd(ebx + 8));
                }
                let n = rd(ebx + 8) as usize;
                if n != 0 {
                    wd(n + 0xC, rd(ebx + 0xC));
                }
            }
            wd(ebx + 0xC, 0);
            wd(ebx + 8, 0);
            let b = rd(HB) as usize;
            if b == 0 {
                wd(ebx + 8, ebx as u32);
                wd(ebx + 0xC, ebx as u32);
                wd(HB, ebx as u32);
            } else {
                let t = rd(b + 0xC);
                wd(ebx + 0xC, t);
                wd(ebx + 8, b as u32);
                let e = rd(b + 0xC) as usize;
                wd(e + 8, ebx as u32);
                wd(b + 0xC, ebx as u32);
            }
            ebx = ebp;
        }
    }
}

// --- ai_scheduled_tasks_tick (0x452820) -------------------------------------------------------

keep_ecx_edx!(tasks_tick_thunk, tasks_tick);

extern "C" fn tasks_tick() {
    unsafe {
        bump(C::TkCalls);
        const H: usize = 0x00EE_2C0C;
        let esi0 = rd(H) as usize;
        if esi0 != 0 {
            let now = rd(0x00E8_43AC) as i32;
            let mut eax = esi0;
            loop {
                let t = rd(eax + 0x14) as i32;
                if t >= 0 && time_due(t, now) {
                    bump(C::TkFire);
                    let cnt = (rd(eax + 0x10) as i32).wrapping_sub(1);
                    wd(eax + 0x10, cnt as u32);
                    if cnt > 0 {
                        let mut ecx = now.wrapping_add(0x29A);
                        wd(eax + 0x14, ecx as u32);
                        if ecx > 0x6B49_D200 {
                            ecx = ecx.wrapping_add(0x94B6_2E00u32 as i32);
                            wd(eax + 0x14, ecx as u32);
                        }
                    } else {
                        wd(eax + 0x14, 0xFFFF_FFFF);
                    }
                }
                eax = rd(eax) as usize;
                if eax == esi0 || eax == 0 {
                    break;
                }
            }
        }
        // Re-bucket the list by [node+0x10] and concatenate the buckets in order.
        let mut b = [0usize; 4];
        let mut esi = rd(H) as usize;
        while esi != 0 {
            let eax = esi;
            let edi = rd(esi) as usize;
            if edi == esi {
                wd(esi, 0);
                esi = 0;
            } else {
                let prev = rd(eax + 4) as usize;
                esi = edi;
                if prev != 0 {
                    wd(prev, edi as u32);
                }
                let nxt = rd(eax) as usize;
                if nxt != 0 {
                    wd(nxt + 4, rd(eax + 4));
                }
                wd(eax, 0);
            }
            let mut idx = rd(eax + 0x10) as usize;
            if idx > 3 {
                bump(C::TkOob);
                idx = 3;
            }
            let head = b[idx];
            wd(eax + 4, 0);
            if head == 0 {
                wd(eax, eax as u32);
                wd(eax + 4, eax as u32);
                b[idx] = eax;
            } else {
                let hp = rd(head + 4);
                wd(eax + 4, hp);
                wd(eax, head as u32);
                let hp2 = rd(head + 4) as usize;
                wd(hp2, eax as u32);
                wd(head + 4, eax as u32);
            }
        }
        // Concatenate b[0], b[1], b[2], b[3].
        let splice = |a: usize, c: usize| {
            let at = rd(a + 4) as usize;
            wd(at, c as u32);
            let ct = rd(c + 4) as usize;
            wd(ct, a as u32);
            let at2 = rd(c + 4);
            let ct2 = rd(a + 4);
            wd(c + 4, ct2);
            wd(a + 4, at2);
        };
        let mut r = b[0];
        for k in 1..4 {
            if r == 0 {
                r = b[k];
            } else if b[k] != 0 {
                splice(r, b[k]);
            }
        }
        wd(H, r as u32);
    }
}

