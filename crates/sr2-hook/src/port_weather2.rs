    /// Run `orig` and `rust` from the same memory state over `regions`; the outputs must agree.
    unsafe fn same(regions: &[(usize, usize)], what: &str, i: u32, orig: impl FnOnce() -> u64, rust: impl FnOnce() -> u64) {
        let keep = snap(regions);
        let eo = orig();
        let theirs = snap(regions);
        restore(regions, &keep);
        let er = rust();
        let ours = snap(regions);
        if ours != theirs || eo != er {
            let at = (0..ours.len()).find(|&k| ours[k] != theirs[k]);
            let w = |v: &Vec<u8>, k: usize| u32::from_le_bytes([v[k], v[k + 1], v[k + 2], v[k + 3]]);
            let msg = at.map(|k| { let k = k & !3; format!("dword {:#x}: original {:#x} ({}) Rust {:#x} ({})", k, w(&theirs, k), f32::from_bits(w(&theirs, k)), w(&ours, k), f32::from_bits(w(&ours, k))) });
            panic!("{what} case {i}: result original {eo:#x} Rust {er:#x}; first memory difference at snapshot byte {at:?}: {msg:?}");
        }
    }

