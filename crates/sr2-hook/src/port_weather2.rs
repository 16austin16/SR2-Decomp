    /// (state, signalling NaNs allowed, mode: 0 any value, 1 finite only, 2 NaN but no infinities)
    pub struct Rng(pub u64, pub bool, pub u8);
    impl Rng {
        pub fn u32(&mut self) -> u32 {
            self.0 ^= self.0 << 13;
            self.0 ^= self.0 >> 7;
            self.0 ^= self.0 << 17;
            (self.0 >> 16) as u32
        }
        pub fn below(&mut self, n: u32) -> u32 {
            self.u32() % n
        }
        /// A float bit pattern: mostly ordinary values in +-scale, some special ones.
        pub fn fl(&mut self, scale: f32) -> u32 {
            let k = self.below(40);
            if self.2 == 1 && matches!(k, 0 | 1 | 2 | 5) {
                // finite-only mode (x87 and SSE disagree on which NaN payload survives)
                return ((self.below(2001) as f32 - 1000.0) / 100.0 * scale).to_bits();
            }
            match k {
                0 => 0x7FC0_0000,
                1 => if self.1 { 0x7F80_0001 } else { 0x7FC0_0000 }, // signalling NaN only where values are copied
                2 => if self.2 == 2 { 0x7FC0_0000 } else { 0xFF80_0000 },
                3 => 0x8000_0000,
                4 => 0,
                5 => { let v = self.u32(); if v & 0x7F80_0000 == 0x7F80_0000 && (v & 0x7F_FFFF != 0 || self.2 == 2) { 0x7FC0_0000 } else { v } }
                6 => 1.0f32.to_bits(),
                7 | 8 => ((self.below(21) as f32 - 10.0) * scale / 10.0).to_bits(),
                _ => ((self.below(20001) as f32 - 10000.0) / 10000.0 * scale).to_bits(),
            }
        }
        pub fn unit(&mut self) -> f32 {
            (self.u32() % 1_000_001) as f32 / 1_000_000.0
        }
    }

