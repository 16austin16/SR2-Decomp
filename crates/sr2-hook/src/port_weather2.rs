/// 0x4D4480: shadowed on its returned ST0.
extern "C" fn approach_checked(cur: u32, target: u32) -> f64 {
    unsafe {
        let Some((n, orig)) = shadowing(APPROACH) else { return approach_rust(cur, target) };
        let theirs = call_regs_st0(orig, 0, 0, 0, 0, 0, &[cur, target]);
        let ours = approach_rust(cur, target);
        if ours.to_bits() != theirs.to_bits() && !(ours.is_nan() && theirs.is_nan()) {
            mismatch(APPROACH, n, format!("({cur:#x}, {target:#x}): original {theirs}, Rust {ours}"));
            return theirs;
        }
        ours
    }
}
