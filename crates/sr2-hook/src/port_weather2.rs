/// `pow(base, exp)` through the CRT's x87 routine 0xCA05D0 (st1 ^ st0), both operands f32 values.
unsafe fn crt_pow(base: f32, exp: f32) -> f64 {
    let mut out = 0f64;
    unsafe {
        std::arch::asm!(
            "fld dword ptr [{b}]",
            "fld dword ptr [{e}]",
            "call {f}",
            "fstp qword ptr [edi]",
            b = in(reg) &base,
            e = in(reg) &exp,
            f = in(reg) 0x00CA_05D0usize,
            in("edi") &mut out as *mut f64,
            clobber_abi("C"),
        );
    }
    out
}

/// One of the sky / sun objects (0x2526DAC / 0x2526DB0): its flag word is set, its controller
/// (0x9FA700, 0x9F8570) is fed, and the virtual method at slot 13 gets the new value.
unsafe fn sky_object_update(obj: usize, a: u32, b: u32) {
    unsafe {
        let ctl = rd(obj + 0x190) as usize;
        let w = (*((ctl + 0xA) as *const u16) & 0xFFFD) | 1;
        *((ctl + 0xA) as *mut u16) = w;
        call_regs(0x009F_A700, 0, rd(obj + 0x44), 0, 0, 0, &[]);
        call_regs(0x009F_8570, 0, rd(obj + 0x190), 0, 0, 0, &[q32(a)]);
        wb(obj + 0x199, rb(obj + 0x199) | 1);
        wd(obj + 0x158, rd(0x025F_5B14));
        wd(obj + 0x15C, rd(0x025F_5B18));
        wd(obj + 0x160, rd(0x025F_5B1C));
        let f = rd(rd(obj) as usize + 0x34) as usize;
        call_regs(f, 0, obj as u32, 0, 0, 0, &[q32(b)]);
    }
}

/// The tail of an object block: the placed object `dst` (0x2526DB4 / 0x2526DB8) gets the sun / moon
/// position (0x4D63E0 for `src`) and the sky entry for the keyframe's index.
unsafe fn sky_place(dst_addr: usize, src: u32, out: *mut u32, idx_field: usize) {
    unsafe {
        let dst = rd(dst_addr) as usize;
        let r = call_regs(0x004D_63E0, src, 0, 0, out as u32, 0, &[]) as usize;
        wd(dst + 0xC, rd(r));
        wd(dst + 0x10, rd(r + 4));
        wd(dst + 0x14, rd(r + 8));
        let e = rd(idx_field);
        if e as i32 != -1 {
            let entry = call_regs(0x004C_74E0, e, 0, 0, 0, 0, &[]);
            let d = rd(dst_addr) as usize;
            wd(d + 8, entry);
            let d = rd(dst_addr) as usize;
            cpq(d + 0x58, 0x00DD_0550);
        } else {
            let d = rd(dst_addr) as usize;
            wd(d + 0x58, 0);
        }
    }
}

/// 0x4D7160 sky_update (no args, game_render_func step 3 on the render thread): when the level's
/// sky state (0xE96B7C -> table 0x144E760) is 5, blends the two active time-of-day keyframes into
