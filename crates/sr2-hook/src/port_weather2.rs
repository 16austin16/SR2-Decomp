//! Port module: render-thread and game-thread weather / time-of-day / lighting functions that
//! `port_weather.rs` leaves in the original code (doc 52b). Hand-written Rust; the x87 runs at
//! 53-bit precision in the game, so every operation that stays on the x87 stack is an f64
//! operation here and every `fstp dword` is an `as f32`.
//!
//! Threads: the ambient-colour getters, `sky_render_params_update` and the other render-pass
//! functions run on the render thread, the zone fades and the override-target setter on the game
//! thread. The module keeps no state of its own besides the call counters (atomics).

#![allow(unused_imports)]

use std::sync::atomic::{AtomicU32, AtomicUsize, Ordering};

use crate::portlib::*;
use crate::{detour, log};

const SHADOW_CALLS: u32 = 3000;

// --- helpers ---------------------------------------------------------------------------------------

/// A `fld dword` / `fstp dword` round trip of a 32-bit pattern: the bits, except that a
/// signalling NaN is quieted.
fn q32(bits: u32) -> u32 {
    if bits & 0x7F80_0000 == 0x7F80_0000 && bits & 0x007F_FFFF != 0 { bits | 0x0040_0000 } else { bits }
}

/// An f32 in memory loaded onto the x87 stack.
unsafe fn ld(a: usize) -> f64 {
    unsafe { f32::from_bits(rd(a)) as f64 }
}

/// A double constant in the exe.
unsafe fn ld64(a: usize) -> f64 {
    unsafe { f64::from_bits(rd(a) as u64 | (rd(a + 4) as u64) << 32) }
}

/// `fstp dword` of an x87 value.
unsafe fn st(a: usize, v: f64) {
    unsafe { wd(a, (v as f32).to_bits()) }
}

/// `fld dword` + `fstp dword` between two addresses (a signalling NaN comes out quieted).
unsafe fn cpq(dst: usize, src: usize) {
    unsafe { wd(dst, q32(rd(src))) }
}

/// `fcom` then `test ah, 5` / `jp`: taken when ST0 >= operand or unordered.
fn jp5(a: f64, b: f64) -> bool {
    !(a < b)
}

/// `call_regs` for a callee that returns on the x87 stack (popped as a qword).
unsafe fn call_regs_st0(f: usize, eax: u32, ecx: u32, edx: u32, esi: u32, edi: u32, args: &[u32]) -> f64 {
    let mut out = 0f64;
    let block: [u32; 9] =
        [f as u32, ecx, edx, esi, edi, args.as_ptr() as u32, args.len() as u32, eax, &mut out as *mut f64 as u32];
    unsafe {
        std::arch::asm!(
            "push ebx", "push esi", "push edi", "push ebp",
            "mov ebp, esp",
            "mov ebx, eax",
            "mov ecx, [ebx + 24]",
            "mov esi, [ebx + 20]",
            "2:",
            "test ecx, ecx",
            "jz 3f",
            "push dword ptr [esi + ecx*4 - 4]",
            "dec ecx",
            "jmp 2b",
            "3:",
            "mov ecx, [ebx + 4]", "mov edx, [ebx + 8]", "mov esi, [ebx + 12]", "mov edi, [ebx + 16]",
            "mov eax, [ebx + 28]",
            "call dword ptr [ebx]",
            "mov ecx, [ebx + 32]",
            "fstp qword ptr [ecx]",
            "mov esp, ebp",
            "pop ebp", "pop edi", "pop esi", "pop ebx",
            inout("eax") block.as_ptr() => _, lateout("ecx") _, lateout("edx") _,
            clobber_abi("C"),
        );
    }
    out
}

#[derive(Clone, Copy)]
#[allow(dead_code)]
#[repr(C)]
struct Pushad {
    edi: u32,
    esi: u32,
    ebp: u32,
    esp: u32,
    ebx: u32,
    edx: u32,
    ecx: u32,
    eax: u32,
}

/// A naked thunk: `pushad`, then `f(&mut block, &stack args)`, then `popad` (every register comes
/// back as the caller left it, except what `f` sets in the block), then the given return.
macro_rules! regs_thunk {
    ($name:ident, $f:ident, $ret:literal) => {
        #[unsafe(naked)]
        extern "C" fn $name() {
            std::arch::naked_asm!(
                "pushad",
                "sub esp, 128",
                "movups [esp], xmm0",
                "movups [esp + 16], xmm1",
                "movups [esp + 32], xmm2",
                "movups [esp + 48], xmm3",
                "movups [esp + 64], xmm4",
                "movups [esp + 80], xmm5",
                "movups [esp + 96], xmm6",
                "movups [esp + 112], xmm7",
                "lea eax, [esp + 128]",
                "lea ecx, [esp + 164]",
                "push ecx",
                "push eax",
                "call {f}",
                "add esp, 8",
                "movups xmm0, [esp]",
                "movups xmm1, [esp + 16]",
                "movups xmm2, [esp + 32]",
                "movups xmm3, [esp + 48]",
                "movups xmm4, [esp + 64]",
                "movups xmm5, [esp + 80]",
                "movups xmm6, [esp + 96]",
                "movups xmm7, [esp + 112]",
                "add esp, 128",
                "popad",
                $ret,
                f = sym $f,
            )
        }
    };
}

// --- the port table and its shadow bookkeeping -------------------------------------------------

struct Port {
    name: &'static str,
    addr: usize,
    calls: AtomicU32,
    mismatches: AtomicU32,
    original: AtomicUsize,
}

const fn port(name: &'static str, addr: usize) -> Port {
    Port { name, addr, calls: AtomicU32::new(0), mismatches: AtomicU32::new(0), original: AtomicUsize::new(0) }
}

/// Count a call; `Some((call number, original copy))` while it should be shadowed.
fn shadowing(id: usize) -> Option<(u32, usize)> {
    let p = &PORTS[id];
    let n = p.calls.fetch_add(1, Ordering::Relaxed);
    let orig = p.original.load(Ordering::Relaxed);
    if n == SHADOW_CALLS && orig != 0 {
        log(&format!("port_weather2: {}: {SHADOW_CALLS} calls shadowed, {} mismatched", p.name, p.mismatches.load(Ordering::Relaxed)));
    }
    (orig != 0 && n < SHADOW_CALLS).then_some((n, orig))
}

fn mismatch(id: usize, n: u32, what: String) {
    let m = PORTS[id].mismatches.fetch_add(1, Ordering::Relaxed) + 1;
    if m <= 10 {
        log(&format!("port_weather2: {} mismatch (call {n}): {what}", PORTS[id].name));
    }
}

fn snap(regions: &[(usize, usize)]) -> Vec<u8> {
    let mut v = Vec::new();
    for &(a, l) in regions {
        v.extend_from_slice(unsafe { std::slice::from_raw_parts(a as *const u8, l) });
    }
    v
}

fn restore(regions: &[(usize, usize)], bytes: &[u8]) {
    let mut o = 0;
    for &(a, l) in regions {
        unsafe { std::ptr::copy_nonoverlapping(bytes[o..].as_ptr(), a as *mut u8, l) };
        o += l;
    }
}

type RustFn = unsafe fn(&mut Pushad, *const u32);

/// Run a port: while shadowed, the relocated original runs first on the real memory (its writes
/// are saved and undone), then the Rust body; the written `regions` (and EAX when `cmp_eax`) are
/// compared and the original's results are kept on a mismatch. Snapshot shadow.
unsafe fn shadowed(id: usize, r: &mut Pushad, a: *const u32, nargs: usize, regions: &[(usize, usize)], cmp_eax: bool, rust: RustFn) {
    unsafe {
        let Some((n, orig)) = shadowing(id) else {
            rust(r, a);
            return;
        };
        let args: Vec<u32> = (0..nargs).map(|i| *a.add(i)).collect();
        let keep = snap(regions);
        let eo = call_regs(orig, r.eax, r.ecx, r.edx, r.esi, r.edi, &args);
        let theirs = snap(regions);
        restore(regions, &keep);
        let mut r2 = *r;
        rust(&mut r2, a);
        let ours = snap(regions);
        if ours != theirs || (cmp_eax && r2.eax != eo) {
            mismatch(id, n, format!("regs {:x?}: original eax {eo:#x}, Rust {:#x}; outputs differ: {}", [r.eax, r.ecx, r.edx, r.esi, r.edi], r2.eax, ours != theirs));
            restore(regions, &theirs);
            r2.eax = eo;
        }
        *r = r2;
    }
}

