const DT: usize = 0x00E8_437C; // frame time in seconds (f32)

/// 0x4B4E80 tod_zone_fade_start_f32 (ECX = zone record, EDX = &target f32). Re-bases `from` to the
/// current blend when the weight is positive, makes `target` the new target and restarts the blend.
unsafe fn fade_start_f32(rec: usize, target: usize) {
    unsafe {
        if jp5(0.0, ld(rec + 0x10)) {
            cpq(rec, target);
            wb(rec + 0xC, 1);
            wd(rec + 8, 1.0f32.to_bits());
        } else {
            let (x, from, t) = (ld(rec), ld(rec + 4), ld(rec + 8));
            st(rec + 4, (x - from) * t + from);
            cpq(rec, target);
            wb(rec + 0xC, 1);
            wd(rec + 8, 0.0f32.to_bits());
        }
    }
}

/// The weight / blend-factor step shared by the f32 (0x4B4EF0) and vec3 (0x4B5110) zone records:
/// `act` the active byte, `w` the weight, `dur` the duration, `t` the blend factor.
unsafe fn fade_step(rec: usize, animate: u32, act: usize, w: usize, dur: usize, t: usize) {
    unsafe {
        let active = rb(rec + act) != 0;
        if animate as u8 == 0 {
            wd(rec + t, 1.0f32.to_bits());
            wd(rec + w, if active { 1.0f32 } else { 0.0f32 }.to_bits());
            return;
        }
        let d = (ld(DT) / ld(rec + dur)) as f32 as f64;
        let wm = ld(rec + w);
        let wn = if active {
            let v = (wm + d) as f32;
            wd(rec + w, v.to_bits());
            if jp5(v as f64, 1.0) { 1.0f32 } else { v }
        } else {
            let v = (wm - d) as f32;
            wd(rec + w, v.to_bits());
            if jp5(0.0, v as f64) { 0.0f32 } else { v }
        };
        wd(rec + w, wn.to_bits());
        let tn = (d + ld(rec + t)) as f32;
        wd(rec + t, tn.to_bits());
        wd(rec + t, if jp5(tn as f64, 1.0) { 1.0f32 } else { tn }.to_bits());
    }
}

/// 0x4B5050 tod_zone_fade_start_vec3 (ECX = zone record, EDX = &target vec3).
unsafe fn fade_start_vec3(rec: usize, target: usize) {
    unsafe {
        let tnew = if jp5(0.0, ld(rec + 0x20)) {
            1.0f32
        } else {
            let d0 = (ld(rec) - ld(rec + 0xC)) as f32 as f64;
            let d1 = (ld(rec + 4) - ld(rec + 0x10)) as f32 as f64;
            let d2 = (ld(rec + 8) - ld(rec + 0x14)) as f32 as f64;
            let t = ld(rec + 0x18);
            let p0 = (d0 * t) as f32 as f64;
            let p1 = (d1 * t) as f32 as f64;
            let p2 = (t * d2) as f32 as f64;
            st(rec + 0xC, p0 + ld(rec + 0xC));
            st(rec + 0x10, ld(rec + 0x10) + p1);
            st(rec + 0x14, ld(rec + 0x14) + p2);
            0.0f32
        };
        wd(rec, rd(target));
        wd(rec + 4, rd(target + 4));
        let z = rd(target + 8);
        wd(rec + 0x18, tnew.to_bits());
        wb(rec + 0x1C, 1);
        wd(rec + 8, z);
    }
}

/// 0x4D4480 ambient_override_approach (cdecl: current, target) -> ST0: moves `current` towards
/// `target` by the frame time times a rate (faster below a threshold when rising), never past it.
unsafe fn approach_rust(cur: u32, target: u32) -> f64 {
    unsafe {
        let cur = f32::from_bits(cur) as f64;
        let tgt = f32::from_bits(target) as f64;
        let dt = ld(DT);
        if !(tgt > cur) {
            // target <= current or unordered: fall by dt * (double constant)
            let nc = (cur - dt * ld64(0x00E5_BF70)) as f32;
            if (nc as f64) < tgt { tgt } else { nc as f64 }
        } else {
            let mut s = rf(0x00DD_1C8C);
            if ld(0x00DD_1B58) > cur {
                s = ((ld64(0x00E5_C370) - cur) + ld64(0x00E5_BF70)) as f32;
            }
            let nc = (cur + dt * s as f64) as f32;
            if !(nc as f64 > tgt) { nc as f64 } else { tgt }
        }
    }
}

/// 0x4D63E0 sun_world_position (EAX = sky object or 0, ESI = out vec3) -> EAX = ESI: the camera
/// position plus the sun direction (0, length, 0) turned by the object's matrix (+0x20).
unsafe fn sun_world_position(obj: u32, out: usize) {
    unsafe {
        let (cx, cy, cz) = (ld(0x025F_5B14), ld(0x025F_5B18), ld(0x025F_5B1C));
        if obj != 0 {
            let v: [u32; 3] = [0, q32(rd(0x00E9_8FFC)), 0];
            let mut o = [0u32; 3];
            let p = call_regs(0x0040_6810, 0, obj + 0x20, v.as_ptr() as u32, out as u32, 0, &[o.as_mut_ptr() as u32]) as usize;
            st(out, ld(p) + cx);
            st(out + 4, ld(p + 4) + cy);
            st(out + 8, ld(p + 8) + cz);
        } else {
            st(out, cx + 0.0);
            st(out + 4, cy + ld64(0x00E5_CC70));
            st(out + 8, 0.0 + cz);
        }
    }
}

/// The four ambient-colour getters (EAX = out vec3): a debug mode (0x0E98948) of 0 gives white, 1
/// the console override, otherwise the computed colour. Values pass through the x87 (quieted).
unsafe fn ambient_get(out: usize, ovr: usize, comp: usize) {
    unsafe {
        let src = match rd(0x00E9_8948) {
            0 => {
                for i in 0..3 {
                    wd(out + 4 * i, 1.0f32.to_bits());
                }
                return;
            }
            1 => ovr,
            _ => comp,
        };
        for i in 0..3 {
            cpq(out + 4 * i, src + 4 * i);
        }
    }
}

/// 0x4D8FD0 ambient_color_get_slot3 (EAX, ECX = out vec3s; cdecl a0..a4): the fourth ambient slot
/// (mode as above, raw dword copies) and the next computed values.
unsafe fn ambient_slot3(r: &Pushad, a: *const u32) {
    unsafe {
        let (a0, a1, a2, a3, a4) = (*a as usize, *a.add(1) as usize, *a.add(2) as usize, *a.add(3) as usize, *a.add(4) as usize);
        match rd(0x00E9_8948) {
            0 => {
                for i in 0..3 {
                    wd(a0 + 4 * i, 1.0f32.to_bits());
                }
            }
            1 => {
                for i in 0..3 {
                    wd(a0 + 4 * i, rd(0x00E9_D3F0 + 4 * i));
                }
            }
            _ => {
                for i in 0..3 {
                    wd(a0 + 4 * i, rd(0x0265_8E0C + 4 * i));
                }
            }
        }
        for i in 0..3 {
            wd(a1 + 4 * i, rd(0x0265_8E24 + 4 * i));
        }
        for i in 0..3 {
            wd(a2 + 4 * i, rd(0x0265_8E30 + 4 * i));
        }
        for i in 0..3 {
            wd(r.ecx as usize + 4 * i, rd(0x0265_8E3C + 4 * i));
        }
        for i in 0..3 {
            wd(r.eax as usize + 4 * i, rd(0x0265_8E48 + 4 * i));
        }
        cpq(a3, 0x0265_8E54);
        cpq(a4, 0x0265_8E58);
    }
}

/// 0x4DF030 sky_weather_params_gather (EAX, ECX and arg0 = out vec3s): copies the weather results
/// 0x2659828.. out and has 0x4E3230 blend them in place.
unsafe fn params_gather(r: &Pushad, a: *const u32) -> u32 {
    unsafe {
        let (o1, o3, o2) = (r.eax as usize, r.ecx as usize, *a as usize);
        for i in 0..3 {
            wd(o1 + 4 * i, rd(0x0265_9828 + 4 * i));
        }
        for i in 0..3 {
            wd(o2 + 4 * i, rd(0x0265_9834 + 4 * i));
        }
        for i in 0..3 {
            wd(o3 + 4 * i, rd(0x0265_9840 + 4 * i));
        }
        call_regs(0x004E_3230, o1 as u32, o3 as u32, rd(0x0265_9848), r.esi, o2 as u32, &[o3 as u32])
    }
}

/// 0x4D4560 tod_ambient_override_targets_set (cdecl f32): the 15 target floats 0xE9D408.. all get
/// the argument.
unsafe fn override_targets_set(v: u32) {
    unsafe {
        let v = q32(v);
        for i in 0..15 {
            wd(0x00E9_D408 + 4 * i, v);
        }
    }
}

// --- 0x4D7E20 sky_render_params_update ------------------------------------------------------------------

/// The time-of-day keyframe array (0x250-byte records); the blend uses the two records picked by
/// 0xF9E2F4 / 0xF9E2F8 and the factor 0xF9E2F0.
const KEYFRAMES: usize = 0x0265_4200;

/// One of the four colour groups of the sky block: the vec3 at `fb` in both keyframes is blended
/// (`l`); when either keyframe has the group's override flag the override colours (`ovr`) are
/// blended as well and mixed in by a pulse `0.5 + 0.5 sin(bl * ka + kb)` (`bl` is the byte
/// 0x140E72B, the constants are doubles in the exe).
unsafe fn sky_color_group(k1: usize, k2: usize, fb: usize, flag: usize, ovr: usize, ka: usize, kb: usize, bl: f64, t: f64) -> ([u32; 3], bool) {
    unsafe {
        let mut l = [0f32; 3];
        for i in 0..3 {
            let a = ld(k1 + fb + 4 * i);
            let d = (ld(k2 + fb + 4 * i) - a) as f32 as f64;
            let m = (d * t) as f32 as f64;
            l[i] = (m + a) as f32;
        }
        let (f1, f2) = (rb(k1 + flag) != 0, rb(k2 + flag) != 0);
        if !(f1 || f2) {
            return ([l[0].to_bits(), l[1].to_bits(), l[2].to_bits()], false);
        }
        let mut r = [0f32; 3];
        for i in 0..3 {
            let po = if f1 { k1 + ovr } else { k1 + fb };
            let qo = if f2 { k2 + ovr } else { k2 + fb };
            let p = f32::from_bits(rd(po + 4 * i)) as f64;
            let q = f32::from_bits(rd(qo + 4 * i)) as f64;
            let e = (q - p) as f32 as f64;
            let m = (e * t) as f32 as f64;
            r[i] = (p + m) as f32;
        }
        let a = (bl * ld64(ka) + ld64(kb)) as f32;
        let s = call_regs_st0(0x0042_8CD0, 0, 0, 0, 0, 0, &[a.to_bits()]);
        let c = ld64(0x00E5_BF70);
        let g = (s * c + c) as f32 as f64;
        let mut w = [0u32; 3];
        for i in 0..3 {
            let u = (r[i] as f64 - l[i] as f64) as f32 as f64;
            let v = (u * g) as f32 as f64;
            w[i] = ((l[i] as f64 + v) as f32).to_bits();
        }
        (w, true)
    }
}

/// A scalar blended in one x87 chain: `(k2 - k1) * t + k1`, rounded once.
unsafe fn sky_lerp1(k1: usize, k2: usize, off: usize, t: f64) -> u32 {
    unsafe {
        let a = ld(k1 + off);
        ((((ld(k2 + off) - a) * t) + a) as f32).to_bits()
    }
}

/// A vec3 blended with f32 intermediates: the difference, the scaled difference, the sum.
unsafe fn sky_lerp3(k1: usize, k2: usize, off: usize, t: f64) -> [u32; 3] {
    unsafe {
        let mut o = [0u32; 3];
        for i in 0..3 {
            let a = ld(k1 + off + 4 * i);
            let d = (ld(k2 + off + 4 * i) - a) as f32 as f64;
            let m = (d * t) as f32 as f64;
            o[i] = ((m + a) as f32).to_bits();
        }
        o
    }
}

/// 0x4D7E20 sky_render_params_update (no args, render_stage1): blends the two active time-of-day
/// keyframes into the 30-dword sky block, pulses four colour groups when their override flags are
/// set, lets the weather blender 0x4DF0C0 mix in the weather record, publishes its first three
/// dwords at 0x2658CF0 and sets up the skybox (0x4D6330).
unsafe fn sky_render_params_update() {
    unsafe {
        let k1 = KEYFRAMES.wrapping_add((rd(0x00F9_E2F8) as usize).wrapping_mul(0x250));
        let k2 = KEYFRAMES.wrapping_add((rd(0x00F9_E2F4) as usize).wrapping_mul(0x250));
        let mut t = ld(0x00F9_E2F0);
        let mut a = [0u32; 30];
        let mut b = [0u32; 30];
        let bl = rb(0x0140_E72B) as f64;
        let groups: [(usize, usize, usize, usize, usize); 4] = [
            (0x14, 0x74, 0x44, 0x00E5_D238, 0x00E5_C408),
            (0x20, 0x75, 0x50, 0x00E5_D230, 0x00E5_C9E0),
            (0x2C, 0x76, 0x5C, 0x00E5_D228, 0x00E5_CDC0),
            (0x38, 0x77, 0x68, 0x00E5_D220, 0x00DD_50E8),
        ];
        for (n, &(fb, flag, ovr, ka, kb)) in groups.iter().enumerate() {
            let (w, overridden) = sky_color_group(k1, k2, fb, flag, ovr, ka, kb, bl, t);
            a[3 * n..3 * n + 3].copy_from_slice(&w);
            if overridden {
                // the original reloads the blend factor after an override block used it up
                t = ld(0x00F9_E2F0);
            }
        }
        for (i, off) in [(12, 0x78), (13, 0x7C), (14, 0x80), (15, 0x84), (18, 0x94), (19, 0x9C), (16, 0x98), (17, 0xA0)] {
            a[i] = sky_lerp1(k1, k2, off, t);
        }
        for (i, off) in [(20, 0x88), (23, 0xA4), (26, 0xB0)] {
            let o = sky_lerp3(k1, k2, off, t);
            a[i..i + 3].copy_from_slice(&o);
        }
        a[29] = sky_lerp1(k1, k2, 0xBC, t);
        call_regs(0x004D_F0C0, a.as_ptr() as u32, b.as_mut_ptr() as u32, 0, k1 as u32, k2 as u32, &[]);
        wd(0x0265_8CF0, b[0]);
        wd(0x0265_8CF4, b[1]);
        wd(0x0265_8CF8, b[2]);
        let flag = rb(0x0252_6DC6) as u32;
        call_regs(0x004D_6330, rd(0x00F5_BB6C), flag, b.as_mut_ptr() as u32, k1 as u32, k2 as u32, &[0x00F6_EC10, rd(0x00F5_BB6C), b.as_mut_ptr() as u32, flag]);
    }
}

