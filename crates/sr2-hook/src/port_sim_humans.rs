/// The session gate with values already read: no session, or (b56 clear or b2b set) and S+0x3F8.
unsafe fn mf_gate(s: u32, b56: u8, b2b: u8) -> bool {
    unsafe { s == 0 || ((b56 == 0 || b2b != 0) && rb(s as usize + 0x3F8) != 0) }
}

/// The gate reading the globals now (S first, then the flags).
unsafe fn mf_gate_live() -> bool {
    unsafe {
        let s = rd(0x0252_8C14);
        if s == 0 {
            return true;
        }
        mf_gate(s, rb(0x0252_8B56), rb(0x0252_8B2B))
    }
}

