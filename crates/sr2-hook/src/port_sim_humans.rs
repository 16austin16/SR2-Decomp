unsafe fn mission_fail_body() {
    unsafe {
        if (rb(0x0252_7BD2) == 1 && rb(0x0252_7BD3) != 0) || rb(0x0252_7BDB) != 0 {
            call(0x0069_6120);
        }
        // Read once; case 3 tests these register copies again (the callees in between keep them).
        let s = rd(0x0252_8C14);
        let b56 = rb(0x0252_8B56);
        let b2b = rb(0x0252_8B2B);
        if !mf_gate(s, b56, b2b) {
            return;
        }
        match rd(0x0145_0380) {
            0 => {
                call_regs(0x006A_17B0, 0, 0, s, 0, 0, &[0]);
                call(0x006A_18A0);
                call(0x0083_2970);
            }
            1 => call(0x004C_46F0),
            2 => mf_case2(),
            3 => mf_case3(s, b56, b2b),
            4 => mf_case4(),
            6 => mf_case6(),
            7 => {
                if mf_fade_out_step() {
                    call(0x009F_2100);
                    call(0x009D_F230);
                    mf_render_thread_kick();
                    call_regs(0x006A_1950, 1, 0, 0, 0, 0, &[]); // falls into case 10
                }
            }
            8 => mf_case8(),
            9 => {
                call(0x004C_46F0);
                if rd(0x0252_6D9C) != 2 {
                    call_regs(0x00D1_4D00, 0x00EA_C198, 0, 0, 0, 0, &[]);
                    mf_fade_in_call();
                }
                if !al(c0(0x004D_1900)) || !mf_gate_live() {
                    return;
                }
                wd(0x0145_0380, 0);
                call_regs(0x006A_17B0, 0, 0, 0, 0, 0, &[1]);
                call(0x006A_18A0);
                call(0x004C_46F0); // falls into case 1
            }
            10 => _ = call_regs(0x006A_1950, 1, 0, 0, 0, 0, &[]), // mission_fail_flow_begin(1)
            _ => {} // 5 and anything above 10
        }
    }
}

/// Case 2: fade out, then (with a cutscene record) play the fail cutscene; state 3.
unsafe fn mf_case2() {
    unsafe {
        call(0x004C_46F0);
        let m = rd(0x027B_3C60);
        let mut ecx = m;
        let rec = if rd(m as usize + 0x3C) == 1 {
            rd(rd(m as usize + 0x90) as usize + 0x154)
        } else {
            rd(m as usize + 0x98)
        };
        if rd(0x0252_6D9C) != 1 {
            mf_fade_out_call();
            ecx = rd(0x027B_3C60);
        }
        if !mf_fade_is_full() {
            return;
        }
        if rec != 0 {
            // `sete cl; push ecx`: the flag carries the upper bytes of the M pointer.
            let flag = (ecx & 0xFFFF_FF00) | (rd(ecx as usize + 0x3C) == 2) as u32;
            let first = rd(rec as usize);
            call_regs(0x006C_3BA0, 0, 0x027A_C83C, first, 0, rec, &[first, flag, 0]); // cutscene_play
            let mut slot = rd(0x0252_7C9C);
            wd(0x0252_7C9C, 0);
            call_regs(0x0075_4020, 0, 0, 0, p32(&mut slot), rec, &[]); // conversation_stop
            let m = rd(0x027B_3C60);
            let kind = rd(m as usize + 0x3C);
            if kind == 1 {
                let o = rd(m as usize + 0x90);
                let fv = vslot(o, 0x5C / 4);
                let r = call_regs(fv, fv as u32, o, rd(o as usize), 0, rec, &[]);
                if r != 0 {
                    call_regs(0x006C_8FB0, 0, r + 0x28, r + 0x1C, 0, rec, &[r + 0x28]);
                } else {
                    let pl = rd(0x0217_03D4);
                    call_regs(0x006C_8FB0, pl, 0, pl + 0x14, 0, rec, &[pl + 0x20]);
                }
                let o = rd(rd(0x027B_3C60) as usize + 0x90);
                let fv = vslot(o, 0x60 / 4);
                let r = call_regs(fv, fv as u32, o, rd(o as usize), 0, rec, &[]);
                if r != 0 && rb(0x0252_7D23) != 1 {
                    call_regs(0x006B_EBB0, r, r + 0x28, r + 0x1C, 0, rec, &[]);
                }
            } else if kind == 2 {
                wb(0x0252_6D96, 0);
            }
        }
        if !mf_gate_live() {
            return;
        }
        wd(0x0145_0380, 3);
        call(0x004C_46F0);
    }
}

/// Case 3: wait for the cutscene, then state 4 and the kind's follow-up.
unsafe fn mf_case3(s: u32, b56: u8, b2b: u8) {
    unsafe {
        if al(c0(0x006C_6D20)) || al(c0(0x006C_6D50)) {
            return;
        }
        let m = rd(0x027B_3C60);
        let kind = rd(m as usize + 0x3C);
        if kind == 2 {
            let mut esi = m;
            let cb = rd(m as usize + 0x90);
            if cb != 0 {
                let a = rd(m as usize + 0x94);
                call_regs(cb as usize, cb, a, s, m, 0, &[a]);
                esi = rd(0x027B_3C60);
            }
            call_regs(0x006A_2B40, 0, esi, s, esi, 0, &[1]); // mission_end(1)
            return;
        }
        if !mf_gate(s, b56, b2b) {
            return;
        }
        wd(0x0145_0380, 4);
        match kind {
            0 | 3 => {
                if rd(0x00E9_6C00) != 4 {
                    wd(0x00E9_6C04, 4);
                    wd(0x0252_7BB4, 0);
                }
            }
            1 => {
                let z = rd(0x00E9_6C00) == 0;
                wd(0x0140_91B0, rd(m as usize + 0x90));
                wb(0x0140_91B4, 0);
                wb(0x0140_91B5, 0);
                if !z {
                    wd(0x00E9_6C04, 0);
                    wd(0x0252_7BB4, 0x0140_91B0);
                }
            }
            _ => {}
        }
    }
}

