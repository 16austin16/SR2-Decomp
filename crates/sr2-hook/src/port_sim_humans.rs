//! Port module: human_update (0x9D6D60) and mission_fail_flow_do_frame (0x6A5BB0).
//!
//! Both are call skeletons: every callee is still the original game function, called with the
//! registers the LTCG build passes it (checked against the disassembly of each callee). The
//! control flow, the bit tests and the x87 arithmetic are reproduced here; every `fstp dword` of
//! the original is an `as f32`.
//!
//! effect_object_update (0x505480) is not ported: it is a ~13 KB function with a 0x6A8-byte,
//! 16-byte-aligned frame, not a followable call sequence.

use std::sync::atomic::{AtomicU32, Ordering};

use crate::portlib::*;

static HUMAN_UPDATE_CALLS: AtomicU32 = AtomicU32::new(0);
static MISSION_FAIL_CALLS: AtomicU32 = AtomicU32::new(0);

const HUMAN_UPDATE: usize = 0x009D_6D60;
const MISSION_FAIL_FLOW_DO_FRAME: usize = 0x006A_5BB0;

const NONE: u32 = 0xFFFF_FFFF;

/// Install this module's replacements (called from hooks::install_all).
pub fn install() {
    let mut n = 0;
    if replace_pinned("human_update", HUMAN_UPDATE, &HUMAN_UPDATE_BODY, human_update_thunk as extern "C" fn() as usize) {
        n += 1;
    }
    if replace_pinned(
        "mission_fail_flow_do_frame",
        MISSION_FAIL_FLOW_DO_FRAME,
        &MISSION_FAIL_FLOW_DO_FRAME_BODY,
        mission_fail_flow_do_frame_thunk as extern "C" fn() as usize,
    ) {
        n += 1;
    }
    crate::log(&format!("port_sim_humans: replaced {n}/2 with Rust"));
}

/// One line for the periodic log.
pub fn summary() -> String {
    let parts: Vec<String> = [("human_update", &HUMAN_UPDATE_CALLS), ("mission_fail_flow_do_frame", &MISSION_FAIL_CALLS)]
        .iter()
        .filter_map(|(name, c)| {
            let v = c.load(Ordering::Relaxed);
            (v != 0).then(|| format!("{name} {v}"))
        })
        .collect();
    if parts.is_empty() { String::new() } else { format!("port_sim_humans: {}", parts.join(", ")) }
}

// --- local helpers -------------------------------------------------------------------------------

unsafe fn rw(p: usize) -> u16 {
    unsafe { *(p as *const u16) }
}

/// A qword constant (the x87 `fld qword` operands).
unsafe fn rq(p: usize) -> f64 {
    unsafe { *(p as *const f64) }
}

fn f(bits: u32) -> f64 {
    f32::from_bits(bits) as f64
}

/// A `fld dword` / `fstp dword` round trip: the bits, except that a signalling NaN is quieted.
fn q32(bits: u32) -> u32 {
    if bits & 0x7F80_0000 == 0x7F80_0000 && bits & 0x007F_FFFF != 0 { bits | 0x0040_0000 } else { bits }
}

fn p32<T>(x: &mut T) -> u32 {
    x as *mut T as u32
}

/// `call_regs` for a callee that returns on the x87 stack: the result is popped as a qword.
unsafe fn call_regs_st0(f: usize, eax: u32, ecx: u32, edx: u32, esi: u32, edi: u32, args: &[u32]) -> f64 {
    let mut out = 0f64;
    let block: [u32; 9] =
        [f as u32, ecx, edx, esi, edi, args.as_ptr() as u32, args.len() as u32, eax, &mut out as *mut f64 as u32];
    unsafe {
        std::arch::asm!(
            "push ebx", "push esi", "push edi", "push ebp",
            "mov ebp, esp",
            "mov ebx, eax",
            "mov ecx, [ebx + 24]",
            "mov esi, [ebx + 20]",
            "2:",
            "test ecx, ecx",
            "jz 3f",
            "push dword ptr [esi + ecx*4 - 4]",
            "dec ecx",
            "jmp 2b",
            "3:",
            "mov ecx, [ebx + 4]", "mov edx, [ebx + 8]", "mov esi, [ebx + 12]", "mov edi, [ebx + 16]",
            "mov eax, [ebx + 28]",
            "call dword ptr [ebx]",
            "mov ecx, [ebx + 32]",
            "fstp qword ptr [ecx]",
            "mov esp, ebp",
            "pop ebp", "pop edi", "pop esi", "pop ebx",
            inout("eax") block.as_ptr() => _, lateout("ecx") _, lateout("edx") _,
            clobber_abi("C"),
        );
    }
    out
}

/// The CRT float-to-int (0xDA0140, `_ftol2`): ST0 in, EAX out.
unsafe fn ftol(x: f64) -> u32 {
    let r: u32;
    unsafe {
        std::arch::asm!(
            "fld qword ptr [{p}]",
            "call {f}",
            p = in(reg) &x as *const f64,
            f = in(reg) 0x00DA_0140usize,
            out("eax") r,
            clobber_abi("C"),
        );
    }
    r
}

/// The object of a handle in the 4096-slot table 0x2149C64 (stride 16), or 0 when stale.
unsafe fn obj_from_handle(h: u32) -> u32 {
    unsafe {
        if h == 0 {
            return 0;
        }
        let o = rd(0x0214_9C64 + ((h & 0xFFF) << 4) as usize);
        if o != 0 && rd(o as usize + 0x44) == h { o } else { 0 }
    }
}

fn al(r: u32) -> bool {
    r & 0xFF != 0
}

/// Call a game function with no register or stack arguments, returning EAX.
unsafe fn c0(f: usize) -> u32 {
    unsafe { call_regs(f, 0, 0, 0, 0, 0, &[]) }
}

// --- human_update (0x9D6D60) ---------------------------------------------------------------------

// cdecl (human, f32 dt), called for every human by humans_update_all. Doc 15, "human_update
// porting map", corrected against the disassembly.

keep_ecx_edx_arg2!(human_update_thunk, human_update);

extern "C" fn human_update(h: u32, dt: u32) {
    HUMAN_UPDATE_CALLS.fetch_add(1, Ordering::Relaxed);
    unsafe { human_update_body(h, dt) };
}

unsafe fn human_update_body(h: u32, dt: u32) {
    unsafe {
        let p = h as usize;
        wb(p + 0x1160, rb(p + 0x1160) & 0xFB);
        call_regs(0x009A_7DF0, 0, 0, 0, 0, 0, &[h, q32(dt)]); // human_update_core

        // Co-op revive. The assets test 0x9E99F0 takes EDI = human +0x13B0.
        let bl0 = rb(p + 0x1161);
        let dl = (bl0 >> 4) & 1;
        let mut ready = false;
        if dl != 0 && rb(p + 0x129D) == 1 {
            ready = al(call_regs(0x009E_99F0, 0, 0, 0, 0, rd(p + 0x13B0), &[]));
        }
        let first = rd(rd(0x0252_8C14) as usize + 0x400);
        let mut below = false;
        let mut e = first;
        while e != 0 {
            if (rd(e as usize + 0x3C) as i32) < 13 {
                below = true;
                break;
            }
            e = rd(e as usize + 0x22CC);
            if e == first {
                break;
            }
        }
        if (ready && !below) || (rb(0x0252_8B56) != 0 && dl == 1) {
            wb(p + 0x1161, bl0 & 0xEF);
            let fv = vslot(h, 7);
            call_regs(fv, fv as u32, h, rd(p), 0xD, 0, &[1, 1]);
            let a = rd(p + 0x570);
            if a != 0 {
                wb(a as usize + 0x130, rb(a as usize + 0x130) & 0xFD);
            }
            if al(c0(0x009F_6240)) {
                wd(p + 0x80, rd(p + 0x80) | 0x14);
            }
        }

        if rb(p + 0x18E8) & 2 != 0 {
            // Not alive: the effect key is 0xBDCA30's CRC of the empty string 0xDC5797 with the
            // seed EDX = +0x18D8.
            if rd(p + 0x18D4) == 1 {
                let mut key = 0u32;
                call_regs(0x00BD_CA30, p32(&mut key), 0, rd(p + 0x18D8), 0, 0, &[0x00DC_5797]);
                let r = call_regs(0x00A5_EB50, p32(&mut key), 0, 0, 0, 0, &[]);
                if rb(p + 0x591) == 0 {
                    call_regs(0x0099_DD20, r.wrapping_add(0x1C), 0, 0, 0, 0, &[h, 1, NONE, 0]);
                }
            }
            human_update_hud(h);
            return;
        }

        let player = rd(0x0217_03D4);
        if rb(p + 0x1162) & 2 != 0 {
            // Bone transform (ECX = rig index [[+0x5E0]], bone = word +0xCE4) of the vector
            // 0x252A6D0 into +0x730..0x738.
            let mut v = [q32(rd(0x0252_A6D0)), q32(rd(0x0252_A6D4)), q32(rd(0x0252_A6D8)), 0];
            let bone = rw(p + 0xCE4) as i16 as i32 as u32;
            let rig = rd(p + 0x5E0);
            call_regs(0x00CE_DF10, rig, rd(rig as usize), bone, 0, player, &[bone, h + 0x14, h + 0x20, p32(&mut v), 0]);
            wd(p + 0x760, rd(p + 0x760) & !1);
            wd(p + 0x730, v[0]);
            wb(p + 0x75C, rb(p + 0x75C) & 0xFE);
            wd(p + 0x734, v[1]);
            wd(p + 0x738, v[2]);
            wd(p + 0x748, NONE);
        } else if rb(p + 0xC0) & 0x40 != 0 {
            // 0x9B5C00(EAX bit 0 = 0, EDX = &+0x564, ESI = 0 ms, cdecl human, [0xE87998] = -1.0).
            call_regs(0x009B_5C00, 0, 0, h + 0x564, 0, player, &[h, q32(rd(0x00E8_7998))]);
        } else if rd(p + 0x100C) == 0 && !al(c0(0x006C_6D20)) {
            // Look target: origin + view direction (0x9C5FD0) x 1000.
            let mut dir = [0u32; 4];
            let dp = p32(&mut dir);
            call_regs(0x009C_5FD0, h, dp, 0, 0, player, &[dp]);
            let o = if h == player {
                [rd(0x025F_5B20), rd(0x025F_5B24), rd(0x025F_5B28)]
            } else {
                [rd(p + 0x12A0), rd(p + 0x12A4), rd(p + 0x12A8)]
            };
            let k = rq(0x00E5_C0D8);
            let s0 = (f(dir[0]) * k) as f32;
            let s1 = (f(dir[1]) * k) as f32;
            let s2 = (k * f(dir[2])) as f32;
            let mut aim = [
                (s0 as f64 + f(o[0])) as f32,
                (f(o[1]) + s1 as f64) as f32,
                (f(o[2]) + s2 as f64) as f32,
                0.0,
            ];
            // 100.0 is pushed before 0x960C30 (which takes only ESI) as 0x9B5C00's argument.
            let arg = q32(rd(0x00DD_0C54));
            let r = call_regs(0x0096_0C30, 0, 0, 0, h, player, &[]);
            call_regs(0x009B_5C00, r, 0, p32(&mut aim), 0, player, &[h, arg]);
        }

        // Local player or not (+0x44 handle resolves to the player object).
        let me = obj_from_handle(rd(p + 0x44));
        if !(me != 0 && me == player) {
            call_regs(0x009C_1B90, 0, 0, 0, 0, player, &[h]); // human_ai_think
            if rb(0x0252_8B48) == 1 && rb(0x0252_8B49) == 0 {
                return;
            }
            if !al(call_regs(0x009C_4370, h, 0, 0, 0, player, &[]))
                && !al(call_regs(0x009C_60A0, h, 0, 0, 0, player, &[]))
            {
                return;
            }
            if rb(p + 0x10C8) != 0
                || al(call_regs(0x0098_5630, 0, 0, 0, 0, player, &[h]))
                || al(c0(0x006C_6D20))
            {
                return;
            }
            wd(p + 0x11C8, call_regs(0x009D_AAF0, 0, 0, 0, 0, player, &[h, h + 0x11CC]));
            return;
        }

        // Vehicle push-out timer +0x14DC.
        let t = h + 0x14DC;
        if (rd(t as usize) as i32) >= 0 && al(call_regs(0x00BD_D230, t, 0, 0, 0, t, &[])) {
            let mut go = true;
            let veh = call_regs(0x00AE_28F0, 0, rd(p + 0xD74), 0, 0, t, &[]); // vehicle_from_handle
            if veh != 0 && rd(veh as usize + 0x8554) == 0x11 {
                let st = call_regs_st0(0x00AA_6A90, 0, veh, 0, veh, t, &[]);
                if st > rq(0x00E5_CE88) {
                    go = false;
                }
            }
            if rb(p + 0x148) == 0xA5 {
                go = false;
            }
            if veh != 0 && go {
                let mut q = [0u32; 16];
                let qp = p32(&mut q);
                call_regs(0x0043_3190, qp, 0, 0, veh, t, &[]);
                call_regs(0x00B0_72F0, qp, 0, 0, veh, t, &[h, qp]);
            }
            wd(t as usize, NONE);
        }

        // Ragdoll / held object.
        if !((rb(0x0252_7D14) != 0 && rb(0x0252_7CF7) != 0) || rb(0x0252_7D15) != 0) {
            if rb(p + 0x1163) & 0x10 != 0 && al(call_regs(0x009D_6CF0, 0, h, 0, 0, 0, &[])) {
                call_regs(0x009D_A130, 0, 0, 0, h, 0, &[]);
            }
            if al(call_regs(0x009D_6BF0, 0, 0, 0, h, 0, &[]))
                && (rb(p + 0x1163) & 8 != 0 || (rb(p + 0xD0) & 4 != 0 && rb(p + 0x591) != 7))
            {
                let mut out = [0u32; 4];
                let src = if h == rd(0x0217_03D4) { 0x025F_5B50 } else { h + 0x12C4 };
                human_velocity_push(p, src, p32(&mut out));
            }
        }

        // Zoom FOV 0x25F5D38.
        if rb(p + 0x1161) & 1 != 0 {
            call_regs(0x0096_0A80, 0, 0, 0, h, 0, &[1, 0]);
            let t = h + 0x11EC;
            if (rd(t as usize) as i32) >= 0 {
                let v: Option<f32> = if al(call_regs(0x00BD_D230, t, 0, t, h, 0, &[])) {
                    if al(call_regs(0x00BD_D390, t, 0, t, h, 0, &[])) {
                        Some(f32::from_bits(q32(rd(p + 0x11E8))))
                    } else {
                        None
                    }
                } else {
                    let rem = call_regs(0x00BD_D260, t, 0, t, h, 0, &[]) as i32;
                    let r = (rem as f64 / rq(0x00E5_C638)) as f32;
                    let e8 = rf(p + 0x11E8) as f64;
                    Some((r as f64 * (rf(p + 0x11E4) as f64 - e8) + e8) as f32)
                };
                if let Some(v) = v
                    && rb(0x0252_6BA3) == 0
                {
                    let out = if v as f64 > rq(0x00DD_50E8) {
                        let hi = f32::from_bits(q32(rd(0x00E5_C3D4)));
                        if hi as f64 <= v as f64 { hi } else { v }
                    } else {
                        f32::from_bits(q32(rd(0x00DD_1C88)))
                    };
                    wf(0x025F_5D38, out);
                    wb(0x0252_6BA3, 0);
                }
            }
        }

        call(0x009D_5A60);
        if h == rd(0x0217_03D4) {
            human_update_stats(h);
        }
        human_update_local_tail(h);
        human_update_hud(h);
    }
}

/// +0x3D8 = *0xBDDCC0(EDI = src, ESI = out); +0x564 = position + that x 20.
unsafe fn human_velocity_push(p: usize, src: u32, out: u32) {
    unsafe {
        let r = call_regs(0x00BD_DCC0, 0, 0, 0, out, src, &[]) as usize;
        wd(p + 0x3D8, rd(r));
        wd(p + 0x3DC, rd(r + 4));
        wd(p + 0x3E0, rd(r + 8));
        let k = rq(0x00E5_C120);
        let sx = (rf(p + 0x3D8) as f64 * k) as f32;
        let sy = (rf(p + 0x3DC) as f64 * k) as f32;
        let sz = (k * rf(p + 0x3E0) as f64) as f32;
        let x = (rf(p + 0x14) as f64 + sx as f64) as f32;
        let y = (rf(p + 0x18) as f64 + sy as f64) as f32;
        let z = (rf(p + 0x1C) as f64 + sz as f64) as f32;
        wf(p + 0x564, x);
        wf(p + 0x568, y);
        wf(p + 0x56C, z);
    }
}

/// One timed stat award: the gate, the award callback from the 24-byte table 0x27DA820 (cdecl
/// arg, 0xE84380), then 0x6B3B30(EDI = entry) for each listed entry.
unsafe fn stat_award(idx: usize, arg: u32, cnt: usize, list: usize, threshold: i32) {
    unsafe {
        if (rd(0x0252_7CE8) as i32) <= threshold || al(c0(0x006B_6460)) {
            return;
        }
        if rd(0x027B_3C60) != 0 && rb(0x0252_7C76) != 0 {
            return;
        }
        if rb(0x0252_7B5A) != 0 {
            return;
        }
        let fv = rd(0x027D_A820 + rd(idx).wrapping_mul(24) as usize);
        if fv == 0 {
            return;
        }
        call_regs(fv as usize, fv, 0, 0, 0, 0, &[arg, 0x00E8_4380]);
        let mut i: i32 = 0;
        if (rd(cnt) as i32) > i {
            loop {
                call_regs(0x006B_3B30, 0, 0, 0, i as u32, rd(list + (i as usize) * 4), &[]);
                i += 1;
                if i >= rd(cnt) as i32 {
                    break;
                }
            }
        }
    }
}

/// The local player's time counter, stat awards and HUD timer text (0x9D73D2..0x9D7679).
unsafe fn human_update_stats(h: u32) {
    unsafe {
        let p = h as usize;
        wf(p + 0x18C0, (rf(0x00E8_4380) as f64 + rf(p + 0x18C0) as f64) as f32);
        let st = rd(0x00E9_6C00) as i32;
        if (11..=13).contains(&st) {
            stat_award(0x0145_7758, 0x0145_7750, 0x0145_7760, 0x0145_7764, 0x11C);
            // 0x55ADF0(EAX = &+0x10C4, ESI = slot) for slots 1..7: all must be found.
            let mut all = true;
            for slot in 1..=7u32 {
                let r = call_regs(0x0055_ADF0, h + 0x10C4, 0, 0, slot, h + 0x10C4, &[]);
                all &= r != 0;
            }
            if all {
                stat_award(0x0145_900C, 0x0145_9004, 0x0145_9014, 0x0145_9018, 0x179);
            }
            if rd(0x0252_97E8) == 1 && (c0(0x009F_2170) as i32) > 0 {
                stat_award(0x0145_9050, 0x0145_9048, 0x0145_9058, 0x0145_905C, 0x17A);
            }
        }
        if h != rd(0x0217_03D4) {
            return;
        }
        call_regs(0x0069_0710, 7, 0, 0, 0, 0, &[q32(rd(0x00E8_437C))]);
        let t = h + 0xF8C;
        if (rd(t as usize) as i32) >= 0 && !al(call_regs(0x00BD_D230, t, 0, t, 0, 0, &[])) {
            let rem = call_regs(0x00BD_D260, t, 0, t, 0, 0, &[]) as i32;
            let secs = (rem as f64 / rq(0x00E5_C0D8)) as f32;
            let r = call_regs_st0(0x0049_12D0, 0, 0, 0, 0, 0, &[secs.to_bits()]) as f32;
            let i = ftol(r as f64);
            let fmt = call_regs(0x007F_49E0, i, 0, 0, 0x00E3_CAA4, 0x00E3_CA60, &[i]);
            let mut buf = [0u8; 1024];
            let b = buf.as_mut_ptr() as u32;
            call_regs(0x00C1_4C20, fmt, 0, b, 0x00E3_CAA4, 0x00E3_CA60, &[fmt, i]); // wsprintf_1024
            call_regs(0x0079_D700, rd(0x00EA_D20C), 0, 0, b, 0x00E3_CA60, &[0x0347_B04C]);
        } else {
            let e = rd(0x0347_B04C);
            if e != 0 {
                let idx = e & 0x1FFF;
                if (idx as i32) < 0x3C {
                    let rec = idx * 60 + 0x029E_6C28;
                    if rd((idx * 60 + 0x029E_6C48) as usize) == e {
                        call_regs(0x0079_D1B0, 3, rec, e, 0, 0, &[]);
                    }
                }
            }
        }
    }
}

/// 0x9D7679..0x9D7B17: pick-up scan, lock-on, heartbeat, vehicle-damage timer, hit flash and the
/// "targeted" bit.
unsafe fn human_update_local_tail(h: u32) {
    unsafe {
        let p = h as usize;
        call_regs(0x009D_53F0, 0, 0, 0, h, 0, &[]);
        call_regs(0x0093_0F30, 0, 0, 0, h, 0, &[h]);
        call_regs(0x009D_4810, h, 0, 0, h, 0, &[]);
        call_regs(0x0049_1AA0, h, 0, 0, h, 0, &[]);

        // Lock-on.
        let fl = rd(rd(0x0217_03D4) as usize + 0x139C);
        let c = (fl >> 1) & 1 != 0 && rb(0x0252_976E) != 0;
        let a = (fl >> 2) & 1 != 0 && rb(0x0252_976F) != 0;
        let bl = c || a;
        let mut full_find = false;
        if !(rb(0x0252_8B48) == 1 && rb(0x0252_8B49) == 0) {
            let mut ok = false;
            let w = rd(p + 0x10CC);
            if w != 0 {
                let i = rd(w as usize + 0xC4);
                if i != 0 {
                    let d = rd(i as usize + 8);
                    if d != 0 && al(call_regs(0x00B7_2800, d, 0, 0, h, 0, &[])) {
                        ok = true;
                    }
                }
            }
            if (!ok && !al(call_regs(0x009C_60A0, h, 0, 0, h, 0, &[]))) || rb(p + 0x10C8) != 0 {
                full_find = true;
            }
        }
        if full_find {
            wd(p + 0x11C8, call_regs(0x009D_AAF0, 0, 0, 0, h, 0, &[h, h + 0x11CC]));
            wf(0x025F_5C88, 1.0);
            wf(0x025F_5C8C, 1.0);
        } else if !al(call_regs(0x0098_5630, 0, 0, 0, h, 0, &[h])) && !bl {
            wd(p + 0x11C8, call_regs(0x009D_AAF0, 0, 0, 0, h, 0, &[h, h + 0x11CC]));
            call_regs(0x009E_2FA0, 0, 0, 0, h, 0, &[]);
        } else if h == rd(0x0217_03D4) {
            let w = rd(p + 0x10CC);
            if w != 0 {
                let i = rd(w as usize + 0xC4);
                if i != 0 && rd(i as usize + 8) != 0 {
                    wd(p + 0x11C8, call_regs(0x009E_2B70, 0, 0, 0, h, 0, &[]));
                }
            }
        }

        // Low-health heartbeat (timer 0xEB7E14, voice handle 0xEB7E1C).
        let n = rd(p + 0x1120) as i32;
        let hr: f32 = if n > 0 { (rf(p + 0x1124) as f64 / n as f64) as f32 } else { 0.0 };
        let thr = rf(0x0279_74E0);
        // `fcompp; test ah, 0x41; jne`: stop when thr <= hr or unordered.
        let mut stop = !(thr as f64 > hr as f64);
        if !stop {
            stop = al(call_regs(0x0098_5630, 0, 0, 0, h, 0, &[h]))
                || al(c0(0x006C_6D20))
                || rd(0x0252_6D9C) != 0
                || rd(0x00E8_CF80) != NONE;
        }
        if stop {
            wd(0x00EB_7E14, NONE);
            call_regs(0x0047_FEB0, 0, 0x00EB_7E1C, 0, h, 0, &[]); // audio_voice_stop
        } else if (rd(0x00EB_7E14) as i32) < 0 || al(call_regs(0x00BD_D230, 0x00EB_7E14, 0, 0, h, 0, &[])) {
            call_regs(0x0047_FEB0, 0, 0x00EB_7E1C, 0, h, 0, &[]);
            let cue = rw(0x00E8_8174) as u32;
            let mut params = [0u32; 32];
            let pp = p32(&mut params);
            call_regs(0x0046_4920, cue, 0, 0, pp, 0, &[cue, 0, 0]); // audio_play_params_init
            let mut hnd = [0u32; 4];
            let r = call_regs(0x0046_5B90, pp, p32(&mut hnd), 0, pp, 0, &[]) as usize; // audio_play
            wd(0x00EB_7E1C, rd(r));
            wd(0x00EB_7E20, rd(r + 4));
            wd(0x00EB_7E24, rd(r + 8));
            let ratio = hr as f64 / thr as f64;
            let b = rf(0x0279_74E8) as f64;
            let a = rf(0x0279_74E4) as f64;
            let iv = ((b - a) * ratio + a) as f32;
            let ms = ftol(iv as f64);
            call_regs(0x00BD_D100, ms, 0x00EB_7E14, 0, pp, 0, &[]); // timer_set
        }

        // Vehicle damage timer +0x14E0 (vehicle state +0x4C == 5 and its +0x30 term).
        let veh = obj_from_handle(rd(p + 0xD74));
        if veh == 0 || rd(veh as usize + 0x4C) != 5 {
            wd(p + 0x14E0, NONE);
        } else {
            let v = veh as usize;
            let v30 = rf(v + 0x30) as f64;
            if 0.0 < v30 {
                let val = ((rf(v + 0x2C) as f64 * 0.0 + v30) + rf(v + 0x34) as f64 * 0.0) as f32;
                if val as f64 > rf(0x00DD_1C8C) as f64 {
                    wd(p + 0x14E0, time_add(rd(0x00E8_43AC) as i32, 0xDAC) as u32);
                }
            }
        }

        // Hit flash +0x1560 (timer) / +0x155C (duration, as unsigned).
        let t = p + 0x1560;
        if (rd(t) as i32) >= 0 {
            let rem = call_regs(0x00BD_D260, t as u32, 0, 0, h, t as u32, &[]) as i32;
            let tot = rd(p + 0x155C) as i32;
            let mut d = tot as f64;
            if tot < 0 {
                d += rf(0x00E5_BFD8) as f64;
            }
            let r = rem as f64 / d;
            let v: f32 = if r > 0.0 {
                if r >= 1.0 { 1.0 } else { r as f32 }
            } else {
                0.0
            };
            let kv = (v as f64 * rq(0x00E5_CC00)) as f32;
            if (rd(0x0276_CFFC) as i32) < 1 {
                wd(0x0276_CFFC, 1);
                // The original stores a dword whose low byte is 1 and whose upper three bytes are
                // whatever its stack slot held; only the byte is written here.
                wb(0x0276_D000, 1);
                wf(0x0276_D004, kv);
            }
            let tt = (v as f64 * rq(0x00E5_CDF8) + 1.0) as f32;
            let mut vec = [tt.to_bits(), tt.to_bits(), tt.to_bits(), 0];
            call_regs(0x00D1_4700, 0, 0, 0, p32(&mut vec), t as u32, &[]);
            wd(0x00E9_D7D4, vec[0]);
            wd(0x00E9_D7D8, vec[1]);
            wd(0x00E9_D7DC, vec[2]);
            if time_due(rd(t) as i32, rd(0x00E8_43AC) as i32) {
                wd(t, NONE);
            }
        }

        // +0x1163 bit 0x40: some live human on 0x215FFC0 (next +0x1160) is in state 3 (+0x149).
        let b = rb(p + 0x1163);
        if b & 0x40 != 0 {
            let bl = b & 0xBF;
            wb(p + 0x1163, bl);
            let mut e = rd(0x0215_FFC0);
            if e != 0 {
                let s = rd(0x0252_8C14);
                loop {
                    let ev = e as usize;
                    let mut skip = false;
                    let c = rd(ev + 0xB0);
                    if c != 0 && s != 0 {
                        let a = rd(s as usize + 0x408);
                        if a != 0 && (rb(c as usize) != rb(a as usize + 0x1B0) || rb(c as usize + 0x67C) & 1 != 0) {
                            skip = true;
                        }
                    }
                    if !skip
                        && rb(ev + 0x80) & 0xB == 0
                        && !al(call_regs(0x0098_5630, 0, 0, 0, e, s, &[e]))
                        && rb(ev + 0x149) == 3
                    {
                        wb(p + 0x1163, bl | 0x40);
                        break;
                    }
                    e = rd(ev + 0x1160);
                    if e == rd(0x0215_FFC0) || e == 0 {
                        break;
                    }
                }
            }
        }
    }
}

/// 0x9D7B17: the local player's HUD updates, then the zone bit +0x1164 bit 1.
