/// The main per-part pass. `bufp` = the zeroed per-list f32 accumulators.
unsafe fn s8_parts(e: usize, bufp: usize, live_total: &mut i32, kept: &mut i32) {
    let mut p = rd(e + 0xC4) as usize;
    while p != 0 {
        bump(C::S8Part);
        let l = rd(p);
        let next = if l != rd(e + 0xC4) { l as usize } else { 0 };
        let old_age = f32::from_bits(q32(rd(p + 0x1C)));
        let mut looped = false;
        let dt = if cutscene_in_progress() { rf(0x027E_671C) } else { rf(0x00E8_437C) };
        let ending = (rb(p + 0x204) >> 3) & 1;

        // 8a: age and loop wrap.
        if ending != 0 {
            bump(C::S8Ending);
            let v = (ld(p + 0x1E0) - dt as f64) as f32;
            wf(p + 0x1E0, v);
            if fcmp(0.0, v as f64) & 0x41 == 0 {
                wf(p + 0x1E0, 0.0);
            }
        }
        let age = (dt as f64 + ld(p + 0x1C)) as f32;
        wf(p + 0x1C, age);
        let j = rd(e + 0xD4) as usize;
        if !pf(fcmp(ld(j + 0x10), age as f64), 5) {
            bump(C::S8Expired);
            let kind = rd(e + 0xCC);
            if kind <= 4 {
                let mut wrap = false;
                if kind <= 2 {
                    let c = rd(p + 0x28) as i32;
                    if c > 0 {
                        wd(p + 0x28, (c - 1) as u32);
                        wrap = true;
                    } else {
                        wf(p + 0x1C, rf(j + 0x10));
                    }
                } else {
                    wd(p + 0x28, rd(p + 0x28).wrapping_add(1));
                    wrap = ending == 0;
                }
                if wrap {
                    bump(C::S8Wrap);
                    // The original never leaves this loop when J[0x10] <= 0 and age >= 0; the
                    // bound only turns that hang into a long stall.
                    let mut guard = 0u32;
                    loop {
                        let jj = rd(e + 0xD4) as usize;
                        if pf(fcmp(ld(jj + 0x10), ld(p + 0x1C)), 0x41) {
                            break;
                        }
                        wf(p + 0x1C, (ld(p + 0x1C) - ld(jj + 0x10)) as f32);
                        guard += 1;
                        if guard > 100_000_000 {
                            break;
                        }
                    }
                    looped = true;
                }
            }
        }

        // 8b: voices.
        s8b_voices(e, p, ending, looped);

        // 8c: T and wobble.
        bump(C::S8c);
        let j = rd(e + 0xD4) as usize;
        let jd = ld(j + 0x10);
        let frac = (ld(p + 0x1C) / jd) as f32;
        let prev_frac = (old_age as f64 / jd) as f32;
        let p1dc = rf(p + 0x1DC);
        let (t, t_prev);
        if !pf(fcmp(0.0, p1dc as f64), 0x41) {
            t = (p1dc as f64 * jd) as f32;
            t_prev = t;
        } else {
            t_prev = old_age;
            t = rf(p + 0x1C);
        }
        let mut wob = Buf::new();
        wob.set(0, q32(rd(0x0252_A6D0)));
        wob.set(1, q32(rd(0x0252_A6D4)));
        wob.set(2, q32(rd(0x0252_A6D8)));
        if rb(0x0252_6E2B) != 0 {
            bump(C::S8Wobble);
            let a = rd(0x0252_6E4C);
            let s = call_regs_st0(0x0042_8CD0, 0, 0, 0, 0, 0, &[q32(a)]) as f32;
            let c = call_regs_st0(0x0040_B820, 0, 0, 0, 0, 0, &[q32(a)]) as f32;
            let k = (ld(0x00E9_8FAC) * rq(0x00E5_BFC8)) as f32;
            let w0 = (s as f64 * k as f64) as f32;
            let w1 = (k as f64 * 0.0f32 as f64) as f32;
            let w2 = (k as f64 * c as f64) as f32;
            let i = rd(e + 0xD0) as usize;
            let sc = f32::from_bits(q32(rd(i + 0x20)));
            wob.setf(0, (sc as f64 * w0 as f64) as f32);
            wob.setf(1, (sc as f64 * w1 as f64) as f32);
            wob.setf(2, (sc as f64 * w2 as f64) as f32);
        }

        // 8d: force-field phase.
        let mut now = rd(0x00E8_43AC) as i32;
        let mut alive: u32 = 0;
        s8d_force_field(e, p, t, frac, &mut now, &mut alive);

        // 8e: emitter lists.
        if rb(p + 0x204) & 0x80 == 0 {
            if rd(e + 0xDC) as i32 > 0 {
                s8e_emitters(e, p, bufp, t, t_prev, frac, prev_frac, looped, wob.p(), live_total);
                now = rd(0x00E8_43AC) as i32;
            }
        } else {
            bump(C::S8eCulled);
        }

        // 8f: lights.
        let jl = rd(e + 0xD4) as usize;
        if rd(jl + 0x40) as i32 > 0 {
            s8f_lights(e, p, t);
            now = rd(0x00E8_43AC) as i32;
        }

        // 8g: end of the part.
        let j = rd(e + 0xD4) as usize;
        let mut keep = false;
        if fcmp(ld(j + 0x10), ld(p + 0x1C)) & 0x41 == 0 {
            keep = true;
        } else if alive > 0 {
            keep = true;
        } else if rd(p) as usize == p && *live_total > 0 {
            keep = true;
        } else {
            if rd(p + 0x18) as i32 >= 0 {
                let d = cd(rd(p + 0x18) as i32, now);
                if d.wrapping_neg() < 0x5DC {
                    keep = true;
                }
            }
            if !keep && !pf(fcmp(0.0, ld(p + 0x1E0)), 5) {
                keep = true;
            }
            if !keep && rd(e + 0xCC) == 4 {
                keep = true;
            }
        }
        if keep {
            bump(C::S8gKeep);
            *kept += 1;
        } else {
            bump(C::S8gDestroy);
            destroy_part(e, p);
        }
        p = next;
    }
}

// --- S8b ---------------------------------------------------------------------------------------

unsafe fn stop_voice_a(p: usize) {
    let h = p + 0x1E8;
    let slot = rb(h);
    if slot == 0xFF {
        return;
    }
    let generation = rd(h) >> 8;
    if generation == 0 {
        return;
    }
    let o = slot as usize * 0x19C;
    if generation != rd(0x00EE_B9AC + o) || rd(0x00EE_B8F8 + o) == NONE {
        return;
    }
    if rb(0x00EE_BA8E + o) & 0x80 != 0 {
        return;
    }
    let w = rw(0x00EE_BA90 + o) as u32;
    if ((w >> 1) | w) & 0x800 != 0 {
        return;
    }
    ww(0x00EE_BA8C + o, rw(0x00EE_BA8C + o) & 0xFF7F);
    ww(0x00EE_BA90 + o, (w | 0x400) as u16);
}

/// The 0x5C-byte audio_play parameter block (zeroed, 1.0 volume / pitch, cue, owner part).
struct Blk(Buf);

impl Blk {
    fn new(cue: u16, p: usize) -> Blk {
        let mut b = Buf::new();
        b.setf(3, 1.0);
        b.setf(4, 1.0);
        let w0 = b.get(0);
        b.set(0, (w0 & 0xFFFF_0000) | cue as u32);
        let w12 = b.get(12);
        b.set(12, (w12 & 0xFFFF_0000) | 0xFFFF);
        let w12 = b.get(12);
        b.set(12, (w12 & 0x0000_FFFF) | (1 << 16));
        b.set(19, p as u32);
        Blk(b)
    }
    fn pos(&mut self, src: usize) {
        for k in 0..3 {
            self.0.set(7 + k, unsafe { rd(src + 4 * k) });
        }
    }
    /// The word at +0x58.
    fn flags(&mut self, v: u16) {
        let w = self.0.get(22);
        self.0.set(22, (w & 0xFFFF_0000) | v as u32);
    }
    fn word58(&self) -> u16 {
        self.0.get(22) as u16
    }
    /// `audio_play(EAX = &block, ECX = &out)` and the 12-byte handle copied to `dst`.
    unsafe fn play(&mut self, dst: usize) {
        let mut out = Buf::new();
        let r = call_regs(0x0046_5B90, self.0.p(), out.p(), 0, 0, 0, &[]) as usize;
        copy_dwords(dst, r, 3);
    }
}

unsafe fn s8b_voices(e: usize, p: usize, ending: u8, looped: bool) {
    if rb(p + 0x205) & 2 != 0 {
        bump(C::S8Silent);
        if voice_alive(p + 0x1E8) {
            voice_fade_out(p + 0x1E8);
        }
        if voice_alive(p + 0x1F4) {
            voice_fade_out(p + 0x1F4);
        }
        return;
    }
    let a = p + 0x1E8;
    let a_alive = voice_alive(a);
    let mut audible = false;
    let i = rd(e + 0xD0) as usize;
    if i != 0 {
        let cue = rw(i + 0x26);
        if cue != 0xFFFF {
            let lx = f32::from_bits(q32(rd(0x00EE_B254)));
            let ly = f32::from_bits(q32(rd(0x00EE_B258)));
            let lz = f32::from_bits(q32(rd(0x00EE_B25C)));
            let ent = rd(0x00EE_5558 + cue as usize * 4) as usize;
            let snd = rd(0x00EE_9178 + (rd(ent + 0x10) & 0xFFF) as usize * 4) as usize;
            let vx = (lx as f64 - ld(p + 0x2C)) as f32;
            let vy = (ly as f64 - ld(p + 0x30)) as f32;
            let vz = (lz as f64 - ld(p + 0x34)) as f32;
            let r = (ld(snd + 0x28) * rq(0x00E5_C400)) as f32;
            let d2 = sumsq(vx, vy, vz);
            let r2 = (r as f64 * r as f64) as f32;
            audible = fcmp(r2 as f64, d2 as f64) & 0x41 == 0;
        }
    }
    if a_alive {
        if audible {
            if !voice_pos_check(p + 0x2C, a) {
                wd(a, 0xFF);
            }
        } else {
            bump(C::S8VoiceAStop);
            stop_voice_a(p);
        }
    } else if audible {
        if ending == 0 {
            bump(C::S8VoiceAStart);
            let mut b = Blk::new(rw(i + 0x26), p);
            b.pos(p + 0x2C);
            b.flags(b.word58() | 1);
            b.play(a);
        }
    } else {
        stop_voice_a(p);
    }

    // Second voice (B at P+0x1F4).
    let i = rd(e + 0xD0) as usize;
    if i != 0 && rb(i + 0x2E) & 0x40 != 0 {
        let cue2 = (call_regs(0x0050_3FE0, i as u32, 0, 0, 0, 0, &[p as u32, looped as u32]) & 0xFFFF) as u16;
        let bh = p + 0x1F4;
        if cue2 != 0xFFFF && rb(p + 0x204) & 8 == 0 {
            if voice_alive(bh) {
                voice_fade_out(bh);
            }
            let i = rd(e + 0xD0) as usize;
            let f = rw(i + 0x2E) as u32;
            bump(C::S8VoiceBStart);
            if f & 0x100 != 0 {
                let mut b = Blk::new(cue2, p);
                let old = b.word58() as u32;
                b.flags((((old ^ f) & 0x400 ^ old) | 0x2B0) as u16);
                b.play(bh);
                if !voice_pos_check(p + 0x2C, bh) {
                    wd(bh, 0xFF);
                }
            } else {
                let mut b = Blk::new(cue2, p);
                b.pos(p + 0x2C);
                let old = b.word58() as u32;
                b.flags((((f & 0x80) << 1) | (f & 0x400) | (old & 0xFAFF) | 1) as u16);
                b.play(bh);
            }
        } else {
            let i = rd(e + 0xD0) as usize;
            let f = rw(i + 0x2E) as u32;
            if f & 0x100 == 0 && f & 0x200 != 0 && !voice_pos_check(p + 0x2C, bh) {
                wd(bh, 0xFF);
            }
        }
    }
}

// --- S8d ---------------------------------------------------------------------------------------

unsafe fn curve_scalar(key_count: u32, t: f32, keys: u32) -> f64 {
    call_regs_st0(0x0051_4F80, 0, 0, 0, key_count, 0, &[t.to_bits(), keys])
}

/// `curve_eval_vec3(EDX = out, t, count, keys)`; returns the result pointer.
unsafe fn curve_vec3(out: u32, t: f32, count: u32, keys: u32) -> usize {
    call_regs(0x0051_51E0, 0, 0, out, 0, 0, &[t.to_bits(), count, keys]) as usize
}

/// `curve_eval_quat(EAX = count, out, t, keys)`; returns the result pointer.
unsafe fn curve_quat(count: u32, out: u32, t: f32, keys: u32) -> usize {
    call_regs(0x0051_5340, count, 0, 0, 0, 0, &[out, t.to_bits(), keys]) as usize
}

unsafe fn quat_to_mat(q: u32, m: u32) {
    call_regs(0x00C0_57D0, q, m, 0, 0, 0, &[]);
}

/// `mat33_mul(EAX = out, ECX = A, stdcall B)`; returns the result pointer.
unsafe fn mat_mul(out: u32, a: u32, b: u32) -> usize {
    call_regs(0x00BE_2F50, out, a, 0, 0, 0, &[b]) as usize
}

unsafe fn body_transform(h: u32, pos: u32, mat: u32) {
    call_regs(0x006F_C760, 0, 0, 0, pos, mat, &[h]);
}

unsafe fn s8d_force_field(e: usize, p: usize, t: f32, frac: f32, now: &mut i32, alive: &mut u32) {
    if rb(p + 0x204) & 2 != 0 {
        bump(C::S8dPhase);
        let j = rd(e + 0xD4) as usize;
        let d = cd(rd(p + 0x14) as i32, *now);
        let lim = ftol(ld(j + 0x10) * rq(0x00E5_C0D8) + rq(0x00E5_BF98));
        if !(d.wrapping_neg() < lim) {
            bump(C::S8dEnded);
            end_phase(p, *now);
        }
    }
    if rb(p + 0x204) & 2 != 0 {
        let ns = rd(rd(e + 0xD4) as usize + 0x20) as i32;
        if ns > 0 {
            let mut s = 0i32;
            loop {
                let h = rd(p + 0x98 + 4 * s as usize);
                if h != NONE {
                    let body = body_obj(h);
                    let q = rd(body + 0xB8) as usize;
                    if q != 0 && (rb(q + 0x26) >> 2) & 3 != 0 {
                        *alive += 1;
                    }
                    let vp = rd(p + 0x118 + 4 * s as usize) as usize;
                    if vp != 0 {
                        let mut pt = Buf::new();
                        let mut mt = Buf::new();
                        body_transform(h, pt.p(), mt.p());
                        if !voice_pos_check(pt.p() as usize, vp + 0x30) {
                            wd(vp + 0x30, 0xFF);
                        }
                    }
                    *now = rd(0x00E8_43AC) as i32;
                }
                s += 1;
                if !(s < rd(rd(e + 0xD4) as usize + 0x20) as i32) {
                    break;
                }
            }
        }
        // 0x507371: `fld1; fcomp frac; test ah,0x41; jne skip`.
        if fcmp(1.0, frac as f64) & 0x41 == 0 {
            let nk = rd(rd(e + 0xD4) as usize + 0x38) as i32;
            if nk > 0 {
                let mut k = 0i32;
                let mut off = 0usize;
                loop {
                    let j = rd(e + 0xD4) as usize;
                    let r = rd(j + 0x3C) as usize + off;
                    s8d_item(e, p, j, r, t, frac);
                    off += 0x2C;
                    k += 1;
                    let j2 = rd(e + 0xD4) as usize;
                    if !(k < rd(j2 + 0x38) as i32) {
                        break;
                    }
                }
                *now = rd(0x00E8_43AC) as i32;
            }
        }
    }
    // 0x507AB2
    if rb(p + 0x204) & 2 != 0 && *alive == 0 {
        end_phase(p, *now);
    }
}

/// One force item `r` (0x2C bytes at J[0x3C]).
unsafe fn s8d_item(e: usize, p: usize, j: usize, r: usize, t: f32, _frac: f32) {
    bump(C::S8dItems);
    let a = curve_scalar(rd(r + 4), t, rd(r + 8)) as f32;
    let b = curve_scalar(rd(r + 0x0C), t, rd(r + 0x10)) as f32;
    // fcom 0.001 vs A: `test ah,0x41; je` skips when 0.001 > A (ordered); then the same for B.
    if fcmp(ld(0x00DD_5984), a as f64) & 0x41 == 0 {
        return;
    }
    if fcmp(ld(0x00DD_5984), b as f64) & 0x41 == 0 {
        return;
    }
    let c = (curve_scalar(rd(r + 0x14), t, rd(r + 0x18)) / rq(0x00E5_C190)) as f32;
    let b2 = (b as f64 * b as f64) as f32;
    let mut w1 = Buf::new();
    let mut w2 = Buf::new();
    curve_vec3(w1.p(), t, rd(r + 0x1C), rd(r + 0x20));
    curve_vec3(w2.p(), t, rd(r + 0x24), rd(r + 0x28));
    let pm = p + 0x38;
    let o1 = vxm(w1.v3(0), pm);
    let w1w = [
        (o1[0] as f64 + ld(p + 0x2C)) as f32,
        (ld(p + 0x30) + o1[1] as f64) as f32,
        (ld(p + 0x34) + o1[2] as f64) as f32,
    ];
    let w2w = vxm(w2.v3(0), pm);

    let ns = rd(rd(e + 0xD4) as usize + 0x20) as i32;
    let _ = j;
    if ns <= 0 {
        return;
    }
    let mut s = 0i32;
    loop {
        let h = rd(p + 0x98 + 4 * s as usize);
        if h != NONE {
            let mut pb = Buf::new();
            let mut mb = Buf::new();
            body_transform(h, pb.p(), mb.p());
            let dv = [
                (pb.f(0) as f64 - w1w[0] as f64) as f32,
                (pb.f(1) as f64 - w1w[1] as f64) as f32,
                (pb.f(2) as f64 - w1w[2] as f64) as f32,
            ];
            let d2 = sumsq(dv[0], dv[1], dv[2]);
            // fcompp B2 vs d2; `test ah,5; jnp` skips when B2 < d2.
            if pf(fcmp(b2 as f64, d2 as f64), 5) {
                s8d_apply(r, p, h, dv, w2w, a, c, b2, d2);
            }
        }
        s += 1;
        if !(s < rd(rd(e + 0xD4) as usize + 0x20) as i32) {
            break;
        }
    }
}

/// The per-body part of a force item: build the direction, scale, apply the impulse and the
/// random torque.
unsafe fn s8d_apply(r: usize, _p: usize, h: u32, dv: [f32; 3], w2w: [f32; 3], a: f32, c: f32, b2: f32, d2: f32) {
    let mut v = Buf::new();
    v.set(0, q32(rd(0x0252_A6D0)));
    v.set(1, q32(rd(0x0252_A6D4)));
    v.set(2, q32(rd(0x0252_A6D8)));
    let mut m = Buf::new();
    let kind = rd(r);
    if kind == 1 || kind == 2 {
        // 0x5077B0 (type 1: the direction to the body, normalised) / 0x5076BB (type 2: W2w).
        if kind == 1 {
            bump(C::S8dType1);
            for k in 0..3 {
                v.setf(k, dv[k]);
            }
            call_regs(0x00BD_E150, 0, 0, 0, v.p(), 0, &[]);
        } else {
            bump(C::S8dType2);
            for k in 0..3 {
                v.setf(k, w2w[k]);
            }
        }
        call_regs(0x00BE_4B20, v.p(), m.p(), 0, 0, 0, &[]);
        let cone_a = (1.0 - c as f64 * rq(0x00E5_BF70)) as f32;
        call_regs(0x00BD_E7C0, 0, 0, 0, v.p(), 0, &[cone_a.to_bits(), 1.0f32.to_bits()]);
        let (x, y, z) = (v.f(0), v.f(1), v.f(2));
        let mf = |i: usize| m.f(i);
        v.setf(0, dot3(mf(0), x, mf(3), y, mf(6), z));
        v.setf(1, dot3(mf(1), x, mf(4), y, mf(7), z));
        v.setf(2, dot3(mf(2), x, mf(5), y, mf(8), z));
    } else {
        bump(C::S8dType0);
    }
    // g = 1 - clamp(d2 / B2): ratio <= 0 or NaN -> 1.0, ratio >= 1 -> 0.0.
    let ratio = d2 as f64 / b2 as f64;
    let g: f32 = if pf(fcmp(0.0, ratio), 5) {
        1.0
    } else if fcmp(1.0, ratio) & 0x41 == 0 {
        (1.0 - ratio) as f32
    } else {
        0.0
    };
    let dt2 = if cutscene_blocking() != 0 { rf(0x00E8_4380) } else { rf(0x00E8_437C) };
    let r1 = [
        (v.f(0) as f64 * g as f64) as f32,
        (g as f64 * v.f(1) as f64) as f32,
        (g as f64 * v.f(2) as f64) as f32,
    ];
    let r2 = [
        (r1[0] as f64 * a as f64) as f32,
        (a as f64 * r1[1] as f64) as f32,
        (a as f64 * r1[2] as f64) as f32,
    ];
    let mut r3 = Buf::new();
    r3.setf(0, (r2[0] as f64 * dt2 as f64) as f32);
    r3.setf(1, (dt2 as f64 * r2[1] as f64) as f32);
    r3.setf(2, (dt2 as f64 * r2[2] as f64) as f32);
    bump(C::S8dImpulse);
    call_regs(0x006F_CEC0, 0, h, 0, 0, 0, &[r3.p()]);
    let mut u = Buf::new();
    call_regs(0x00BD_E750, 0, 0, 0, u.p(), 0, &[]);
    let s2 = (((g as f64 * a as f64) * c as f64) * dt2 as f64) as f32;
    let body = body_obj(h);
    let mut w = Buf::new();
    w.setf(0, (s2 as f64 * u.f(0) as f64) as f32);
    w.setf(1, (s2 as f64 * u.f(1) as f64) as f32);
    w.setf(2, (s2 as f64 * u.f(2) as f64) as f32);
    w.setf(3, 0.0);
    call_regs(0x00D5_8FF0, 0, 0, 0, body as u32, 0, &[]);
    let vt = rd(body + 0xD0) as usize;
    call_regs(rd(vt + 0x50) as usize, 0, (body + 0xD0) as u32, 0, 0, 0, &[w.p()]);
}

// --- S8e ---------------------------------------------------------------------------------------

#[allow(clippy::too_many_arguments)]
unsafe fn s8e_emitters(
    e: usize,
    p: usize,
    bufp: usize,
    t: f32,
    t_prev: f32,
    frac: f32,
    prev_frac: f32,
    looped: bool,
    wobble: u32,
    live_total: &mut i32,
) {
    let mut i = 0i32;
    loop {
        let l = rd(e + 0xE0 + 4 * i as usize) as usize;
        if l != 0 && rd(e + 0xCC) != 4 {
            bump(C::S8e);
            let g = rd(l) as usize;
            let def = rd(g + 0x2C) as usize + rd(l + 4) as usize * 0xC0;
            let bi = rd(def + 0x0C) as i32;
            let al_ = !pf(fcmp(0.0, rf(p + 0x1DC) as f64), 0x41);
            let mut cur_pos = Buf::new();
            let mut cur_mat = Buf::new();
            let mut prev_pos = Buf::new();
            let mut prev_mat = Buf::new();
            let (pos_ptr, mat_ptr, ppos_ptr, pmat_ptr);
            if bi < 0 {
                // NOBODY (0x50802B)
                bump(C::S8eNobody);
                if rb(def + 6) & 0x10 != 0 {
                    copy_dwords(p + 0x5C, p + 0x2C, 3);
                    copy_dwords(p + 0x68, p + 0x38, 9);
                }
                pos_ptr = (p + 0x2C) as u32;
                mat_ptr = (p + 0x38) as u32;
                ppos_ptr = (p + 0x5C) as u32;
                pmat_ptr = (p + 0x68) as u32;
            } else {
                let h = rd(p + 0x98 + 4 * bi as usize);
                if h == NONE {
                    // CURVE (0x507B74)
                    bump(C::S8eCurve);
                    let rec2 = rd(g + 0x24) as usize + bi as usize * 0x30;
                    let mut o1 = Buf::new();
                    let mut o2 = Buf::new();
                    let r1 = curve_vec3(o1.p(), t, rd(rec2 + 0x0C), rd(rec2 + 0x10));
                    let off_cur = [rd(r1), rd(r1 + 4), rd(r1 + 8)];
                    let r2 = curve_vec3(o2.p(), t_prev, rd(rec2 + 0x0C), rd(rec2 + 0x10));
                    let off_prev = [rd(r2), rd(r2 + 4), rd(r2 + 8)];
                    let mut q1 = Buf::new();
                    let mut q2 = Buf::new();
                    let rq1 = curve_quat(rd(rec2 + 0x14), q1.p(), t, rd(rec2 + 0x18));
                    let qc = [rd(rq1), rd(rq1 + 4), rd(rq1 + 8), rd(rq1 + 12)];
                    let rq2 = curve_quat(rd(rec2 + 0x14), q2.p(), t_prev, rd(rec2 + 0x18));
                    let qp = [rd(rq2), rd(rq2 + 4), rd(rq2 + 8), rd(rq2 + 12)];
                    let mut qcb = Buf::new();
                    let mut qpb = Buf::new();
                    for k in 0..4 {
                        qcb.set(k, qc[k]);
                        qpb.set(k, qp[k]);
                    }
                    let mut mc = Buf::new();
                    let mut mp = Buf::new();
                    quat_to_mat(qcb.p(), mc.p());
                    quat_to_mat(qpb.p(), mp.p());
                    let pm = p + 0x38;
                    let oc = vxm(off_cur.map(f32::from_bits), pm);
                    for k in 0..3 {
                        let pv = ld(p + 0x2C + 4 * k);
                        let v = if k == 0 { (oc[0] as f64 + pv) as f32 } else { (pv + oc[k] as f64) as f32 };
                        cur_pos.setf(k, v);
                    }
                    let mut tmp = Buf::new();
                    let rm = mat_mul(tmp.p(), pm as u32, mc.p());
                    copy_dwords(cur_mat.p() as usize, rm, 9);
                    let op = vxm(off_prev.map(f32::from_bits), pm);
                    for k in 0..3 {
                        let pv = ld(p + 0x2C + 4 * k);
                        let v = if k == 0 { (op[0] as f64 + pv) as f32 } else { (pv + op[k] as f64) as f32 };
                        prev_pos.setf(k, v);
                    }
                    let mut tmp2 = Buf::new();
                    let rm2 = mat_mul(tmp2.p(), pm as u32, mp.p());
                    copy_dwords(prev_mat.p() as usize, rm2, 9);
                } else {
                    // PHYS (0x507E23)
                    bump(C::S8ePhys);
                    body_transform(h, cur_pos.p(), cur_mat.p());
                    let mut vel = Buf::new();
                    let mut ang = Buf::new();
                    call_regs(0x006F_C990, 0, h, 0, 0, 0, &[vel.p()]);
                    call_regs(0x006F_CBD0, 0, h, 0, 0, 0, &[ang.p()]);
                    let dt3 = if cutscene_blocking() != 0 { rf(0x00E8_4380) } else { rf(0x00E8_437C) };
                    for k in 0..3 {
                        let tv = (dt3 as f64 * vel.f(k) as f64) as f32;
                        prev_pos.setf(k, (cur_pos.f(k) as f64 - tv as f64) as f32);
                    }
                    let len = call_xmm0(0x00BD_E340, ang.p());
                    let angle = (len as f64 * dt3 as f64) as f32;
                    let mut rot = Buf::new();
                    call_regs(0x00BE_2E10, 0, 0, 0, rot.p(), ang.p(), &[angle.to_bits()]);
                    let mut tmp = Buf::new();
                    let rm = mat_mul(tmp.p(), rot.p(), cur_mat.p());
                    copy_dwords(prev_mat.p() as usize, rm, 9);
                }
                // Common tail of CURVE / PHYS: def[6] & 0x10 copies the current transform.
                let l2 = l;
                let g2 = rd(l2) as usize;
                let def2 = rd(g2 + 0x2C) as usize + rd(l2 + 4) as usize * 0xC0;
                if rb(def2 + 6) & 0x10 != 0 {
                    for k in 0..3 {
                        prev_pos.set(k, cur_pos.get(k));
                    }
                    for k in 0..9 {
                        prev_mat.set(k, cur_mat.get(k));
                    }
                }
                pos_ptr = cur_pos.p();
                mat_ptr = cur_mat.p();
                ppos_ptr = prev_pos.p();
                pmat_ptr = prev_mat.p();
            }
            let r = call_regs(
                0x0050_F880,
                pos_ptr,
                0,
                pmat_ptr,
                0,
                0,
                &[
                    l as u32,
                    mat_ptr,
                    frac.to_bits(),
                    ppos_ptr,
                    prev_frac.to_bits(),
                    looped as u32,
                    (bufp + 4 * i as usize) as u32,
                    wobble,
                    al_ as u32,
                    t.to_bits(),
                    rd(p + 0x0C),
                ],
            );
            *live_total = live_total.wrapping_add(r as i32);
        }
        i += 1;
        if !(i < rd(e + 0xDC) as i32) {
            break;
        }
    }
}

