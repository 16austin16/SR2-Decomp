/// Lifetime timer, stop rules and the explosion knockdown. True = return from the whole update.
unsafe fn s7_timer(e: usize) -> bool {
    let t = rd(e + 0x354) as i32;
    if t < 0 {
        return false;
    }
    bump(C::S7Timer);
    let now = rd(0x00E8_43AC) as i32;
    let elapsed = if t <= now { now.wrapping_sub(t) < 0x35A4_E900 } else { t.wrapping_sub(now) >= 0x35A4_E900 };
    if elapsed {
        bump(C::S7StopTimer);
        s7_stop(e);
        return true;
    }
    let c = rb(0x0252_8B48);
    if !(c == 1 && rb(0x0252_8B49) == 0) {
        let pl = rd(0x0217_03D4) as usize;
        let dx = (ld(pl + 0x14) - ld(e + 0x14)) as f32;
        let dy = (ld(pl + 0x18) - ld(e + 0x18)) as f32;
        let dz = (ld(pl + 0x1C) - ld(e + 0x1C)) as f32;
        let s = sumsq(dx, dy, dz);
        let dist = call_regs_st0(0x0040_EA20, 0, 0, 0, 0, 0, &[s.to_bits()]);
        if fcmp(dist, ld(0x00DD_358C)) & 0x41 == 0 {
            bump(C::S7StopFar);
            s7_stop(e);
            return true;
        }
    }
    if rb(e + 0x84) & 1 != 0 {
        bump(C::S7StopActive);
        s7_stop(e);
        return true;
    }
    let i = rd(e + 0xD0) as usize;
    if rd(i + 8) != rd(0x0265_9DD0) {
        return false;
    }
    bump(C::S7Blast);
    let r = ld(0x0279_74D4) as f32 as f64;
    let (ex, ey, ez) = (ld(e + 0x14), ld(e + 0x18), ld(e + 0x1C));
    let mut mn = Buf::new();
    let mut mx = Buf::new();
    mn.setf(0, (ex - r) as f32);
    mn.setf(1, (ey - r) as f32);
    mn.setf(2, (ez - r) as f32);
    mx.setf(0, (ex + r) as f32);
    mx.setf(1, (ey + r) as f32);
    mx.setf(2, (r + ez) as f32);
    let mut hs = Buf::new();
    let cnt = call_regs(0x006F_E460, 0, mn.p(), 0, 0, 0, &[mx.p(), hs.p(), 10, 0x0008_005E, 0, 0]);
    let mut k = 0usize;
    while (k as u32) < cnt && k < 10 {
        let h = hs.get(k);
        k += 1;
        if h == 0 {
            continue;
        }
        let ent = ent_raw(h);
        if ent == 0 || rd(ent + 0x44) != h || rd(ent + 0x4C) != 1 {
            continue;
        }
        let force = if rb(0x0252_8B48) == 1 && rb(0x0252_8B49) == 0 { rd(0x0279_749C) } else { rd(0x0279_748C) };
        bump(C::S7Knock);
        call_regs(0x0098_D3C0, 0, 0, 0, 0, 0, &[ent as u32, q32(force), 0, 0, 0]);
    }
    false
}

unsafe fn s7_stop(e: usize) {
    call_regs(0x0050_AB60, 0, 0, 0, 0, e as u32, &[0, 0]);
    wd(e + 0x354, NONE);
}

