unsafe fn s8f_lights(e: usize, p: usize, t: f32) {
    let mut k = 0i32;
    let mut hp = p + 0x19C;
    let mut recoff = 0usize;
    loop {
        let obj = light_obj(rd(hp));
        let j = rd(e + 0xD4) as usize;
        let rec = rd(j + 0x44) as usize + recoff;
        if obj != 0 {
            bump(C::S8f);
            let bi = rd(rec) as i32;
            let mut pos = Buf::new();
            let mut mat = Buf::new();
            let pm = p + 0x38;
            if bi < 0 {
                copy_dwords(pos.p() as usize, p + 0x2C, 3);
                copy_dwords(mat.p() as usize, pm, 9);
            } else {
                let b = rd(p + 0x98 + 4 * bi as usize);
                if b == NONE {
                    let rec2 = rd(j + 0x24) as usize + bi as usize * 0x30;
                    let mut o1 = Buf::new();
                    let r1 = curve_vec3(o1.p(), t, rd(rec2 + 0x0C), rd(rec2 + 0x10));
                    for k in 0..3 {
                        pos.set(k, rd(r1 + 4 * k));
                    }
                    let mut q = Buf::new();
                    let rq1 = curve_quat(rd(rec2 + 0x14), q.p(), t, rd(rec2 + 0x18));
                    let mut qb = Buf::new();
                    for k in 0..4 {
                        qb.set(k, rd(rq1 + 4 * k));
                    }
                    quat_to_mat(qb.p(), mat.p());
                    let mut ob = Buf::new();
                    let ro = call_regs(0x00BD_DE20, ob.p(), pm as u32, 0, 0, 0, &[pos.p()]) as usize;
                    let (ox, oy, oz) = (rf(ro), rf(ro + 4), rf(ro + 8));
                    pos.setf(0, (ld(p + 0x2C) + ox as f64) as f32);
                    pos.setf(1, (oy as f64 + ld(p + 0x30)) as f32);
                    pos.setf(2, (oz as f64 + ld(p + 0x34)) as f32);
                    let mut tmp = Buf::new();
                    let rm = mat_mul(tmp.p(), pm as u32, mat.p());
                    copy_dwords(mat.p() as usize, rm, 9);
                } else {
                    body_transform(b, pos.p(), mat.p());
                }
            }
            // The light's own offset and orientation in that frame.
            let mut off2 = Buf::new();
            curve_vec3(off2.p(), t, rd(rec + 0x14), rd(rec + 0x18));
            let o = vxm(off2.v3(0), mat.p() as usize);
            let world = [
                (o[0] as f64 + pos.f(0) as f64) as f32,
                (pos.f(1) as f64 + o[1] as f64) as f32,
                (pos.f(2) as f64 + o[2] as f64) as f32,
            ];
            let mut wbuf = Buf::new();
            for k in 0..3 {
                wbuf.setf(k, world[k]);
            }
            let mut q2 = Buf::new();
            let rq2 = curve_quat(rd(rec + 0x1C), q2.p(), t, rd(rec + 0x20));
            let mut qb2 = Buf::new();
            for k in 0..4 {
                qb2.set(k, rd(rq2 + 4 * k));
            }
            let mut m2 = Buf::new();
            quat_to_mat(qb2.p(), m2.p());
            let mut tmp = Buf::new();
            let rm = mat_mul(tmp.p(), mat.p(), m2.p());
            let mut m3 = Buf::new();
            copy_dwords(m3.p() as usize, rm, 9);
            call_regs(0x00BE_4170, 0, 0, 0, 0, 0, &[m3.p()]);
            let obj2 = light_obj(rd(hp));
            if obj2 != 0 {
                for k in 0..3 {
                    wd(obj2 + 0x10 + 4 * k, wbuf.get(k));
                }
                for k in 0..9 {
                    wd(obj2 + 0x1C + 4 * k, m3.get(k));
                }
                let sh = rd(obj2 + 0x12C) as usize;
                if sh != 0 {
                    let mut out = Buf::new();
                    call_regs(0x0070_E280, 0, m3.p(), out.p(), 0, 0, &[wbuf.p()]);
                    call_regs(0x00D5_5980, out.p(), 0, 0, rd(sh), 0, &[]);
                }
            }
            let mut inten = curve_scalar(rd(rec + 0x24), t, rd(rec + 0x28)) as f32;
            if rb(p + 0x204) & 8 != 0 {
                inten = ((ld(p + 0x1E0) / rq(0x00E5_C550)) * inten as f64) as f32;
            }
            let obj3 = light_obj(rd(hp));
            if obj3 != 0 {
                wd(obj3 + 0x64, q32(inten.to_bits()));
            }
        }
        hp += 4;
        recoff += 0x2C;
        k += 1;
        let j2 = rd(e + 0xD4) as usize;
        if !(k < rd(j2 + 0x40) as i32) {
            break;
        }
    }
}

