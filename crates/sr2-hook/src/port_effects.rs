//! Port module: effect_object_update (0x505480..0x50871F, 13,088 bytes) as one whole-function
//! replacement (ECX = effect object, plain `ret`).
//!
//! The original is read at instruction level in docs/analysis/46_effect_object_update.md (sections
//! S0..S9); every detail used here was re-checked against the disassembly. Callees stay the
//! original game functions, called with the registers the LTCG build passes them. The x87
//! arithmetic runs at 53-bit precision, so intermediates are f64 and every `fstp dword` is an
//! `as f32`; compares reproduce the C0/C2/C3 flags (`fcmp`) and the `test ah, mask` + `jp` / `jnp`
//! parity trick (`pf`).
//!
//! Deviations from doc 46 found on the way (the code is what counts):
//! - S8d: the block at 0x5077B0 is force-field type 1 (the normalised direction to the body) and
//!   the block at 0x5076BB is type 2 (the second curve vector); the doc lists the addresses the
//!   other way round. The basis multiply is `V' = (m0 x + m3 y) + m6 z` etc. in both.
//! - S8d impulse scale is `f32(((g * A) * C) * dt)` with NO intermediate f32 stores.
//! - S8f intensity is `f32((P[0x1E0] / 0.6) * inten)` with no rounding of the quotient.
//! - physics_body_apply_linear_impulse is entered with ECX = the body handle `h`.
//! - S4: the lower-bound test is `lo > loc` -> miss, the z upper bound test is `ah & 1` (so an
//!   unordered `hi` vs `loc` is a miss on z only, a hit-through on x and y).

