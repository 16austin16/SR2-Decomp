fn bump(c: C) {
    CNT[c as usize].fetch_add(1, Ordering::Relaxed);
}

// --- Install / summary ----------------------------------------------------------------------

/// Install this module's replacements (called from hooks::install_all).
pub fn install() {
    let ok = replace_pinned("effect_object_update", FUNC, &EFFECT_OBJECT_UPDATE_BODY, effect_object_update_thunk as extern "C" fn() as usize);
    crate::log(&format!("port_effects: replaced {}/1 with Rust", ok as u32));
}

/// Per-function call counts for the periodic log.
pub fn summary() -> String {
    if CNT[C::Calls as usize].load(Ordering::Relaxed) == 0 {
        return String::new();
    }
    let parts: Vec<String> = (0..C::N as usize)
        .filter_map(|i| {
            let v = CNT[i].load(Ordering::Relaxed);
            (v != 0).then(|| format!("{} {v}", NAMES[i]))
        })
        .collect();
    format!("port_effects: {}", parts.join(", "))
}

// --- Local helpers --------------------------------------------------------------------------

unsafe fn rw(p: usize) -> u16 {
    *(p as *const u16)
}

unsafe fn ww(p: usize, v: u16) {
    *(p as *mut u16) = v
}

/// A qword constant (the x87 `fld qword` / `fmul qword` operands).
unsafe fn rq(p: usize) -> f64 {
    *(p as *const f64)
}

/// `fld dword`.
unsafe fn ld(p: usize) -> f64 {
    rf(p) as f64
}

/// A `fld dword` / `fstp dword` round trip: the bits, except that a signalling NaN is quieted.
fn q32(bits: u32) -> u32 {
    if bits & 0x7F80_0000 == 0x7F80_0000 && bits & 0x007F_FFFF != 0 { bits | 0x0040_0000 } else { bits }
}

fn al(r: u32) -> bool {
    r & 0xFF != 0
}

/// The x87 condition bits `fnstsw ax` leaves in AH after comparing `a` (ST0) with `b`: C0 (1) when
/// a < b, C3 (0x40) when equal, all three (C0|C2|C3) when unordered.
fn fcmp(a: f64, b: f64) -> u8 {
    if a.is_nan() || b.is_nan() {
        0x45
    } else if a < b {
        0x01
    } else if a == b {
        0x40
    } else {
        0
    }
}

/// `test ah, mask` then `jp`: PF is set when the masked byte has an even number of one bits.
fn pf(ah: u8, mask: u8) -> bool {
    (ah & mask).count_ones() % 2 == 0
}

/// `_ftol2_sse`: cvttsd2si (0x80000000 when out of range or NaN).
fn ftol(x: f64) -> i32 {
    if x.is_nan() || x >= 2147483648.0 || x <= -2147483649.0 { i32::MIN } else { x as i32 }
}

/// `(x*x + y*y) + z*z` the way the x87 code sums it (f64 until the single store).
fn sumsq(x: f32, y: f32, z: f32) -> f32 {
    (((x as f64) * (x as f64) + (y as f64) * (y as f64)) + (z as f64) * (z as f64)) as f32
}

/// `(a*x + b*y) + c*z`, one store.
fn dot3(a: f32, x: f32, b: f32, y: f32, c: f32, z: f32) -> f32 {
    (((a as f64) * (x as f64) + (b as f64) * (y as f64)) + (c as f64) * (z as f64)) as f32
}

/// `v x M` for a row-major 3x3 at `m` as the game's code spells it out: `x' = m0 x + m3 y + m6 z`,
/// `y' = m1 x + m4 y + m7 z`, `z' = m2 x + m5 y + m8 z`.
unsafe fn vxm(v: [f32; 3], m: usize) -> [f32; 3] {
    [
        dot3(rf(m), v[0], rf(m + 0x0C), v[1], rf(m + 0x18), v[2]),
        dot3(rf(m + 0x04), v[0], rf(m + 0x10), v[1], rf(m + 0x1C), v[2]),
        dot3(rf(m + 0x08), v[0], rf(m + 0x14), v[1], rf(m + 0x20), v[2]),
    ]
}

/// The signed circular clock difference `CD(pt)` (doc 46, S8d): -(time since pt) in ms, or +1.8e9
/// when `pt < 0`.
fn cd(pt: i32, now: i32) -> i32 {
    if pt < 0 {
        return 0x6B49_D200;
    }
    if pt > now {
        let d = pt.wrapping_sub(now);
        if d > 0x35A4_E900 { d.wrapping_add(0x94B6_2E00u32 as i32) } else { d }
    } else {
        let c = now.wrapping_sub(pt);
        if c > 0x35A4_E900 { pt.wrapping_sub(now).wrapping_add(0x6B49_D200) } else { c.wrapping_neg() }
    }
}

/// `P[0x204] &= ~2; P[0x18] = NOW wrapped` (the force-field phase ends).
unsafe fn end_phase(p: usize, now: i32) {
    wb(p + 0x204, rb(p + 0x204) & 0xFD);
    wd(p + 0x18, (if now > 0x6B49_D200 { now - 0x6B49_D200 } else { now }) as u32);
}

/// 16-byte aligned scratch (matrices, vectors, call blocks), accessed volatile because callees
/// write it through the pointer.
#[repr(C, align(16))]
struct Buf([u32; 32]);

impl Buf {
    fn new() -> Buf {
        Buf([0; 32])
    }
    fn p(&mut self) -> u32 {
        self.0.as_mut_ptr() as u32
    }
    fn get(&self, i: usize) -> u32 {
        unsafe { std::ptr::read_volatile(&self.0[i]) }
    }
    fn set(&mut self, i: usize, v: u32) {
        unsafe { std::ptr::write_volatile(&mut self.0[i], v) }
    }
    fn f(&self, i: usize) -> f32 {
        f32::from_bits(self.get(i))
    }
    fn setf(&mut self, i: usize, v: f32) {
        self.set(i, v.to_bits())
    }
    fn v3(&self, i: usize) -> [f32; 3] {
        [self.f(i), self.f(i + 1), self.f(i + 2)]
    }
}

/// `call_regs` for a callee that returns on the x87 stack (popped as a qword).
unsafe fn call_regs_st0(f: usize, eax: u32, ecx: u32, edx: u32, esi: u32, edi: u32, args: &[u32]) -> f64 {
    let mut out = 0f64;
    let block: [u32; 9] =
        [f as u32, ecx, edx, esi, edi, args.as_ptr() as u32, args.len() as u32, eax, &mut out as *mut f64 as u32];
    std::arch::asm!(
        "push ebx", "push esi", "push edi", "push ebp",
        "mov ebp, esp",
        "mov ebx, eax",
        "mov ecx, [ebx + 24]",
        "mov esi, [ebx + 20]",
        "2:",
        "test ecx, ecx",
        "jz 3f",
        "push dword ptr [esi + ecx*4 - 4]",
        "dec ecx",
        "jmp 2b",
        "3:",
        "mov ecx, [ebx + 4]", "mov edx, [ebx + 8]", "mov esi, [ebx + 12]", "mov edi, [ebx + 16]",
        "mov eax, [ebx + 28]",
        "call dword ptr [ebx]",
        "mov ecx, [ebx + 32]",
        "fstp qword ptr [ecx]",
        "mov esp, ebp",
        "pop ebp", "pop edi", "pop esi", "pop ebx",
        inout("eax") block.as_ptr() => _, lateout("ecx") _, lateout("edx") _,
        clobber_abi("C"),
    );
    out
}

/// A callee with ESI = `esi` that returns a scalar in XMM0 (vec3_normalize_safe_len).
unsafe fn call_xmm0(f: usize, esi: u32) -> f32 {
    let mut out = 0f32;
    let block: [u32; 3] = [f as u32, esi, &mut out as *mut f32 as u32];
    std::arch::asm!(
        "push ebx", "push esi", "push edi", "push ebp",
        "mov ebp, esp",
        "mov ebx, eax",
        "mov esi, [ebx + 4]",
        "call dword ptr [ebx]",
        "mov ecx, [ebx + 8]",
        "movss dword ptr [ecx], xmm0",
        "mov esp, ebp",
        "pop ebp", "pop edi", "pop esi", "pop ebx",
        inout("eax") block.as_ptr() => _, lateout("ecx") _, lateout("edx") _,
        clobber_abi("C"),
    );
    out
}

/// The object of a handle in the entity table 0x2149C64 (stride 16), raw (no handle check).
unsafe fn ent_raw(h: u32) -> usize {
    rd(0x0214_9C64 + ((h & 0xFFF) << 4) as usize) as usize
}

/// The light object of a handle, or 0 when stale.
unsafe fn light_obj(h: u32) -> usize {
    if h == 0 {
        return 0;
    }
    let o = 0x02AE_50E0usize.wrapping_add((h & 0xFFFF) as usize * 0x134);
    if rd(o + 8) == h { o } else { 0 }
}

/// The body object of a physics handle: `[0x28F25C0 + h * 24]`.
unsafe fn body_obj(h: u32) -> usize {
    rd(0x028F_25C0usize.wrapping_add((h as usize).wrapping_mul(24))) as usize
}

unsafe fn cutscene_blocking() -> u8 {
    call_regs(0x006C_6D20, 0, 0, 0, 0, 0, &[]) as u8
}

unsafe fn cutscene_in_progress() -> bool {
    al(call_regs(0x006C_6D90, 0, 0, 0, 0, 0, &[]))
}

/// ALIVE(h) of a 12-byte voice handle at address `h`.
unsafe fn voice_alive(h: usize) -> bool {
    let slot = rb(h);
    if slot == 0xFF {
        return false;
    }
    let generation = rd(h) >> 8;
    if generation == 0 {
        return false;
    }
    let o = slot as usize * 0x19C;
    if generation != rd(0x00EE_B9AC + o) {
        return false;
    }
    rd(0x00EE_B8F8 + o) != NONE
}

/// `audio_voice_slot_fade_out(EAX = slot, EDX = 250)`.
unsafe fn voice_fade_out(h: usize) {
    call_regs(0x0047_C740, rb(h) as u32, 0, 250, 0, 0, &[]);
}

/// `audio_voice_position_check(ECX = &pos, EDX = &handle)`.
unsafe fn voice_pos_check(pos: usize, h: usize) -> bool {
    al(call_regs(0x0047_FFC0, 0, pos as u32, h as u32, 0, 0, &[]))
}

/// LIST_UNLINK + `effect_object_part_destroy(E, P)` + the free-list insert (DESTROY_PART).
unsafe fn destroy_part(e: usize, p: usize) {
    let head = rd(e + 0xC4) as usize;
    let mut single = false;
    if head == p {
        let nx = rd(p) as usize;
        if nx == p {
            wd(p, 0);
            wd(p + 4, 0);
            wd(e + 0xC4, 0);
            single = true;
        } else {
            wd(e + 0xC4, nx as u32);
        }
    }
    if !single {
        let prev = rd(p + 4) as usize;
        if prev != 0 {
            wd(prev, rd(p));
        }
        let nx = rd(p) as usize;
        if nx != 0 {
            wd(nx + 4, rd(p + 4));
        }
        wd(p, 0);
        wd(p + 4, 0);
    }
    call_regs(0x0050_47D0, 0, 0, 0, 0, 0, &[e as u32, p as u32]);
    let fh = rd(0x00F9_F67C) as usize;
    wd(0x00F9_F674, rd(0x00F9_F674).wrapping_sub(1));
    if fh == 0 {
        wd(p, p as u32);
        wd(p + 4, p as u32);
        wd(0x00F9_F67C, p as u32);
    } else {
        let hp = rd(fh + 4);
        wd(p, fh as u32);
        wd(p + 4, hp);
        let hp2 = rd(fh + 4) as usize;
        wd(hp2, p as u32);
        wd(fh + 4, p as u32);
    }
}

// --- The thunk -------------------------------------------------------------------------------

#[unsafe(naked)]
extern "C" fn effect_object_update_thunk() {
    std::arch::naked_asm!(
        "push ecx",
        "push edx",
        "push ecx",
        "call {f}",
        "add esp, 4",
        "pop edx",
        "pop ecx",
        "ret",
        f = sym effect_object_update,
    )
}

extern "C" fn effect_object_update(e: u32) {
    bump(C::Calls);
    unsafe { update(e as usize) }
}

/// The whole function. `e` = the effect object.
unsafe fn update(e: usize) {
    // ---- S0: early outs and the stop rule (0x505480) ----
    if rb(0x0252_7280) != 0 {
        bump(C::S0Early);
        return;
    }
    let i0 = rd(e + 0xD0) as usize;
    if rd(i0 + 0x28) == 0 && rd(e + 0xD4) == 0 {
        bump(C::S0Early);
        return;
    }
    if rb(e + 0x84) & 1 != 0 {
        let stop = if rd(e + 0x358) == 0 { rb(i0 + 0x2E) & 0x20 == 0 } else { rd(e + 0xCC) != 1 };
        if stop {
            bump(C::S0Stop);
            call_regs(0x0050_AB60, 0, 0, 0, 0, e as u32, &[0, 0]);
        }
    }

    // ---- S1: reset the centre, expire the timed lists (0x505504) ----
    wd(e + 0x14, rd(0x0252_A6D0));
    wd(e + 0x18, rd(0x0252_A6D4));
    wd(e + 0x1C, rd(0x0252_A6D8));
    let mut live_total: i32 = 0;
    let mut count: i32 = 0;
    let mut kept: i32 = 0;
    if rd(e + 0xDC) as i32 > 0 {
        bump(C::S1);
        let mut i = 0i32;
        loop {
            let l = rd(e + 0xE0 + 4 * i as usize);
            live_total = live_total.wrapping_add(call_regs(0x0050_F780, 0, 0, 0, l, 0, &[]) as i32);
            i += 1;
            if !(i < rd(e + 0xDC) as i32) {
                break;
            }
        }
    }

    // ---- S2: part loop (0x505564) ----
    s2_parts(e, &mut count);

    // ---- S3: centre and radius (0x505B64) ----
    if count > 0 {
        s3_centre(e, count);
    }

    // ---- S4: vehicle boxes (0x505CC2) ----
    let i1 = rd(e + 0xD0) as usize;
    if rb(i1 + 0x2E) & 4 != 0 {
        bump(C::S4Veh);
        if s4_vehicles(e, 0x022A_84E0) {
            bump(C::S4Hit);
            return;
        }
        if s4_vehicles(e, 0x022A_84D4) {
            bump(C::S4Hit);
            return;
        }
    }

    // ---- S5: local player box (0x50639C) ----
    if s5_player(e) {
        bump(C::S5Return);
        return;
    }

    // ---- S6: visibility and fade (0x506448) ----
    s6_visibility(e);

    // ---- S7: lifetime timer, stop, explosion (0x5067D7) ----
    if s7_timer(e) {
        return;
    }

    // ---- S8: main pass per part (0x5069D8) ----
    let n = rd(e + 0xDC) as usize;
    let bytes = n.wrapping_mul(4);
    let mut buf: Vec<Buf> = Vec::new();
    buf.resize_with(bytes.div_ceil(128).max(1), Buf::new);
    let bufp = buf.as_mut_ptr() as usize;
    s8_parts(e, bufp, &mut live_total, &mut kept);

    // ---- S9: tail (0x5086A4) ----
    bump(C::S9);
    wd(e + 0x340, live_total as u32);
    let mut i = 0usize;
    while (i as i32) < rd(e + 0xDC) as i32 {
        let l = rd(e + 0xE0 + 4 * i) as usize;
        if l != 0 {
            wd(l + 0xA4, q32(rd(bufp + 4 * i)));
        }
        i += 1;
    }
    if kept <= 0 && live_total <= 0 && rd(e + 0xCC) != 2 {
        bump(C::S9Self);
        let vt = rd(e) as usize;
        call_regs(rd(vt + 0x10) as usize, 0, e as u32, 0, 0, 0, &[0]);
    }
    drop(buf);
}

// --- S2 ----------------------------------------------------------------------------------------

unsafe fn s2_parts(e: usize, count: &mut i32) {
    let mut p = rd(e + 0xC4) as usize;
    while p != 0 {
        bump(C::S2Part);
        let l = rd(p);
        let next = if l != rd(e + 0xC4) { l as usize } else { 0 };
        let pos = p + 0x2C;
        let mat = p + 0x38;
        copy_dwords(p + 0x5C, pos, 3);
        copy_dwords(p + 0x68, mat, 9);
        if s2_sync(e, p, pos, mat) {
            // ACCUM (0x505A2D)
            wf(e + 0x14, (ld(e + 0x14) + ld(pos)) as f32);
            wf(e + 0x18, (ld(pos + 4) + ld(e + 0x18)) as f32);
            wf(e + 0x1C, (ld(pos + 8) + ld(e + 0x1C)) as f32);
            *count += 1;
        } else {
            destroy_part(e, p);
        }
        p = next;
    }
}

/// Syncs one part's transform. Returns false when the part must be destroyed.
unsafe fn s2_sync(e: usize, p: usize, pos: usize, mat: usize) -> bool {
    let h = rd(p + 0x20);
    if h != 0 {
        let ent = ent_raw(h);
        if ent != 0 && rd(ent + 0x44) == h && rd(ent + 0x4C) == 1 && rd(ent + 0xC8) & 0x40_0000 == 0 {
            wb(p + 0x204, rb(p + 0x204) & 0xCF);
            wd(p + 0x24, NONE);
        }
    }
    let flags = rb(p + 0x204);

    if flags & 4 != 0 {
        // Branch A: physics-body part.
        bump(C::S2PhysBody);
        let mut pt = Buf::new();
        let mut mt = Buf::new();
        let ok = al(call_regs(0x006F_DAC0, 0, 0, 0, 0, pt.p(), &[h, mt.p()]));
        if !ok {
            bump(C::S2PhysBodyGone);
            return false;
        }
        for k in 0..3 {
            wd(pos + 4 * k, pt.get(k));
        }
        for k in 0..9 {
            wd(mat + 4 * k, mt.get(k));
        }
        let mut off = Buf::new();
        off.set(0, q32(rd(e + 0x348)));
        off.set(1, q32(rd(e + 0x34C)));
        off.set(2, q32(rd(e + 0x350)));
        let d = [rd(0x0252_A6D0), rd(0x0252_A6D4), rd(0x0252_A6D8)];
        let differs = (0..3).any(|k| pf(fcmp(off.f(k) as f64, f32::from_bits(d[k]) as f64), 0x44));
        if differs {
            call_regs(0x00BD_E570, mat as u32, off.p(), 0, 0, 0, &[]);
            wf(pos, (off.f(0) as f64 + ld(pos)) as f32);
            wf(pos + 4, (ld(pos + 4) + off.f(1) as f64) as f32);
            wf(pos + 8, (ld(pos + 8) + off.f(2) as f64) as f32);
        }
        return true;
    }

    // Branch B.
    if h == 0 {
        bump(C::S2NoOwner);
        if rd(e + 0x7C) != NONE {
            call_regs(0x006F_C760, 0, 0, 0, pos as u32, mat as u32, &[rd(e + 0x7C)]);
        }
        return true;
    }
    let ent = ent_raw(h);
    if ent == 0 || rd(ent + 0x44) != h {
        bump(C::S2OwnerGone);
        return false;
    }
    let bone = rd(p + 0x24);
    if bone != NONE {
        match rd(ent + 0x4C) {
            1 => {
                bump(C::S2BoneHuman);
                let mut local = [0u32; 9];
                for k in 0..9 {
                    local[k] = q32(rd(e + 0x20 + 4 * k));
                }
                let rig = rd(rd(ent + 0x5E0) as usize);
                call_regs(
                    0x00CE_DF10,
                    0,
                    rig,
                    0,
                    0,
                    0,
                    &[bone, (ent + 0x14) as u32, (ent + 0x20) as u32, pos as u32, mat as u32],
                );
                if rb(e + 0x35C) == 1 {
                    for k in 0..9 {
                        wd(mat + 4 * k, local[k]);
                    }
                }
            }
            5 => {
                bump(C::S2BoneVehicle);
                call_regs(0x00AA_C5C0, bone, mat as u32, 0, 0, 0, &[pos as u32, ent as u32]);
            }
            _ => {
                bump(C::S2BoneVirt);
                let vt1 = rd(rd(ent) as usize + 4) as usize;
                let args = [bone, (ent + 0x14) as u32, (ent + 0x20) as u32, mat as u32];
                let desc = call_regs(vt1, 0, ent as u32, 0, 0, 0, &args);
                call_regs(0x006E_5DB0, pos as u32, 0, desc, 0, 0, &args);
            }
        }
        return true;
    }
    if flags & 0x10 != 0 {
        bump(C::S2Hand0);
        let ent = ent_raw(h);
        if ent == 0 || rd(ent + 0x44) != h || rd(ent + 0x4C) != 1 {
            return false;
        }
        return al(call_regs(0x009C_4430, ent as u32, 0, 0, 0, 0, &[pos as u32, mat as u32]));
    }
    if flags & 0x20 != 0 {
        bump(C::S2Hand1);
        let hum = call_regs(0x0096_0D60, h, 0, 0, 0, 0, &[]);
        if hum == 0 {
            return false;
        }
        return al(call_regs(0x009C_44C0, hum, 0, 0, 0, 0, &[pos as u32, mat as u32]));
    }
    // Plain owner follow (0x505995).
    bump(C::S2Follow);
    copy_dwords(pos, ent + 0x14, 3);
    if rb(e + 0x35C) == 0 {
        copy_dwords(mat, ent + 0x20, 9);
    }
    let mut off = Buf::new();
    off.set(0, q32(rd(e + 0x348)));
    off.set(1, q32(rd(e + 0x34C)));
    off.set(2, q32(rd(e + 0x350)));
    if al(call_regs(0x0040_B6A0, 0, 0x0252_A6D0, off.p(), 0, 0, &[])) {
        call_regs(0x00BD_E570, mat as u32, off.p(), 0, 0, 0, &[]);
        wf(pos, (off.f(0) as f64 + ld(pos)) as f32);
        wf(pos + 4, (ld(pos + 4) + off.f(1) as f64) as f32);
        wf(pos + 8, (ld(pos + 8) + off.f(2) as f64) as f32);
    }
    true
}

// --- S3 ----------------------------------------------------------------------------------------

unsafe fn s3_centre(e: usize, count: i32) {
    bump(C::S3);
    let inv = (1.0f64 / count as f64) as f32;
    wf(e + 0x14, (inv as f64 * ld(e + 0x14)) as f32);
    wf(e + 0x18, (inv as f64 * ld(e + 0x18)) as f32);
    wf(e + 0x1C, (inv as f64 * ld(e + 0x1C)) as f32);
    let r: f32;
    if rd(e + 0xCC) == 4 {
        bump(C::S3Static);
        r = rf(0x00E5_C7D8);
    } else {
        let mut best = [
            f32::from_bits(q32(rd(0x0252_A6D0))),
            f32::from_bits(q32(rd(0x0252_A6D4))),
            f32::from_bits(q32(rd(0x0252_A6D8))),
        ];
        let mut best_d2 = 0.0f32;
        let head = rd(e + 0xC4) as usize;
        let mut c = head;
        if c != 0 {
            loop {
                let dx = (ld(c + 0x2C) - ld(e + 0x14)) as f32;
                let dy = (ld(c + 0x30) - ld(e + 0x18)) as f32;
                let dz = (ld(c + 0x34) - ld(e + 0x1C)) as f32;
                let d2 = sumsq(dx, dy, dz);
                // fcomp st(1): best_d2 vs d2; jp keeps when best >= d2 or unordered.
                if !pf(fcmp(best_d2 as f64, d2 as f64), 5) {
                    best_d2 = d2;
                    best = [dx, dy, dz];
                }
                c = rd(c) as usize;
                if c == head || c == 0 {
                    break;
                }
            }
        }
        let s = sumsq(best[0], best[1], best[2]);
        let sq = call_regs_st0(0x0040_EA20, 0, 0, 0, 0, 0, &[s.to_bits()]);
        let i = rd(e + 0xD0) as usize;
        r = (sq + ld(i + 0x1C)) as f32;
    }
    wf(e + 0x33C, r);
}

// --- S4 ----------------------------------------------------------------------------------------

/// One vehicle list (the two compiler copies, at 0x505CE7 and 0x506049, compute the same
/// boxes: ext = B - A, the shrunk x/z and grown y local box, the centre rel to the world box).
/// Returns true when the effect centre lies inside a vehicle box (the hit flag).
unsafe fn s4_vehicles(e: usize, head_addr: usize) -> bool {
    let mut hit = false;
    let mut v = rd(head_addr) as usize;
    if v == 0 {
        return false;
    }
    loop {
        let dx = (ld(v + 0x14) - ld(e + 0x14)) as f32;
        let mut sq = (dx as f64 * dx as f64) as f32;
        let dy = (ld(v + 0x18) - ld(e + 0x18)) as f32;
        sq = (dy as f64 * dy as f64 + sq as f64) as f32;
        let dz = (ld(v + 0x1C) - ld(e + 0x1C)) as f32;
        let d2 = (dz as f64 * dz as f64 + sq as f64) as f32;
        // fcomp qword 100.0; jp skips when d2 >= 100 or unordered.
        if !pf(fcmp(d2 as f64, rq(0x00E5_C190)), 5) {
            let mut a = Buf::new(); // local min
            let mut b = Buf::new(); // local max
            let mut p0 = Buf::new(); // world min
            let mut q0 = Buf::new(); // world max
            let vt = rd(v) as usize;
            call_regs(rd(vt + 0x0C) as usize, 0, v as u32, 0, 0, 0, &[a.p(), b.p()]);
            let vt = rd(v) as usize;
            call_regs(rd(vt + 0x08) as usize, 0, v as u32, 0, 0, 0, &[p0.p(), q0.p()]);
            let ex = (b.f(0) as f64 - a.f(0) as f64) as f32;
            let ey = (b.f(1) as f64 - a.f(1) as f64) as f32;
            let ez = (b.f(2) as f64 - a.f(2) as f64) as f32;
            let k08 = rq(0x00E5_C2E0);
            let sa = (k08 * ex as f64) as f32;
            let sb = (ey as f64 + rq(0x00E5_BF40)) as f32;
            let sc = (k08 * ez as f64) as f32;
            let half = rq(0x00E5_BF70);
            let mut cen = [0f32; 3];
            for k in 0..3 {
                let dd = (q0.f(k) as f64 - p0.f(k) as f64) as f32;
                let hh = (dd as f64 * half) as f32;
                cen[k] = (p0.f(k) as f64 + hh as f64) as f32;
            }
            let nh = rq(0x00E5_C478);
            let lo = [(nh * sa as f64) as f32, (sb as f64 * nh) as f32, (sc as f64 * nh) as f32];
            let hi = [(sa as f64 * half) as f32, (sb as f64 * half) as f32, (sc as f64 * half) as f32];
            let rel = [
                (ld(e + 0x14) - cen[0] as f64) as f32,
                (ld(e + 0x18) - cen[1] as f64) as f32,
                (ld(e + 0x1C) - cen[2] as f64) as f32,
            ];
            let loc = [
                dot3(rf(v + 0x20), rel[0], rf(v + 0x24), rel[1], rf(v + 0x28), rel[2]),
                dot3(rf(v + 0x2C), rel[0], rf(v + 0x30), rel[1], rf(v + 0x34), rel[2]),
                dot3(rf(v + 0x38), rel[0], rf(v + 0x3C), rel[1], rf(v + 0x40), rel[2]),
            ];
            // x and y: miss when lo > loc (ah & 0x41 == 0) or hi < loc (jnp on ah & 5).
            // z: miss likewise, but the upper test is `test ah, 1; jne` (unordered misses too).
            let mut inside = true;
            for k in 0..3 {
                if fcmp(lo[k] as f64, loc[k] as f64) & 0x41 == 0 {
                    inside = false;
                    break;
                }
                let ah = fcmp(hi[k] as f64, loc[k] as f64);
                let miss = if k < 2 { !pf(ah, 5) } else { ah & 1 != 0 };
                if miss {
                    inside = false;
                    break;
                }
            }
            if inside {
                hit = true;
            }
        }
        v = rd(v + 0x84DC) as usize;
        if v == rd(head_addr) as usize || v == 0 {
            break;
        }
    }
    hit
}

// --- S5 ----------------------------------------------------------------------------------------

/// The effect centre inside the local player's box (min.y lowered by 1.0): the whole update
/// returns.
unsafe fn s5_player(e: usize) -> bool {
    let i = rd(e + 0xD0) as usize;
    if rb(i + 0x2E) & 8 == 0 {
        return false;
    }
    let pl = rd(0x0217_03D4) as usize;
    if pl == 0 {
        return false;
    }
    let mut mn = Buf::new();
    let mut mx = Buf::new();
    let vt = rd(pl) as usize;
    call_regs(rd(vt + 8) as usize, 0, pl as u32, 0, 0, 0, &[mn.p(), mx.p()]);
    let (ex, ey, ez) = (ld(e + 0x14), ld(e + 0x18), ld(e + 0x1C));
    // fcompp with st0 = the box value, st1 = the centre: `test ah,5; jp` bails when !(box < c);
    // `test ah,0x41; jne` bails unless box > c.
    if pf(fcmp(mn.f(0) as f64, ex), 5) {
        return false;
    }
    if fcmp(mx.f(0) as f64, ex) & 0x41 != 0 {
        return false;
    }
    if pf(fcmp(mn.f(1) as f64 - rq(0x00E5_BF40), ey), 5) {
        return false;
    }
    if fcmp(mx.f(1) as f64, ey) & 0x41 != 0 {
        return false;
    }
    if pf(fcmp(mn.f(2) as f64, ez), 5) {
        return false;
    }
    fcmp(mx.f(2) as f64, ez) & 0x41 == 0
}

// --- S6 ----------------------------------------------------------------------------------------

fn fade_clamp(v: f32) -> f32 {
    let vf = v as f64;
    if pf(fcmp(0.0, vf), 5) {
        0.0
    } else if fcmp(1.0, vf) & 0x41 != 0 {
        1.0
    } else {
        v
    }
}

unsafe fn s6_visibility(e: usize) {
    let kind = rd(e + 0xCC);
    if kind == 4 {
        bump(C::S6Static);
        let mut p = rd(e + 0xC4) as usize;
        if p != 0 {
            loop {
                wb(p + 0x204, rb(p + 0x204) | 0x40);
                wf(p + 0x90, 1.0);
                wb(p + 0x205, rb(p + 0x205) & 0xFE);
                p = rd(p) as usize;
                if p == rd(e + 0xC4) as usize || p == 0 {
                    break;
                }
            }
        }
        return;
    }
    let mut p = rd(e + 0xC4) as usize;
    if p == 0 {
        return;
    }
    let step = (ld(0x00E8_437C) / rq(0x00E5_C408)) as f32;
    loop {
        bump(C::S6Part);
        wb(p + 0x205, rb(p + 0x205) & 0xFE);
        wb(p + 0x204, rb(p + 0x204) | 0x40);
        let s205 = rb(p + 0x205);
        let s204 = rb(p + 0x204);
        let dx = (ld(p + 0x2C) - ld(0x025F_5B14)) as f32;
        let mut sq = (dx as f64 * dx as f64) as f32;
        let dy = (ld(p + 0x30) - ld(0x025F_5B18)) as f32;
        sq = (dy as f64 * dy as f64 + sq as f64) as f32;
        let dz = (ld(p + 0x34) - ld(0x025F_5B1C)) as f32;
        let camd2 = (dz as f64 * dz as f64 + sq as f64) as f32;
        let i = rd(e + 0xD0) as usize;
        let mut lim = rf(i + 0x10);
        let cb = cutscene_blocking();
        if cb == 1 {
            lim = rf(i + 0x14);
        }
        if rb(0x0252_6BD2) != 0 && rb(0x0252_6BDF) != 0 {
            let s0 = ld(0x0252_6CB8);
            let s = s0 * s0;
            // fcom st(1): lim vs s; jp (lim >= s or unordered) takes s.
            if pf(fcmp(lim as f64, s), 5) {
                lim = s as f32;
            }
        }
        let c8 = rd(e + 0xC8);
        // fcomp st(1): lim vs camd2; jp (lim >= camd2 or unordered) is not "too far".
        if !pf(fcmp(lim as f64, camd2 as f64), 5) {
            bump(C::S6Far);
            if c8 & 0x80 == 0 || rd(e + 0x340) == 0 {
                wb(p + 0x205, s205 | 1);
            }
            if c8 & 0x80 != 0 && s204 & 0x80 == 0 {
                wb(p + 0x204, s204 | 0x80);
            }
        } else if fcmp(ld(i + 0x18), camd2 as f64) & 0x41 == 0 {
            bump(C::S6Near);
            wb(p + 0x205, s205 | 1);
        } else {
            let r = rf(i + 0x1C);
            let mut mn = Buf::new();
            let mut mxv = Buf::new();
            let nr = (r as f64 * rq(0x00E5_C180)) as f32;
            for k in 0..3 {
                mn.setf(k, nr);
                mxv.setf(k, r);
            }
            let mut a = Buf::new();
            let mut b = Buf::new();
            call_regs(0x00BF_58D0, (p + 0x2C) as u32, (p + 0x2C) as u32, mxv.p(), mn.p(), (p + 0x38) as u32, &[a.p(), b.p()]);
            let mut visible = true;
            if cb == 0 {
                if call_regs(0x00A0_20C0, 0, b.p(), a.p(), 0, 0, &[0x0277_CBF0]) == 0 {
                    visible = false;
                } else if al(call_regs(0x0052_4550, 0, 0, 0, 0, 0, &[a.p(), b.p()])) {
                    visible = false;
                }
            }
            if !visible {
                bump(C::S6Hidden);
                wb(p + 0x205, s205 | 1);
            } else {
                bump(C::S6Visible);
                if rd(e + 0xC8) & 0x80 != 0 && s204 & 0x80 != 0 {
                    wb(p + 0x204, s204 & 0x7F);
                }
            }
        }
        // Fade.
        if rb(p + 0x205) & 1 != 0 {
            let v = (ld(p + 0x90) - step as f64) as f32;
            wf(p + 0x90, v);
            if !pf(fcmp(v as f64, rq(0x00E5_CB58)), 0x41) {
                wb(p + 0x204, rb(p + 0x204) & 0xBF);
            }
            wf(p + 0x90, fade_clamp(v));
        } else {
            let v = (ld(p + 0x90) + step as f64) as f32;
            wf(p + 0x90, v);
            wf(p + 0x90, fade_clamp(v));
        }
        p = rd(p) as usize;
        if p == rd(e + 0xC4) as usize || p == 0 {
            break;
        }
    }
}

