//! Port module: human_update_core (0x9A7DF0), human_state_machine_update (0x9947F0) and the
//! state handlers that are small enough to reproduce exactly.
//!
//! Call skeletons, as in port_sim_humans.rs: every callee is still the original game function,
//! called with the registers the LTCG build passes it (each callee checked at its disassembly,
//! including the registers its own callees read). The control flow, the bit tests and the x87
//! arithmetic are reproduced here; every `fstp dword` of the original is an `as f32`, every
//! `fld dword` / `fstp dword` copy a `q32`.

use std::sync::atomic::{AtomicU32, Ordering};

use crate::portlib::*;

static CORE_CALLS: AtomicU32 = AtomicU32::new(0);
static STATE_MACHINE_CALLS: AtomicU32 = AtomicU32::new(0);
static STATE1_CALLS: AtomicU32 = AtomicU32::new(0);
static STATE8_CALLS: AtomicU32 = AtomicU32::new(0);

const HUMAN_UPDATE_CORE: usize = 0x009A_7DF0;
const HUMAN_STATE_MACHINE_UPDATE: usize = 0x0099_47F0;
const HUMAN_STATE1_UPDATE: usize = 0x0099_8790;
const HUMAN_STATE8_UPDATE: usize = 0x0099_89C0;

const NONE: u32 = 0xFFFF_FFFF;

/// Install this module's replacements (called from hooks::install_all).
pub fn install() {
    let ports: [(&str, usize, &[u8], usize); 4] = [
        ("human_update_core", HUMAN_UPDATE_CORE, &HUMAN_UPDATE_CORE_BODY, human_update_core_thunk as extern "C" fn() as usize),
        (
            "human_state_machine_update",
            HUMAN_STATE_MACHINE_UPDATE,
            &HUMAN_STATE_MACHINE_UPDATE_BODY,
            human_state_machine_update_thunk as extern "C" fn() as usize,
        ),
        ("human_state1_update", HUMAN_STATE1_UPDATE, &HUMAN_STATE1_UPDATE_BODY, human_state1_update_thunk as extern "C" fn() as usize),
        ("human_state8_update", HUMAN_STATE8_UPDATE, &HUMAN_STATE8_UPDATE_BODY, human_state8_update_thunk as extern "C" fn() as usize),
    ];
    let mut n = 0;
    for (name, addr, body, thunk) in ports {
        if replace_pinned(name, addr, body, thunk) {
            n += 1;
        }
    }
    crate::log(&format!("port_humans2: replaced {n}/{} with Rust", ports.len()));
}

/// One line for the periodic log.
pub fn summary() -> String {
    let parts: Vec<String> = [
        ("human_update_core", &CORE_CALLS),
        ("human_state_machine_update", &STATE_MACHINE_CALLS),
        ("human_state1_update", &STATE1_CALLS),
        ("human_state8_update", &STATE8_CALLS),
    ]
    .iter()
    .filter_map(|(name, c)| {
        let v = c.load(Ordering::Relaxed);
        (v != 0).then(|| format!("{name} {v}"))
    })
    .collect();
    if parts.is_empty() { String::new() } else { format!("port_humans2: {}", parts.join(", ")) }
}

// --- local helpers -------------------------------------------------------------------------------

/// A qword constant (the x87 `fld qword` / `fmul qword` operands).
unsafe fn rq(p: usize) -> f64 {
    unsafe { *(p as *const f64) }
}

fn f(bits: u32) -> f64 {
    f32::from_bits(bits) as f64
}

/// A `fld dword` / `fstp dword` round trip: the bits, except that a signalling NaN is quieted.
fn q32(bits: u32) -> u32 {
    if bits & 0x7F80_0000 == 0x7F80_0000 && bits & 0x007F_FFFF != 0 { bits | 0x0040_0000 } else { bits }
}

fn b32(x: f64) -> u32 {
    (x as f32).to_bits()
}

fn p32<T>(x: &mut T) -> u32 {
    x as *mut T as u32
}

fn al(r: u32) -> bool {
    r & 0xFF != 0
}

/// `call_regs` for a callee that returns on the x87 stack: the result is popped as a qword.
unsafe fn call_regs_st0(f: usize, eax: u32, ecx: u32, edx: u32, esi: u32, edi: u32, args: &[u32]) -> f64 {
    let mut out = 0f64;
    let block: [u32; 9] =
        [f as u32, ecx, edx, esi, edi, args.as_ptr() as u32, args.len() as u32, eax, &mut out as *mut f64 as u32];
    unsafe {
        std::arch::asm!(
            "push ebx", "push esi", "push edi", "push ebp",
            "mov ebp, esp",
            "mov ebx, eax",
            "mov ecx, [ebx + 24]",
            "mov esi, [ebx + 20]",
            "2:",
            "test ecx, ecx",
            "jz 3f",
            "push dword ptr [esi + ecx*4 - 4]",
            "dec ecx",
            "jmp 2b",
            "3:",
            "mov ecx, [ebx + 4]", "mov edx, [ebx + 8]", "mov esi, [ebx + 12]", "mov edi, [ebx + 16]",
            "mov eax, [ebx + 28]",
            "call dword ptr [ebx]",
            "mov ecx, [ebx + 32]",
            "fstp qword ptr [ecx]",
            "mov esp, ebp",
            "pop ebp", "pop edi", "pop esi", "pop ebx",
            inout("eax") block.as_ptr() => _, lateout("ecx") _, lateout("edx") _,
            clobber_abi("C"),
        );
    }
    out
}

/// The object of a handle in the 4096-slot table 0x2149C64 (stride 16), or 0 when stale.
unsafe fn obj_from_handle(h: u32) -> u32 {
    unsafe {
        if h == 0 {
            return 0;
        }
        let o = rd(0x0214_9C64 + ((h & 0xFFF) << 4) as usize);
        if o != 0 && rd(o as usize + 0x44) == h { o } else { 0 }
    }
}

/// The "in a vehicle" test used twice by human_update_core and once per human by its threat
/// scan: the handle is set, the human is not the cutscene actor [0xEBCE9C] (unless the cutscene
/// kind is 7 or 8), human_entering_or_exiting_vehicle (0x9B92E0, EAX = human) is false and
/// vehicle_from_handle (0xAE28F0, ECX = handle +0xD74) gives a vehicle. `kind` is [0xEBCEA0] as
/// the caller read it.
unsafe fn in_vehicle(h: u32, kind: u32) -> bool {
    unsafe {
        let p = h as usize;
        let hh = rd(p + 0x44);
        if hh == 0 {
            return false;
        }
        let c = rd(0x00EB_CE9C);
        if c != 0 && hh == rd(c as usize + 0x44) && kind != 7 && kind != 8 {
            return false;
        }
        if al(call_regs(0x009B_92E0, h, 0, 0, 0, 0, &[])) {
            return false;
        }
        call_regs(0x00AE_28F0, 0, rd(p + 0xD74), 0, 0, 0, &[]) != 0
    }
}

/// anim_track_is_playing (0xCECB80): ECX = the rig's anim object [[+0x5E0]], cdecl (set, track).
unsafe fn anim_playing(rig: u32, set: u32, track: u32) -> bool {
    unsafe { al(call_regs(0x00CE_CB80, 0, rd(rig as usize), rig, 0, NONE, &[set, track])) }
}

/// One slot of the three-entry human lists 0xF53908 / 0xF53914 holds `h`.
unsafe fn listed(h: u32, base: usize) -> bool {
    unsafe { (0..3).any(|i| rd(base + i * 4) == h) }
}

// --- human_update_core (0x9A7DF0) ----------------------------------------------------------------

// cdecl (human, f32 dt), from human_update (0x9D6D60) and 0x9CF8D9. Doc 15, "human_update_core
// porting map", corrected against the disassembly. The original keeps EBP = human and, from
// 0x9A8391 on, EDI = -1; those are passed to the callees that see them.

keep_ecx_edx_arg2!(human_update_core_thunk, human_update_core);

extern "C" fn human_update_core(h: u32, dt: u32) {
    CORE_CALLS.fetch_add(1, Ordering::Relaxed);
    unsafe { core_body(h, dt) };
}

unsafe fn core_body(h: u32, dt: u32) {
    unsafe {
        let p = h as usize;
        if h == 0 || rb(p + 0x80) & 0xB != 0 {
            return;
        }
        let (x, y, z) = (rd(p + 0x14), rd(p + 0x18), rd(p + 0x1C));
        wd(p + 0xCC, rd(p + 0xCC) & 0xFFFF_CFFF);
        wb(p + 0xC08, rb(p + 0xC08) & 0x7F);
        wd(p + 0x50, x);
        wd(p + 0x54, y);
        wd(p + 0x58, z);

        // Passenger test: `slow` is 0x9A62D0 (EAX = human, ESI = vehicle), `pass` the flag A.
        let mut slow = false;
        let mut pass = false;
        let hh = rd(p + 0x44);
        if hh != 0 {
            let c = rd(0x00EB_CE9C);
            let kind = rd(0x00EB_CEA0);
            let actor = c != 0 && hh == rd(c as usize + 0x44) && kind != 7 && kind != 8;
            if !actor && !al(call_regs(0x009B_92E0, h, 0, 0, 0, 0, &[])) {
                let vh = rd(p + 0xD74);
                if call_regs(0x00AE_28F0, 0, vh, vh, 0, 0, &[]) != 0 && !(rd(p + 0x4C) == 1 && rb(p + 0x3CC) == 1) {
                    let v = call_regs(0x00AE_28F0, 0, vh, vh, 0, 0, &[]);
                    if v != 0 {
                        slow = al(call_regs(0x009A_62D0, h, 0, 0, v, 0, &[]));
                        pass = !slow;
                    }
                }
            }
        }

        core_time_scale(h, dt, slow, pass);
        core_clock(h, dt);

        // Pending damage +0xC20 (amount) / +0xC28 (source handle) unless dead (0x985630).
        if !al(call_regs(0x0098_5630, 0, 0, 0, 0, 0, &[h])) {
            let c20 = rd(p + 0xC20);
            // `fldz; fcomp; test ah, 0x44; jnp`: skipped only when exactly 0.
            if f(c20) != 0.0 {
                let amt = q32(c20);
                let src = call_regs(0x0096_0D60, rd(p + 0xC28), 0, 0, 0, 0, &[]); // human_from_handle
                call_regs_st0(0x0098_47A0, 0, src, 0, 0, 0, &[h, amt, 0, 0]); // human_take_damage
                wd(p + 0xC20, 0);
                wd(p + 0xC28, 0);
            }
        }

        // Pending knockdown +0xC24: 0x98D3C0(ECX = 0, cdecl human, 0x98E2A0(), 0, 0, 0).
        if (rd(p + 0xC0) >> 10) & 1 == 0 && rb(p + 0xC24) == 1 {
            let k = call_regs_st0(0x0098_E2A0, 0, 0, 0, 0, 0, &[]) as f32;
            call_regs(0x0098_D3C0, 0, 0, 0, 0, 0, &[h, k.to_bits(), 0, 0, 0]);
        }

        // Collision-ignore window (+0xC8 bit 0x40, timer +0xF94), 0x7190C0(ECX = human, on).
        let c8 = rd(p + 0xC8);
        wb(p + 0xC24, 0);
        let now;
        if c8 & 0x40 != 0 && c8 & 0x20_0000 == 0 {
            call_regs(0x0071_90C0, 0, h, 0, c8, 0, &[0]);
            now = rd(0x00E8_43AC);
            wd(p + 0xC8, rd(p + 0xC8) & !0x40);
            wd(p + 0xF94, time_add(now as i32, 100) as u32);
        } else {
            now = rd(0x00E8_43AC);
        }
        if (rd(p + 0xF94) as i32) >= 0 && time_due(rd(p + 0xF94) as i32, now as i32) {
            call_regs(0x0071_90C0, 0, h, 0, 0, 0, &[1]);
            wd(p + 0xF94, NONE);
        }

        call_regs(0x0096_E400, 0, 0, 0, 0, 0, &[h]);
        core_reload(h);

        // Grab release: +0xD0C set with no live held weapon.
        if rd(p + 0xD0C) != NONE {
            let w = rd(p + 0x10CC);
            let mut live = false;
            if w != 0 {
                let i = rd(w as usize + 0xC4);
                live = i != 0 && (rd(i as usize + 0x2C) as i32) >= 0;
            }
            if !live {
                wd(p + 0xD0C, NONE);
                if al(call_regs(0x0080_6720, h, 0, 0, 0, NONE, &[]))
                    && (!al(call_regs(0x0096_3540, h, 0, 0, 0, NONE, &[])) || rb(p + 0x1164) & 4 != 0)
                {
                    call_regs(0x0096_0A80, 0, 0, 0, h, NONE, &[1, 0]);
                }
            }
        }

        core_cutscene_lod(h);

        call_regs(0x0098_9630, h, 0, 0, 0, NONE, &[]);
        call_regs(0x009B_6C70, 0, 0, 0, 0, NONE, &[h]);
        call_regs(0x009B_0F10, 0, 0, 0, 0, NONE, &[h]);
        call_regs(0x009A_4CB0, 0, h, 0, 0, NONE, &[]);

        // Anim state override: for a local (or unflagged) human with +0xC0 bit 0x400000 and no
        // rig action, 0x9695F0(ECX = human, cdecl &-1); clear bits 0xC00000.
        let c = rd(p + 0xB0);
        let mut local = true;
        if c != 0 {
            let s = rd(0x0252_8C14);
            if s != 0 {
                let a = rd(s as usize + 0x408);
                if a != 0 && (rb(c as usize) != rb(a as usize + 0x1B0) || rb(c as usize + 0x67C) & 1 != 0) {
                    local = false;
                }
            }
        }
        if local && rd(p + 0xC0) & 0x40_0000 != 0 && rd(rd(p + 0x5E0) as usize + 0x164) == NONE {
            let mut v = NONE;
            call_regs(0x0096_95F0, 0, h, 0, 0, NONE, &[p32(&mut v)]);
            wd(p + 0xC0, rd(p + 0xC0) & 0xFF3F_FFFF);
        }

        if rd(p + 0xC0) & 0x4_0000 != 0 && obj_from_handle(rd(p + 0x374)) != 0 {
            call_regs(0x009C_9F80, 0, 0, 0, 0, NONE, &[h]);
        }

        // Rig actions 0x1AD / 0x1AE finished: 0x91AF30(human, action == 0x1AD).
        let rig = rd(p + 0x5E0);
        let act = rd(rig as usize + 0x164);
        if (act == 0x1AE || act == 0x1AD) && anim_playing(rig, rd(0x015B_87A4), NONE) && rd(p + 0xEF8) != NONE {
            call_regs(0x0091_AF30, 0, 0, 0, act, NONE, &[h, (act == 0x1AD) as u32]);
        }

        // 0x96F3A0 action with table flag 0x400 and its anim playing.
        let r = call_regs(0x0096_F3A0, 0, 0, 0, act, NONE, &[h]);
        if r != NONE && (rd(r.wrapping_mul(12).wrapping_add(0x00E9_0E48) as usize) >> 10) & 1 != 0 {
            let rig = rd(p + 0x5E0);
            if anim_playing(rig, rd(0x015B_87B8), rd(rig as usize + 0x168)) {
                wd(p + 0x101C, NONE);
                wd(p + 0x1024, 0);
                wd(p + 0x1020, NONE);
            }
        }

        // The state machine, unless in a vehicle. ESI = the action read above, EDI = -1.
        if !in_vehicle(h, rd(0x00EB_CEA0)) {
            call_regs(HUMAN_STATE_MACHINE_UPDATE, h, 0, 0, act, NONE, &[]);
        }

        if rb(p + 0x595) != 0 {
            core_ragdoll(h);
        } else {
            core_anim_hit(h);
        }

        // The local player with +0xC0 bit 0x400: 0x6AE180(EAX = human, cdecl 0x1E2, -1.0, 0xFFFF, 1).
        if (rd(p + 0xC0) >> 10) & 1 != 0
            && h == rd(0x0217_03D4)
            && !al(call_regs(0x007C_5770, h, 0, 0, 0, 0, &[]))
        {
            call_regs(0x006A_E180, h, 0, 0, 0, 0, &[0x1E2, q32(rd(0x00E8_7998)), 0xFFFF, 1]);
        }

        call_regs(0x0043_72E0, h, 0, 0, 0, 0, &[]);

        // Auto-fire: weapon_fire(human, human_from_handle(+0xC04), 0, 0, 0, +0xCF & 1, 0).
        if rb(p + 0xC8) & 0x10 != 0
            && rb(p + 0x10C8) == 0
            && al(call_regs(0x009C_4370, h, 0, 0, 0, 0, &[]))
            && al(call_regs(0x0099_4BC0, h, 0, 0, 0, 0, &[]))
            && al(call_regs(0x009C_2FD0, 0, 0, 0, 0, h, &[]))
        {
            let bit = rb(p + 0xCF) as u32 & 1;
            let t = call_regs(0x0096_0D60, rd(p + 0xC04), 0, 0, 0, h, &[]);
            call_regs(0x009C_0500, 0, 0, 0, 0, h, &[h, t, 0, 0, 0, bit, 0]);
        }

        core_combat_timer(h);
        core_threat_scan(h);

        // Weapon type 10 with +0xC0 bit 0x40: 0x96CB70(human, -1, 1, 1, 0).
        if rb(p + 0xC0) & 0x40 != 0 {
            let w = rd(p + 0x10CC);
            if w != 0 {
                let i = rd(w as usize + 0xC4);
                if i != 0 && rd(rd(i as usize + 8) as usize + 0x34) == 10 {
                    call_regs(0x0096_CB70, 0, 0, 0, 0, 0, &[h, NONE, 1, 1, 0]);
                }
            }
        }

        // Animation: anim_rig_prepare(rig, 1) unless hidden; anim_rig_update(rig, dt).
        if (rd(p + 0x80) >> 4) & 1 == 0 {
            let d4 = rd(p + 0xD4);
            let mut skip = false;
            if d4 != 0 {
                let e = rd(d4 as usize + 8);
                skip = e != 0 && rb(e as usize + 0x60) & 1 != 0;
            }
            if !skip {
                call_regs(0x006F_1BE0, 0, 0, 0, 0, 0, &[rd(p + 0x5E0), 1]);
            }
        }
        call_regs(0x006F_2020, 0, 0, 0, 0, 0, &[rd(p + 0x5E0), q32(dt)]);
        call_regs(0x009A_68D0, h, 0, 0, 0, 0, &[]);

        // Network session: clear +0xC0 bit 0x400 unless 0x98E270 (EDX = human).
        let s = rd(0x0252_8C14);
        if s != 0 && (rb(0x0252_8B56) == 0 || rb(0x0252_8B2B) != 0) && rb(s as usize + 0x3F8) != 0 {
            let c0 = rd(p + 0xC0);
            if c0 & 0x400 != 0 && !al(call_regs(0x0098_E270, 0, 0, h, c0, 0, &[])) {
                wd(p + 0xC0, c0 & !0x400);
            }
        }
    }
}

/// 0x9A7EAD..0x9A80DA: the per-human time scale +0xD64, then its clamp to [M, 1].
unsafe fn core_time_scale(h: u32, dt: u32, slow: bool, pass: bool) {
    unsafe {
        let p = h as usize;
        let c8 = rd(p + 0xC8);
        let dl = rb(0x00E8_825F) != 0;
        let dtf = f(dt);
        let d64 = p + 0xD64;
        // `fld [M]; fcom st(1); test ah, 5; jp`: M when M >= v or unordered.
        let floor = |v: f64| -> u32 {
            let mb = rd(0x0252_9718);
            if f(mb) < v { b32(v) } else { q32(mb) }
        };
        if c8 & 0x400 != 0 && !(dl && listed(h, 0x00F5_3908)) {
            // Ramp up over +0xD6C ms from the timestamp +0xD68.
            let el = call_regs(0x00BD_D2A0, (p + 0xD68) as u32, 0, 0, c8, 0, &[]) as i32;
            let tot = rd(p + 0xD6C) as i32;
            if el >= tot {
                wd(p + 0xC8, c8 & !0x400);
                wf(d64, 1.0);
            } else {
                wd(d64, b32(el as f64 / tot as f64));
            }
        } else if c8 & 0x800 != 0 {
            // Ramp down to M.
            let el = call_regs(0x00BD_D2A0, (p + 0xD68) as u32, 0, 0, c8, 0, &[]) as i32;
            let tot = rd(p + 0xD6C) as i32;
            if el >= tot {
                let mb = rd(0x0252_9718);
                wd(p + 0xC8, rd(p + 0xC8) & !0x800);
                wd(d64, q32(mb));
            } else {
                wd(d64, b32(1.0 - el as f64 / tot as f64));
            }
        } else if dl && listed(h, 0x00F5_3908) {
            let v = f(rd(d64)) - dtf * rq(0x00E5_C808);
            wd(d64, floor(v));
        } else if dl && listed(h, 0x00F5_3914) {
            let v = rq(0x00E5_C808) * dtf + f(rd(d64));
            // `fcom st(2)` against 1.0: 1.0 when v >= 1 or unordered.
            let s = if v < 1.0 { v as f32 } else { 1.0f32 };
            wf(d64, s);
            if s as f64 >= 1.0 {
                call_regs(0x0049_2D00, 0, 0, h, c8, 0, &[]);
            }
        } else if slow {
            let v = f(rd(d64)) - (dtf + dtf);
            wd(d64, floor(v));
        } else if pass {
            let v = (dtf + dtf) + f(rd(d64));
            wd(d64, if v < 1.0 { b32(v) } else { 1.0f32.to_bits() });
        } else {
            wf(d64, 1.0);
        }

        // Clamp: s = M when M >= a (or unordered), else a; then 1.0 when 1 <= s (or unordered),
        // else M when a <= M (or unordered), else a.
        let ab = rd(d64);
        let a = f(ab);
        let mb = rd(0x0252_9718);
        let m = f(mb);
        let s = if m < a { q32(ab) } else { q32(mb) };
        let out = if !(1.0 > f(s)) {
            1.0f32.to_bits()
        } else if !(a > m) {
            q32(mb)
        } else {
            q32(ab)
        };
        wd(d64, out);
    }
}

/// 0x9A80C5..0x9A813B: the animation clock +0x5B0 advances by dt, or by the real frame time
/// [0xE84380] while a cutscene plays (cutscene +0xAFF clear, real time <= 0.5) for a
/// script-controlled player or a human 0x6C6E80 (EDI = human) accepts.
unsafe fn core_clock(h: u32, dt: u32) {
    unsafe {
        let p = h as usize;
        let mut real = false;
        if rb(0x0252_7D14) != 0
            && rb(rd(0x0252_7D10) as usize + 0xAFF) == 0
            && !(f(rd(0x00DD_1C8C)) < f(rd(0x00E8_4380)))
        {
            real = (rd(p + 0x4C) == 1 && rb(p + 0x3CC) == 1) || al(call_regs(0x006C_6E80, 0, 0, 0, 0, h, &[]));
        }
        let add = if real { rd(0x00E8_4380) } else { dt };
        wd(p + 0x5B0, b32(f(rd(p + 0x5B0)) + f(add)));
    }
}

/// 0x9A8266..0x9A8391: reload steps for the held weapon.
unsafe fn core_reload(h: u32) {
    unsafe {
        let p = h as usize;
        if !al(call_regs(0x009C_81E0, 0, 0, 0, h, 0, &[])) {
            return;
        }
        let w = rd(p + 0x10CC);
        if w == 0 {
            return;
        }
        let info = rd(w as usize + 0xC4);
        let iv = info as usize;
        // true: go to the anim check at 0x9A82F1; false: the multi-step path at 0x9A8335.
        let mut anim_check = false;
        if info != 0 && al(call_regs(0x00B7_2800, rd(iv + 8), 0, 0, info, info, &[])) {
            let t24 = (iv + 0x24) as u32;
            if (rd(iv + 0x24) as i32) >= 0 && !al(call_regs(0x00BD_D230, t24, 0, 0, info, info, &[])) {
                anim_check = true;
            } else if !al(call_regs(0x0080_6720, h, 0, 0, info, info, &[]))
                && al(call_regs(0x009C_9130, 0, 0, 0, info, h, &[]))
                && (rd(iv + 0x28) as i32) >= 0
                && !al(call_regs(0x00BD_D230, (iv + 0x28) as u32, 0, 0, info, h, &[]))
            {
                anim_check = true;
            }
        }
        if anim_check {
            let rig = rd(p + 0x5E0);
            if anim_playing(rig, rd(0x015B_8784), rd(p + 0xD08)) {
                if info != 0 {
                    let d = rd(iv + 8);
                    if !(d != 0 && rd(d as usize + 0xC) & 0x800 != 0) {
                        call_regs(0x009C_82A0, h, 0, 0, info, info, &[0]); // weapon_reload_step
                    }
                }
                return;
            }
        }
        let i2 = rd(w as usize + 0xC4);
        if i2 == 0 || (rd(i2 as usize + 0x2C) as i32) < 0 {
            return;
        }
        let rig = rd(p + 0x5E0);
        if !anim_playing(rig, rd(0x015B_8784), rd(p + 0xD0C)) {
            return;
        }
        let n = (call_regs(0x00B7_3CC0, h, 0, 0, info, info, &[]) as i32).wrapping_sub(rd(iv + 0x10) as i32);
        let mut left = n;
        while left > 0 {
            call_regs(0x009C_82A0, h, 0, 0, left as u32, info, &[0]);
            left -= 1;
        }
    }
}

/// 0x9A83E9..0x9A8592: the cutscene LOD weight for +0x3CC == 2 humans whose rig flag +0x26C is
/// 1, by distance to the camera 0x25F5B14.
unsafe fn core_cutscene_lod(h: u32) {
    unsafe {
        let p = h as usize;
        if rb(p + 0x3CC) != 2 {
            return;
        }
        let blocking = (rb(0x0252_7D14) != 0 && rb(0x0252_7CF7) != 0) || rb(0x0252_7D15) != 0;
        if blocking && rb(p + 0x1074) == 0 {
            return;
        }
        let r = rd(p + 0x5E0) as usize + 0x264;
        if rb(r + 8) != 1 {
            return;
        }
        let pp = rd(r + 4) as usize;
        let ab = q32(rd(pp + 0x24));
        wd(p + 0x3D0, ab);
        let s60 = q32(rd(pp + 0x28));
        let s1c = q32(rd(pp + 0x2C));
        let a = f(ab);
        let mut s18 = ab;
        if f(rd(0x00DD_1B58)) > a {
            s18 = b32(a - rq(0x00E5_BFC8));
        }
        let dx = b32(f(rd(p + 0x14)) - f(rd(0x025F_5B14)));
        let dy = b32(f(rd(p + 0x18)) - f(rd(0x025F_5B18)));
        let dz = b32(f(rd(p + 0x1C)) - f(rd(0x025F_5B1C)));
        let sq = b32((f(dy) * f(dy) + f(dx) * f(dx)) + f(dz) * f(dz));
        let d = (call_regs_st0(0x0040_EA20, 0, 0, 0, 0, NONE, &[sq]) as f32) as f64;
        // `fcom` d against 20.0; `jp`: out of range when d >= 20 or unordered.
        if !(d < f(rd(0x00DD_071C))) {
            wb(p + 0x1074, 0);
            return;
        }
        let q15 = rq(0x00E5_C380);
        let mut w = 1.0f32;
        if q15 < d {
            let t = (d - q15) as f32;
            w = (1.0 - t as f64 * rq(0x00E5_C510)) as f32;
        }
        let aa = w as f64 * f(s18);
        let kc = rq(0x00E5_C1B8);
        let b = (f(s60) / (f(rd(0x0279_7458)) * kc)) as f32;
        let c = b32(b as f64 + aa);
        let dd = (f(s1c) / (f(rd(0x0279_7454)) * kc)) as f32;
        let e = b32(aa + dd as f64);
        // stdcall (e, c, c), ESI = +0x106C.
        call_regs(0x0095_BE10, 0, 0, 0, h + 0x106C, NONE, &[e, c, c]);
        wb(p + 0x1074, 1);
    }
}

/// 0x9A8749..0x9A8862: ragdolled: the impulse, then +0xC0 bit 0x80000 = speed^2 >= 64 (9 with
/// +0xC0 bit 0x10000000), or unordered.
unsafe fn core_ragdoll(h: u32) {
    unsafe {
        let p = h as usize;
        let o = call_regs(0x0071_0DB0, 0, h, 0, 0, NONE, &[]);
        if o != 0 && rb(o as usize + 0x1100) != 0 {
            let rig = rd(p + 0x5E0) as usize;
            let go = if rd(rig + 0x164) == NONE {
                true
            } else {
                let tr = rd(rig + 0x168);
                let v = call_regs_st0(0x00CE_D680, 0, rd(rig), tr, 0, NONE, &[rd(0x015B_87C4), tr]);
                // `fcomp [0.0]; test ah, 0x41; jp`: skipped when v > 0 or unordered.
                v <= f(rd(0x00DD_32C0))
            };
            if go {
                let mut v50 = [0u32; 4];
                call_regs(0x0073_5DD0, 0, rd(p + 0x570), 0, 0, NONE, &[p32(&mut v50)]); // thiscall, ret 4
                call_regs(0x0071_52E0, 0, 0, 0, h, NONE, &[p32(&mut v50), 1.0f32.to_bits()]);
            }
        }
        if rd(p + 0xC0) & 0x10_0000 != 0 {
            return;
        }
        let mut v = [0u32; 4];
        call_regs(0x0071_8260, 0, h, 0, p32(&mut v), NONE, &[]);
        let c0 = rd(p + 0xC0);
        let (x, y, z) = (f(v[0]), f(v[1]), f(v[2]));
        let s1c = f(b32((y * y + x * x) + z * z));
        let t = if (c0 >> 28) & 1 != 0 { q32(rd(0x00E3_8AE0)) } else { q32(rd(0x00DD_0740)) };
        let thr = f(b32(f(t) * f(t)));
        // `fcompp; test ah, 0x41; jne`: set when thr <= speed^2 or unordered.
        wd(p + 0xC0, if !(thr > s1c) { c0 | 0x8_0000 } else { c0 & 0xFFF7_FFFF });
    }
}

/// 0x9A8867..0x9A898F: not ragdolled: an animation-driven hit (anim 0x15B87C4 playing, for a
/// locally owned human or +0xCC bit 0x10000000).
unsafe fn core_anim_hit(h: u32) {
    unsafe {
        let p = h as usize;
        let rig = rd(p + 0x5E0);
        let rv = rig as usize;
        if !anim_playing(rig, rd(0x015B_87C4), rd(rv + 0x168)) {
            return;
        }
        if !al(call_regs(0x0080_6720, h, 0, 0, 0, rig, &[])) && rd(p + 0xCC) & 0x1000_0000 == 0 {
            return;
        }
        let a = rd(rv + 0x164);
        let mut ebx = 0u32;
        if a == 0x14C {
            ebx = if al(call_regs(0x0096_3540, h, 0, a, 0, rig, &[])) { rd(0x0279_7A40) } else { rd(0x0279_7A3C) };
        }
        let mut s18 = 0u32;
        let mut esi = 0u32;
        if a != NONE {
            let fl = rd(a.wrapping_mul(12).wrapping_add(0x00E9_0E48) as usize) >> 21;
            if fl & 1 != 0 {
                let e = rd(rv + 0x1D8);
                if e != 0 {
                    esi = rd(e as usize + 0x1DC);
                    if esi != 0 {
                        let cl = rb(esi as usize + 0xB25);
                        if cl != 0xFF {
                            let ecx = (fl & 0xFFFF_FF00) | cl as u32;
                            s18 = b32(call_regs_st0(0x0098_0F80, esi, ecx, a, esi, rig, &[]));
                        }
                    }
                }
            }
        }
        call_regs(0x009A_C180, 0, 0, 0, esi, rig, &[h, ebx, esi, 0, 0, 1, 1, 0]);
        // `fucom` against 0: damage unless exactly 0.
        if f(s18) != 0.0 {
            let mut wpn = 0u32;
            if esi != 0 {
                let w = rd(esi as usize + 0x10CC);
                if w != 0 {
                    let i = rd(w as usize + 0xC4);
                    if i != 0 {
                        wpn = rd(i as usize + 8);
                    }
                }
            }
            call_regs_st0(0x0098_47A0, 0, esi, 0, esi, rig, &[h, q32(s18), 0, wpn]); // human_take_damage
        }
        if rd(p + 0xCC) & 0x1000_0000 != 0 {
            call_regs(0x006A_E560, 0, 0, 0, esi, rig, &[h, 0x714, 0]);
        }
    }
}

/// 0x9A8A34..0x9A8BE1: the combat timer +0xF78.
unsafe fn core_combat_timer(h: u32) {
    unsafe {
        let p = h as usize;
        let t = p + 0xF78;
        if rb(p + 0x590) == 3 {
            wd(t, time_add(rd(0x00E8_43AC) as i32, 5000) as u32);
            return;
        }
        if (rd(t) as i32) < 0
            || !al(call_regs(0x00BD_D230, t as u32, 0, 0, 0, 0, &[]))
            || al(call_regs(0x009B_92E0, h, 0, 0, 0, 0, &[]))
        {
            return;
        }
        // DL: 0x926600 (ECX = human; script-controlled player), then +0xCF8 and 0x9AFF50.
        let mut dl = false;
        if al(call_regs(0x0092_6600, 0, h, 0, 0, 0, &[])) && rd(p + 0xCF8) != 0 {
            let mut s1c = 0u32;
            dl = al(call_regs(0x009A_FF50, 0, 0, 0, 0, h, &[p32(&mut s1c)]));
        }
        let w = rd(p + 0x10CC);
        let info = if w != 0 { rd(w as usize + 0xC4) } else { 0 };
        let c0 = rd(p + 0xC0);
        if dl || (c0 >> 30) & 1 != 0 || (c0 >> 29) & 1 != 0 {
            wd(t, time_add(rd(0x00E8_43AC) as i32, 5000) as u32);
            return;
        }
        if info == 0 || !al(call_regs(0x009C_4370, h, 0, 0, 0, info, &[])) || rb(p + 0x10C8) != 0 {
            return;
        }
        let iv = info as usize;
        let clip = call_regs(0x00B7_3CC0, h, 0, 0, info, info, &[]) as i32;
        if (rd(iv + 0x10) as i32) <= clip
            && (call_regs(0x009C_3EA0, 0, 0, 0, h, info, &[0]) as i32) >= 0
            && al(call_regs(0x0080_6720, h, 0, 0, h, info, &[]))
            && al(call_regs(0x009C_53C0, 0, 0, 0, h, info, &[h]))
        {
            wd(t, NONE);
        }
        if rb(rd(iv + 8) as usize + 0x10) & 0x20 == 0 {
            return;
        }
        let a18 = rd(iv + 0x18) as i32 as f64;
        let clip = call_regs(0x00B7_3CC0, h, 0, 0, info, info, &[]) as i32;
        // `fcompp; test ah, 1; jne`: stop when clip * 0.5 < [info+0x18].
        if (clip as f64 * rq(0x00E5_BF70)) < a18 {
            return;
        }
        if (call_regs(0x009C_3EA0, 0, 0, 0, h, info, &[1]) as i32) >= 0
            && al(call_regs(0x0080_6720, h, 0, 0, h, info, &[]))
            && al(call_regs(0x009C_53C0, 0, 0, 0, h, info, &[h]))
        {
            wd(t, NONE);
        }
    }
}

/// 0x9A8BE1..0x9A8DC5: is another live, active human within 1 m on the ground plane (and the
/// 0x43A620 object not), then move-state index 5 of the 28-entry table at +0x570 follows it
/// through 0x735EF0 (ECX = +0x570, EDI = 5 or 0, thiscall 1).
unsafe fn core_threat_scan(h: u32) {
    unsafe {
        let p = h as usize;
        let mut near = false;
        if al(call_regs(0x0098_E8A0, 0, 0, h, 0, 0, &[])) {
            let other = call_regs(0x0098_E710, 0, 0, h, 0, 0, &[]);
            let head = rd(0x0215_E908);
            let mut e = head;
            if e != 0 {
                let kind = rd(0x00EB_CEA0);
                loop {
                    let ev = e as usize;
                    let mut hit = false;
                    if e != h
                        && e != other
                        && !al(call_regs(0x0098_5630, 0, 0, 0, e, head, &[e]))
                        && rd(ev + 0x80) & 0x10 == 0
                        && rd(ev + 0x80) & 0x20 != 0
                        && !in_vehicle(e, kind)
                        && !al(call_regs(0x009B_92E0, e, 0, 0, e, head, &[]))
                        && al(call_regs(0x0042_1740, h, 0, 0, e, head, &[e]))
                    {
                        let s20 = q32(rd(p + 0x14));
                        let s28 = q32(rd(p + 0x1C));
                        let s2c = q32(rd(ev + 0x14));
                        let s34 = q32(rd(ev + 0x1C));
                        let mut v = [b32(f(s2c) - f(s20)), 0, b32(f(s34) - f(s28)), 0];
                        let l = call_regs_st0(0x0041_2080, p32(&mut v), 0, 0, e, head, &[]);
                        // `fcomp [1.0]; test ah, 0x41; jnp`: within when l <= 1.
                        hit = l <= f(rd(0x00DD_518C));
                    }
                    if hit {
                        let o = call_regs(0x0043_A620, h, 0, 0, e, head, &[]);
                        if o == 0 {
                            near = true;
                        } else {
                            let s38 = q32(rd(o as usize + 0x14));
                            let s40 = q32(rd(o as usize + 0x1C));
                            let mut v = [b32(f(s38) - f(rd(p + 0x14))), 0, b32(f(s40) - f(rd(p + 0x1C))), 0];
                            let l = call_regs_st0(0x0041_2080, p32(&mut v), 0, 0, e, head, &[]);
                            near = !(l <= f(rd(0x00DD_518C)));
                        }
                        break;
                    }
                    e = rd(ev + 0xB8);
                    if e == head || e == 0 {
                        break;
                    }
                }
            }
        }
        let c = rd(p + 0x570);
        let cv = c as usize;
        let cur = rd(rd(cv + 0x10) as usize + 0x10);
        let idx = (0..0x1C).find(|&i| rd(cv + 0x14 + i * 4) == cur).unwrap_or(0x1C);
        let edi = if near {
            if idx == 5 {
                return;
            }
            5
        } else {
            if idx != 5 {
                return;
            }
            0
        };
        call_regs(0x0073_5EF0, 0, c, 0, cur, edi, &[1]);
    }
}

