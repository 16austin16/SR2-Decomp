// EAX = human. Clears +0x53E; with +0x4A0 bit 4 in state 0 (not ragdolled) and the timer +0x4E4
// elapsed, 0xA1E5B0(ECX = 0, ESI = human); then the handler of state +0x591 (1-8). The jump
// table at 0x9948CC sends state 7 to 0x99A2D0 and state 8 to 0x9989C0.

