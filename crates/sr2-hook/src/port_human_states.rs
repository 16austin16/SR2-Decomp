/// Sub-state 0x15, recover.
unsafe fn s7_recover(h: u32, b: u32) {
    unsafe {
        bump(S7_15);
        let p = h as usize;
        let skip_fade = (rb(0x0252_8B48) == 1 && rb(0x0252_8B49) == 0)
            || h != rd(LOCAL_PLAYER)
            || al(call_regs(0x004D_1920, 0, 0, 0, h, 0, &[]));
        if !skip_fade {
            if rd(0x0252_6D9C) == 1 {
                return;
            }
            bump(S7_15_FADE);
            call_regs(0x004D_1090, 0, 0, 0, h, 0, &[0xFA, 0, 1.0f32.to_bits()]);
            wd(p + 0xCC, rd(p + 0xCC) | 8);
            return;
        }
        if rb(p + 0x595) != 0 {
            bump(S7_15_RAG);
            let l = b + 0x40;
            if al(call_regs(0x0092_5460, 0, 0, h + 0x63C, h, l, &[])) {
                let eq = call_regs(0x0092_6650, h, 0, 0, h, l, &[]);
                call_regs(0x009A_0B00, 0, h + 0x20, l, h, l, &[h, eq, 0, 1, 0]);
            }
            let cc = rd(p + 0xCC);
            if cc & 0x10 != 0 {
                wd(p + 0xCC, cc & 0xFFFF_FFEF);
                let count = rd(p + 0xC3C);
                let mut esi = h;
                let mut rp = h + 0xC48;
                for _ in 0..count {
                    let o = call_regs(0x0096_0D60, rp - 8, 0, 0, esi, rp, &[]);
                    if o != 0 {
                        let dir = b + 0x1C;
                        esi = dir;
                        vwf(dir, (rf(p + 0x14) as f64 - rf(rp as usize) as f64) as f32);
                        vwf(dir + 8, (rf(p + 0x1C) as f64 - rf(rp as usize + 8) as f64) as f32);
                        vwf(dir + 4, 0.0);
                        call_regs(0x00BD_E150, 0, 0, 0, esi, rp, &[]);
                        call_regs(0x00BE_49A0, dir, 0, 0, esi, rp, &[b + 0xB4]);
                        call_regs(0x009A_0B00, 0, b + 0xB4, rp, esi, rp, &[o, 0, 1, 1, 0]);
                    }
                    rp += 0x18;
                }
            }
            call_regs(0x0071_9310, 0, h, 0, h, 0, &[rd(p + 0x5E0), h + 0x14, h + 0x20, h + 0x14, h + 0x20]);
            wb(p + 0x595, 3);
            call_regs(0x009A_D780, 0, 0, 0, h, 0, &[]);
            if h == rd(LOCAL_PLAYER) {
                call_regs(0x0049_2DF0, 0, 0, 0, h, 0, &[]);
            }
        }
        state_set(h, 7, 0x12, 0);
        let cc = rd(p + 0xCC);
        if cc & 8 != 0 {
            wd(p + 0xCC, cc & 0xFFFF_FFF7);
            call_regs(0x004D_1270, 0, 0, 0, h, 0, &[0xFA, 0]);
        }
    }
}

unsafe fn state7_body(h: u32) {
    unsafe {
        let p = h as usize;
        let sub = (rb(p + 0x592) as i8 as i32).wrapping_sub(0x11) as u32;
        if sub > 4 {
            return;
        }
        let mut fr = Frame([0; 60]);
        let b = fr.0.as_mut_ptr() as u32;
        std::hint::black_box(&mut fr);
        match sub {
            0 => s7_down(h, b),
            1 => s7_getup(h),
            2 => s7_arrest(h),
            3 => bump(S7_14),
            _ => s7_recover(h, b),
        }
    }
}

