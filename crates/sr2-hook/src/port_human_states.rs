//! Port module: human states 4, 2 and 3 (0x999980, 0x99CFF0, 0x99E490).
//!
//! Call skeletons as in port_humans2.rs: every callee is still the original game function, called
//! with the registers the LTCG build passes it. The handlers are reached from the Rust dispatcher
//! (human_state_machine_update) through call_regs, so EBX / EBP arrive as call_regs leaves them;
//! none of the callees was found to read them (see each handler). Skipped on purpose: the
//! handlers that build C++ objects on the stack (states 5, 6, 7).

use std::sync::atomic::{AtomicU32, Ordering};

use crate::portlib::*;

const HUMAN_STATE4_UPDATE: usize = 0x0099_9980;
const HUMAN_STATE2_UPDATE: usize = 0x0099_CFF0;
const HUMAN_STATE3_UPDATE: usize = 0x0099_E490;

// Counter slots.
const S4: usize = 0;
const S4_SUB1: usize = 1;
const S4_SUB2: usize = 2;
const S4_SUB3: usize = 3;
const S4_SUB4: usize = 4;
const S4_PKT: usize = 5;
const S2: usize = 6;
const S2_LOCKED: usize = 7;
const S2_TAIL_IDLE: usize = 8;
const S2_M0: usize = 9;
const S2_M1: usize = 10;
const S2_M1_TAIL: usize = 11;
const S2_M2_STATIC: usize = 12;
const S2_M2_MOVE: usize = 13;
const S2_M2_DONE: usize = 14;
const S3: usize = 15;
const S3_LOCKED: usize = 16;
const S3_FAIL: usize = 17;
const S3_COPY: usize = 18;
const S3_CLOSE: usize = 19;
const S3_ANIM: usize = 20;
const S3_NOANIM: usize = 21;
const NCOUNT: usize = 22;

static COUNTS: [AtomicU32; NCOUNT] = [const { AtomicU32::new(0) }; NCOUNT];

fn bump(i: usize) {
    COUNTS[i].fetch_add(1, Ordering::Relaxed);
}

/// Install this module's replacements (called from hooks::install_all).
pub fn install() {
    let ports: [(&str, usize, &[u8], usize); 3] = [
        ("human_state4_update", HUMAN_STATE4_UPDATE, &HUMAN_STATE4_BODY, human_state4_thunk as extern "C" fn() as usize),
        ("human_state2_update", HUMAN_STATE2_UPDATE, &HUMAN_STATE2_BODY, human_state2_thunk as extern "C" fn() as usize),
        ("human_state3_update", HUMAN_STATE3_UPDATE, &HUMAN_STATE3_BODY, human_state3_thunk as extern "C" fn() as usize),
    ];
    let mut n = 0;
    for (name, addr, body, thunk) in ports {
        if replace_pinned(name, addr, body, thunk) {
            n += 1;
        }
    }
    crate::log(&format!("port_human_states: replaced {n}/{} with Rust", ports.len()));
}

/// One line for the periodic log.
pub fn summary() -> String {
    let c = |i: usize| COUNTS[i].load(Ordering::Relaxed);
    if c(S4) == 0 && c(S2) == 0 && c(S3) == 0 {
        return String::new();
    }
    format!(
        "port_human_states: state4 {} (sub1 {}, sub2 {}, sub3 {}, sub4 {}, pkt {}), state2 {} (locked {}, idle-tail {}, m0 {}, m1 {}, m1-tail {}, m2-static {}, m2-move {}, m2-done {}), state3 {} (locked {}, fail {}, copy {}, close {}, anim {}, no-anim {})",
        c(S4), c(S4_SUB1), c(S4_SUB2), c(S4_SUB3), c(S4_SUB4), c(S4_PKT),
        c(S2), c(S2_LOCKED), c(S2_TAIL_IDLE), c(S2_M0), c(S2_M1), c(S2_M1_TAIL), c(S2_M2_STATIC), c(S2_M2_MOVE), c(S2_M2_DONE),
        c(S3), c(S3_LOCKED), c(S3_FAIL), c(S3_COPY), c(S3_CLOSE), c(S3_ANIM), c(S3_NOANIM),
    )
}

// --- local helpers -------------------------------------------------------------------------------

fn al(r: u32) -> bool {
    r & 0xFF != 0
}

/// A `fld dword` / `fstp dword` round trip: the bits, except that a signalling NaN is quieted.
fn q32(bits: u32) -> u32 {
    if bits & 0x7F80_0000 == 0x7F80_0000 && bits & 0x007F_FFFF != 0 { bits | 0x0040_0000 } else { bits }
}

unsafe fn rq(p: usize) -> f64 {
    unsafe { *(p as *const f64) }
}

/// `call_regs` for a callee that returns on the x87 stack: the result is popped as a qword.
unsafe fn call_regs_st0(f: usize, eax: u32, ecx: u32, edx: u32, esi: u32, edi: u32, args: &[u32]) -> f64 {
    let mut out = 0f64;
    let block: [u32; 9] =
        [f as u32, ecx, edx, esi, edi, args.as_ptr() as u32, args.len() as u32, eax, &mut out as *mut f64 as u32];
    unsafe {
        std::arch::asm!(
            "push ebx", "push esi", "push edi", "push ebp",
            "mov ebp, esp",
            "mov ebx, eax",
            "mov ecx, [ebx + 24]",
            "mov esi, [ebx + 20]",
            "2:",
            "test ecx, ecx",
            "jz 3f",
            "push dword ptr [esi + ecx*4 - 4]",
            "dec ecx",
            "jmp 2b",
            "3:",
            "mov ecx, [ebx + 4]", "mov edx, [ebx + 8]", "mov esi, [ebx + 12]", "mov edi, [ebx + 16]",
            "mov eax, [ebx + 28]",
            "call dword ptr [ebx]",
            "mov ecx, [ebx + 32]",
            "fstp qword ptr [ecx]",
            "mov esp, ebp",
            "pop ebp", "pop edi", "pop esi", "pop ebx",
            inout("eax") block.as_ptr() => _, lateout("ecx") _, lateout("edx") _,
            clobber_abi("C"),
        );
    }
    out
}

/// human_state_set (0x9954C0): ECX = state, EDX = sub-state, cdecl human.
unsafe fn state_set(h: u32, st: u32, sub: u32, edi: u32) {
    unsafe { call_regs(0x0099_54C0, 0, st, sub, h, edi, &[h]) };
}

// --- state 4 (0x999980) --------------------------------------------------------------------------

// EAX = human (ESI in the original). Tail-jumps to 0x999690 in sub-state 4 with EAX = human.
// Registers: ESI = human for every callee (0x999400 and 0x999190 read it); EDI = the rig's track
// (+0x168) from the prologue on, which 0x96F280 pushes as an argument; EBP = the rig, which no
// callee was found to read (the checker's EBP/EBX hits are the callees' own saves).

#[unsafe(naked)]
extern "C" fn human_state4_thunk() {
    std::arch::naked_asm!(
        "push ecx",
        "push edx",
        "push eax",
        "call {f}",
        "add esp, 4",
        "pop edx",
        "pop ecx",
        "ret",
        f = sym human_state4_update,
    )
}

extern "C" fn human_state4_update(h: u32) {
    bump(S4);
    unsafe {
        let p = h as usize;
        wd(p + 0xC8, rd(p + 0xC8) & 0xFFFF_FFEF);
        if rd(p + 0x4C) == 1 && rb(p + 0x3CC) == 1 {
            bump(S4_PKT);
            call_regs(0x0099_4340, h + 0x564, h, 0, h, 0, &[h + 0x564, 0, 0, 1]);
        }
        let rig = rd(p + 0x5E0);
        let track = rd(rig as usize + 0x168);
        // The animation progress: stored as f32 (fstp dword).
        let prog = call_regs_st0(0x0096_F280, 0, 0, 0, h, track, &[h]) as f32;
        let k = rf(0x00DD_1B58);
        let mut sub = (rb(p + 0x592) as i8 as i32).wrapping_sub(1) as u32;
        if sub > 3 {
            return;
        }
        if sub == 0 {
            bump(S4_SUB1);
            let playing = al(call_regs(0x00CE_CB80, 0, rd(rig as usize), 0, h, track, &[rd(0x015B_8794), track]));
            // fcomp + `test ah, 0x41; jp`: returns when K > p or unordered.
            if !playing && !(k <= prog) {
                return;
            }
            wd(p + 0xC8, (rd(p + 0xC8) & 0xFEFF_FFFF) | 0x0080_0000);
            state_set(h, 4, 2, track);
            sub = 1;
        }
        if sub == 1 {
            bump(S4_SUB2);
            if al(call_regs(0x0099_9400, 0, 0, 0, h, track, &[])) {
                return;
            }
            if !(k <= prog) {
                return;
            }
            let id = if rb(p + 0x61D) != 0 || rb(p + 0x61C) != 0 { 0x3A } else { 0x39 };
            let c = q32(rd(0x00E8_7998));
            call_regs(0x0096_F5F0, 0, h, 0, h, track, &[id, 0x53E, 0x1_0000, 0, 1.0f32.to_bits(), c]);
            state_set(h, 4, 3, track);
        } else if sub == 2 {
            bump(S4_SUB3);
            if al(call_regs(0x0099_9400, 0, 0, 0, h, track, &[])) {
                return;
            }
            if !(1.0f32 <= prog) {
                return;
            }
            call_regs(0x0099_9190, 0, 0, 0, h, track, &[1, 1]);
            let id = if rb(p + 0x61D) != 0 {
                0x3E
            } else if rb(p + 0x61C) != 0 {
                0x3D
            } else {
                0x3C
            };
            let c = q32(rd(0x00E8_7998));
            call_regs(0x0096_FCA0, 0, h, 0, h, track, &[id, 0, 1, 0, 1.0f32.to_bits(), c, 0, 0xFFFF_FFFF]);
        } else {
            bump(S4_SUB4);
            call_regs(0x0099_9690, h, 0, 0, h, 0, &[]);
        }
    }
}

// --- state 2 (0x99CFF0) --------------------------------------------------------------------------

// EAX = human (EDI in the original). The tails (0x99CC30, EAX = human only) and 0x99CA90 /
// 0x95F090 see ESI as the caller's ESI (state 2 only saves it) except in the interpolated move,
// where ESI = &human+0x510; EDI = human throughout.

#[unsafe(naked)]
extern "C" fn human_state2_thunk() {
    std::arch::naked_asm!(
        "push ecx",
        "push edx",
        "push esi",
        "push eax",
        "call {f}",
        "add esp, 8",
        "pop edx",
        "pop ecx",
        "ret",
        f = sym human_state2_update,
    )
}

extern "C" fn human_state2_update(h: u32, esi_in: u32) {
    unsafe { state2_body(h, esi_in) };
}

unsafe fn state2_body(h: u32, esi_in: u32) {
    unsafe {
        let p = h as usize;
        bump(S2);
        if rb(p + 0x470) & 0x40 != 0 {
            bump(S2_LOCKED);
            return;
        }
        let mut m = rb(p + 0x474);
        if m != 2 && rd(p + 0x498) == 0 && rd(p + 0x49C) == 0 {
            bump(S2_TAIL_IDLE);
            call_regs(0x0099_CC30, h, 0, 0, esi_in, h, &[]);
            return;
        }
        let f = (rd(p + 0x80) >> 5) & 1;
        if m as i8 == 0 {
            bump(S2_M0);
            wd(p + 0x514, 0xFFFF_FFFF);
            wb(p + 0x474, 1);
            m = 1;
        }
        if m as i8 == 1 {
            bump(S2_M1);
            // The flag argument is a dword whose upper bytes are stack garbage in the original;
            // the callee only tests the byte.
            if al(call_regs(0x0099_C7B0, 0, 0, 0, esi_in, h, &[h, f])) {
                return;
            }
            bump(S2_M1_TAIL);
            call_regs(0x0099_CC30, h, 0, 0, esi_in, h, &[]);
            return;
        }
        if m as i8 != 2 {
            return;
        }
        if f & 0xFF == 0 {
            bump(S2_M2_STATIC);
            call_regs(0x0095_F090, h, 0, 0, esi_in, h, &[h + 0x4EC, 0, 0xFFFF_FFFF, 0]);
            call_regs(0x00BE_49A0, h + 0x4F8, 0, 0, esi_in, h, &[h + 0x20]);
            call_regs(0x0099_CA90, 0, 0, 0, esi_in, h, &[]);
            return;
        }
        // The interpolated move.
        bump(S2_M2_MOVE);
        let esi = h + 0x510;
        let ok = al(call_regs(0x0099_3CD0, 0, 0, 0, esi_in, h, &[]));
        let mut t: f64 = 1.0;
        if (rd(p + 0x510) as i32) >= 0 {
            let elapsed = al(call_regs(0x00BD_D230, esi, 0, 0, esi, h, &[]));
            if !elapsed {
                let rem = call_regs(0x00BD_D260, esi, 0, 0, esi, h, &[]) as i32;
                let x = ((200i32.wrapping_sub(rem)) as f64 * rq(0x00E5_C5D0)) as f32;
                // fcom 0: x <= 0 or NaN gives 0; fcom 1.0: x >= 1.0 gives 1.0; else x.
                t = if !(x > 0.0) {
                    0.0
                } else if x >= 1.0 {
                    1.0
                } else {
                    x as f64
                };
            }
        }
        let b = |o: usize| rf(p + o) as f64;
        let d0 = (b(0x4EC) - b(0x504)) as f32;
        let d1 = (b(0x4F0) - b(0x508)) as f32;
        let d2 = (b(0x4F4) - b(0x50C)) as f32;
        let s0 = (d0 as f64 * t) as f32;
        let s1 = (d1 as f64 * t) as f32;
        let s2 = (d2 as f64 * t) as f32;
        let mut pos = [0u32; 3];
        pos[0] = ((b(0x504) + s0 as f64) as f32).to_bits();
        pos[1] = ((b(0x508) + s1 as f64) as f32).to_bits();
        pos[2] = ((b(0x50C) + s2 as f64) as f32).to_bits();
        if !al(call_regs(0x009B_92E0, h, 0, 0, esi, h, &[])) {
            pos[1] = q32(rd(p + 0x18));
        }
        // fucompp t, 1.0 with `test ah, 0x44; jp`: only exact equality passes.
        let done = t == 1.0;
        call_regs(0x0095_F090, h, 0, 0, esi, h, &[pos.as_mut_ptr() as u32, 0, 0xFFFF_FFFF, 0]);
        let v = [
            ((b(0x4F8) + b(0x14)) as f32).to_bits(),
            ((b(0x4FC) + b(0x18)) as f32).to_bits(),
            ((b(0x500) + b(0x1C)) as f32).to_bits(),
        ];
        // EAX is 0x95F090's result, which 0x994340 does not read.
        call_regs(0x0099_4340, 0, h, 0, esi, h, &[v.as_ptr() as u32, 0, 0, 0]);
        if !ok || !done {
            return;
        }
        bump(S2_M2_DONE);
        wd(p + 0x510, 0xFFFF_FFFF);
        if rb(p + 0x4A0) & 4 == 0 {
            call_regs(0x0099_CA90, 0, 0, 0, esi, h, &[]);
            return;
        }
        if al(call_regs(0x00A1_E5B0, 0, 0, 0, h, h, &[])) {
            return;
        }
        call_regs(0x0099_CA90, 0, 0, 0, h, h, &[]);
    }
}

// --- state 3 (0x99E490) --------------------------------------------------------------------------

keep_ecx_edx_arg1!(human_state3_thunk, human_state3_update);

extern "C" fn human_state3_update(h: u32) {
    bump(S3);
    unsafe {
        let p = h as usize;
        if rb(p + 0x470) & 0x40 != 0 {
            bump(S3_LOCKED);
            return;
        }
        let mut t = [0u32; 12];
        let tp = t.as_mut_ptr() as u32;
        call_regs(0x0073_5C80, 0, rd(p + 0x570), 0, h, 0, &[tp]);
        call_regs(0x0099_48F0, tp, 0, 0, h, 0, &[h, h + 0x20]);
        let r = call_regs(0x00B1_9AE0, h, 0, 0, h, 0, &[tp, tp + 0xC]);
        if r == 0 || r == 0xFFFF_FFFF {
            bump(S3_FAIL);
            call_regs(0x0099_E650, 0, 0, 0, h, 0, &[0]);
            return;
        }
        let blk = h + 0xE40;
        let mut esi = h;
        let mut edi = 0u32;
        if rb(p + 0x474) == 2 {
            bump(S3_COPY);
            for (i, v) in t.iter().take(3).enumerate() {
                wd(blk as usize + i * 4, *v);
            }
            copy_dwords(blk as usize + 0xC, tp as usize + 0xC, 9);
            esi = tp + 0x30;
            edi = blk + 0x30;
            call_regs(0x0099_DEA0, 0, blk + 0x24, blk, esi, edi, &[h]);
        }
        state2_body(h, esi);
        if rb(p + 0x470) & 4 == 0 {
            return;
        }
        let d = call_regs_st0(0x00BD_EA80, tp, blk, 0, esi, edi, &[]);
        // fcomp: continues only when d > 0.04 (d <= 0.04 or NaN closes).
        if !(d > rf(0x00E9_9A34) as f64) {
            bump(S3_CLOSE);
            call_regs(0x0099_E650, 0, 0, 0, h, edi, &[1]);
            return;
        }
        let ok = if rb(p + 0x474) == 2 {
            al(call_regs(0x0099_E6D0, 0, 0, 0, esi, edi, &[h, 0, 0]))
        } else {
            call_regs(0x0099_DC70, tp, 0, 0, esi, edi, &[h]) != 0
        };
        if ok {
            bump(S3_ANIM);
            call_regs(0x0096_CB70, 0, 0, 0, esi, edi, &[h, 0xFFFF_FFFF, 1, 1, 0]);
        } else {
            bump(S3_NOANIM);
            call_regs(0x0099_E650, 0, 0, 0, h, edi, &[0]);
        }
    }
}

