// --- local helpers -------------------------------------------------------------------------------

fn al(r: u32) -> bool {
    r & 0xFF != 0
}

/// A `fld dword` / `fstp dword` round trip: the bits, except that a signalling NaN is quieted.
fn q32(bits: u32) -> u32 {
    if bits & 0x7F80_0000 == 0x7F80_0000 && bits & 0x007F_FFFF != 0 { bits | 0x0040_0000 } else { bits }
}

unsafe fn rq(p: usize) -> f64 {
    unsafe { *(p as *const f64) }
}

/// `call_regs` for a callee that returns on the x87 stack: the result is popped as a qword.
unsafe fn call_regs_st0(f: usize, eax: u32, ecx: u32, edx: u32, esi: u32, edi: u32, args: &[u32]) -> f64 {
    let mut out = 0f64;
    let block: [u32; 9] =
        [f as u32, ecx, edx, esi, edi, args.as_ptr() as u32, args.len() as u32, eax, &mut out as *mut f64 as u32];
    unsafe {
        std::arch::asm!(
            "push ebx", "push esi", "push edi", "push ebp",
            "mov ebp, esp",
            "mov ebx, eax",
            "mov ecx, [ebx + 24]",
            "mov esi, [ebx + 20]",
            "2:",
            "test ecx, ecx",
            "jz 3f",
            "push dword ptr [esi + ecx*4 - 4]",
            "dec ecx",
            "jmp 2b",
            "3:",
            "mov ecx, [ebx + 4]", "mov edx, [ebx + 8]", "mov esi, [ebx + 12]", "mov edi, [ebx + 16]",
            "mov eax, [ebx + 28]",
            "call dword ptr [ebx]",
            "mov ecx, [ebx + 32]",
            "fstp qword ptr [ecx]",
            "mov esp, ebp",
            "pop ebp", "pop edi", "pop esi", "pop ebx",
            inout("eax") block.as_ptr() => _, lateout("ecx") _, lateout("edx") _,
            clobber_abi("C"),
        );
    }
    out
}

/// human_state_set (0x9954C0): ECX = state, EDX = sub-state, cdecl human.
unsafe fn state_set(h: u32, st: u32, sub: u32, edi: u32) {
    unsafe { call_regs(0x0099_54C0, 0, st, sub, h, edi, &[h]) };
}

// --- state 4 (0x999980) --------------------------------------------------------------------------

// EAX = human (ESI in the original). Tail-jumps to 0x999690 in sub-state 4 with EAX = human.
// Registers: ESI = human for every callee (0x999400 and 0x999190 read it); EDI = the rig's track
// (+0x168) from the prologue on, which 0x96F280 pushes as an argument; EBP = the rig, which no
// callee was found to read (the checker's EBP/EBX hits are the callees' own saves).

#[unsafe(naked)]
extern "C" fn human_state4_thunk() {
    std::arch::naked_asm!(
        "push ecx",
        "push edx",
        "push eax",
        "call {f}",
        "add esp, 4",
        "pop edx",
        "pop ecx",
        "ret",
        f = sym human_state4_update,
    )
}

extern "C" fn human_state4_update(h: u32) {
    bump(S4);
    unsafe {
        let p = h as usize;
        wd(p + 0xC8, rd(p + 0xC8) & 0xFFFF_FFEF);
        if rd(p + 0x4C) == 1 && rb(p + 0x3CC) == 1 {
            bump(S4_PKT);
            call_regs(0x0099_4340, h + 0x564, h, 0, h, 0, &[h + 0x564, 0, 0, 1]);
        }
        let rig = rd(p + 0x5E0);
        let track = rd(rig as usize + 0x168);
        // The animation progress: stored as f32 (fstp dword).
        let prog = call_regs_st0(0x0096_F280, 0, 0, 0, h, track, &[h]) as f32;
        let k = rf(0x00DD_1B58);
        let mut sub = (rb(p + 0x592) as i8 as i32).wrapping_sub(1) as u32;
        if sub > 3 {
            return;
        }
        if sub == 0 {
            bump(S4_SUB1);
            let playing = al(call_regs(0x00CE_CB80, 0, rd(rig as usize), 0, h, track, &[rd(0x015B_8794), track]));
            // fcomp + `test ah, 0x41; jp`: returns when K > p or unordered.
            if !playing && !(k <= prog) {
                return;
            }
            wd(p + 0xC8, (rd(p + 0xC8) & 0xFEFF_FFFF) | 0x0080_0000);
            state_set(h, 4, 2, track);
            sub = 1;
        }
        if sub == 1 {
            bump(S4_SUB2);
            if al(call_regs(0x0099_9400, 0, 0, 0, h, track, &[])) {
                return;
            }
            if !(k <= prog) {
                return;
            }
            let id = if rb(p + 0x61D) != 0 || rb(p + 0x61C) != 0 { 0x3A } else { 0x39 };
            let c = q32(rd(0x00E8_7998));
            call_regs(0x0096_F5F0, 0, h, 0, h, track, &[id, 0x53E, 0x1_0000, 0, 1.0f32.to_bits(), c]);
            state_set(h, 4, 3, track);
        } else if sub == 2 {
            bump(S4_SUB3);
            if al(call_regs(0x0099_9400, 0, 0, 0, h, track, &[])) {
                return;
            }
            if !(1.0f32 <= prog) {
                return;
            }
            call_regs(0x0099_9190, 0, 0, 0, h, track, &[1, 1]);
            let id = if rb(p + 0x61D) != 0 {
                0x3E
            } else if rb(p + 0x61C) != 0 {
                0x3D
            } else {
                0x3C
            };
            let c = q32(rd(0x00E8_7998));
            call_regs(0x0096_FCA0, 0, h, 0, h, track, &[id, 0, 1, 0, 1.0f32.to_bits(), c, 0, 0xFFFF_FFFF]);
        } else {
            bump(S4_SUB4);
            call_regs(0x0099_9690, h, 0, 0, h, 0, &[]);
        }
    }
}

// --- state 2 (0x99CFF0) --------------------------------------------------------------------------

// EAX = human (EDI in the original). The tails (0x99CC30, EAX = human only) and 0x99CA90 /
// 0x95F090 see ESI as the caller's ESI (state 2 only saves it) except in the interpolated move,
// where ESI = &human+0x510; EDI = human throughout.

#[unsafe(naked)]
extern "C" fn human_state2_thunk() {
    std::arch::naked_asm!(
        "push ecx",
        "push edx",
        "push esi",
        "push eax",
        "call {f}",
        "add esp, 8",
        "pop edx",
        "pop ecx",
        "ret",
        f = sym human_state2_update,
    )
}

extern "C" fn human_state2_update(h: u32, esi_in: u32) {
    unsafe { state2_body(h, esi_in) };
}

unsafe fn state2_body(h: u32, esi_in: u32) {
    unsafe {
        let p = h as usize;
        bump(S2);
        if rb(p + 0x470) & 0x40 != 0 {
            bump(S2_LOCKED);
            return;
        }
        let mut m = rb(p + 0x474);
        if m != 2 && rd(p + 0x498) == 0 && rd(p + 0x49C) == 0 {
            bump(S2_TAIL_IDLE);
            call_regs(0x0099_CC30, h, 0, 0, esi_in, h, &[]);
            return;
        }
        let f = (rd(p + 0x80) >> 5) & 1;
        if m as i8 == 0 {
            bump(S2_M0);
            wd(p + 0x514, 0xFFFF_FFFF);
            wb(p + 0x474, 1);
            m = 1;
        }
        if m as i8 == 1 {
            bump(S2_M1);
            // The flag argument is a dword whose upper bytes are stack garbage in the original;
            // the callee only tests the byte.
            if al(call_regs(0x0099_C7B0, 0, 0, 0, esi_in, h, &[h, f])) {
                return;
            }
            bump(S2_M1_TAIL);
            call_regs(0x0099_CC30, h, 0, 0, esi_in, h, &[]);
            return;
        }
        if m as i8 != 2 {
            return;
        }
        if f & 0xFF == 0 {
            bump(S2_M2_STATIC);
            call_regs(0x0095_F090, h, 0, 0, esi_in, h, &[h + 0x4EC, 0, 0xFFFF_FFFF, 0]);
            call_regs(0x00BE_49A0, h + 0x4F8, 0, 0, esi_in, h, &[h + 0x20]);
            call_regs(0x0099_CA90, 0, 0, 0, esi_in, h, &[]);
            return;
        }
        // The interpolated move.
        bump(S2_M2_MOVE);
        let esi = h + 0x510;
        let ok = al(call_regs(0x0099_3CD0, 0, 0, 0, esi_in, h, &[]));
        let mut t: f64 = 1.0;
        if (rd(p + 0x510) as i32) >= 0 {
            let elapsed = al(call_regs(0x00BD_D230, esi, 0, 0, esi, h, &[]));
            if !elapsed {
                let rem = call_regs(0x00BD_D260, esi, 0, 0, esi, h, &[]) as i32;
                let x = ((200i32.wrapping_sub(rem)) as f64 * rq(0x00E5_C5D0)) as f32;
                // fcom 0: x <= 0 or NaN gives 0; fcom 1.0: x >= 1.0 gives 1.0; else x.
                t = if !(x > 0.0) {
                    0.0
                } else if x >= 1.0 {
                    1.0
                } else {
                    x as f64
                };
            }
        }
        let b = |o: usize| rf(p + o) as f64;
        let d0 = (b(0x4EC) - b(0x504)) as f32;
        let d1 = (b(0x4F0) - b(0x508)) as f32;
        let d2 = (b(0x4F4) - b(0x50C)) as f32;
        let s0 = (d0 as f64 * t) as f32;
        let s1 = (d1 as f64 * t) as f32;
        let s2 = (d2 as f64 * t) as f32;
        let mut pos = [0u32; 3];
        pos[0] = ((b(0x504) + s0 as f64) as f32).to_bits();
        pos[1] = ((b(0x508) + s1 as f64) as f32).to_bits();
        pos[2] = ((b(0x50C) + s2 as f64) as f32).to_bits();
        if !al(call_regs(0x009B_92E0, h, 0, 0, esi, h, &[])) {
            pos[1] = q32(rd(p + 0x18));
        }
        // fucompp t, 1.0 with `test ah, 0x44; jp`: only exact equality passes.
        let done = t == 1.0;
        call_regs(0x0095_F090, h, 0, 0, esi, h, &[pos.as_mut_ptr() as u32, 0, 0xFFFF_FFFF, 0]);
        let v = [
            ((b(0x4F8) + b(0x14)) as f32).to_bits(),
            ((b(0x4FC) + b(0x18)) as f32).to_bits(),
            ((b(0x500) + b(0x1C)) as f32).to_bits(),
        ];
        // EAX is 0x95F090's result, which 0x994340 does not read.
        call_regs(0x0099_4340, 0, h, 0, esi, h, &[v.as_ptr() as u32, 0, 0, 0]);
        if !ok || !done {
            return;
        }
        bump(S2_M2_DONE);
        wd(p + 0x510, 0xFFFF_FFFF);
        if rb(p + 0x4A0) & 4 == 0 {
            call_regs(0x0099_CA90, 0, 0, 0, esi, h, &[]);
            return;
        }
        if al(call_regs(0x00A1_E5B0, 0, 0, 0, h, h, &[])) {
            return;
        }
        call_regs(0x0099_CA90, 0, 0, 0, h, h, &[]);
    }
}

// --- state 3 (0x99E490) --------------------------------------------------------------------------

keep_ecx_edx_arg1!(human_state3_thunk, human_state3_update);

extern "C" fn human_state3_update(h: u32) {
    bump(S3);
    unsafe {
        let p = h as usize;
        if rb(p + 0x470) & 0x40 != 0 {
            bump(S3_LOCKED);
            return;
        }
        let mut t = [0u32; 12];
        let tp = t.as_mut_ptr() as u32;
        call_regs(0x0073_5C80, 0, rd(p + 0x570), 0, h, 0, &[tp]);
        call_regs(0x0099_48F0, tp, 0, 0, h, 0, &[h, h + 0x20]);
        let r = call_regs(0x00B1_9AE0, h, 0, 0, h, 0, &[tp, tp + 0xC]);
        if r == 0 || r == 0xFFFF_FFFF {
            bump(S3_FAIL);
            call_regs(0x0099_E650, 0, 0, 0, h, 0, &[0]);
            return;
        }
        let blk = h + 0xE40;
        let mut esi = h;
        let mut edi = 0u32;
        if rb(p + 0x474) == 2 {
            bump(S3_COPY);
            for (i, v) in t.iter().take(3).enumerate() {
                wd(blk as usize + i * 4, *v);
            }
            copy_dwords(blk as usize + 0xC, tp as usize + 0xC, 9);
            esi = tp + 0x30;
            edi = blk + 0x30;
            call_regs(0x0099_DEA0, 0, blk + 0x24, blk, esi, edi, &[h]);
        }
        state2_body(h, esi);
        if rb(p + 0x470) & 4 == 0 {
            return;
        }
        let d = call_regs_st0(0x00BD_EA80, tp, blk, 0, esi, edi, &[]);
        // fcomp: continues only when d > 0.04 (d <= 0.04 or NaN closes).
        if !(d > rf(0x00E9_9A34) as f64) {
            bump(S3_CLOSE);
            call_regs(0x0099_E650, 0, 0, 0, h, edi, &[1]);
            return;
        }
        let ok = if rb(p + 0x474) == 2 {
            al(call_regs(0x0099_E6D0, 0, 0, 0, esi, edi, &[h, 0, 0]))
        } else {
            call_regs(0x0099_DC70, tp, 0, 0, esi, edi, &[h]) != 0
        };
        if ok {
            bump(S3_ANIM);
            call_regs(0x0096_CB70, 0, 0, 0, esi, edi, &[h, 0xFFFF_FFFF, 1, 1, 0]);
        } else {
            bump(S3_NOANIM);
            call_regs(0x0099_E650, 0, 0, 0, h, edi, &[0]);
        }
    }
}

// --- states 5, 6 and 7: shared helpers -----------------------------------------------------------

// The original frames are modelled as one zeroed, 16-aligned buffer per call. Every `[esp+X]` of
// the original is `base + X` here, with `base` = the ESP after the prologue's pushes (state 5: the
// frame is `sub esp, 0x70` + 4 pushes; state 6: aligned, `sub esp, 0xE8` + 2 pushes; state 7:
// `sub esp, 0xC8` + 4 pushes), adjusted for pending argument pushes where the original has them.
// The C++ objects the callees build on (ray queries, audio params) sit at the same offsets as in
// the original frame, so the constructors / methods see the same layout.

#[repr(C, align(16))]
struct Frame([u32; 60]);

const OBJ_LIST: usize = 0x0214_9C64;
const LOCAL_PLAYER: usize = 0x0217_03D4;
const NOW: usize = 0x00E8_43AC;

/// Frame accesses are volatile: the callees read and write the buffer behind the compiler's back.
unsafe fn vr(p: u32) -> u32 {
    unsafe { std::ptr::read_volatile(p as *const u32) }
}

unsafe fn vw(p: u32, v: u32) {
    unsafe { std::ptr::write_volatile(p as *mut u32, v) }
}

unsafe fn vwf(p: u32, v: f32) {
    unsafe { vw(p, v.to_bits()) }
}

unsafe fn vrf(p: u32) -> f32 {
    unsafe { f32::from_bits(vr(p)) }
}

/// clamp(t, 0, 1) as the x87 code does it: t <= 0 or NaN gives 0, t >= 1 gives 1.
fn clamp01(t: f32) -> f32 {
    if !(t > 0.0) {
        0.0
    } else if t >= 1.0 {
        1.0
    } else {
        t
    }
}

/// 0x96FCA0 (ECX = human, cdecl id, 0, 1, f32 0.0, 1.0, -1.0, 0, -1): the "play(id)" shape.
unsafe fn play_anim(h: u32, id: u32, esi: u32, edi: u32) -> bool {
    unsafe {
        let c = q32(rd(0x00E8_7998));
        al(call_regs(0x0096_FCA0, 0, h, 0, esi, edi, &[id, 0, 1, 0, 1.0f32.to_bits(), c, 0, 0xFFFF_FFFF]))
    }
}

// --- state 5 (0x9976E0), cdecl (human) ------------------------------------------------------------

// The original runs with EBP = human, EBX = -1 and ESI = human on entry (EDI is whatever the caller
// had; the dispatcher passes 0). Callees that read registers: 0x997420 / 0x6FC610 / 0x999190 read
// ESI = human; 0x464D90 reads ESI = &params and EDI = &human+0xF10; 0x96F280 gets EDI = the rig's
// track from sub-state 7 on (the ports below pass it); 0x963090 / 0x997D10 / 0x95F090 / 0x997590 /
// 0x9974C0 read EAX; the rest only ECX / EDX. The frame has the audio handle (12 bytes) at +0x14
// and the audio params (0x5C bytes) at +0x20; the same +0x14 area is the move step's output vec3
// and the finish's exit velocity.

keep_ecx_edx_arg1!(human_state5_thunk, human_state5_update);

extern "C" fn human_state5_update(h: u32) {
    bump(S5);
    unsafe { state5_body(h) };
}

/// The "start" body shared by sub-states 6 and 7 (after their play succeeded).
unsafe fn s5_start(h: u32, next: u32, esi: u32, edi: u32, b: u32) {
    unsafe {
        let p = h as usize;
        call_regs(0x0073_5C80, 0, rd(p + 0x570), 0, esi, edi, &[h + 0xF04]);
        copy_dwords(p + 0xF1C, p + 0x20, 9);
        call_regs(0x006F_C610, 0, 0, 0, h, h + 0xF40, &[0x17, 0]);
        let o = rd(p + 0x570) as usize;
        if o != 0 {
            wb(o + 0x130, rb(o + 0x130) | 2);
        }
        wd(p + 0xC0, rd(p + 0xC0) & 0xFFFF_FDFF);
        wd(p + 0xC8, rd(p + 0xC8) & 0xFFFF_EFFF);
        s5_audio(h, 0x00E8_84A0, b);
        state_set(h, 5, next, h + 0xF10);
    }
}

/// audio_play_params_init (ESI = &params, EDI = &human+0xF10, cdecl cue word, human, (int8) +0xF65)
/// then audio_play (EAX = &params, ECX = &handle).
unsafe fn s5_audio(h: u32, cue_at: usize, b: u32) {
    unsafe {
        let p = h as usize;
        let f65 = rb(p + 0xF65) as i8 as i32 as u32;
        let cue = rd(cue_at) & 0xFFFF;
        call_regs(0x0046_4D90, 0, cue, 0, b + 0x20, h + 0xF10, &[cue, h, f65]);
        call_regs(0x0046_5B90, b + 0x20, b + 0x14, 0, b + 0x20, h + 0xF10, &[]);
    }
}

/// Move step of sub-states 8 and 9 (EAX = human).
unsafe fn s5_move(h: u32, esi: u32, edi: u32, b: u32) {
    unsafe {
        bump(S5_MOVE);
        let f = call_regs_st0(0x0099_7590, h, 0, 0, esi, edi, &[]) as f32;
        let out = b + 0x14;
        call_regs(
            0x0099_74C0,
            h + 0xF1C,
            out,
            h + 0x20,
            esi,
            edi,
            &[out, h + 0x20, h + 0xF04, h + 0xF10, h + 0xF40, f.to_bits()],
        );
        call_regs(0x0095_F090, h, 0, 0, esi, edi, &[out, 0, 0xFFFF_FFFF, 0]);
    }
}

/// `jmp 0x997D10` with EAX = human: the registers are the caller's (restored by the epilogue).
unsafe fn s5_tail(h: u32) {
    unsafe {
        bump(S5_TAIL);
        call_regs(0x0099_7D10, h, 0, 0, h, 0, &[]);
    }
}

/// Sub-state 10's finish.
unsafe fn s5_finish(h: u32, esi: u32, track: u32, b: u32) {
    unsafe {
        bump(S5_FINISH);
        let p = h as usize;
        call_regs(0x0099_7D10, h, 0, 0, esi, track, &[]);
        wd(p + 0x1024, 0);
        let c8 = (rd(p + 0xC8) & 0xFFFF_7FFF) | 0x1000;
        wd(p + 0x101C, 0xFFFF_FFFF);
        wd(p + 0x1020, 0xFFFF_FFFF);
        wd(p + 0xC8, c8);
        call_regs(0x0099_9190, 0, 0, 0, h, track, &[1, 1]);
        let id = call_regs(0x0099_73F0, 0, h, 0, h, track, &[]);
        play_anim(h, id, h, track);
        let v = b + 0x14;
        vw(v, 0);
        vw(v + 4, 0);
        vw(v + 8, 0);
        let a = h + 0x5D4;
        if al(call_regs(0x00BD_DAE0, a, 0, 0, a, track, &[])) && !al(call_regs(0x00BD_DA80, 0, a, 0, a, track, &[])) {
            vw(v, rd(a as usize));
            vw(v + 4, rd(a as usize + 4));
            vw(v + 8, rd(a as usize + 8));
            call_regs(0x00BD_E570, h + 0x20, v, 0, a, track, &[]);
        }
        call_regs(0x0073_5E70, 0, rd(p + 0x570), 0, a, track, &[v]);
    }
}

unsafe fn state5_body(h: u32) {
    unsafe {
        let p = h as usize;
        let mut fr = Frame([0; 60]);
        let b = fr.0.as_mut_ptr() as u32;
        std::hint::black_box(&mut fr);
        let edi0 = 0u32;
        // The own handle resolves to the local player.
        let hd = rd(p + 0x44);
        if hd != 0 {
            let o = rd(((hd & 0xFFF) << 4) as usize + OBJ_LIST);
            if o != 0 && rd(o as usize + 0x44) == hd {
                let pl = rd(LOCAL_PLAYER);
                if o == pl {
                    wd(0x00E8_DD90, 0xFFFF_FFFF);
                    if pl != 0 {
                        wb(pl as usize + 0x1162, rb(pl as usize + 0x1162) & 0xF8);
                    }
                }
            }
        }
        // The record check.
        let rec = rd(p + 0xF68);
        let ok = 'chk: {
            if rec == 0 {
                break 'chk false;
            }
            let hi = rec >> 16;
            let lo = rec & 0xFFFF;
            if hi == 0xFFFF || hi >= 0x866 {
                break 'chk false;
            }
            let list = rd(0x00F7_AAE8 + hi as usize * 4);
            if list == 0 {
                break 'chk false;
            }
            let e = (lo.wrapping_sub(1) << 5).wrapping_add(rd(list as usize + 0x150));
            if e == 0 {
                break 'chk false;
            }
            rb(e as usize + 0x18) & 2 != 0
        };
        if !ok {
            bump(S5_ABORT);
            call_regs(0x0099_7420, 0, 0, 0, h, edi0, &[0]);
            let o = rd(p + 0x570) as usize;
            if o != 0 {
                wb(o + 0x130, rb(o + 0x130) & 0xFD);
            }
            call_regs(0x0096_3090, h, 0, 0, h, edi0, &[1, 0]);
            return;
        }
        let sub = (rb(p + 0x592) as i8 as i32).wrapping_sub(5) as u32;
        if sub > 6 {
            return;
        }
        match sub {
            0 => {
                bump(S5_SUB5);
                state_set(h, 5, 7, edi0);
            }
            1 => {
                bump(S5_SUB6);
                if play_anim(h, 0x1A9, h, edi0) {
                    s5_start(h, 8, h, edi0, b);
                } else {
                    bump(S5_FAIL);
                    call_regs(0x0099_7420, 0, 0, 0, h, edi0, &[1]);
                }
            }
            2 => {
                bump(S5_SUB7);
                let track = rd(rd(p + 0x5E0) as usize + 0x168);
                let pr = call_regs_st0(0x0096_F280, 0, 0, 0, h, track, &[h]);
                // fcom: continues only when 1.0 <= p (NaN returns).
                if !(pr >= 1.0) {
                    return;
                }
                let id = call_regs(0x0099_7360, 0, h, 0, h, track, &[]);
                if play_anim(h, id, h, track) {
                    s5_start(h, 9, h, track, b);
                } else {
                    bump(S5_FAIL);
                    call_regs(0x0099_7420, 0, 0, 0, h, track, &[1]);
                }
            }
            3 | 4 => {
                let nine = sub == 4;
                bump(if nine { S5_SUB9 } else { S5_SUB8 });
                let track = rd(rd(p + 0x5E0) as usize + 0x168);
                let pr = call_regs_st0(0x0096_F280, 0, 0, 0, h, track, &[h]);
                // fcomp + `test ah, 1; jne`: p < 1.0 or NaN runs the move step.
                if !(pr >= 1.0) {
                    s5_move(h, h, track, b);
                    return;
                }
                call_regs(0x0095_F090, h, 0, 0, h, track, &[h + 0xF10, 0, 0xFFFF_FFFF, 0]);
                copy_dwords(p + 0x20, p + 0xF40, 9);
                let two = rb(p + 0xD0) & 2 != 0;
                // After the `rep movsd`: ESI = human+0xF64, EDI = human+0x44.
                let (esi, edi) = (h + 0xF64, h + 0x44);
                if !nine {
                    let (id, next) = if two { (0x1A8, 0xB) } else { (0x1A4, 0xA) };
                    if play_anim(h, id, esi, edi) {
                        state_set(h, 5, next, edi);
                    } else {
                        bump(S5_FAIL);
                        s5_tail(h);
                    }
                } else {
                    let id = if two {
                        call_regs(0x0099_7390, 0, h, 0, esi, edi, &[])
                    } else {
                        call_regs(0x0099_73C0, 0, h, 0, esi, edi, &[])
                    };
                    if !play_anim(h, id, esi, edi) {
                        bump(S5_FAIL);
                        s5_tail(h);
                        return;
                    }
                    if two {
                        state_set(h, 5, 0xB, edi);
                    } else {
                        // EBX = &human+0xF10 from here on.
                        s5_audio(h, 0x00E8_84A4, b);
                        state_set(h, 5, 0xA, h + 0xF10);
                    }
                }
            }
            5 => {
                bump(S5_SUB10);
                let rig = rd(p + 0x5E0);
                let track = rd(rig as usize + 0x168);
                let pr = call_regs_st0(0x0096_F280, 0, 0, 0, rig, track, &[h]);
                if !(pr >= 1.0)
                    && !al(call_regs(0x00CE_CBC0, 0, rd(rig as usize), 0, rig, track, &[rd(0x015B_87B8), track]))
                {
                    return;
                }
                s5_finish(h, rig, track, b);
            }
            _ => {
                bump(S5_SUB11);
                let track = rd(rd(p + 0x5E0) as usize + 0x168);
                let pr = call_regs_st0(0x0096_F280, 0, 0, 0, h, track, &[h]);
                if !(pr >= 1.0) {
                    return;
                }
                s5_tail(h);
            }
        }
    }
}

