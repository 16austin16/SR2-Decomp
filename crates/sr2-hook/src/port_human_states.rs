//! Port module: human states 4, 2, 3, 5, 6 and 7 (0x999980, 0x99CFF0, 0x99E490, 0x9976E0, 0x9989E0,
//! 0x99A2D0).
//!
//! Call skeletons as in port_humans2.rs: every callee is still the original game function, called
//! with the registers the LTCG build passes it. The handlers are reached from the Rust dispatcher
//! (human_state_machine_update) through call_regs, so EBX / EBP arrive as call_regs leaves them;
//! none of the callees was found to read them (see each handler). States 5, 6 and 7 build C++
//! objects on their stack (an audio params block; ray queries with constructor 0x418540 and
//! destructor 0x4080B0): they get a zeroed frame buffer with the original's offsets, and the
//! constructors / methods are still the game's own, called by address.

