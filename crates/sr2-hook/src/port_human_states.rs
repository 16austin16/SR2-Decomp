/// The ledge check of sub-state 12. Returns true when the handler returns (the climb was started).
unsafe fn s6_ledge(h: u32, b: u32) -> bool {
    unsafe {
        let p = h as usize;
        let r = call_regs(0x007F_5CD0, b + 0xAC, b + 0x38, h, h, 0, &[b + 0x38, b + 0xAC, b + 0x34]);
        if r == 0 {
            return false;
        }
        let px = vrf(b + 0x38) as f64;
        let py = vrf(b + 0x3C) as f64;
        let pz = vrf(b + 0x40) as f64;
        let dy = (py - rf(p + 0x18) as f64) as f32;
        vwf(b + 0x18, dy);
        let dyd = dy as f64;
        let s = rf(0x00EB_7C20) as f64;
        // fcomp 0.5*s vs dy: passes when 0.5*s <= dy; fcompp 1.25*s vs dy: bails when 1.25*s < dy.
        if !(rq(0x00E5_BF70) * s <= dyd) || !(s * rq(0x00E5_BF48) >= dyd) {
            return false;
        }
        call_regs(0x0041_8540, 0, b + 0x50, 0, h, r, &[]);
        vw(b + 0x44, 0);
        vw(b + 0x48, 0);
        vw(b + 0x4C, 0x8000_0000);
        let dx = (rf(p + 0x14) as f64 - px) as f32;
        let dyv = (rf(p + 0x18) as f64 - py) as f32;
        let dz = (rf(p + 0x1C) as f64 - pz) as f32;
        vwf(b + 0x28, dx);
        vwf(b + 0x2C, dyv);
        vwf(b + 0x30, dz);
        let nx = vrf(b + 0xC4) as f64;
        let ny = vrf(b + 0xC8) as f64;
        let nz = vrf(b + 0xCC) as f64;
        let dot = ((nx * dx as f64) + (ny * dyv as f64)) + (nz * dz as f64);
        let dotf = dot as f32;
        vwf(b + 0x18, dotf);
        let c25 = rq(0x00E5_BFC8);
        // fcomp 0.0: the positive branch only for dot > 0.
        let (ox, oy, oz) = if (dotf as f64) > rf(0x00DD_32C0) as f64 {
            ((nx * c25) as f32, (ny * c25) as f32, (nz * c25) as f32)
        } else {
            (((-nx) * c25) as f32, ((-ny) * c25) as f32, ((-nz) * c25) as f32)
        };
        vwf(b + 0x28, ox);
        vwf(b + 0x2C, oy);
        vwf(b + 0x30, oz);
        let sx = (px + ox as f64) as f32;
        let sy = (oy as f64 + py) as f32;
        let sz = (pz + oz as f64) as f32;
        vwf(b + 0x1C, sx);
        vwf(b + 0x20, sy);
        vwf(b + 0x24, sz);
        vwf(b + 0x50, sx);
        vwf(b + 0x54, sy);
        vwf(b + 0x58, sz);
        vwf(b + 0x5C, sx);
        vwf(b + 0x64, sz);
        vw(b + 0x9C, 0x4C);
        vwf(b + 0x60, (sy as f64 - rq(0x00E5_C1B8)) as f32);
        let hit = al(call_regs(0x006F_A330, 0, b + 0x50, 0, h, r, &[b + 0x44, 1]));
        if hit {
            let rp = vr(b + 0x44) as usize;
            let v = (py - rf(rp + 4) as f64) as f32;
            vwf(b + 0x18, v);
            // fcomp 0.75 + `test ah, 5; jnp`: no ledge when v < 0.75.
            if (v as f64) < rf(0x00DD_1B58) as f64 {
                call_regs(0x0040_80B0, 0, b + 0x44, 0, h, r, &[]);
                return false;
            }
        }
        bump(S6_LEDGE);
        let k = vr(b + 0x34);
        call_regs(0x0099_7E20, b + 0xAC, b + 0x38, 0, h, r, &[h, k, r]);
        call_regs(0x0040_80B0, 0, b + 0x44, 0, h, r, &[]);
        true
    }
}

/// The fall test, then the dive test, of sub-state 12.
unsafe fn s6_fall(h: u32, b: u32, owned: bool) {
    unsafe {
        let p = h as usize;
        let vy = vrf(b + 0xD4);
        let g = rf(0x0279_7400) as f64;
        let mut dive = true;
        if rd(p + 0xC8) & 0x1000 == 0 {
            let a = vy.abs();
            vwf(b + 0x34, a);
            // fcomp 0.1 + `test ah, 5; jp`: |V.y| >= 0.1 or NaN goes to the dive test.
            if (a as f64) < rq(0x00DD_50E8) {
                dive = false;
            }
        }
        if dive {
            // fcompp -G vs V.y + `test ah, 0x41; jne`: only V.y < -G passes.
            if (vy as f64) < -g {
                bump(S6_DIVE);
                state_set(h, 6, 13, 0);
                wd(p + 0xC8, rd(p + 0xC8) & 0xFFFF_EFFF);
            }
            return;
        }
        bump(S6_STALL);
        let t = h + 0xF6C;
        if (rd(t as usize) as i32) < 0 {
            wd(t as usize, time_add(rd(NOW) as i32, 750) as u32);
            return;
        }
        if !al(call_regs(0x00BD_D230, t, 0, 0, h, t, &[])) {
            return;
        }
        bump(S6_STALL_FIRE);
        if owned {
            call_regs(0x009A_C180, 0, 0, 0, h, t, &[h, 0, 0, 0, 0, 0, 1, 0]);
            wd(p + 0xC0, rd(p + 0xC0) & 0xFFFF_FFFD);
        }
        call_regs(0x006A_E180, h, 0, 0, h, t, &[0x1E7, q32(rd(0x00E8_7998)), 0xFFFF, 1]);
        wd(p + 0xC0, rd(p + 0xC0) & 0xFFFF_FDFF);
        wd(t as usize, 0xFFFF_FFFF);
    }
}

unsafe fn state6_body(h: u32) {
    unsafe {
        if h == 0 {
            // The original skips the owned test here and then dereferences the null human.
            return;
        }
        let p = h as usize;
        let mut fr = Frame([0; 60]);
        let b = fr.0.as_mut_ptr() as u32;
        std::hint::black_box(&mut fr);
        let edi0 = 0u32;
        // owned = the inline human_owned_locally test.
        let mut owned = true;
        let c = rd(p + 0xB0);
        if c != 0 {
            let g = rd(0x0252_8C14);
            if g != 0 {
                let g2 = rd(g as usize + 0x408);
                if g2 != 0 && (rb(c as usize) != rb(g2 as usize + 0x1B0) || rb(c as usize + 0x67C) & 1 != 0) {
                    owned = false;
                }
            }
        }
        let w = rd(p + 0x10CC);
        if w != 0 {
            let r = rd(w as usize + 0xC4);
            if r != 0 && (rd(r as usize + 0x2C) as i32) >= 0 {
                call_regs(0x009C_5140, h, 0, 0, h, edi0, &[]);
            }
        }
        if rd(p + 0x4C) == 1 && rb(p + 0x3CC) == 1 && owned {
            let q = call_regs(0x009D_7DD0, 0, rd(p + 0x44), 0, h, edi0, &[]);
            if rb(q as usize + 0x1161) & 1 != 0 {
                call_regs(0x009D_A290, 0, q, 0, h, edi0, &[0]);
            }
        }
        let hd = rd(p + 0x44);
        wd(p + 0xC8, rd(p + 0xC8) & 0xFFFF_FFEF);
        if hd != 0 {
            let o = rd(((hd & 0xFFF) << 4) as usize + OBJ_LIST);
            if o != 0 && rd(o as usize + 0x44) == hd && rd(o as usize + 0x4C) == 1 && rb(o as usize + 0x3CC) == 1 {
                call_regs(0x0099_4340, o, h, 0, h, edi0, &[h + 0x564, 0, 0, 1]);
                let hd2 = rd(p + 0x44);
                if hd2 != 0 {
                    let o2 = rd(((hd2 & 0xFFF) << 4) as usize + OBJ_LIST);
                    if o2 != 0 && rd(o2 as usize + 0x44) == hd2 {
                        let pl = rd(LOCAL_PLAYER);
                        if o2 == pl {
                            wd(0x00E8_DD90, 0xFFFF_FFFF);
                            if pl != 0 {
                                wb(pl as usize + 0x1162, rb(pl as usize + 0x1162) & 0xF8);
                            }
                        }
                    }
                }
            }
        }
        // V: 16 bytes from (+0x570 -> +8) +0x10 (movaps).
        let vp = rd(rd(p + 0x570) as usize + 8) as usize;
        for i in 0..4usize {
            vw(b + 0xD0 + i as u32 * 4, rd(vp + 0x10 + i * 4));
        }
        let sub = (rb(p + 0x592) as i8 as i32).wrapping_sub(0xC);
        match sub {
            0 => {
                bump(S6_SUB12);
                if rb(p + 0x593) != 5 && s6_ledge(h, b) {
                    return;
                }
                s6_fall(h, b, owned);
            }
            1 => {
                bump(S6_SUB13);
                if al(call_regs(0x009C_BC60, h, 0, 0, h, edi0, &[])) && owned {
                    call_regs(0x009C_AF90, 0, h, 0, h, edi0, &[0, 0]);
                }
                let vy = vrf(b + 0xD4) as f64;
                let g = rf(0x0279_7400) as f64;
                // fcompp -G vs V.y + `test ah, 5; jp`: only -G < V.y continues.
                if -g < vy && rb(p + 0xC3) & 1 == 0 {
                    state_set(h, 6, 12, edi0);
                    call_regs(0x006A_E560, 0, 0, 0, h, edi0, &[h, 0, 0]);
                } else {
                    call_regs(0x006A_EE30, h, 0, 0, h, edi0, &[]);
                }
                if al(call_regs(0x0096_3540, h, 0, 0, h, edi0, &[])) && h == rd(LOCAL_PLAYER) {
                    call_regs(0x0099_F420, h, 0, 0, h, edi0, &[q32(rd(0x00E4_4850))]);
                }
            }
            2 => {
                bump(S6_SUB14);
                call_regs(0x0099_8810, h, 0, 0, h, edi0, &[]);
            }
            _ => {}
        }
    }
}

