/// One line for the periodic log.
pub fn summary() -> String {
    let mut parts: Vec<String> = (0..NAMES.len())
        .filter_map(|i| {
            let c = COUNTS[i].load(Ordering::Relaxed);
            if c == 0 {
                return None;
            }
            Some(if ORIGINAL[i].load(Ordering::Relaxed) != 0 {
                format!("{} {c} ({} mismatched)", NAMES[i], MISMATCHES[i].load(Ordering::Relaxed))
            } else {
                format!("{} {c}", NAMES[i])
            })
        })
        .collect();
    let fb = TOD_FALLBACKS.load(Ordering::Relaxed);
    if fb != 0 {
        parts.push(format!("time-of-day x87 fallbacks {fb}"));
    }
    if parts.is_empty() { String::new() } else { format!("port_render: {}", parts.join(", ")) }
}

