//! Port module: the activity / diversion loaders and update bodies of doc 50 ("Ten large port
//! maps"), ported whole and checked against the disassembly.
//!
//! Every port here writes a lot of game state and calls original functions with side effects, so
//! none has a snapshot shadow; each keeps per-branch hit counters instead (see `summary`).

#![allow(unused_imports)]

use std::sync::atomic::{AtomicU32, Ordering};

use crate::portlib::*;
use crate::{detour, log};

/// The offline differential test (see `difftest`) sends every call into the game through a
/// recording stub; the real build calls the game directly.
#[cfg(test)]
unsafe fn call_regs(f: usize, eax: u32, ecx: u32, edx: u32, esi: u32, edi: u32, args: &[u32]) -> u32 {
    unsafe { crate::portlib::call_regs(difftest::redirect(f), eax, ecx, edx, esi, edi, args) }
}


// =================================================================================================
// 0x64C410  fraud_level_instance::load_from_table  (4267 bytes, thiscall, ret 0xC, /GS frame)
// =================================================================================================
//
// Reads the fraud activity's xtbl element after the shared activity_level_instance loader, resets
// the fraud globals, then restores the weapon state of the local player and (when there is one)
// the co-op partner. The two weapon blocks are unrolled copies of one routine in the original;
// they differ in two places, both kept (`partner` flag): how the partner's best weapon is picked,
// and which test decides that the human is in a vehicle.
//
// Doc 50 differences found at the disassembly: `Coop_Goal` is read into `this+0x60` (the same slot
// as `Goal`), not `this+0x64` (that one is always set to 0x7FFFFFFF); `Crazy_Hit_Chance` is not
// copied to 0x140C4BC (that global is set to 1.0 and then read from `Ring_Money_Percent`).

const FRAUD_ADDR: usize = 0x0064_C410;

const HANDLE_TABLE: usize = 0x0214_9C64;
const GAME_NOW: usize = 0x00E8_43AC;
const LOCAL_PLAYER: usize = 0x0217_03D4;
const COOP_RING: usize = 0x0217_043C;
const IS_COOP: usize = 0x0252_8B49;
const NET_SESSION: usize = 0x0252_8C14;
const VEH_ENTRY: usize = 0x00EB_CE9C;
const VEH_MODE: usize = 0x00EB_CEA0;

// Per-branch counters.
const H_CALLS: usize = 0;
const H_COOP_GOAL: usize = 1;
const H_PARTNER: usize = 2;
const H_NET_P: usize = 3;
const H_NET_PART: usize = 4;
const H_LOCAL_P: usize = 5;
const H_LOCAL_PART: usize = 6;
const H_W_KIND8: usize = 7;
const H_W_KIND0: usize = 8;
const H_W_NONE: usize = 9;
const H_CLEAR_HAND: usize = 10;
const H_SAME_WEAPON: usize = 11;
const H_LOCKON: usize = 12;
const H_EARLY_EXIT: usize = 13;
const H_EQUIP: usize = 14;
const H_STAMP: usize = 15;
const H_CALLBACK: usize = 16;
const H_POST: usize = 17;
const H_COOP_TAIL: usize = 18;
const HIT_NAMES: [&str; 19] = [
    "calls", "coop_goal", "partner", "net_player", "net_partner", "local_player", "local_partner", "w_kind8", "w_kind0",
    "w_none", "clear_hand", "same_weapon", "lockon", "early_exit", "equip", "stamp", "callback", "post", "coop_tail",
];
static HITS: [AtomicU32; 19] = [const { AtomicU32::new(0) }; 19];

fn hit(i: usize) {
    HITS[i].fetch_add(1, Ordering::Relaxed);
}

/// The object a handle names, 0 when the slot is empty or holds another handle (the inlined
/// `handle_lookup`; the original always tests the handle for 0 first where it matters).
unsafe fn hobj(h: u32) -> u32 {
    if h == 0 {
        return 0;
    }
    unsafe {
        let o = rd(HANDLE_TABLE + (((h & 0xFFF) as usize) << 4));
        if o != 0 && rd(o as usize + 0x44) == h { o } else { 0 }
    }
}

/// `hobj` that also requires the object to be a human (`[obj+0x4C] == 1`).
unsafe fn human_obj(h: u32) -> u32 {
    unsafe {
        let o = hobj(h);
        if o != 0 && rd(o as usize + 0x4C) == 1 { o } else { 0 }
    }
}

/// Weapon-list node kind: `[[[node+0xC4]+8]+0x3C]`; the caller has checked `[node+0xC4]`.
unsafe fn node_kind(n: u32) -> u32 {
    unsafe { rd(rd(rd(n as usize + 0xC4) as usize + 8) as usize + 0x3C) }
}

/// First node of the circular list (links at +0xB4) whose kind is `kind`, or 0.
unsafe fn ring_find(head: u32, kind: u32) -> u32 {
    unsafe {
        let mut n = head;
        if n == 0 {
            return 0;
        }
        loop {
            if rd(n as usize + 0xC4) != 0 && node_kind(n) == kind {
                return n;
            }
            n = rd(n as usize + 0xB4);
            if n == head || n == 0 {
                return 0;
            }
        }
    }
}

/// First human on the co-op ring (links at +0x1294) that is not the local player, or 0.
unsafe fn first_other_human(player: u32) -> u32 {
    unsafe {
        let start = rd(COOP_RING);
        let mut p = start;
        if p == 0 {
            return 0;
        }
        loop {
            if p != player {
                return p;
            }
            p = rd(p as usize + 0x1294);
            if p == start || p == 0 {
                return 0;
            }
        }
    }
}

/// `*(dst) = f32 round-trip through the x87 stack` (a signalling NaN comes out quiet).
fn x87_f32(v: f32) -> f32 {
    (v as f64) as f32
}

/// `clamp(v, 0, 1)` the way the x87 code does it: NaN and anything <= 0 give 0.0.
fn clamp01(v: f32) -> f32 {
    let v = v as f64;
    if v <= 0.0 || v.is_nan() {
        0.0
    } else if 1.0 <= v {
        1.0
    } else {
        v as f32
    }
}

unsafe fn get_uint(name: usize, dest: usize, elem: u32) {
    unsafe { call_regs(0x00B7_4910, 0, name as u32, 0, dest as u32, 0, &[elem]) };
}

unsafe fn get_float(name: usize, dest: usize, elem: u32) {
    unsafe { call_regs(0x00B7_4EF0, 0, name as u32, 0, dest as u32, 0, &[elem]) };
}

/// The "send my weapon state to the other machine" test and packet of the unrolled blocks. Returns
/// true when the packet went out (the original then skips the local restore).
///
/// The original builds the packet in a stack buffer whose byte 3 is never written when
/// `[0xE8BBCC]` is set (it carries stack garbage); here it is 0.
unsafe fn send_weapon_packet(h: u32, partner: bool) -> bool {
    unsafe {
        if h == 0 {
            return false;
        }
        let o = hobj(h);
        if o == 0 {
            return false;
        }
        let q = rd(o as usize + 0xB0);
        if q == 0 {
            return false;
        }
        let x = rd(NET_SESSION);
        if x == 0 {
            return false;
        }
        let me = rd(x as usize + 0x408);
        if me == 0 {
            return false;
        }
        // Same owner byte and the "remote" bit clear: this machine owns the human, restore locally.
        if rb(q as usize) == rb(me as usize + 0x1B0) && rb(q as usize + 0x67C) & 1 == 0 {
            return false;
        }
        hit(if partner { H_NET_PART } else { H_NET_P });
        let n: usize = if rb(0x00E8_BBCC) != 0 { 4 } else { 3 };
        let mut buf = [0u8; 16];
        buf[0] = 0x68;
        buf[n] = 0x0A;
        let hw = (rd(q as usize + 2) & 0xFFFF) as u16;
        buf[n + 1..n + 3].copy_from_slice(&hw.to_le_bytes());
        buf[n + 3] = 0;
        buf[n + 4] = 1;
        buf[1..3].copy_from_slice(&((n + 2) as u16).to_le_bytes());
        // The peer whose owner byte matches: ring at [x+0x400], links at +0x22CC.
        let start = rd(x as usize + 0x400);
        let mut peer = 0u32;
        if start != 0 {
            let owner = rb(q as usize);
            let mut c = start;
            loop {
                if rb(c as usize + 0x1B0) == owner {
                    peer = c;
                    break;
                }
                c = rd(c as usize + 0x22CC);
                if c == start || c == 0 {
                    break;
                }
            }
        }
        call_regs(0x0081_4670, 0, 0, 0, peer, 0, &[buf.as_ptr() as u32, (n + 5) as u32, 0, 0]);
        true
    }
}

/// The "mode 7 or 8 does not apply" test: false (go on) when the current vehicle entry does not
/// name this human, or its mode is 7 or 8.
unsafe fn vehicle_mode_blocks(hs: u32) -> bool {
    unsafe {
        let g = rd(VEH_ENTRY);
        if g == 0 || hs != rd(g as usize + 0x44) {
            return false;
        }
        let m = rd(VEH_MODE);
        m != 7 && m != 8
    }
}

/// `vehicle_interaction_rider_find` (ESI = handle) twice; true when its result says kind 1 or 2.
unsafe fn rider_blocks(hs: u32) -> bool {
    unsafe {
        let r = call_regs(0x00B0_7A30, 0, 0, 0, hs, 0, &[]);
        if r != 0 && rd(r as usize + 4) == 1 {
            return true;
        }
        let r = call_regs(0x00B0_7A30, 0, 0, 0, hs, 0, &[]);
        r != 0 && rd(r as usize + 4) == 2
    }
}

/// The weapon-state restore for one human. `p` is the human's `+0x10C4` block: `[p]` the weapon
/// list head, `[p+8]` the current node, `[p+0xC]` its kind, `[p+0x10]` the owner handle, `[p+0x14]`
/// the "weapon changed" callback `(handle, new node, old node)`.
unsafe fn restore_weapons(p: u32, partner: bool) {
    unsafe {
        hit(if partner { H_LOCAL_PART } else { H_LOCAL_P });
        let pa = p as usize;
        let h = rd(pa + 0x10);
        let head = rd(pa);

        // The weapon to bring up: a kind-8 node when the list has one, otherwise a kind-0 node.
        let has8 = if partner { call_regs(0x0055_ADF0, p, 0, 0, 8, 0, &[]) != 0 } else { ring_find(head, 8) != 0 };
        let mut w = if has8 { ring_find(head, 8) } else { ring_find(head, 0) };
        hit(if w == 0 { H_W_NONE } else if has8 { H_W_KIND8 } else { H_W_KIND0 });

        // Step 1: drop the "has weapon in hand" state of the human when it is in the right state.
        'clear: {
            if h == 0 {
                break 'clear;
            }
            let o = human_obj(h);
            if o == 0 {
                break 'clear;
            }
            if vehicle_mode_blocks(h) || rider_blocks(h) {
                break 'clear;
            }
            let ev = rd(o as usize + 0xD74);
            let veh = hobj(ev);
            if veh == 0 || rd(veh as usize + 0x4C) != 5 {
                break 'clear;
            }
            if w != 0 {
                let info = rd(w as usize + 0xC4);
                if info == 0 {
                    break 'clear;
                }
                let d = rd(info as usize + 8);
                if d == 0 {
                    break 'clear;
                }
                if !(0xF..=0x12).contains(&rd(d as usize + 0x20)) {
                    break 'clear;
                }
            }
            let s = human_obj(h);
            if s == 0 {
                break 'clear;
            }
            if call_regs(0x0096_0C30, 0, 0, 0, s, 0, &[]) & 0xFF == 0 {
                break 'clear;
            }
            hit(H_CLEAR_HAND);
            let sa = s as usize;
            let c = rd(sa + 0x10CC);
            wd(sa + 0xC0, rd(sa + 0xC0) & !0x20);
            wd(sa + 0xB44, 0xFFFF_FFFF);
            if c != 0 {
                let i = rd(c as usize + 0xC4);
                if i != 0 {
                    wb(i as usize + 0xD, rb(i as usize + 0xD) & 0xEF);
                }
            }
            call_regs(0x0096_CB70, 0, 0, 0, 0, 0, &[s, 0xFFFF_FFFF, 1, 1, 0]);
        }

        // Step 2: already holding that node.
        let cur = rd(pa + 8);
        if cur == w {
            hit(H_SAME_WEAPON);
            let k = if w != 0 && rd(w as usize + 0xC4) != 0 { node_kind(w) } else { 0 };
            wd(pa + 0xC, k);
            return;
        }

        // Step 3: switch the human over.
        'stamp: {
            let h1 = rd(pa + 0x10);
            let o1 = human_obj(h1);
            if o1 == 0 {
                break 'stamp;
            }
            let oa = o1 as usize;
            if o1 == rd(LOCAL_PLAYER) && rd(0x0252_A12C) != 0 {
                hit(H_LOCKON);
                call_regs(0x00B6_A8B0, 0, 0, 0, 0, 0, &[0f32.to_bits()]);
                wd(0x0252_A130, 0);
                wd(0x0252_A12C, 0);
                call_regs(0x0047_FEB0, 0, 0x00EB_D05C, 0, 0, 0, &[]);
            }
            let c = rd(oa + 0x10CC);
            if c != 0 {
                let i = rd(c as usize + 0xC4);
                if i != 0 && (rd(i as usize + 0x2C) as i32) >= 0 && rb(oa + 0x80) & 0xB == 0 {
                    call_regs(0x009C_5140, o1, 0, 0, 0, 0, &[]);
                }
            }
            if rb(oa + 0xC2) & 1 != 0 && w != 0 {
                hit(H_EARLY_EXIT);
                return;
            }
            if rb(oa + 0x149) == 0x18 {
                hit(H_EARLY_EXIT);
                return;
            }
            if rd(oa + 0xEA8) != 0 && w != 0 {
                let i = rd(w as usize + 0xC4);
                if i != 0 {
                    let d = rd(i as usize + 8);
                    if call_regs(0x00B7_2740, d, 0, 0, 0, 0, &[]) & 0xFF != 0 || rd(d as usize + 0x10) & 0x4000 != 0 {
                        hit(H_EARLY_EXIT);
                        return;
                    }
                }
            }
            if rb(oa + 0x3CC) == 1 && w != 0 {
                wb(oa + 0x1162, rb(oa + 0x1162) & 0xFB);
            }
            call_regs(0x009C_8C20, 0, 0, 0, 0, 0, &[o1, 1]);

            // Is the human in a state where the new weapon may be equipped?
            let hs = rd(oa + 0x44);
            if hs == 0 {
                break 'stamp;
            }
            if vehicle_mode_blocks(hs) {
                break 'stamp;
            }
            if partner {
                if call_regs(0x009B_92E0, o1, 0, 0, 0, 0, &[]) & 0xFF != 0 {
                    break 'stamp;
                }
            } else if rider_blocks(hs) {
                break 'stamp;
            }
            let ev = rd(oa + 0xD74);
            if call_regs(0x00AE_28F0, 0, ev, 0, 0, 0, &[]) == 0 {
                break 'stamp;
            }
            if w != 0 {
                let i = rd(w as usize + 0xC4);
                if i == 0 {
                    break 'stamp;
                }
                let d = rd(i as usize + 8);
                if d == 0 {
                    break 'stamp;
                }
                let flag = (rd(oa + 0xD78) == 0) as u32;
                if call_regs(0x00B7_2D30, d, ev, ev, 0, 0, &[o1, flag]) & 0xFF != 0 {
                    break 'stamp;
                }
                hit(H_EQUIP);
                w = call_regs(0x0055_AE30, 0, 0, 0, 0, 0, &[p, 1, 0, 0, 0]);
            }
        }

        // Step 4: stamp the equip time on the node.
        if w != 0 {
            let i = rd(w as usize + 0xC4);
            if i != 0 {
                hit(H_STAMP);
                let now = rd(GAME_NOW) as i32;
                let t = time_add(now, 0) as u32;
                wd(i as usize + 0x24, t);
                let i = rd(w as usize + 0xC4);
                wd(i as usize + 0x28, t);
                let i = rd(w as usize + 0xC4);
                wd(i as usize + 0x34, 0xFFFF_FFFF);
            }
        }

        // Step 5: make it current and tell the owner.
        let cur = rd(pa + 8);
        let old_kind = if cur != 0 && rd(cur as usize + 0xC4) != 0 { node_kind(cur) } else { 0 };
        let h1 = rd(pa + 0x10);
        let f = rd(pa + 0x14);
        wd(pa + 0xC, old_kind);
        wd(pa + 8, w);
        hit(H_CALLBACK);
        call_regs(f as usize, f, old_kind, h1, p, 0, &[h1, w, cur]);
        let h2 = rd(pa + 0x10);
        if h2 == 0 {
            return;
        }
        let o2 = hobj(h2);
        if o2 == 0 || o2 != rd(LOCAL_PLAYER) {
            return;
        }
        hit(H_POST);
        let s = human_obj(h2);
        let es = if s != 0 && rb(s as usize + 0x3CC) == 1 { s } else { 0 };
        call_regs(0x0079_75E0, 0, es, 0, 0, 0, &[]);
        call_regs(0x0079_8140, 0, 0, 0, 0, 0, &[es]);
        call_regs(0x0055_8BE0, 0, 0, 0, w, 0, &[]);
    }
}

extern "C" fn fraud_load_rs(this: u32, a1: u32, elem: u32, a3: u32) {
    unsafe {
        hit(H_CALLS);
        let t = this as usize;
        wf(0x0140_C4AC, 0.0);
        wf(0x0140_C4A8, 0.0);
        wf(0x0140_C4A4, 0.0);
        let now = rd(GAME_NOW) as i32;
        wb(t + 0x20, 0);
        wb(t + 0x21, 0);
        wd(t + 0x24, 0);
        wd(t + 0x28, 0);
        wd(0x0252_7974, 0);
        wd(0x00E9_76D0, 0);
        wd(0x00EA_A560, time_add(now, 0x7D0) as u32);
        for a in [0x0252_7990, 0x0252_7994, 0x0252_7998, 0x0252_799C, 0x0252_79A4, 0x0252_79A8, 0x0252_79AC, 0x0252_79B0] {
            wd(a, 0);
        }
        wb(0x0140_BB81, 1);
        wd(0x0252_798C, 0);
        wd(t + 0x1C, 0);
        wb(0x0252_7965, 1);
        wb(0x0252_79FC, 0);
        call_regs(0x0068_A160, 0x0C, this, 0, 0, 0, &[]);

        call_regs(0x0053_F700, 0, this, 0, 0, 0, &[a1, elem, a3]);

        let player = rd(LOCAL_PLAYER);
        get_uint(0x00DF_6C18, t + 0x60, elem); // Goal
        if rb(IS_COOP) != 0 && first_other_human(player) != 0 {
            hit(H_COOP_GOAL);
            get_uint(0x00DF_B448, t + 0x60, elem); // Coop_Goal (same slot as Goal)
        }
        wd(t + 0x64, 0x7FFF_FFFF);
        let mut dur = 0u32;
        get_uint(0x00DD_C3BC, &mut dur as *mut u32 as usize, elem); // Duration, seconds
        wd(t + 0x68, (dur as i32).wrapping_mul(1000) as u32);
        get_uint(0x00DF_B454, t + 0x6C, elem); // Max_Spots
        get_float(0x00DF_B460, 0x0252_7970, elem); // Crazy_Chance
        get_float(0x00DF_B470, t + 0x2C, elem); // Crazy_Hit_Chance
        wf(0x0140_C4BC, 1.0);
        get_float(0x00DF_B484, 0x0140_C4BC, elem); // Ring_Money_Percent
        wd(0x00EA_A56C, 0xFFFF_FFFF);
        wf(t + 0x40, 0.0);
        wd(0x0140_C498, 0);
        let partner = if rb(IS_COOP) != 0 { first_other_human(rd(LOCAL_PLAYER)) } else { 0 };
        if partner != 0 {
            hit(H_PARTNER);
        }

        call_regs(0x0064_B370, 0, 0, 0, 0, 0, &[0x00EA_A3F0]);
        wd(0x00EA_A3F0, rd(player as usize + 0x44));
        call_regs(0x0096_8690, 0, 0, 0, 0, 0, &[player, 0x0140_C514]);
        let big = rd(0x00E5_D100);
        wd(0x00EA_A400, big);
        wd(0x00EA_A404, big);
        wd(0x00EA_A408, big);

        // The local player's weapons, then the partner's.
        let p1 = player + 0x10C4;
        if !send_weapon_packet(rd(p1 as usize + 0x10), false) {
            restore_weapons(p1, false);
        }
        if partner != 0 {
            let p2 = partner + 0x10C4;
            if !send_weapon_packet(rd(p2 as usize + 0x10), true) {
                restore_weapons(p2, true);
            }
        }

        wf(0x0252_79BC, 0.0);
        wd(t + 0x30, a1);
        wb(0x0252_7966, 0);
        wb(0x00E8_E2EF, 0);
        wb(0x00E8_B217, 0);
        wd(0x0140_C44C, 1);
        wd(0x00EA_A590, 0xFFFF_FFFF);
        wd(0x00EA_A55C, 0xFFFF_FFFF);
        wd(0x00EA_A6F8, 0xFFFF_FFFF);
        call_regs(0x0068_BAC0, 0x0F, 0, 0, 0, 0, &[]);
        wf(0x00E9_A128, x87_f32(rf(0x0140_C4B0)));
        wd(t + 0x58, 1);
        wd(t + 0x54, 0xFFFF_FFFF);
        wf(0x0215_D7A4, clamp01(rf(0x0252_7970)));
        wf(0x0215_D7A0, clamp01(rf(t + 0x2C)));
        wf(0x00E8_88AC, 1.0);
        wb(0x0252_9623, 1);
        call_regs(0x0064_C0A0, this, 0, 0, 0, 0, &[]);
        wd(0x00EA_A58C, time_add(rd(GAME_NOW) as i32, 0xFA0) as u32);
        let net = rd(NET_SESSION);
        if net != 0
            && (rb(0x0252_8B56) == 0 || rb(0x0252_8B2B) != 0)
            && rb(net as usize + 0x3F8) != 0
            && call_regs(0x009D_7BD0, 0, 0, 0, 0, 0, &[]) != 0
        {
            hit(H_COOP_TAIL);
            call_regs(0x0064_9D10, 0, 0, 0, 0, 0, &[2, 0]);
        }
    }
}

/// thiscall, three stack arguments popped by the callee (ret 0xC).
#[unsafe(naked)]
extern "C" fn fraud_load_thunk() {
    std::arch::naked_asm!(
        "push dword ptr [esp + 12]",
        "push dword ptr [esp + 12]",
        "push dword ptr [esp + 12]",
        "push ecx",
        "call {f}",
        "add esp, 16",
        "ret 12",
        f = sym fraud_load_rs,
    )
}


