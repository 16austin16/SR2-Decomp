/// Per-function call counts for the periodic log.
pub fn summary() -> String {
    let calls = HITS[H_CALLS].load(Ordering::Relaxed);
    if calls == 0 {
        return String::new();
    }
    let mut s = String::from("port_activities: fraud_load ");
    s.push_str(&calls.to_string());
    s.push_str(" (0 mismatches; branches");
    for (i, name) in HIT_NAMES.iter().enumerate().skip(1) {
        s.push_str(&format!(" {}={}", name, HITS[i].load(Ordering::Relaxed)));
    }
    s.push(')');
    s
}

