/// `div d` on EDX:EAX (raises the same divide error as the original when `d` is 0 or the quotient
/// overflows).
#[inline(always)]
unsafe fn div32(edx: u32, eax: u32, d: u32) -> (u32, u32) {
    let (q, rem);
    unsafe {
        std::arch::asm!("div {d:e}", d = in(reg) d, inout("eax") eax => q, inout("edx") edx => rem, options(nomem, nostack));
    }
    (q, rem)
}

#[inline(always)]
unsafe fn tls_2c() -> u32 {
    let t: u32;
    unsafe {
        std::arch::asm!("mov {}, fs:[0x2c]", out(reg) t, options(nostack, readonly));
    }
    t
}

