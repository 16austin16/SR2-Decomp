unsafe fn start_msg(r: &mut Pushad, a: *const u32, edi_v: u32, esi_v: u32) {
    unsafe {
        let (esi0, edi0) = (r.esi, r.edi);
        let mut s = St::of(r);
        s.edi = edi_v;
        s.esi = esi_v;
        let e = s.call(0x7F49E0, &[]);
        s.esi = *a.add(1);
        s.edi = *a;
        s.call(0xC14C40, &[e]);
        s.put(r);
        r.esi = esi0;
        r.edi = edi0;
    }
}

