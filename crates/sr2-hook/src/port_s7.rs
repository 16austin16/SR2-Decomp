//! Port module s7 (round 9): small functions from many subsystems, ported from the originals' bytes.
//!
//! Every port is pinned to its whole original body by `replace_pinned`. Each runs behind one `pushad`
//! thunk that also saves XMM0-7; the Rust body edits the saved registers, `popad` restores them.
//! Callees stay original and are called by address with the registers the original sets up (`St`
//! threads EBX / EBP / ESI / EDI and the ECX / EDX a callee leaves behind).
//!
//! Check: the shared judge (`sr2-judge`); no shadow runs in the game.

#![allow(unused_imports, dead_code)]

use std::sync::atomic::{AtomicU32, Ordering};

