extern "C" fn p_moveact(r: &mut Pushad, a: *const u32) {
    unsafe {
        cnt(ID_MOVEACT);
        let mut s = St::of(r);
        if *a != rd(0x0217_03D4) {
            s.eax = 0;
            s.put(r);
            return;
        }
        s.eax = rd(0x0252_7888);
        if s.eax == 0 {
            s.eax = 0;
            s.put(r);
            return;
        }
        s.ecx = rd(s.eax as usize + 8);
        s.edx = rd(s.ecx as usize);
        s.eax = rd(s.edx as usize + 8);
        let f = s.eax as usize;
        s.call(f, &[]);
        if s.eax != 9 {
            s.eax = 0;
            s.put(r);
            return;
        }
        s.ecx = rd(0x0252_7888);
        if rb(s.ecx as usize + 0x1C) == 0 {
            s.edx = rd(0x0217_03D4);
            s.eax = rd(s.edx as usize + 0x5E0);
            if rd(s.eax as usize + 0x164) != 0x33F {
                s.eax = 0;
                s.put(r);
                return;
            }
        }
        s.eax = 1;
        s.put(r);
    }
}

