extern "C" fn p_chunk07(r: &mut Pushad, _a: *const u32) {
    unsafe {
        cnt(ID_CHUNK07);
        let o = r.eax as usize;
        let mut ecx = r.ecx;
        let edx = rd(o);
        let mut esi = rd(edx.wrapping_add(ecx) as usize);
        ecx = ecx.wrapping_add(4);
        wd(o + 0x6C, esi);
        esi = edx.wrapping_add(ecx);
        ecx = ecx.wrapping_add(rd(o + 0x6C));
        let t = rb(o + 0x1C) & 0x13;
        wd(o + 0x68, esi);
        esi = rd(edx.wrapping_add(ecx) as usize);
        ecx = edx.wrapping_add(ecx).wrapping_add(4);
        wd(o + 0x74, esi);
        wd(o + 0x70, ecx);
        if t != 0 {
            ecx = 0;
            wd(o + 0x6C, 0);
            wd(o + 0x68, 0);
            wd(o + 0x74, 0);
            wd(o + 0x70, 0);
        }
        r.ecx = ecx;
        r.edx = edx;
    }
}

extern "C" fn p_chunk14(r: &mut Pushad, _a: *const u32) {
    unsafe {
        cnt(ID_CHUNK14);
        let o = r.ecx as usize;
        let mut eax = rd(o).wrapping_add(r.edx);
        let mut edx = rd(eax as usize);
        eax = eax.wrapping_add(4);
        wd(o + 0x194, edx);
        wd(o + 0x198, eax);
        if (edx as i32) > 0 {
            let mut edi = 0u32;
            let mut esi = 0u32;
            loop {
                eax = rd(o + 0x198);
                edx = rd(eax.wrapping_add(esi) as usize);
                eax = eax.wrapping_add(esi);
                if edx == 0xFFFF_FFFF {
                    wd(eax as usize, 0);
                } else {
                    wd(eax as usize, rd(o + 0x118).wrapping_add(edx));
                }
                edi = edi.wrapping_add(1);
                esi = esi.wrapping_add(0x3C);
                if (edi as i32) >= (rd(o + 0x194) as i32) {
                    break;
                }
            }
        }
        r.eax = eax;
        r.edx = edx;
    }
}

