extern "C" fn e_norm(r: &mut Pushad, _a: *const u32) {
    unsafe {
        count(0);
        let v = r.esi as usize;
        let (x, y, z) = (fx(v), fx(v + 4), fx(v + 8));
        let sumsq = add87(add87(mul87(y, y), mul87(x, x)), mul87(z, z)) as f32;
        let mut rg = [r.eax, r.ecx, r.edx];
        let len = lean_sqrt(SQRTF, &[sumsq.to_bits()], &mut rg);
        let inv = (1.0f64 / len) as f32 as f64;
        wf(v, (x * inv) as f32);
        wf(v + 4, (y * inv) as f32);
        wf(v + 8, (z * inv) as f32);
        r.eax = rg[0];
        r.ecx = rg[1];
        r.edx = rg[2];
    }
}
