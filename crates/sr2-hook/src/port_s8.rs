/// `fnstsw ax` after `fld1; fcom dword [m]` with an otherwise empty x87 stack (TOP = 7): returns
/// (equal, AX).
#[inline(always)]
fn fcom_one(m: f64) -> (bool, u32) {
    if m.is_nan() {
        (false, 0x3800 | 0x4500 | 1)
    } else if 1.0 > m {
        (false, 0x3800)
    } else if 1.0 < m {
        (false, 0x3800 | 0x0100)
    } else {
        (true, 0x3800 | 0x4000)
    }
}

