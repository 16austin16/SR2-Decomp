const COOKIE: usize = 0x00E8_0B50;
const SEC_CHECK: usize = 0x00C9_604F;

/// `_ftol2_sse(v)` with `K` dummy values below the argument (the x87 depth the original has there).
#[inline(always)]
unsafe fn ftol<const K: usize>(v: f64, eax: &mut u32, ecx: &mut u32, edx: &mut u32) {
    let p = &v as *const f64;
    unsafe {
        std::arch::asm!(
            ".rept {k}", "fldz", ".endr",
            "fld qword ptr [{p}]",
            "call {f}",
            ".rept {k}", "fstp st(0)", ".endr",
            k = const K,
            p = in(reg) p,
            f = in(reg) FTOL2,
            inout("eax") *eax,
            inout("ecx") *ecx,
            inout("edx") *edx,
            clobber_abi("C"),
        );
    }
}


/// The original's argument checks, in its order (volatile reads: a bad `set` must fault at the same
/// read as the original, not be reordered behind the cheap tests).
#[inline(always)]
unsafe fn morph_guard(set: usize, group: u32, target: u32) -> bool {
    unsafe {
        let v = |p: usize| std::ptr::read_volatile(p as *const u32);
        set != 0
            && (group as i32) >= 0
            && (group as i32) <= v(set + 0xC) as i32
            && (target as i32) >= 0
            && (target as i32) < v(set + 8) as i32
            && v(set + 0x18) == 2
    }
}

/// The security-cookie call that ends both functions, with the registers the original has there.
unsafe fn cookie_call(r: &mut Pushad, eax: u32, ecx: u32, edx: u32) {
    unsafe {
        let mut s = St::of(r);
        s.eax = eax;
        s.ecx = ecx;
        s.edx = edx;
        call_plain::<0>(SEC_CHECK, &mut s, &[]);
        r.eax = s.eax;
        r.ecx = s.ecx;
        r.edx = s.edx;
    }
}

