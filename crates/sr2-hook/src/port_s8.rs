/// The seven general registers as the original holds them. `x` carries an x87 value in or out.
#[repr(C)]
#[derive(Clone, Copy)]
struct St {
    eax: u32,
    ecx: u32,
    edx: u32,
    ebx: u32,
    esi: u32,
    edi: u32,
    ebp: u32,
    x: [u32; 2],
}

impl St {
    #[inline(always)]
    fn of(r: &Pushad) -> St {
        St { eax: r.eax, ecx: r.ecx, edx: r.edx, ebx: r.ebx, esi: r.esi, edi: r.edi, ebp: r.ebp, x: [0; 2] }
    }

    #[inline(always)]
    fn set_f(&mut self, v: f64) {
        let b = v.to_bits();
        self.x = [b as u32, (b >> 32) as u32];
    }
}

/// Generates a call helper. `$pre` runs with EBX = the `St` block (loads an x87 argument), `$post`
/// with EDI = the `St` block just after the call (stores an x87 result).
macro_rules! gen_call {
    ($name:ident, $pre:literal, $post:literal) => {
        #[inline(never)]
        unsafe fn $name<const K: usize>(f: usize, st: &mut St, args: &[u32]) {
            let mut a8 = [0u32; 8];
            a8[..args.len()].copy_from_slice(args);
            let block: [u32; 3] = [f as u32, a8.as_ptr() as u32, st as *mut St as u32];
            unsafe {
                std::arch::asm!(
                    "push ebx", "push esi", "push edi", "push ebp",
                    "push dword ptr [eax + 8]",
                    "push dword ptr fs:[0x14]",
                    "mov ebx, eax",
                    "mov fs:[0x14], esp",
                    "push dword ptr [ebx]",
                    "mov esi, [ebx + 4]",
                    "mov ecx, 8",
                    "2:",
                    "push dword ptr [esi + ecx*4 - 4]",
                    "dec ecx",
                    "jnz 2b",
                    "mov ebx, [ebx + 8]",
                    ".rept {k}", "fldz", ".endr",
                    $pre,
                    "mov eax, [ebx]", "mov ecx, [ebx + 4]", "mov edx, [ebx + 8]",
                    "mov esi, [ebx + 16]", "mov edi, [ebx + 20]", "mov ebp, [ebx + 24]", "mov ebx, [ebx + 12]",
                    "call dword ptr [esp + 32]",
                    "push edi",
                    "mov edi, fs:[0x14]",
                    "mov edi, [edi + 4]",
                    $post,
                    ".rept {k}", "fstp st(0)", ".endr",
                    "mov [edi], eax", "mov [edi + 4], ecx", "mov [edi + 8], edx", "mov [edi + 12], ebx",
                    "mov [edi + 16], esi", "mov [edi + 24], ebp",
                    "pop dword ptr [edi + 20]",
                    "mov esp, fs:[0x14]",
                    "pop dword ptr fs:[0x14]",
                    "add esp, 4",
                    "pop ebp", "pop edi", "pop esi", "pop ebx",
                    k = const K,
                    inout("eax") block.as_ptr() => _, lateout("ecx") _, lateout("edx") _,
                    clobber_abi("C"),
                );
            }
        }
    };
}

