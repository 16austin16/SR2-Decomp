extern "C" fn e_dist(r: &mut Pushad, a: *const u32) -> f64 {
    unsafe {
        count(1);
        let (pa, pb) = (rd(a as usize) as usize, rd(a as usize + 4) as usize);
        let (fdx, fdy, fdz) = (sub87(fx(pa), fx(pb)) as f32, sub87(fx(pa + 4), fx(pb + 4)) as f32, sub87(fx(pa + 8), fx(pb + 8)) as f32);
        let (dx, dy, dz) = (fdx as f64, fdy as f64, fdz as f64);
        let sumsq = add87(add87(mul87(dx, dx), mul87(dy, dy)), mul87(dz, dz)) as f32;
        wd(a as usize, sumsq.to_bits()); // the original spills the sum over its first argument slot
        let mut rg = [pa as u32, pb as u32, r.edx];
        let len = lean_dist(SQRTF, &[sumsq.to_bits(), fdx.to_bits(), fdy.to_bits(), fdz.to_bits()], &mut rg);
        r.eax = rg[0];
        r.ecx = rg[1];
        r.edx = rg[2];
        len
    }
}
