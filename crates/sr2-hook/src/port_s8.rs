/// Lean calls into the game's functions: EAX / ECX / EDX (and ESI where passed) are set, the stack
/// arguments are pushed straight from `a`, `K` dummy values go below an x87 argument, the callee pops
/// what it pops (`$clean` is the rest). Used on the hot paths instead of the generic `gen_call!` helpers.
macro_rules! lean {
    ($name:ident, $clean:literal, $esi:literal, [$($push:literal),*]) => {
        #[inline(always)]
        unsafe fn $name<const K: usize>(f: usize, a: &[u32], r: &mut [u32; 3]) {
            let p = a.as_ptr();
            unsafe {
                std::arch::asm!(
                    ".rept {k}", "fldz", ".endr",
                    "push esi",
                    concat!("mov esi, [ebx + ", $esi, "]"),
                    $( concat!("push dword ptr [ebx + ", $push, "]"), )*
                    "call edi",
                    concat!("add esp, ", $clean),
                    "pop esi",
                    ".rept {k}", "fstp st(0)", ".endr",
                    k = const K,
                    in("ebx") p,
                    in("edi") f,
                    inout("eax") r[0],
                    inout("ecx") r[1],
                    inout("edx") r[2],
                    clobber_abi("C"),
                );
            }
        }
    };
}
/// The same for a callee that returns an f64 on ST0 (popped here).
macro_rules! lean_f {
    ($name:ident, $clean:literal, [$($push:literal),*]) => {
        #[inline(always)]
        unsafe fn $name(f: usize, a: &[u32], r: &mut [u32; 3]) -> f64 {
            let p = a.as_ptr();
            let mut out = 0f64;
            unsafe {
                std::arch::asm!(
                    $( concat!("push dword ptr [{p} + ", $push, "]"), )*
                    "call {f}",
                    concat!("add esp, ", $clean),
                    "fstp qword ptr [{o}]",
                    p = in(reg) p,
                    f = in(reg) f,
                    o = in(reg) &mut out as *mut f64,
                    inout("eax") r[0],
                    inout("ecx") r[1],
                    inout("edx") r[2],
                    clobber_abi("C"),
                );
            }
            out
        }
    };
}
