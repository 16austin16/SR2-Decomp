/// What `fld dword` / `fstp dword` does to a signalling NaN.
#[inline(always)]
fn q(b: u32) -> u32 {
    if b & 0x7F80_0000 == 0x7F80_0000 && b & 0x007F_FFFF != 0 { b | 0x0040_0000 } else { b }
}

/// The x87 picks the NaN with the larger significand when both operands are NaNs (SSE takes the
/// first); every other case (one NaN, the default NaN) already matches SSE.
#[inline(always)]
fn pick87(a: f64, b: f64, r: f64) -> f64 {
    if r.is_nan() && a.is_nan() && b.is_nan() {
        let (ma, mb) = (a.to_bits() & 0x000F_FFFF_FFFF_FFFF, b.to_bits() & 0x000F_FFFF_FFFF_FFFF);
        if mb > ma || (mb == ma && b.is_sign_positive() && a.is_sign_negative()) { b } else { a }
    } else {
        r
    }
}
#[inline(always)]
fn add87(a: f64, b: f64) -> f64 {
    pick87(a, b, a + b)
}
#[inline(always)]
fn sub87(a: f64, b: f64) -> f64 {
    pick87(a, b, a - b)
}
#[inline(always)]
fn mul87(a: f64, b: f64) -> f64 {
    pick87(a, b, a * b)
}

#[inline(always)]
unsafe fn fx(p: usize) -> f64 {
    unsafe { f32::from_bits(rd(p)) as f64 }
}

#[inline(always)]
unsafe fn rw(p: usize) -> u16 {
    unsafe { *(p as *const u16) }
}

#[inline(always)]
unsafe fn ww(p: usize, v: u16) {
    unsafe { *(p as *mut u16) = v }
}

#[inline(always)]
unsafe fn dbl(p: usize) -> f64 {
    unsafe { f64::from_bits(*(p as *const u64)) }
}

