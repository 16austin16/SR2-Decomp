/// `character_ragdoll(name, [ms = 3600000], [force = -1.0], [animation])`: a nil optional still
/// consumes its slot; 0xA3C9A0 (EAX = ms, ECX = animation name or 0, EDI = human, stack force).
unsafe fn character_ragdoll_impl(l: u32) -> i32 {
    unsafe {
        let n = nargs(l).min(4);
        let name = tostring(l, -n);
        let mut c = n - 1;
        let time: u32 = if c <= 0 {
            3_600_000
        } else if is_nil(slot(l, -c)) {
            c -= 1;
            3_600_000
        } else {
            let v = int_arg(l, -c);
            c -= 1;
            v
        };
        let force: f32 = if c <= 0 {
            -1.0
        } else if is_nil(slot(l, -c)) {
            c -= 1;
            -1.0
        } else {
            let v = number_arg(l, -c) as f32;
            c -= 1;
            v
        };
        let anim: u32 = if c <= 0 || is_nil(slot(l, -c)) { 0 } else { tostring(l, -c) };
        if name == 0 {
            return 0;
        }
        let h = human_named(name);
        if h != 0 {
            call_regs(0x00A3_C9A0, time, anim, 0, 0, h, &[force.to_bits()]);
        }
    }
    0
}
counted!(character_ragdoll, I_CHARACTER_RAGDOLL, character_ragdoll_impl);

