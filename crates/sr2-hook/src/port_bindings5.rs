/// `on_searchlight_track(callback, name)`: a human standing on a live kind-1 entity whose byte
/// +0x3CC is 1 gets the callback itself (type 0xB); any other human gets it on its script object
/// (+0x1178 + 0xBC, type 0x10).
unsafe fn on_searchlight_track_impl(l: u32) -> i32 {
    unsafe {
        let n = nargs(l).min(2);
        let cb = tostring(l, -n);
        let name = tostring(l, 1 - n);
        if name == 0 {
            return 0;
        }
        let h = human_named(name);
        if h == 0 {
            return 0;
        }
        let handle = rd(h as usize + 0x44);
        let mut on_entity = false;
        if handle != 0 {
            let ent = rd(ENTITY_TABLE + (((handle & 0xFFF) as usize) << 4));
            on_entity = ent != 0
                && rd(ent as usize + 0x44) == handle
                && rd(ent as usize + 0x4C) == 1
                && rb(ent as usize + 0x3CC) == 1;
        }
        if on_entity {
            cb_set(HUMAN_CALLBACK_SET, h + 0x1234, 0xB, cb);
        } else {
            cb_set(OBJECT_CALLBACK_SET, rd(h as usize + 0x1178) + 0xBC, 0x10, cb);
        }
    }
    0
}
