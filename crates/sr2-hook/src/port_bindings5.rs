/// `notoriety_get_decimal(gang)` -> number (nothing for an unknown gang): the level (record
/// stride 60 at 0x279AA60) as a float, plus below level 5 the progress float (+4) divided by the
/// int at 0x1409B50[level] (the divide and add at 53-bit precision, stored through a float).
unsafe fn notoriety_get_decimal_impl(l: u32) -> i32 {
    unsafe {
        let n = nargs(l).min(1);
        let name = tostring(l, -n);
        let team = call_regs(0x0055_F5E0, 0, 0, 0, 0, name, &[]);
        if team == 0xFFFF_FFFF {
            return 0;
        }
        let rec = 0x0279_AA60usize.wrapping_add((team as usize).wrapping_mul(60));
        let level = rd(rec) as i32;
        let mut f = level as f64 as f32;
        if level < 5 {
            let prog = f32::from_bits(rd(rec + 4)) as f64;
            let div = rd(0x0140_9B50usize.wrapping_add((level as usize).wrapping_mul(4))) as i32;
            f = (prog / div as f64 + f as f64) as f32;
        }
        push_number(l, f as f64);
    }
    1
}
