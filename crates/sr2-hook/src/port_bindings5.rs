/// `vehicle_pathfind_check_done(name)` -> number: 2.0 (the double at 0xE5BFE8) unless the vehicle
/// exists, is not skipped (a kind-1 vehicle with no seats) and has an occupant (0x960D60 on
/// +0x8ABC); then 0x684030 (EAX = 2, EDX = the vehicle, it edits a list) is pushed as an int.
unsafe fn vehicle_pathfind_check_done_impl(l: u32) -> i32 {
    unsafe {
        let n = nargs(l).min(1);
        let name = tostring(l, -n);
        let v = vehicle_from_name(name);
        let mut res: Option<u32> = None;
        if v != 0 {
            let vp = v as usize;
            let skip = rb(vp + 0x84D8) == 1 && (rd(vp + 0x6CE8) as i32) <= 0;
            if !skip && call_regs(0x0096_0D60, rd(vp + 0x8ABC), 0, 0, 0, 0, &[]) != 0 {
                res = Some(call_regs(0x0068_4030, 2, 0, v, 0, 0, &[]));
            }
        }
        match res {
            Some(r) => push_number(l, r as i32 as f64),
            None => push_number(l, rf64(0x00E5_BFE8)),
        }
    }
    1
}
