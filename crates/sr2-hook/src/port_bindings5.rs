// --- Lua 5.0 argument access (as in port_bindings3.rs) ---------------------------------------

unsafe fn top(l: u32) -> u32 {
    unsafe { rd(l as usize + 8) }
}

unsafe fn nargs(l: u32) -> i32 {
    unsafe { (top(l).wrapping_sub(rd(l as usize + 0xC)) as i32) >> 4 }
}

unsafe fn tostring(l: u32, i: i32) -> u32 {
    unsafe { call_regs(LUA_TOSTRING, i as u32, l, 0, 0, 0, &[]) }
}

/// The slot of index `i` as the bindings compute it inline: positive indexes are base-relative
/// (0 when at or past top), the others go through luaA_index.
unsafe fn slot(l: u32, i: i32) -> u32 {
    unsafe {
        if i > 0 {
            let a = rd(l as usize + 0xC).wrapping_add((i as u32 - 1) * 16);
            if a < top(l) { a } else { 0 }
        } else {
            call_regs(LUAA_INDEX, i as u32, l, 0, 0, 0, &[])
        }
    }
}

/// The "nil -> absent" test: the slot exists and holds nil.
unsafe fn is_nil(p: u32) -> bool {
    unsafe { p != 0 && rd(p as usize) == 0 }
}

unsafe fn number_arg(l: u32, i: i32) -> f64 {
    let mut out = 0f64;
    unsafe {
        std::arch::asm!(
            "call {f}",
            "fstp qword ptr [edi]",
            f = in(reg) LUA_TONUMBER,
            in("eax") i,
            in("ecx") l,
            in("edi") &mut out as *mut f64,
            clobber_abi("C"),
        );
    }
    out
}

/// `_ftol2(lua_tonumber(i))`: truncation, the low dword of the 64-bit result.
unsafe fn int_arg(l: u32, i: i32) -> u32 {
    let out = unsafe { number_arg(l, i) };
    if out.abs() < 9.2e18 { out as i64 as u32 } else { 0 }
}

/// The truth test of a slot pointer: missing, nil or false -> false.
unsafe fn truth(p: u32) -> bool {
    unsafe {
        if p == 0 {
            return false;
        }
        match rd(p as usize) {
            0 => false,
            1 => rd(p as usize + 8) != 0,
            _ => true,
        }
    }
}

/// A count-guarded optional flag at the fixed position `-m` (m = arguments left): missing or
/// nil -> `def`, else the truth test.
unsafe fn flag_at(l: u32, m: i32, def: bool) -> bool {
    unsafe {
        if m <= 0 || is_nil(slot(l, -m)) { def } else { truth(slot(l, -m)) }
    }
}

unsafe fn push(l: u32, tt: u32, v: impl FnOnce(usize)) {
    unsafe {
        let t = top(l) as usize;
        wd(t, tt);
        v(t + 8);
        wd(l as usize + 8, t as u32 + 16);
    }
}

unsafe fn push_bool(l: u32, b: bool) {
    unsafe { push(l, 1, |p| wd(p, b as u32)) };
}

unsafe fn push_number(l: u32, x: f64) {
    unsafe { push(l, 3, |p| *(p as *mut f64) = x) };
}

unsafe fn rf64(p: usize) -> f64 {
    unsafe { *(p as *const f64) }
}

