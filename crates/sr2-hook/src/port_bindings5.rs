/// A human by name with the inline "found byte" pattern: `script_find_object_by_name(ECX = name,
/// EAX = &found)`, else `script_object_to_human(ESI = name)` (follower, then script object).
unsafe fn human_named(name: u32) -> u32 {
    unsafe {
        let mut found: u32 = 0;
        let obj = call_regs(SCRIPT_FIND_OBJECT_BY_NAME, &mut found as *mut u32 as u32, name, 0, 0, 0, &[]);
        if found as u8 != 0 { obj } else { call_regs(SCRIPT_OBJECT_TO_HUMAN, obj, 0, 0, name, 0, &[]) }
    }
}

/// A human by follower index (when the name is a follower) or by script object, with no player
/// lookup and no +0x2C test. `None` when the object does not exist.
unsafe fn follower_or_object_human(name: u32) -> Option<u32> {
    unsafe {
        let idx = follower_index(name);
        if idx > 0 {
            return Some(follower_get(idx));
        }
        let o = object_find(name);
        if o == 0 { None } else { Some(vcall(o, 13)) }
    }
}

unsafe fn cb_set(f: usize, ecx: u32, ty: u32, name: u32) {
    let mut t = ty;
    unsafe { call_regs(f, &mut t as *mut u32 as u32, ecx, 0, 0, 0, &[name]) };
}

// --- Shadow harness ------------------------------------------------------------------------

/// The pushed slots as comparable words: type, then the payload (strings by content).
unsafe fn snapshot(l: u32, from: u32, to: u32) -> Vec<u32> {
    let mut v = Vec::new();
    unsafe {
        let mut p = from;
        while p < to {
            let tt = rd(p as usize);
            v.push(tt);
            match tt {
                0 => {}
                3 => {
                    v.push(rd(p as usize + 8));
                    v.push(rd(p as usize + 12));
                }
                4 => {
                    let idx = -(((to - p) / 16) as i32);
                    let s = tostring(l, idx);
                    if s != 0 {
                        let mut q = s as usize;
                        while rb(q) != 0 && q - (s as usize) < 0x10000 {
                            v.push(rb(q) as u32);
                            q += 1;
                        }
                    }
                    v.push(0xFFFF_FFFF);
                }
                _ => v.push(rd(p as usize + 8)),
            }
            p += 16;
        }
    }
    v
}

/// Run the Rust body, then (for the first 3000 calls) the relocated original on the same stack
/// position, compare the Lua stack effect and keep the original's.
unsafe fn shadowed(i: usize, l: u32, rust: unsafe fn(u32) -> i32) -> i32 {
    let n = CALLS[i].fetch_add(1, Ordering::Relaxed);
    let orig = ORIGINALS[i].load(Ordering::Relaxed);
    if orig == 0 || n >= SHADOW_CALLS {
        return unsafe { rust(l) };
    }
    unsafe {
        let t0 = top(l);
        let r1 = rust(l);
        let t1 = top(l);
        let s1 = snapshot(l, t0, t1);
        wd(l as usize + 8, t0);
        let r2 = call_regs(orig, 0, 0, 0, 0, 0, &[l]) as i32;
        let t2 = top(l);
        let s2 = snapshot(l, t0, t2);
        if r1 != r2 || t1 != t2 || s1 != s2 {
            let m = MISMATCHES[i].fetch_add(1, Ordering::Relaxed) + 1;
            if m <= 10 {
                log(&format!(
                    "port_bindings5: {} mismatch (call {n}): original {r2} results {s2:?}, Rust {r1} results {s1:?}",
                    BINDINGS[i].name
                ));
            }
        }
        if n + 1 == SHADOW_CALLS {
            log(&format!(
                "port_bindings5: {}: {SHADOW_CALLS} calls shadowed, {} mismatched",
                BINDINGS[i].name,
                MISMATCHES[i].load(Ordering::Relaxed)
            ));
        }
        r2
    }
}

macro_rules! counted {
    ($name:ident, $idx:expr, $body:ident) => {
        extern "C" fn $name(l: u32) -> i32 {
            CALLS[$idx].fetch_add(1, Ordering::Relaxed);
            unsafe { $body(l) }
        }
    };
}

macro_rules! shadow_checked {
    ($name:ident, $idx:expr, $body:ident) => {
        extern "C" fn $name(l: u32) -> i32 {
            unsafe { shadowed($idx, l, $body) }
        }
    };
}


// --- 122 audio_fade_out ----------------------------------------------------------------------

/// `audio_fade_out(voice, [ms])`: a missing or nil `ms` is 0, which stops the voice (0x47FEB0,
/// ECX -> {voice, -1, -1}); otherwise a live voice (slot = low byte, generation = the rest, both
/// matching the slot table at 0xEEB8F8, stride 0x19C) gets 0x47C740 (EAX = slot, EDX = ms).
unsafe fn audio_fade_out_impl(l: u32) -> i32 {
    unsafe {
        let n = nargs(l).min(2);
        let id = int_arg(l, -n);
        let m = n - 1;
        let ms: u32 = if m <= 0 || is_nil(slot(l, -m)) { 0 } else { int_arg(l, -m) };
        let mut h = [id, 0xFFFF_FFFF, 0xFFFF_FFFF];
        if ms == 0 {
            call_regs(0x0047_FEB0, 0, h.as_mut_ptr() as u32, 0, 0, 0, &[]);
            return 0;
        }
        let s = id & 0xFF;
        if s == 0xFF {
            return 0;
        }
        let generation = id >> 8;
        if generation == 0 {
            return 0;
        }
        let rec = s.wrapping_mul(0x19C);
        if generation != rd(0x00EE_B9AC + rec as usize) || rd(0x00EE_B8F8 + rec as usize) == 0xFFFF_FFFF {
            return 0;
        }
        call_regs(0x0047_C740, s, rec, ms, generation, 0xFFFF_FFFF, &[]);
    }
    0
}
counted!(audio_fade_out, I_AUDIO_FADE_OUT, audio_fade_out_impl);

