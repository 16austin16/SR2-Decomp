//! Script bindings ranked 121-160 by call sites in the shipped Lua scripts (the same method as
//! docs/analysis/43_bindings_41_80.md), plus the next simple ones down to rank 200, in Rust.
//! Rank 135 pcr_mark_changed is already Rust; script_profiler_start_section (3 bytes),
//! menu_open_enter_name_result_string, navpoint_in_player_fov, message, damage_indicator_on,
//! city_chunk_swap, hud_bar_on and distance_display_off are not ported.
//!
//! Argument reading follows the originals exactly, as in port_bindings5.rs: argument k is read at
//! `k - 1 - n` (n clamped to the most a binding reads), so a missing argument is the stale slot at
//! `L->top`. Optional flags test the slot for nil first, then the truth test (the number 0 is
//! true); "stale" flags have no count guard and read index `1 - n`. Flags passed to callees as a
//! byte inside L's own argument slot keep L's upper three bytes; flags the original builds in a
//! register or an uninitialised local (so their upper bytes are unknowable) are passed clean,
//! which is safe because every such callee reads a byte.
//!
//! Bindings that only read state and push (thread_check_done, character_is_ready, get_language,
//! character_is_player, notoriety_get_decimal, completion_is_coop, crouch_is_crouching) are
//! shadow-checked against a relocated copy of the original for the first 3000 calls: the Lua
//! stack effect (values pushed, result count) is compared and the original's effect is kept. The
//! others write game state and only count calls.


