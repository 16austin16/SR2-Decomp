/// One line for the periodic log.
pub fn summary() -> String {
    let mut parts: Vec<String> = PORTS
        .iter()
        .filter_map(|p| {
            let c = p.calls.load(Ordering::Relaxed);
            (c > 0).then(|| format!("{} {c} ({})", p.name, p.mismatches.load(Ordering::Relaxed)))
        })
        .collect();
    let b: Vec<String> = BRANCH.iter().enumerate().filter(|(_, v)| v.load(Ordering::Relaxed) > 0).map(|(i, v)| format!("b{i}={}", v.load(Ordering::Relaxed))).collect();
    if !b.is_empty() {
        parts.push(format!("branches {}", b.join(" ")));
    }
    if parts.is_empty() { String::new() } else { format!("port_physics: {}", parts.join(", ")) }
}

