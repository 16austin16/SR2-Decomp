const SHADOW_CALLS: u32 = 3000;

/// A game data address. The offline tests keep the game's data at `difftest::DELTA` above it.
const fn g(a: usize) -> usize {
    #[cfg(test)]
    {
        a + difftest::DELTA
    }
    #[cfg(not(test))]
    {
        a
    }
}

/// The offline tests send every call into the game through a stub or a relocated original.
#[cfg(test)]
unsafe fn call_regs(f: usize, eax: u32, ecx: u32, edx: u32, esi: u32, edi: u32, args: &[u32]) -> u32 {
    unsafe { crate::portlib::call_regs(difftest::redirect(f), eax, ecx, edx, esi, edi, args) }
}

const HANDLES: usize = g(0x0214_9C64); // object table, 16-byte entries

// --- registers and the call helper -----------------------------------------------------------------

/// The `pushad` block, lowest address first.
#[repr(C)]
#[derive(Clone, Copy)]
#[allow(dead_code)] // esp is never read
struct Pushad {
    edi: u32,
    esi: u32,
    ebp: u32,
    esp: u32,
    ebx: u32,
    edx: u32,
    ecx: u32,
    eax: u32,
}

#[repr(C)]
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
struct Regs {
    eax: u32,
    ecx: u32,
    edx: u32,
    ebx: u32,
    esi: u32,
    edi: u32,
    ebp: u32,
}

impl Regs {
    fn of(p: &Pushad) -> Regs {
        Regs { eax: p.eax, ecx: p.ecx, edx: p.edx, ebx: p.ebx, esi: p.esi, edi: p.edi, ebp: p.ebp }
    }
}

#[repr(C)]
struct Block {
    f: u32,
    r: Regs,
    esp: u32,
    st0: [u32; 2],
    want_st0: u32,
    n: u32,
    args: [u32; 8],
}

/// Call `f` with all seven registers from `r` and up to eight stack arguments, then capture all
/// seven registers into `r` and, when `want_st0`, pop ST0 (returned). The block pointer is kept in
/// nine stack copies above the arguments, so it is found again whatever the callee pops (up to 32
/// bytes); nothing is global, so any thread may call it.
unsafe fn call_full(f: usize, r: &mut Regs, args: &[u32], want_st0: bool) -> f64 {
    let mut b = Block { f: f as u32, r: *r, esp: 0, st0: [0; 2], want_st0: want_st0 as u32, n: args.len() as u32, args: [0; 8] };
    b.args[..args.len()].copy_from_slice(args);
    unsafe {
        std::arch::asm!(
            "push ebp", "push ebx", "push esi", "push edi",
            "mov [eax + 32], esp",
            "push dword ptr [eax]",
            "push eax", "push eax", "push eax", "push eax", "push eax", "push eax", "push eax", "push eax", "push eax",
            "sub esp, 32",
            "mov ecx, [eax + 48]",
            "xor edx, edx",
            "2:",
            "cmp edx, ecx",
            "jae 3f",
            "mov ebx, [eax + 52 + edx*4]",
            "mov [esp + edx*4], ebx",
            "inc edx",
            "jmp 2b",
            "3:",
            "mov ecx, [eax + 8]", "mov edx, [eax + 12]", "mov ebx, [eax + 16]",
            "mov esi, [eax + 20]", "mov edi, [eax + 24]", "mov ebp, [eax + 28]",
            "mov eax, [eax + 4]",
            "call dword ptr [esp + 68]",
            "push ebx",
            "mov ebx, [esp + 36]",
            "mov [ebx + 4], eax", "mov [ebx + 8], ecx", "mov [ebx + 12], edx",
            "mov [ebx + 20], esi", "mov [ebx + 24], edi", "mov [ebx + 28], ebp",
            "pop dword ptr [ebx + 16]",
            "cmp dword ptr [ebx + 44], 0",
            "je 4f",
            "fstp qword ptr [ebx + 36]",
            "4:",
            "mov esp, [ebx + 32]",
            "pop edi", "pop esi", "pop ebx", "pop ebp",
            inout("eax") &mut b as *mut Block => _,
            lateout("ecx") _,
            lateout("edx") _,
            clobber_abi("C"),
        );
    }
    *r = b.r;
    f64::from_bits(b.st0[0] as u64 | (b.st0[1] as u64) << 32)
}

/// A naked thunk: `pushad`, then `f(&mut block, &stack args)`, then `popad`. The Rust body puts
/// its result in the block's EAX; an `f32` return stays on ST0.
macro_rules! regs_thunk {
    ($name:ident, $f:ident) => {
        regs_thunk!($name, $f, "ret");
    };
    ($name:ident, $f:ident, $ret:literal) => {
        #[unsafe(naked)]
        extern "C" fn $name() {
            std::arch::naked_asm!(
                "pushad",
                "mov eax, esp",
                "lea ecx, [esp + 36]",
                "push ecx",
                "push eax",
                "call {f}",
                "add esp, 8",
                "popad",
                $ret,
                f = sym $f,
            )
        }
    };
}

