// --- 0x7042B0 physics_box_to_mesh_lists (ECX = &center, EDX = triangle list or 0, stack (vertex list,
//     tetra list, &rot 3x3, &half), plain ret) ------------------------------------------------------

/// A real x87 operation on two f32 operands: `fld dest; f<op> dword src; fstp dword out`. Using
/// the instructions themselves gives the original's exact results whatever the precision control
/// word says, and its NaN choices (the larger significand wins, ties go by operand role). `dest`
/// is the register operand (ST0), `src` the second one.
macro_rules! x87op {
    ($name:ident, $ins:literal) => {
        fn $name(dest: f32, src: f32) -> f32 {
            let mut out = 0f32;
            unsafe {
                std::arch::asm!(
                    "fld dword ptr [{d}]",
                    concat!($ins, " dword ptr [{s}]"),
                    "fstp dword ptr [{o}]",
                    d = in(reg) &dest,
                    s = in(reg) &src,
                    o = in(reg) &mut out,
                    out("st(0)") _,
                    options(nostack),
                );
            }
            out
        }
    };
}
x87op!(x_add, "fadd");
x87op!(x_sub, "fsub"); // dest - src
x87op!(x_subr, "fsubr"); // src - dest
x87op!(x_mul, "fmul");

/// `fld dword`: the f32 with a signalling NaN quieted.
unsafe fn ld(p: usize) -> f32 {
    f32::from_bits(q32(unsafe { rd(p) }))
}

unsafe fn rh(p: usize) -> u16 {
    unsafe { *(p as *const u16) }
}

unsafe fn wh(p: usize, v: u16) {
    unsafe { *(p as *mut u16) = v }
}

/// Eight corners of the oriented box (centre c, axes u, v, w scaled by the half extents), each
/// built left to right with an f32 store after every operation: the signs of u, v, w for the
/// corners in order are (+ + -), (+ + +), (+ - +), (+ - -), (- + -), (- + +), (- - +), (- - -).
/// Appends them to the vertex list, then six tetrahedra to `tl` (unless 0) and twelve triangles
/// to `tris` (unless 0), all indices offset by the old vertex count. Index words are 16-bit.
unsafe fn box_to_mesh(c: usize, tris: usize, vl: usize, tl: usize, rot: usize, half: usize) {
    unsafe {
        let n = rh(vl) as usize;
        let out = vl + n * 12 + 4;
        let b = n as u32;
        let (hx, hy, hz) = (ld(half), ld(half + 4), ld(half + 8));
        // the products: the first two of each axis have the matrix element as the register
        // operand, the third the half extent
        // (a memory operand keeps a signalling NaN as it is, a register operand was quieted by its
        // `fld`: x87 prefers a quiet NaN over a signalling one whatever the payloads)
        let u = [x_mul(rf(rot), hx), x_mul(rf(rot + 4), hx), x_mul(hx, rf(rot + 8))];
        let v = [x_mul(rf(rot + 12), hy), x_mul(rf(rot + 16), hy), x_mul(hy, rf(rot + 20))];
        let w = [x_mul(rf(rot + 24), hz), x_mul(rf(rot + 28), hz), x_mul(hz, rf(rot + 32))];
        let cc = [rf(c), rf(c + 4), rf(c + 8)];
        let ccq = [ld(c), ld(c + 4), ld(c + 8)];
        // c + u (the y lane has u as the register operand), c - u, and the reversed c - u of corner 7
        let cu: [f32; 3] = [x_add(cc[0], u[0]), x_add(u[1], cc[1]), x_add(cc[2], u[2])];
        let cmu: [f32; 3] = [x_sub(cc[0], u[0]), x_sub(cc[1], u[1]), x_sub(cc[2], u[2])];
        let cmu7: [f32; 3] = [x_subr(u[0], ccq[0]), x_subr(u[1], ccq[1]), x_subr(u[2], ccq[2])];
        for k in 0..8usize {
            for i in 0..3 {
                let a = match k {
                    0..=3 => cu[i],
                    4..=6 => cmu[i],
                    _ => cmu7[i],
                };
                // v: + for corners 0, 1, 4, 5; - for 2, 3, 6; corner 7 uses the reversed form
                let a = match k {
                    0 | 1 | 4 | 5 => x_add(a, v[i]),
                    2 | 3 | 6 => x_sub(a, v[i]),
                    _ => x_subr(v[i], a),
                };
                // w: + for corners 1, 2, 5, 6; - for 0, 3, 4, 7
                let a = match k {
                    1 | 2 | 5 | 6 => x_add(a, w[i]),
                    _ => x_sub(a, w[i]),
                };
                wf(out + k * 12 + i * 4, a);
            }
        }
        wh(vl, rh(vl).wrapping_add(8));
        if tl != 0 {
            const TET: [[u32; 4]; 6] = [[0, 2, 3, 7], [0, 2, 6, 7], [0, 1, 2, 6], [0, 1, 5, 6], [0, 5, 6, 7], [0, 4, 5, 7]];
            for t in TET {
                let cnt = rh(tl) as usize;
                let e = tl + cnt * 8 + 2;
                wh(tl, (cnt as u16).wrapping_add(1));
                for (j, &k) in t.iter().enumerate() {
                    wh(e + j * 2, b.wrapping_add(k) as u16);
                }
            }
        }
        if tris != 0 {
            const TRI: [[u32; 3]; 12] = [[0, 1, 2], [0, 2, 3], [1, 5, 6], [1, 6, 2], [5, 4, 7], [5, 7, 6], [4, 0, 3], [4, 3, 7], [0, 4, 5], [0, 5, 1], [3, 7, 6], [3, 6, 2]];
            for t in TRI {
                let cnt = rh(tris) as usize;
                let e = tris + cnt * 6 + 2;
                wh(tris, (cnt as u16).wrapping_add(1));
                for (j, &k) in t.iter().enumerate() {
                    wh(e + j * 2, b.wrapping_add(k) as u16);
                }
            }
        }
    }
}

extern "C" fn box_to_mesh_entry(r: &mut Pushad, args: *const u32) {
    let p = *r;
    unsafe {
        let (vl, tl, rot, half) = (*args as usize, *args.add(1) as usize, *args.add(2) as usize, *args.add(3) as usize);
        let tris = p.edx as usize;
        let mut regions: Vec<(usize, usize)> = Vec::new();
        if shadow_pending(BOX_TO_MESH) {
            let n = rh(vl) as usize;
            regions.push((vl, 2));
            regions.push((vl + n * 12 + 4, 96));
            if tl != 0 {
                regions.push((tl, 2));
                regions.push((tl + rh(tl) as usize * 8 + 2, 48));
            }
            if tris != 0 {
                regions.push((tris, 2));
                regions.push((tris + rh(tris) as usize * 6 + 2, 72));
            }
        }
        shadowed(BOX_TO_MESH, &p, args, 4, &regions, 0, || {
            box_to_mesh(p.ecx as usize, tris, vl, tl, rot, half);
            p.eax
        });
    }
}
regs_thunk!(box_to_mesh_thunk, box_to_mesh_entry);

/// True while the port still shadows (so the region lists are only built then).
fn shadow_pending(id: usize) -> bool {
    let p = &PORTS[id];
    p.original.load(Ordering::Relaxed) != 0 && p.calls.load(Ordering::Relaxed) < SHADOW_CALLS
}

/// `fld dword; fstp dword`: the bits, a signalling NaN quieted.
fn q32(bits: u32) -> u32 {
    if bits & 0x7F80_0000 == 0x7F80_0000 && bits & 0x007F_FFFF != 0 { bits | 0x0040_0000 } else { bits }
}


// --- 0x713830 ragdoll_limb_collision_update (ECX = ragdoll record, plain ret) ------------------------------

const RAYCAST_ADDR: usize = 0x006F_A330;
const GROUND_ADJUST: usize = 0x0071_57D0; // ECX = object, EDX = &vec3
const HEAP_FREE: usize = 0x00D2_B7D0; // ECX = heap, stack (data, bytes, 0x17), pops 12
const LIMB_SWEEP: usize = 0x0071_33F0; // ECX = &f32, EDI = &vec3, stack (body, partner body, record)
const BODY_WAKE: usize = 0x00D5_8FF0; // ESI = body
const SET_INFO_ADDR: usize = 0x006F_DBB0; // EAX = info, EDX = entity
const HEAP_SLOT: usize = g(0x031B_F2BC);
const HEAP_IMPORT: usize = g(0x00DB_807C);
const CLOCK: usize = g(0x00E8_43AC);
const NO_COLLIDE: u32 = 0x8002E;

/// `fld v; fcomp qword [0.0]; fnstsw; test ah, 5; jp` keeps `v` (>= 0.0 or NaN), else it becomes
/// 0.0; then `s = f32(v + 2.2352)` (`fld v; fadd qword; fstp dword`). Real x87 instructions, so the
/// result is the original's whatever the precision control word is.
unsafe fn limb_scale(vbits: u32) -> (u32, f32) {
    let sw: u16;
    unsafe {
        std::arch::asm!(
            "fld dword ptr [{v}]",
            "fcomp qword ptr [{c}]",
            "fnstsw ax",
            v = in(reg) &vbits,
            c = in(reg) g(0x00E5_BFA0),
            out("ax") sw,
            out("st(0)") _,
            options(nostack),
        );
    }
    let keep = ((sw >> 8) as u8 & 5).count_ones() % 2 == 0;
    let v = if keep { vbits } else { 0 };
    let mut s = 0f32;
    unsafe {
        std::arch::asm!(
            "fld dword ptr [{v}]",
            "fadd qword ptr [{c}]",
            "fstp dword ptr [{o}]",
            v = in(reg) &v,
            c = in(reg) g(0x00E5_D6A8),
            o = in(reg) &mut s,
            out("st(0)") _,
            options(nostack),
        );
    }
    (v, s)
}

/// vel = splat(s) * dir + old, in the original's SSE order.
unsafe fn limb_velocity(s: f32, dir: &Vec4, old: &Vec4, out: &mut Vec4) {
    unsafe {
        std::arch::asm!(
            "movss xmm0, dword ptr [{s}]",
            "movaps xmm2, xmm0",
            "shufps xmm2, xmm0, 0",
            "movaps xmm0, xmmword ptr [{d}]",
            "mulps xmm2, xmm0",
            "movaps xmm1, xmmword ptr [{old}]",
            "addps xmm2, xmm1",
            "movaps xmmword ptr [{o}], xmm2",
            s = in(reg) &s,
            d = in(reg) dir.0.as_ptr(),
            old = in(reg) old.0.as_ptr(),
            o = in(reg) out.0.as_mut_ptr(),
            out("xmm0") _,
            out("xmm1") _,
            out("xmm2") _,
            options(nostack),
        );
    }
}

/// The filter refresh after a direct store into a limb body: deferred while the world steps.
unsafe fn limb_refresh(body: u32, ecx: u32, p: &Pushad) {
    unsafe {
        if rd(STEP_COUNTER) > 0 {
            br(16);
            call_regs(FILTER_DEFER_ADDR, p.eax, ecx, body, p.esi, p.edi, &[]);
        } else {
            br(17);
            let world = rd(WORLD);
            call_regs(FILTER_UPDATE, 0, ecx, body, p.esi, p.edi, &[world, body, 1]);
        }
    }
}

/// Per limb of the ragdoll: a ground probe stores the last ground point; then (when the owner's
/// timer allows) every limb whose entry has a pending bit gets its sweep test; a limb that must not
/// collide gets the no-collide filter and a velocity push along the sweep direction, and so do its
/// child limbs; one that no longer needs it gets its saved filter back.
unsafe fn limb_update(rec: u32, p: &Pushad) {
    unsafe {
        let r = rec as usize;
        let fl = rb(r + 0x1298);
        if fl & 8 != 0 {
            br(13);
            wb(r + 0x1298, fl & 0xF7);
            return;
        }
        // ground ray from the last ground point to the position of body 1
        let last = [rd(r + 0x11AC), rd(r + 0x11B0), rd(r + 0x11B4)];
        let body1 = rd(rd(r + 0xF74) as usize + 4) as usize;
        let pos = [q32(rd(body1 + 0x110)), q32(rd(body1 + 0x114)), q32(rd(body1 + 0x118))];
        let owner = rd(r + 0xF70);
        let mut req = [0u32; 0x20];
        req[..3].copy_from_slice(&last);
        req[3..6].copy_from_slice(&pos);
        req[0x13] = 0x5D;
        if owner != 0 {
            let o = rd(HANDLES + (owner as usize & 0xFFF) * 16);
            if o != 0 && rd(o as usize + 0x44) == owner && rd(o as usize + 0x4C) == 1 && rb(o as usize + 0x3CC) == 1 {
                req[0x15] = 0x10;
            }
        }
        let mut out = [0u32, 0, 0x8000_0000];
        let hit = call_regs(RAYCAST_ADDR, owner, req.as_mut_ptr() as u32, out.as_mut_ptr() as u32, p.esi, rec, &[out.as_mut_ptr() as u32, 1]) as u8 == 1;
        let point = if hit {
            br(14);
            let human = call_regs(HUMAN_FROM_HANDLE, rd(r + 0xF70), req.as_ptr() as u32, out.as_ptr() as u32, p.esi, rec, &[]);
            call_regs(GROUND_ADJUST, human, human, req.as_mut_ptr() as u32, p.esi, rec, &[]);
            [req[0], req[1], req[2]]
        } else {
            br(15);
            [req[3], req[4], req[5]]
        };
        wd(r + 0x11AC, point[0]);
        wd(r + 0x11B0, point[1]);
        wd(r + 0x11B4, point[2]);
        let cap = out[2];
        if (cap as i32) >= 0 {
            let heap = call_regs(rd(HEAP_IMPORT) as usize, cap, 0, 0, cap, rec, &[rd(HEAP_SLOT)]);
            let c = cap & 0x3FFF_FFFF;
            let bytes = c.wrapping_mul(0x3C);
            call_regs(HEAP_FREE, heap, heap, out[0], c, rec, &[out[0], bytes, 0x17]);
        }
        // the owner's timer: with a deadline the limb pass runs only when it is due (a missing or
        // non-human owner reads address 0xF94, as the original does)
        let ow = {
            let o = if owner == 0 { 0 } else { rd(HANDLES + (owner as usize & 0xFFF) * 16) };
            if owner == 0 || o == 0 || rd(o as usize + 0x44) != owner {
                0
            } else if rd(o as usize + 0x4C) == 1 {
                o
            } else {
                0
            }
        };
        let t = rd(ow as usize + 0xF94) as i32;
        if t >= 0 {
            let now = rd(CLOCK) as i32;
            if t > now {
                if t.wrapping_sub(now) < 0x35A4_E900 {
                    return;
                }
            } else if now.wrapping_sub(t) >= 0x35A4_E900 {
                return;
            }
        }
        // the limb order and each limb's partner, one table (the original's two stack arrays are
        // adjacent)
        let tbl: [u32; 22] = [1, 2, 3, 4, 0, 7, 8, 5, 6, 9, 0xA, 2, 0xFFFF_FFFF, 1, 1, 1, 3, 4, 2, 2, 7, 8];
        let count = rd(r + 0xF7C);
        let mut done = 0u32;
        let mut i = 0u32;
        let mut ab = [0u32; 4]; // the f32 and the vec3 the sweep writes
        while i < count {
            let limb = if (i as usize) < tbl.len() { tbl[i as usize] } else { 0 };
            let entry = (rd(r + 0xFAC) as usize).wrapping_add((limb as usize).wrapping_mul(8));
            let al = rb(entry);
            if al & 3 != 0 {
                wb(entry, al & 0xFD);
                if done & (1u32 << (limb & 31)) == 0 && limb != 1 {
                    let bodies = rd(r + 0xF74) as usize;
                    let own = rd(bodies + limb as usize * 4);
                    let pid = tbl[11 + limb as usize];
                    let pbody = rd(bodies.wrapping_add((pid as usize).wrapping_mul(4)));
                    let a = call_regs(LIMB_SWEEP, pbody, ab.as_mut_ptr() as u32, 0, entry as u32, ab.as_mut_ptr().add(1) as u32, &[own, pbody, rec]) as u8;
                    let b = rb(entry);
                    wb(entry, (b & !1) | (a & 1));
                    if rb(entry) & 1 == 0 {
                        let sf = rd(entry + 4);
                        if sf != rd(own as usize + 0x2C) {
                            br(18);
                            wd(own as usize + 0x2C, sf);
                            limb_refresh(own, pid, p);
                        }
                    } else {
                        br(19);
                        let cur = rd(own as usize + 0x2C);
                        if cur != NO_COLLIDE {
                            wd(entry + 4, cur);
                            call_regs(SET_INFO_ADDR, NO_COLLIDE, pid, own, p.esi, ab.as_mut_ptr().add(1) as u32, &[]);
                        }
                        let dir = Vec4([q32(ab[1]), q32(ab[2]), q32(ab[3]), 0]);
                        let old = Vec4([rd(own as usize + 0x1A0), rd(own as usize + 0x1A4), rd(own as usize + 0x1A8), rd(own as usize + 0x1AC)]);
                        let (_, sc) = limb_scale(ab[0]);
                        let mut vel = Vec4([0; 4]);
                        limb_velocity(sc, &dir, &old, &mut vel);
                        let vp = vel.0.as_ptr() as u32;
                        call_regs(BODY_WAKE, 0, pid, 0, own, ab.as_mut_ptr().add(1) as u32, &[]);
                        let motion = own.wrapping_add(0xD0);
                        let f = rd(rd(motion as usize) as usize + 0x40);
                        call_regs(f as usize, vp, motion, f, own, ab.as_mut_ptr().add(1) as u32, &[vp]);
                        let kids: &[u32] = match limb {
                            2 => &[0, 7, 8, 9, 10],
                            3 => &[5],
                            4 => &[6],
                            7 => &[9],
                            8 => &[10],
                            _ => &[],
                        };
                        for &c in kids {
                            let ent = (rd(r + 0xFAC) as usize).wrapping_add(c as usize * 8);
                            let cb = rd(rd(r + 0xF74) as usize + c as usize * 4);
                            let cur = rd(cb as usize + 0x2C);
                            if cur != NO_COLLIDE {
                                br(20);
                                wd(ent + 4, cur);
                                wd(cb as usize + 0x2C, NO_COLLIDE);
                                limb_refresh(cb, NO_COLLIDE, p);
                            }
                            call_regs(BODY_WAKE, cur, NO_COLLIDE, 0, cb, ent as u32, &[]);
                            let cm = cb.wrapping_add(0xD0);
                            let cf = rd(rd(cm as usize) as usize + 0x40);
                            call_regs(cf as usize, vp, cm, cf, cb, ent as u32, &[vp]);
                            wb(ent, rb(ent) | 1);
                            done |= 1u32 << (c & 31);
                        }
                    }
                }
            }
            i += 1;
        }
    }
}

extern "C" fn limb_update_entry(r: &mut Pushad, _: *const u32) {
    let p = *r;
    count(LIMB_UPDATE);
    unsafe { limb_update(p.ecx, &p) };
}
regs_thunk!(limb_update_thunk, limb_update_entry);


// --- 0x6FA330 physics_raycast (ECX = request, stack (&out header, flag byte), plain ret -> AL) ------------

const R_CLAMP: usize = 0x00BF_65F0; // EAX = &vec3, ECX = box max, ESI = &out vec3, stack box min; ST0 junk
const COLL_CTOR: usize = 0x006F_4DC0; // ECX = collector
const COLL_DTOR: usize = 0x006F_4F20; // ECX = collector
const CAST_RAY: usize = 0x00D7_F660; // ECX = [world+0x54], EDX = ray record, stack (caster, filter, 0, collector), pops 16
const HEAP_ALLOC: usize = 0x00D2_B850; // ECX = heap, stack (bytes, 0x17), pops 8
const ARRAY_GROW: usize = 0x00D9_8D30; // cdecl (&array, element size)
const HIT_FILL: usize = 0x0070_1F90; // ECX = record, stack (&collector hit), pops 4
const HIT_POST: usize = 0x006F_5ED0; // ECX = record, EDX = 0, ten stack arguments, pops 0x28
const BOX_MIN: u32 = g(0x0290_FA80) as u32;
const BOX_MAX: u32 = g(0x0290_FA8C) as u32;
const WORLD_PTR: usize = g(0x0252_7D94);
const CASTER_VT: u32 = g(0x00E1_898C) as u32;
const CLOSEST_VT: u32 = g(0x00E1_89EC) as u32;

/// `call_regs` for a callee that returns on the x87 stack (popped, the value dropped).
unsafe fn call_regs_pop(f: usize, eax: u32, ecx: u32, edx: u32, esi: u32, edi: u32, args: &[u32]) {
    let block: [u32; 8] = [f as u32, ecx, edx, esi, edi, args.as_ptr() as u32, args.len() as u32, eax];
    unsafe {
        #[cfg(test)]
        let block = {
            let mut b = block;
            b[0] = difftest::redirect(f) as u32;
            b
        };
        std::arch::asm!(
            "push ebx", "push esi", "push edi", "push ebp",
            "mov ebp, esp",
            "mov ebx, eax",
            "mov ecx, [ebx + 24]",
            "mov esi, [ebx + 20]",
            "2:",
            "test ecx, ecx",
            "jz 3f",
            "push dword ptr [esi + ecx*4 - 4]",
            "dec ecx",
            "jmp 2b",
            "3:",
            "mov ecx, [ebx + 4]", "mov edx, [ebx + 8]", "mov esi, [ebx + 12]", "mov edi, [ebx + 16]",
            "mov eax, [ebx + 28]",
            "call dword ptr [ebx]",
            "fstp st(0)",
            "mov esp, ebp",
            "pop ebp", "pop edi", "pop esi", "pop ebx",
            inout("eax") block.as_ptr() => _, lateout("ecx") _, lateout("edx") _,
            clobber_abi("C"),
        );
    }
}

/// The frame of the original: 0x4D4 bytes of locals; every offset below is the original's `esp`
/// offset, so the sub-structures sit where they did (the collector at +0x70 or +0x140, the caster
/// at +0xF0, the ray record at +0x40, the two result arrays at +0x20 and +0x14).
#[repr(C, align(16))]
struct RayFrame([u32; 0x140]);

unsafe fn raycast(rq: u32, out: u32, flag: u32, p: &Pushad) -> u32 {
    unsafe {
        let mut fr = RayFrame([0; 0x140]);
        let b = fr.0.as_mut_ptr() as usize;
        let r = rq as usize;
        // the from / to points, copied through the FPU (quiet)
        let (f0, f1, f2) = (q32(rd(r)), q32(rd(r + 4)), q32(rd(r + 8)));
        let (t0, t1, t2) = (q32(rd(r + 0xC)), q32(rd(r + 0x10)), q32(rd(r + 0x14)));
        wd(b + 0x20, f0);
        wd(b + 0x24, f1);
        wd(b + 0x28, f2);
        wd(b + 0x14, t0);
        wd(b + 0x18, t1);
        wd(b + 0x1C, t2);
        wd(b + 0x2C, out);
        // the thread block carries the request's filter words while the cast runs
        let blk = thread_block();
        let r44 = rd(r + 0x44);
        wd(blk + 0x6C, rd(r + 0x54));
        wd(blk + 0x64, rd(r + 0x48));
        wd(blk + 0x70, r44);
        wd(b + 0x38, blk as u32);
        // clamp both ends into the world box
        call_regs_pop(R_CLAMP, rq, BOX_MAX, r44, (b + 0x20) as u32, rq, &[BOX_MIN]);
        call_regs_pop(R_CLAMP, rq.wrapping_add(0xC), BOX_MAX, r44, (b + 0x14) as u32, rq, &[BOX_MIN]);
        // the ray record at +0x40: clamped from, 0.0, clamped to, 0.0, flag byte 1, the kind
        let (c0, c1, c2) = (q32(rd(b + 0x20)), q32(rd(b + 0x24)), q32(rd(b + 0x28)));
        let (u0, u1, u2) = (q32(rd(b + 0x14)), q32(rd(b + 0x18)), q32(rd(b + 0x1C)));
        wd(b + 0x40, c0);
        wd(b + 0x44, c1);
        wd(b + 0x48, c2);
        wd(b + 0x64, rd(r + 0x4C));
        wd(out as usize + 4, 0);
        let mode = rd(r + 0x50);
        wd(b + 0x4C, 0);
        wd(b + 0x50, u0);
        wd(b + 0x54, u1);
        wd(b + 0x58, u2);
        wd(b + 0x5C, 0);
        wb(b + 0x60, 1);
        // result arrays {data, size, capacity | no-free flag}
        wd(b + 0x20, 0);
        wd(b + 0x24, 0);
        wd(b + 0x28, 0x8000_0000);
        wd(b + 0x14, 0);
        wd(b + 0x18, 0);
        wd(b + 0x1C, 0x8000_0000);
        let mut count: u32 = 0; // ebx
        let mut esi: u32 = 0x8000_0000;
        if mode == 0 {
            br(21);
            // closest hit
            wd(b + 0x90, 0x3F80_0000);
            wd(b + 0x94, 0xFFFF_FFFF);
            wd(b + 0x74, 0x3F80_0000);
            wd(b + 0xA0, 0xFFFF_FFFF);
            wd(b + 0xE0, 0xFFFF_FFFF);
            wd(b + 0xE4, 0xFFFF_FFFF);
            wd(b + 0xE8, 0);
            let filter = rd(r + 0x54);
            let world = rd(WORLD_PTR);
            wd(b + 0xD0, 0);
            wd(b + 0xC0, 0);
            wd(b + 0x130, 0);
            wd(b + 0x134, 0);
            wd(b + 0xEC, filter);
            wd(b + 0x70, CLOSEST_VT);
            wd(b + 0xF0, CASTER_VT);
            call_regs(CAST_RAY, world, rd(world as usize + 0x54), (b + 0x40) as u32, 0x8000_0000, rq, &[(b + 0xF0) as u32, rd(world as usize + 0x70), 0, (b + 0x70) as u32]);
            if rd(b + 0xD0) != 0 {
                br(22);
                call_regs(ARRAY_GROW, (b + 0x20) as u32, 0, 0, 0x8000_0000, rq, &[(b + 0x20) as u32, 0x60]);
                let size = rd(b + 0x24);
                let rec = (rd(b + 0x20) as usize).wrapping_add(size as usize * 0x60);
                call_regs(HIT_FILL, rec as u32, rec as u32, 0, 0x8000_0000, rq, &[(b + 0x80) as u32]);
                wd(rec + 0x50, rd(b + 0xD0));
                call_regs(ARRAY_GROW, (b + 0x14) as u32, 0, 0, 0x8000_0000, rq, &[(b + 0x14) as u32, 0xC]);
                let csize = rd(b + 0x18);
                let cdata = rd(b + 0x14);
                esi = rd(b + 0x1C);
                let dst = (cdata as usize).wrapping_add(csize as usize * 12);
                wd(dst, rd(b + 0xE0));
                wd(dst + 4, rd(b + 0xE4));
                wd(dst + 8, rd(b + 0xE8));
                count = size.wrapping_add(1);
            }
        } else if mode.wrapping_sub(1) == 0 {
            br(23);
            // every hit: copy the collector's records and companions into fresh arrays
            call_regs(COLL_CTOR, rq, (b + 0x140) as u32, r44, 0x8000_0000, rq, &[]);
            wd(b + 0x4CC, rd(r + 0x54));
            let world = rd(WORLD_PTR);
            let filter = rd(world as usize + 0x70);
            wd(b + 0xF0, CASTER_VT);
            wd(b + 0x130, 0);
            wd(b + 0x134, 0);
            call_regs(CAST_RAY, world, rd(world as usize + 0x54), (b + 0x40) as u32, 0x8000_0000, 0, &[(b + 0xF0) as u32, filter, 0, (b + 0x140) as u32]);
            count = rd(b + 0x154);
            if (count as i32) > 0 {
                let heap = call_regs(rd(HEAP_IMPORT) as usize, world, 0, count, 0x8000_0000, 0, &[rd(HEAP_SLOT)]);
                let n = rd(b + 0x154);
                let newp = call_regs(HEAP_ALLOC, heap, heap, n, 0x8000_0000, 0, &[n.wrapping_mul(0x60), 0x17]);
                count = rd(b + 0x154);
                wd(b + 0x20, newp);
                wd(b + 0x28, count);
                if (count as i32) > 0 {
                    let src0 = rd(b + 0x150) as usize;
                    for i in 0..count as usize {
                        let s = src0.wrapping_add(i * 0x60);
                        let d = (newp as usize).wrapping_add(i * 0x60);
                        copy_dwords(d, s, 4);
                        wd(d + 0x10, q32(rd(s + 0x10)));
                        for k in 0..12 {
                            wd(d + 0x14 + k * 4, rd(s + 0x14 + k * 4));
                        }
                        wd(d + 0x50, rd(s + 0x50));
                    }
                }
            }
            let c2 = rd(b + 0x464);
            if (c2 as i32) > 0 {
                let heap = call_regs(rd(HEAP_IMPORT) as usize, world, 0, c2, 0x8000_0000, 0, &[rd(HEAP_SLOT)]);
                let n = rd(b + 0x464);
                let newc = call_regs(HEAP_ALLOC, heap, heap, n, 0x8000_0000, 0, &[n.wrapping_mul(12), 0x17]);
                let n2 = rd(b + 0x464);
                wd(b + 0x14, newc);
                wd(b + 0x1C, n2);
                esi = n2;
                if (n2 as i32) > 0 {
                    let src0 = rd(b + 0x460) as usize;
                    for i in 0..n2 as usize {
                        let s = src0.wrapping_add(i * 12);
                        let d = (newc as usize).wrapping_add(i * 12);
                        wd(d, rd(s));
                        wd(d + 4, rd(s + 4));
                        wd(d + 8, rd(s + 8));
                    }
                }
            }
            call_regs(COLL_DTOR, rq, (b + 0x140) as u32, r44, esi, rq, &[]);
        }
        // the post pass: one callback per record with the ids, the fraction and the flags
        let kind = rd(b + 0x64);
        let is_r = (kind == 0x52) as u32;
        let is_v = (kind == 0x56) as u32;
        if count != 0 {
            let mut comp = rd(b + 0x14);
            let mut rec = rd(b + 0x20);
            let mut left = count;
            while left != 0 {
                let mut last = 0xFFFF_FFFFu32;
                for k in 0..8usize {
                    let id = rd(rec as usize + 0x20 + k * 4);
                    if id == 0xFFFF_FFFF {
                        break;
                    }
                    last = id;
                }
                let frac = q32(rd(rec as usize + 0x10));
                call_regs(
                    HIT_POST,
                    out,
                    rec,
                    0,
                    rec,
                    comp,
                    &[out, (b + 0x40) as u32, (b + 0x50) as u32, frac, rd(rec as usize + 0x50), last, is_r, is_v, comp, flag],
                );
                comp = comp.wrapping_add(12);
                rec = rec.wrapping_add(0x60);
                left -= 1;
            }
            esi = rd(b + 0x1C);
        }
        // epilogue: release the thread block words, free the temporary arrays
        let found = rd(out as usize + 4) != 0;
        wd(blk + 0x6C, 0);
        wd(blk + 0x64, 0);
        wd(blk + 0x70, 0);
        let mut eax = blk as u32;
        if (esi as i32) >= 0 {
            let heap = call_regs(rd(HEAP_IMPORT) as usize, blk as u32, 0, 0, esi, rq, &[rd(HEAP_SLOT)]);
            let n = esi & 0x3FFF_FFFF;
            eax = call_regs(HEAP_FREE, heap, heap, rd(b + 0x14), n, rq, &[rd(b + 0x14), n.wrapping_mul(12), 0x17]);
        }
        if rd(b + 0x28) & 0x8000_0000 == 0 {
            let heap = call_regs(rd(HEAP_IMPORT) as usize, eax, 0, 0, esi, rq, &[rd(HEAP_SLOT)]);
            let n = rd(b + 0x28) & 0x3FFF_FFFF;
            eax = call_regs(HEAP_FREE, heap, heap, rd(b + 0x20), esi, rq, &[rd(b + 0x20), n.wrapping_mul(0x60), 0x17]);
        }
        let _ = p;
        (eax & !0xFF) | found as u32
    }
}

extern "C" fn raycast_entry(r: &mut Pushad, args: *const u32) {
    let p = *r;
    count(RAYCAST);
    unsafe {
        r.eax = raycast(p.ecx, *args, *args.add(1), &p);
    }
}
