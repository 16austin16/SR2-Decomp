/// out = linvel + cross(angvel, point - centre of mass), with the original's SSE lane order:
/// `d = p - com` (subps), `a.yzx * d.zxy - a.zxy * d.yzx` (mulps / subps), `+ linvel` (addps); the
/// three lanes leave through x87 `fld / fstp`.
unsafe fn point_velocity(index: u32, out: u32, point: u32) {
    unsafe {
        use std::arch::x86::*;
        let pt = point as usize;
        let body = rd(BODY_TABLE + index as usize * 0x18) as usize;
        // the point goes through fld / fstp into the stack vector, w from fldz
        let pv = _mm_set_ps(0.0, f32::from_bits(q32(rd(pt + 8))), f32::from_bits(q32(rd(pt + 4))), f32::from_bits(q32(rd(pt))));
        let com = _mm_load_ps((body + 0x130) as *const f32);
        let d = _mm_sub_ps(pv, com);
        let a = _mm_load_ps((body + 0x1B0) as *const f32);
        let d_zxy = _mm_shuffle_ps::<0xD2>(d, d);
        let a_yzx = _mm_shuffle_ps::<0xC9>(a, a);
        let t1 = _mm_mul_ps(a_yzx, d_zxy);
        let d_yzx = _mm_shuffle_ps::<0xC9>(d, d);
        let a_zxy = _mm_shuffle_ps::<0xD2>(a, a);
        let t2 = _mm_mul_ps(a_zxy, d_yzx);
        let lin = _mm_load_ps((body + 0x1A0) as *const f32);
        let res = _mm_add_ps(_mm_sub_ps(t1, t2), lin);
        let mut lanes = [0u32; 4];
        _mm_storeu_ps(lanes.as_mut_ptr() as *mut f32, res);
        for k in 0..3 {
            wd(out as usize + k * 4, q32(lanes[k]));
        }
    }
}

