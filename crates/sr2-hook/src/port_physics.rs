/// Branch counters for the ports that cannot be shadowed.
static BRANCH: [AtomicU32; 32] = [const { AtomicU32::new(0) }; 32];

fn br(i: usize) {
    BRANCH[i].fetch_add(1, Ordering::Relaxed);
}

/// Count a call; `Some((call number, original copy))` while it should be shadowed.
fn shadowing(id: usize) -> Option<(u32, usize)> {
    let p = &PORTS[id];
    let n = p.calls.fetch_add(1, Ordering::Relaxed);
    let orig = p.original.load(Ordering::Relaxed);
    if n == SHADOW_CALLS && orig != 0 {
        log(&format!("port_physics: {}: {SHADOW_CALLS} calls shadowed, {} mismatched", p.name, p.mismatches.load(Ordering::Relaxed)));
    }
    (orig != 0 && n < SHADOW_CALLS).then_some((n, orig))
}

fn count(id: usize) {
    PORTS[id].calls.fetch_add(1, Ordering::Relaxed);
}

fn mismatch(id: usize, n: u32, what: String) {
    let m = PORTS[id].mismatches.fetch_add(1, Ordering::Relaxed) + 1;
    if m <= 10 {
        log(&format!("port_physics: {} mismatch (call {n}): {what}", PORTS[id].name));
    }
}

unsafe fn save(regions: &[(usize, usize)]) -> Vec<u8> {
    let mut v = Vec::new();
    for &(a, l) in regions {
        v.extend_from_slice(unsafe { std::slice::from_raw_parts(a as *const u8, l) });
    }
    v
}

unsafe fn load(regions: &[(usize, usize)], s: &[u8]) {
    let mut at = 0;
    for &(a, l) in regions {
        unsafe { std::ptr::copy_nonoverlapping(s[at..at + l].as_ptr(), a as *mut u8, l) };
        at += l;
    }
}

/// Run the Rust body, and for the first `SHADOW_CALLS` calls also the original copy from the same
/// snapshot of `regions` (restored in between). EAX bits in `mask` and the regions must agree;
/// otherwise the original's EAX and writes are kept.
unsafe fn shadowed(id: usize, p: &Pushad, args: *const u32, nargs: usize, regions: &[(usize, usize)], mask: u32, ours: impl FnOnce() -> u32) -> u32 {
    let Some((n, orig)) = shadowing(id) else { return ours() };
    unsafe {
        let a: Vec<u32> = (0..nargs).map(|i| *args.add(i)).collect();
        let before = save(regions);
        let mut ro = Regs::of(p);
        call_full(orig, &mut ro, &a, false);
        let after_o = save(regions);
        load(regions, &before);
        let e = ours();
        let after_r = save(regions);
        if after_o != after_r || (ro.eax ^ e) & mask != 0 {
            mismatch(id, n, format!("in {:x?} args {a:x?}: original eax {:#x}, Rust {e:#x}, memory equal: {}", Regs::of(p), ro.eax, after_o == after_r));
            load(regions, &after_o);
            return ro.eax;
        }
        e
    }
}

/// As `shadowed`, for a function returning an f32 on ST0.
unsafe fn shadowed_st0(id: usize, p: &Pushad, ours: impl FnOnce() -> f32) -> f32 {
    let Some((n, orig)) = shadowing(id) else { return ours() };
    unsafe {
        let mut ro = Regs::of(p);
        let st = call_full(orig, &mut ro, &[], true) as f32;
        let e = ours();
        if st.to_bits() != e.to_bits() && !(st.is_nan() && e.is_nan()) {
            mismatch(id, n, format!("eax {:#x}: original {st:e}, Rust {e:e}", p.eax));
            return st;
        }
        e
    }
}

/// EAX with AL replaced.
fn lo(eax: u32, al: bool) -> u32 {
    (eax & !0xFF) | al as u32
}

/// The object of a handle (slot table 0x2149C64, 16-byte entries), or 0 when 0 / stale.
unsafe fn resolve(h: u32) -> u32 {
    if h == 0 {
        return 0;
    }
    let o = unsafe { rd(HANDLES + (h as usize & 0xFFF) * 16) };
    if o != 0 && unsafe { rd(o as usize + 0x44) } == h { o } else { 0 }
}

/// The value of `fs:[0x2C]` slot 0: the thread block.
unsafe fn thread_block() -> usize {
    let tls: usize;
    unsafe {
        std::arch::asm!("mov {}, dword ptr fs:[0x2C]", out(reg) tls, options(nostack, readonly));
        rd(tls) as usize
    }
}

