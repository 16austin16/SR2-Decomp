// --- 0x9D7DD0 handle_to_player_human (ECX = handle -> EAX), 0x5D8850 (EAX = &handle) ---------------

/// The live type-1 object of the handle, kept only when byte +0x3CC is 1 (`sub cl,1; neg cl; sbb
/// ecx,ecx; not ecx; and eax,ecx`: the mask is all ones only for a zero result of the sub).
unsafe fn player_human(h: u32) -> u32 {
    unsafe {
        let o = resolve(h);
        if o == 0 || rd(o as usize + 0x4C) != 1 {
            return 0;
        }
        if rb(o as usize + 0x3CC) == 1 { o } else { 0 }
    }
}

extern "C" fn player_human_entry(r: &mut Pushad, _: *const u32) {
    let p = *r;
    r.eax = unsafe { shadowed(PLAYER_HUMAN, &p, std::ptr::null(), 0, &[], u32::MAX, || player_human(p.ecx)) };
}
regs_thunk!(player_human_thunk, player_human_entry);

