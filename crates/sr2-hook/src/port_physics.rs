// --- 0x70C1F0 constraint_slot_alloc / 0x70C290 constraint_slot_release -------------------------------

const CSLOTS: usize = g(0x0176_95F0); // 0x200 slots of 20 bytes
const C_USED_HEAD: usize = g(0x0252_7DF0);
const C_FREE_HEAD: usize = g(0x0252_7DF4);
const C_USED_COUNT: usize = g(0x0252_7DEC);

/// Take the head of the free ring, append it to the used ring; EAX = its index (address - base) / 20.
unsafe fn cslot_alloc() -> u32 {
    unsafe {
        let s = rd(C_FREE_HEAD) as usize;
        if s == 0 {
            return 0xFFFF_FFFF;
        }
        let next = rd(s + 0xC) as usize;
        let tailp = s + 0x10;
        if next == s {
            wd(C_FREE_HEAD, 0);
        } else {
            let prev = rd(s + 0x10) as usize;
            let nx = rd(s + 0xC);
            wd(C_FREE_HEAD, next as u32);
            wd(prev + 0xC, nx);
            let n2 = rd(s + 0xC) as usize;
            let pv = rd(tailp);
            wd(n2 + 0x10, pv);
        }
        let head = rd(C_USED_HEAD) as usize;
        wd(tailp, 0);
        wd(s + 0xC, 0);
        if head == 0 {
            wd(s + 0xC, s as u32);
            wd(tailp, s as u32);
            wd(C_USED_HEAD, s as u32);
        } else {
            let prev = rd(head + 0x10);
            wd(tailp, prev);
            wd(s + 0xC, head as u32);
            let t = rd(head + 0x10) as usize;
            wd(t + 0xC, s as u32);
            wd(head + 0x10, s as u32);
        }
        wd(C_USED_COUNT, rd(C_USED_COUNT).wrapping_add(1));
        let x = (s as u32).wrapping_sub(CSLOTS as u32) as i32;
        let hi = ((x as i64 * 0x6666_6667) >> 32) as i32;
        let q = hi >> 3;
        (q as u32).wrapping_add((q as u32) >> 31)
    }
}

extern "C" fn cslot_alloc_entry(r: &mut Pushad, _: *const u32) {
    let p = *r;
    r.eax = unsafe {
        shadowed(CSLOT_ALLOC, &p, std::ptr::null(), 0, &[(CSLOTS, 0x200 * 20), (C_USED_HEAD, 4), (C_FREE_HEAD, 4), (C_USED_COUNT, 4)], u32::MAX, || cslot_alloc())
    };
}
regs_thunk!(cslot_alloc_thunk, cslot_alloc_entry);

/// Drop the slot's reference, mark it free, unlink it from the used ring and put it on the free ring.
unsafe fn cslot_release(s: usize, p: &Pushad) {
    unsafe {
        let rf = rd(s + 8) as usize;
        if rf != 0 && *((rf + 4) as *const u16) != 0 {
            let c = (*((rf + 6) as *const u16)).wrapping_add(0xFFFF);
            *((rf + 6) as *mut u16) = c;
            if c == 0 {
                br(10);
                let vt = rd(rf);
                let f = rd(vt as usize);
                call_regs(f as usize, vt, rf as u32, f, s as u32, 0, &[1]);
            }
        }
        let used_head = rd(C_USED_HEAD) as usize;
        wd(s + 8, 0);
        wd(s, 0xFFFF_FFFF);
        wd(s + 4, 0);
        let mut unlink = true;
        if used_head == s {
            let next = rd(s + 0xC);
            if next as usize == s {
                wd(C_USED_HEAD, 0);
                unlink = false;
            } else {
                wd(C_USED_HEAD, next);
            }
        }
        if unlink {
            let prev = rd(s + 0x10) as usize;
            let next = rd(s + 0xC);
            wd(prev + 0xC, next);
            let n2 = rd(s + 0xC) as usize;
            let p2 = rd(s + 0x10);
            wd(n2 + 0x10, p2);
        }
        let free = rd(C_FREE_HEAD) as usize;
        wd(s + 0x10, 0);
        wd(s + 0xC, 0);
        if free == 0 {
            wd(C_USED_COUNT, rd(C_USED_COUNT).wrapping_sub(1));
            wd(s + 0xC, s as u32);
            wd(s + 0x10, s as u32);
            wd(C_FREE_HEAD, s as u32);
        } else {
            let tail = rd(free + 0x10);
            wd(C_USED_COUNT, rd(C_USED_COUNT).wrapping_sub(1));
            wd(s + 0x10, tail);
            wd(s + 0xC, free as u32);
            let t2 = rd(free + 0x10) as usize;
            wd(t2 + 0xC, s as u32);
            wd(free + 0x10, s as u32);
        }
        let _ = p;
    }
}

extern "C" fn cslot_release_entry(r: &mut Pushad, _: *const u32) {
    let p = *r;
    count(CSLOT_RELEASE);
    unsafe { cslot_release(p.esi as usize, &p) };
}
regs_thunk!(cslot_release_thunk, cslot_release_entry);

