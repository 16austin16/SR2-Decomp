//! Port module: the game-side physics wrappers and world-object helpers of doc 53 ("Game-side
//! physics and world objects"), ported by hand and checked against the original bytes.
//!
//! Every port goes through a `pushad` thunk: all registers come back as the caller left them except
//! EAX, which carries the result (a superset of what each original preserves; the originals clobber
//! ECX / EDX / EAX with scratch values nothing reads). The Havok calls stay original, called by
//! address with the registers the original has at the call.
//!
//! Checks (see `summary` for the counters):
//! - pure functions and small known writers: a relocated copy of the original runs on the same
//!   registers and stack arguments for the first `SHADOW_CALLS` calls, from a snapshot of the
//!   memory the function can write (restored in between); on a mismatch the original's result and
//!   writes are kept;
//! - functions that reach side-effecting game code: per-branch counters only.
//!
//! Offline: `port_physics_tests.rs` runs the original machine code (loaded from the unpacked exe at
//! its real addresses, callees replaced by recording stubs) against these ports through their
//! real thunks on random worlds and compares registers, ST0, memory and the call stream.

