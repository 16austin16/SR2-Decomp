// --- 83 fade_out -----------------------------------------------------------------------------

/// `fade_out(seconds, [{r, g, b}], [flags = 3])`: the colour table entries default to 0.0 and are
/// truncated to ints for `gfx_set_color(r, g, b, 255)`; bit 0 starts the fade (0x4D1090 with
/// (ms, 0, 1.0f)), bit 1 (online only) sends the u16 duration (0x4D1400).
unsafe fn fade_out_impl(l: u32) -> i32 {
    unsafe {
        let n = nargs(l).min(3);
        let secs = number_arg(l, -n) as f32;
        let left = n - 1;
        let r = opt_float(l, left, 1, 0.0);
        let g = opt_float(l, left, 2, 0.0);
        let b = opt_float(l, left, 3, 0.0);
        let mut flags = 3u32;
        let mut c = n - 1;
        if c > 0 {
            c -= 1;
            if c > 0 && !is_nil(slot(l, -c)) {
                flags = int_arg(l, -c);
            }
        }
        let bi = ftol2_sse(b);
        let gi = ftol2_sse(g);
        let ri = ftol2_sse(r);
        call_regs(0x00D1_4840, 0, 0, 0, 0, 0, &[ri, gi, bi, 0xFF]);
        if flags as u8 & 1 != 0 {
            let ms = ftol2_sse64(secs as f64 * 1000.0);
            call_regs(0x004D_1090, 0, 0, 0, 0, 0, &[ms, 0, 0x3F80_0000]);
        }
        if flags as u8 & 2 != 0 && rb(0x0252_8B48) == 1 {
            let t = fistp_chop(secs as f64 * 1000.0);
            call_regs(0x004D_1400, 0, 0, 0, 0, 0, &[t as u16 as u32]);
        }
    }
    0
}
counted!(fade_out, I_FADE_OUT, fade_out_impl);

