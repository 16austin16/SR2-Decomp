/// `wander_start(name, [navpoint], [radius = -1.0])`: read front to back with a counter (nil
/// consumes its slot). A negative radius falls back to the human's f32 +0x10C; a navpoint gives
/// the centre (+0x1C), else the human's own +0x110..+0x118 (skipped when +0x10C is negative).
