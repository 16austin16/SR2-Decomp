/// Install this module's replacements (called from hooks::install_all).
pub fn install() {
    let mut ok = 0;
    for (i, b) in BINDINGS.iter().enumerate() {
        if let Some(calls) = b.shadow_calls {
            match unsafe { detour::relocate(b.addr, b.body, calls) } {
                Ok(copy) => ORIGINALS[i].store(copy, Ordering::Relaxed),
                Err(e) => log(&format!("port_bindings4: no shadow copy of {}: {e:?}", b.name)),
            }
        }
        if replace_pinned(b.name, b.addr, b.body, b.f as usize) {
            ok += 1;
        }
    }
    log(&format!("port_bindings4: replaced {ok}/{} with Rust", BINDINGS.len()));
}

/// Per-function call counts for the periodic log (with shadow mismatches where checked).
pub fn summary() -> String {
    let parts: Vec<String> = BINDINGS
        .iter()
        .enumerate()
        .filter_map(|(i, b)| {
            let c = CALLS[i].load(Ordering::Relaxed);
            (c > 0).then(|| format!("{} {c} ({})", b.name, MISMATCHES[i].load(Ordering::Relaxed)))
        })
        .collect();
    if parts.is_empty() { String::new() } else { format!("port_bindings4: {}", parts.join(", ")) }
}

