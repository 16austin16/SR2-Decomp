//! Script bindings ranked 81-120 by call sites in the shipped Lua scripts (the same method as
//! docs/analysis/43_bindings_41_80.md; rank 117 get_frame_time is already Rust, and
//! script_profiler_end_section and explosion_create are not ported) in Rust: fade_in,
//! inv_item_remove_all, fade_out, on_weapon_fired, mission_unlock, spawning_vehicles,
//! follower_make_independent, vehicle_exists, hud_bar_set_value, vint_get_time_index,
//! vint_unsubscribe_to_input_event, inv_weapon_add_temporary,
//! set_player_can_enter_exit_vehicles, get_is_host, on_damage, character_evacuate_from_all_vehicles,
//! vehicle_infinite_mass, vint_dataitem_add_subscription, vehicle_max_speed, mesh_mover_hide,
//! inv_weapon_remove_temporary, set_attack_player_flag, character_prevent_flinching, include,
//! on_mover_destroyed, npc_leash_remove, vehicle_prevent_explosion_fling, wander_start,
//! teleport_vehicle, character_kill, character_show, mission_help_clear, character_allow_ragdoll,
//! character_has_specific_human_shield, get_char_vehicle_type, mesh_mover_reset and npc_go_idle.
//!
//! Argument reading follows the originals exactly, as in port_bindings3.rs: argument k is read at
//! `k - 1 - n` (n clamped to the most a binding reads), so a missing argument is the stale slot at
//! `L->top`. Optional flags test the slot for nil first, then the truth test (the number 0 is
//! true); "stale" flags have no count guard and read index `1 - n`. Flags passed to callees as a
//! byte inside L's own argument slot keep L's upper three bytes; flags the original builds in a
//! register or an uninitialised local (so their upper bytes are unknowable) are passed clean,
//! which is safe because every such callee reads a byte.
//!
//! Bindings that only read state and push (vehicle_exists, vint_get_time_index, get_is_host,
//! character_has_specific_human_shield, get_char_vehicle_type) are shadow-checked against a
//! relocated copy of the original for the first 3000 calls: the Lua stack effect (values pushed,
//! result count) is compared and the original's effect is kept. The others write game state and
//! only count calls.
//!
//! Everything, including the unchecked bar index of hud_bar_set_value and the NULL names that
//! crash script_follower_index or `include`'s string search, is kept as in the original.

