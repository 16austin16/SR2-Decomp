// --- Shadow harness ------------------------------------------------------------------------

/// The pushed slots as comparable words: type, then the payload (strings by content).
unsafe fn snapshot(l: u32, from: u32, to: u32) -> Vec<u32> {
    let mut v = Vec::new();
    unsafe {
        let mut p = from;
        while p < to {
            let tt = rd(p as usize);
            v.push(tt);
            match tt {
                0 => {}
                3 => {
                    v.push(rd(p as usize + 8));
                    v.push(rd(p as usize + 12));
                }
                4 => {
                    let idx = -(((to - p) / 16) as i32);
                    let s = tostring(l, idx);
                    if s != 0 {
                        let mut q = s as usize;
                        while rb(q) != 0 && q - (s as usize) < 0x10000 {
                            v.push(rb(q) as u32);
                            q += 1;
                        }
                    }
                    v.push(0xFFFF_FFFF);
                }
                _ => v.push(rd(p as usize + 8)),
            }
            p += 16;
        }
    }
    v
}

/// Run the Rust body, then (for the first 3000 calls) the relocated original on the same stack
/// position, compare the Lua stack effect and keep the original's.
unsafe fn shadowed(i: usize, l: u32, rust: unsafe fn(u32) -> i32) -> i32 {
    let n = CALLS[i].fetch_add(1, Ordering::Relaxed);
    let orig = ORIGINALS[i].load(Ordering::Relaxed);
    if orig == 0 || n >= SHADOW_CALLS {
        return unsafe { rust(l) };
    }
    unsafe {
        let t0 = top(l);
        let r1 = rust(l);
        let t1 = top(l);
        let s1 = snapshot(l, t0, t1);
        wd(l as usize + 8, t0);
        let r2 = call_regs(orig, 0, 0, 0, 0, 0, &[l]) as i32;
        let t2 = top(l);
        let s2 = snapshot(l, t0, t2);
        if r1 != r2 || t1 != t2 || s1 != s2 {
            let m = MISMATCHES[i].fetch_add(1, Ordering::Relaxed) + 1;
            if m <= 10 {
                log(&format!(
                    "port_bindings4: {} mismatch (call {n}): original {r2} results {s2:?}, Rust {r1} results {s1:?}",
                    BINDINGS[i].name
                ));
            }
        }
        if n + 1 == SHADOW_CALLS {
            log(&format!(
                "port_bindings4: {}: {SHADOW_CALLS} calls shadowed, {} mismatched",
                BINDINGS[i].name,
                MISMATCHES[i].load(Ordering::Relaxed)
            ));
        }
        r2
    }
}

macro_rules! counted {
    ($name:ident, $idx:expr, $body:ident) => {
        extern "C" fn $name(l: u32) -> i32 {
            CALLS[$idx].fetch_add(1, Ordering::Relaxed);
            unsafe { $body(l) }
        }
    };
}

macro_rules! shadow_checked {
    ($name:ident, $idx:expr, $body:ident) => {
        extern "C" fn $name(l: u32) -> i32 {
            unsafe { shadowed($idx, l, $body) }
        }
    };
}

// --- 81 fade_in ------------------------------------------------------------------------------

/// `fade_in(seconds, [flags = 3])`: bit 0 starts the screen fade (0x4D1270, DL = 0, stack
/// (ms, 0.0f)), bit 1 (online only) sends the duration as a u16 (0x4D1510).
unsafe fn fade_in_impl(l: u32) -> i32 {
    unsafe {
        let n = nargs(l).min(2);
        let secs = number_arg(l, -n) as f32;
        let m = n - 1;
        let flags: u32 = if m <= 0 || is_nil(slot(l, -m)) { 3 } else { int_arg(l, -m) };
        if flags as u8 & 1 != 0 {
            let ms = ftol2_sse64(secs as f64 * 1000.0);
            call_regs(0x004D_1270, 0, 0, 0, 0, 0, &[ms, 0]);
        }
        if flags as u8 & 2 != 0 && rb(0x0252_8B48) == 1 {
            let t = fistp_chop(secs as f64 * 1000.0);
            call_regs(0x004D_1510, 0, 0, 0, 0, 0, &[t as u16 as u32]);
        }
    }
    0
}
counted!(fade_in, I_FADE_IN, fade_in_impl);

