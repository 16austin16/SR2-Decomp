unsafe fn take_damage(h: u32, amount: u32) {
    unsafe {
        std::arch::asm!(
            "push 0",
            "push 0",
            "push {a}",
            "push eax",
            "call {f}",
            "fstp st(0)",
            "add esp, 16",
            f = in(reg) 0x0098_47A0usize,
            a = in(reg) amount,
            in("eax") h,
            in("ecx") 0u32,
            in("edx") 0u32,
            clobber_abi("C"),
        );
    }
}

