/// `teleport_vehicle(name, navpoint)`: the human's vehicle (or the named script vehicle when it
/// is ... in the original's terms: its AI info +0x70 is negative) must be a live vehicle entity
/// (kind 5). Packet 0x19, every seat part's body is woken and 0xAC01C0 gets 0.0f, then packet
/// 0x18 carries the navpoint (+0x1C / +0x28 and the byte +0x50 == 0 flag).
unsafe fn teleport_vehicle_impl(l: u32) -> i32 {
    unsafe {
        let n = nargs(l).min(2);
        let who = tostring(l, -n);
        let nav_name = tostring(l, 1 - n);
        let mut hash = 0u32;
        let ph = &mut hash as *mut u32 as u32;
        call_regs(STRING_CRC32, ph, 0, 0, 0, 0, &[nav_name]);
        let nav = call_regs(NAVPOINT_FIND, ph, 0, 0, 0, 0, &[]);
        if nav == 0 {
            return 0;
        }
        let human = find_human(who);
        let handle;
        if human != 0 {
            handle = rd(human as usize + 0xD74);
        } else {
            let v = vehicle_from_name(who);
            if v == 0 {
                return 0;
            }
            let info = rd(v as usize + 0x84EC);
            if (rd(info as usize + 0x70) as i32) >= 0 {
                return 0;
            }
            handle = rd(v as usize + 0x44);
        }
        if handle == 0 {
            return 0;
        }
        let ent = rd(ENTITY_TABLE + (((handle & 0xFFF) as usize) << 4));
        if ent == 0 || rd(ent as usize + 0x44) != handle || rd(ent as usize + 0x4C) != 5 {
            return 0;
        }
        let ep = ent as usize;
        call_regs(0x00AB_0D60, 0, 0, 0, 0, 0, &[handle, 1]);
        let mut i = 0i32;
        loop {
            let count = if rb(ep + 0x84D8) == 1 { rd(ep + 0x6CE8) as i32 } else { 8 };
            if i >= count {
                break;
            }
            let part = call_regs(0x00AA_77C0, 0, i as u32, ent, 0, 0, &[]);
            if rb(ep + 0x84D8) == 1 && part < rd(ep + 0x55C) {
                let body = rd(ep + 0x554);
                call_regs(0x00D5_8FF0, 0, 0, 0, body, 0, &[]);
                let elem = ent.wrapping_add(0x560).wrapping_add(part.wrapping_mul(0x120));
                call_regs(0x00AC_01C0, ent, 0, elem, 0, 0, &[0]);
            }
            i += 1;
        }
        let flag = (rd(nav as usize + 0x50) == 0) as u32;
        call_regs(0x00AA_85B0, 0, nav + 0x28, 0, 0, 0, &[ent, nav + 0x1C, flag]);
    }
    0
}
