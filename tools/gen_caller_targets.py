"""Generate crates/sr2-hook/src/caller_targets.rs: the vtable slots for the caller survey.

Usage: python -I tools/gen_caller_targets.py bin/SR2_pc.unpacked.exe

A target is (vtable address, slot, original function) for every slot of a game
class (docs/rtti_classes.csv; Havok and the memory pools left out) whose function
is still an unnamed `Class::vfN` in docs/functions.csv. The survey (callers.rs)
wraps each of those vtable cells and logs the return addresses of its calls, so
the callers can name the method.
"""
import csv
import re
import struct
import sys
from pathlib import Path

BASE = 0x400000
ROOT = Path(__file__).resolve().parent.parent
SKIP = ("hk", "Hk", "?$hk")
POOLS = {"mempool_base", "static_mempool_base", "mempool", "virtual_mempool", "page_mempool",
         "split_page_mempool", "async_mempool", "async_virtual_mempool", "compacting_mempool",
         "tracked_mempool", "string_pool", "string_hash_table"}


def main(exe):
    data = open(exe, "rb").read()
    names = {int(r["address"], 16): r["name"]
             for r in csv.DictReader(open(ROOT / "docs/functions.csv", encoding="utf-8"))}
    targets = []
    for r in csv.DictReader(open(ROOT / "docs/rtti_classes.csv", encoding="utf-8")):
        cls = r["name"]
        bases = [b for b in r["bases"].split(" ; ") if b]
        if cls.startswith(SKIP) or cls in POOLS or POOLS & set(bases):
            continue
        for vt in filter(None, r["vtables"].split(" ")):
            va, off = vt.split("@")
            va = int(va, 16)
            for k in range(int(r["n_virtuals"] or 0)):
                f = struct.unpack_from("<I", data, va + 4 * k - BASE)[0]
                # Real slot targets follow padding; past a vtable's end there is data.
                padded = 0x401000 <= f < 0xDB71F4 and (
                    data[f - BASE - 1] in (0xCC, 0xC3, 0x90) or data[f - BASE - 3] == 0xC2)
                if padded and re.search(r"::vf\d", names.get(f, "")):
                    targets.append((va + 4 * k, k, f))
    out = ROOT / "crates/sr2-hook/src/caller_targets.rs"
    lines = [
        "// Generated by tools/gen_caller_targets.py from docs/functions.csv and docs/rtti_classes.csv.",
        "// (vtable cell address, slot, original function): unnamed vfN slots of game classes.",
        f"pub const TARGETS: [(u32, u16, u32); {len(targets)}] = [",
    ]
    lines += [f"    (0x{c:08X}, {k}, 0x{f:08X})," for c, k, f in targets]
    lines.append("];")
    out.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"{len(targets)} targets ({len({f for *_, f in targets})} distinct functions) -> {out}")


if __name__ == "__main__":
    main(sys.argv[1])
