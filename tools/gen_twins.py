"""Find unported functions whose code is identical to a ported one, and write
crates/sr2-hook/src/twins_table.rs for twins.rs.

Identical: same bytes, except rel32 calls / jumps whose target lies outside the function, which
must resolve to the same absolute address. Function extents are "to the next known start"; the hook
re-checks every pair at runtime over the ported function's pinned body length, so a generous
extent here is safe.

Usage: python tools/gen_twins.py
"""
import bisect, csv, os, struct

import capstone

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
exe = open(os.path.join(ROOT, "bin", "SR2_pc.unpacked.exe"), "rb").read()
pe = struct.unpack_from("<I", exe, 0x3C)[0]
so = struct.unpack_from("<H", exe, pe + 20)[0]
_, vs, va, rs, rp = struct.unpack_from("<8sIIII", exe, pe + 24 + so)
text = exe[rp:rp + rs]
base = 0x400000 + va

rows = [r for r in csv.reader(open(os.path.join(ROOT, "docs", "functions.csv"), encoding="utf-8")) if r and r[0].startswith("0x")]
status = {}
for r in rows:
    status[int(r[0], 16)] = (r[1], r[3])
starts = sorted(status)
md = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_32)


def extent(a):
    i = bisect.bisect_right(starts, a)
    return (starts[i] - a) if i < len(starts) else 0


def analyse(a, n):
    """Signature and the offsets of rel32 fields that point outside [a, a+n)."""
    o = a - base
    if o < 0 or o + n > len(text):
        return None
    sig, fix, end = [], [], a
    for ins in md.disasm(text[o:o + n], a):
        end = ins.address + ins.size
        b = bytes(ins.bytes)
        rel = ins.mnemonic == "call" or ins.mnemonic.startswith("j")
        if rel and ins.op_str.startswith("0x"):
            t = int(ins.op_str, 16)
            if a <= t < a + n:
                sig.append((b, None))
            else:
                if ins.size < 5:
                    return None  # short branch out of the function: target differs per copy
                fix.append(ins.address + ins.size - 4 - a)
                sig.append((b[:-4], ("abs", t)))
        else:
            sig.append((b, None))
    if end - a < n - 16:  # disassembly stopped early (data / bad bytes)
        n = end - a
    return tuple(sig), fix, n


groups = {}
for a in starts:
    if not (base <= a < base + len(text)):
        continue
    n = extent(a)
    if not 8 <= n <= 4096:
        continue
    r = analyse(a, n)
    if r is None or len(r[0]) < 3:
        continue
    groups.setdefault(r[0], []).append((a, r[1], r[2]))

pairs = []
for members in groups.values():
    ported = [m for m in members if status[m[0]][1] == "rust"]
    if not ported:
        continue
    p = ported[0]
    for m in members:
        if status[m[0]][1] != "rust":
            pairs.append((m[0], p[0], m[2], m[1]))
# Keep every pair of the existing table: installed twins are marked rust in functions.csv, so a fresh scan no
# longer lists them, and dropping them would uninstall them. twins.rs re-checks each pair at runtime anyway.
out = os.path.join(ROOT, "crates", "sr2-hook", "src", "twins_table.rs")
import re as _re
if os.path.exists(out):
    have = {t for t, _, _, _ in pairs}
    for m in _re.finditer(r"\(0x([0-9a-f]+), 0x([0-9a-f]+), (\d+), &\[([0-9, ]*)\]\)", open(out, encoding="utf-8").read()):
        t = int(m.group(1), 16)
        if t not in have:
            fix = [int(x) for x in m.group(4).split(",") if x.strip()]
            pairs.append((t, int(m.group(2), 16), int(m.group(3)), fix))
pairs.sort()

out = os.path.join(ROOT, "crates", "sr2-hook", "src", "twins_table.rs")
with open(out, "w", encoding="utf-8", newline="\n") as f:
    f.write("// Generated by tools/gen_twins.py: (twin, ported original, twin extent, rel32 fixup offsets).\n")
    f.write("// Each pair is checked again at runtime by twins.rs before it is installed.\n\n")
    f.write(f"pub(crate) static TWINS: [(u32, u32, u16, &[u16]); {len(pairs)}] = [\n")
    for t, p, n, fix in pairs:
        f.write(f"    (0x{t:06x}, 0x{p:06x}, {n}, &[{', '.join(str(x) for x in fix)}]),\n")
    f.write("];\n")
print(len(pairs), "pairs ->", out)
